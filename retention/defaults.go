// defaults.go — величины ПЕТЛИ (не пороги) в единственном экземпляре.
package retention

import "time"

// Величины петли уборки по умолчанию.
//
// Это величины РАСПИСАНИЯ, а не пороги: порог отвечает на вопрос «когда строку
// позволено снять» и выводится из предиката читателя своей таблицы, а эти три —
// на вопрос «как быстро уборка догоняет накопленное, не мешая пути запроса».
// Поэтому они общие для всех предметов и объявлены здесь один раз: восемь
// расписаний об одном предмете разошлись бы молча.
const (
	// DefaultInterval — как часто идёт проход.
	//
	// Задаёт не пропускную способность, а задержку замечания: догон внутри
	// прохода обеспечивает DefaultMaxBatchesPerPass, а интервал определяет лишь,
	// насколько поздно уборка узнает о том, что появилось после прошлого прохода.
	DefaultInterval = 5 * time.Minute

	// DefaultBatch — сколько строк снимает один оператор.
	//
	// На порядок ниже потолка MaxBatch: партия задаёт длину одного DELETE, а тот
	// держит строки, которые в этот момент читает путь запроса. Уборка не вправе
	// быть причиной отказа на пути запроса.
	DefaultBatch = 1000

	// DefaultMaxBatchesPerPass — потолок партий за проход.
	//
	// Даёт скорость догона DefaultBatch × DefaultMaxBatchesPerPass за интервал —
	// двадцать тысяч строк за пять минут, то есть около 66 строк в секунду
	// УСТОЙЧИВО. Величина названа здесь затем, чтобы «догоняет ли уборка внешний
	// темп» был вопросом с числом, а не предположением: темп записи выше этого
	// означает, что догон не обеспечен, и это видно сравнением двух чисел.
	DefaultMaxBatchesPerPass = 20
)

// DefaultConfig — величины петли по умолчанию.
//
// Отдельная функция, а не литерал у каждого вызывающего: литерал, скопированный
// в композиционный корень каждого владельца, и есть та копия, которая расходится
// молча.
func DefaultConfig() Config {
	return Config{
		Interval:          DefaultInterval,
		Batch:             DefaultBatch,
		MaxBatchesPerPass: DefaultMaxBatchesPerPass,
	}
}
