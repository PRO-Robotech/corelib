// Package pagetoken — ЕДИНСТВЕННОЕ объявление формы курсора страницы.
//
// # Зачем пакет существует
//
// Форма токена была записана в дереве трижды: авторитетный кодек в слое
// репозитория, рукописное зеркало в проверке формата на границе приложения — и
// оно бежит ПЕРВЫМ — и свой декодер в общем пакете операций. Четвёртая копия
// жила в другом сервисе.
//
// Пока значения совпадают, это не расхождение, а заряженная ловушка: смена формы
// вносится в три места, и первое же пропущенное даст ответ, зависящий от того,
// какой из декодеров бежал раньше. Оба при этом отвечают «валидно» на валидном
// входе — то есть расходятся ровно там, где расхождение не видно.
//
// Конвенция требует этого прямо: «кодек курсора не переписывать — guard обязан
// звать тот же разбор, что исполняется на пути чтения».
//
// # Почему в фундаменте, а не в слое приложения
//
// Кодек зовут ОБА слоя: проверка формата на границе приложения и репозиторий.
// Репозиторий — адаптер, и импортировать слой use-case ему нельзя (правило
// направления зависимостей). Единственное место, видимое обоим и ни одному не
// принадлежащее, — фундамент.
package pagetoken

import (
	"encoding/base64"
	"strings"
	"time"
)

// Cursor — граница страницы в keyset-порядке: последняя ОТДАННАЯ строка.
type Cursor struct {
	CreatedAt time.Time
	ID        string
}

// # Форм ДВЕ, и это факт дерева, а не недосмотр
//
// iam кодирует стандартным алфавитом с дополнением и разделяет вертикальной
// чертой; nlb — алфавитом URL без дополнения и разделяет нулевым байтом. Токены
// этих служб НЕСОВМЕСТИМЫ, и свести их к одной форме нельзя без слома курсоров,
// уже выданных клиентам, — а выданный курсор клиент держит между страницами.
//
// Поэтому пакет объявляет не одну форму, а СПОСОБ объявить форму: `Codec`.
// Каждая служба берёт свой предобъявленный кодек и не повторяет разбор. Тогда
// смена формы — правка ОДНОГО места, а различие двух форм ВИДНО, вместо того
// чтобы обнаруживаться на чужом токене.
//
// Кодировка канонического кодека — base64 со стандартным алфавитом и
// дополнением, тело — `<RFC3339Nano>|<id>`.
//
// Точность до наносекунд сохраняется НАМЕРЕННО: keyset сравнивает хранимую
// отметку времени, а не усечённую до секунд, которую несёт сообщение ресурса.
// Потеряв точность здесь, страница начала бы повторять или пропускать строки,
// созданные в одну секунду.
//
// Разделитель — вертикальная черта, и тело режется РОВНО НА ДВЕ части: id может
// содержать что угодно, кроме первой черты, поэтому `SplitN(…, 2)` — не деталь
// реализации, а часть формы.
const separator = "|"

// Codec — объявленная форма курсора: чем кодируется и чем разделяется тело.
type Codec struct {
	enc *base64.Encoding
	sep string
}

// Canonical — форма iam: стандартный алфавит с дополнением, разделитель `|`.
var Canonical = Codec{enc: base64.StdEncoding, sep: separator}

// NULSeparatedRawURL — форма nlb: алфавит URL без дополнения, разделитель —
// нулевой байт. Объявлена здесь, а не у nlb, ровно затем, чтобы РАЗЛИЧИЕ ДВУХ
// ФОРМ было видно в одном месте: пока каждая жила у себя, несовместимость
// обнаруживалась только на чужом токене.
var NULSeparatedRawURL = Codec{enc: base64.RawURLEncoding, sep: "\x00"}

// Encode собирает токен канонической формы.
func Encode(c Cursor) string { return Canonical.Encode(c) }

// Encode собирает токен этой формы.
func (k Codec) Encode(c Cursor) string {
	return k.enc.EncodeToString(
		[]byte(c.CreatedAt.UTC().Format(time.RFC3339Nano) + k.sep + c.ID))
}

// Decode разбирает токен.
//
// Пустой токен — ПЕРВАЯ страница, и он возвращает (nil, true): отсутствие
// представимо отдельно от всякого значения, поэтому вызывающий не обязан
// различать «токена не было» и «токен разобрался в нулевой курсор».
//
// Второй ответ — годность, а не ошибка: у вызывающих разный контракт отказа
// (проверка формата отвечает INVALID_ARGUMENT с именем поля, репозиторий —
// своим сигнальным значением), и навязывать им общий тип ошибки значило бы
// заставить каждого переводить её обратно.
func Decode(token string) (*Cursor, bool) { return Canonical.Decode(token) }

// Decode разбирает токен этой формы.
func (k Codec) Decode(token string) (*Cursor, bool) {
	if token == "" {
		return nil, true
	}
	raw, err := k.enc.DecodeString(token)
	if err != nil {
		return nil, false
	}
	parts := strings.SplitN(string(raw), k.sep, 2)
	if len(parts) != 2 || parts[1] == "" {
		return nil, false
	}
	ts, err := time.Parse(time.RFC3339Nano, parts[0])
	if err != nil {
		return nil, false
	}
	return &Cursor{CreatedAt: ts, ID: parts[1]}, true
}

// WellFormed отвечает, разбирается ли токен. Пустой — да (первая страница).
//
// Отдельная функция нужна проверке формата: ей курсор не нужен, нужен вердикт, а
// повторять разбор своим кодом — ровно то, чего пакет и избегает.
func WellFormed(token string) bool {
	_, ok := Decode(token)
	return ok
}
