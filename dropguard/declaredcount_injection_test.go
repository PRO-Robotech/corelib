// declaredcount_injection_test.go — доказательство в ОБЕ стороны для двух суждений,
// перенесённых из оснастки прогона в библиотеку.
//
// # Что доказывается и почему это нельзя было доказать раньше
//
// Оба суждения жили внутри `dropguardtest.Measure` и потому проверялись только
// прогоном против настоящей цепи настоящего сервиса. Уронить их нарочно значило
// испортить дерево, то есть не проверить их никогда: проверка, которую нельзя
// заставить упасть, неотличима от проверки, упасть неспособной.
//
// # Почему ноль снятий разбирается отдельной парой
//
// Прежняя оснастка отвергала цепь без снятий безусловно, рассуждая, что такой
// прогон ничего не утверждает. Рассуждение было верно ОТНОСИТЕЛЬНО ПОПУЛЯЦИИ, на
// которой писалось: у каждого вызывающего снятия были. Свод цепи одного сервиса в
// одну первичную миграцию популяцию расширил — и отказ стал срабатывать на
// правильном ответе. Поэтому здесь утверждается и то, что ноль объявленный молчит,
// и то, что ноль НЕобъявленный (при снятиях в цепи) краснеет: одностороннее
// утверждение зеленело бы на суждении, согласном со всем подряд.
package dropguard_test

import (
	"errors"
	"fmt"
	"io/fs"
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/dropguard"
)

func TestDeclaredDropCount_ProvenByInjection(t *testing.T) {
	// ── ИНЪЕКЦИЯ: цепь приросла снятием, а число не двинулось ───────────────
	t.Run("снятие появилось, число не двинулось — краснеет и называет ОБА числа", func(t *testing.T) {
		got := dropguard.AdjudicateDeclaredDropCount("demo", 5, 12, 4)
		if got == "" {
			t.Fatal("расхождение объявленного и найденного не названо: храповик не держит")
		}
		for _, want := range []string{"demo", "5", "12", "4"} {
			if !strings.Contains(got, want) {
				t.Fatalf("находка не называет %q — по ней не видно, что чинить:\n%s", want, got)
			}
		}
	})

	// ── ИНЪЕКЦИЯ в обратную сторону: снятие исчезло ─────────────────────────
	//
	// Она несущая. Именно этот случай прежняя оснастка обрабатывала отказом
	// «gate would assert nothing» — то есть жаловалась на СЕБЯ вместо того, чтобы
	// назвать расхождение с объявлением вызывающего.
	t.Run("снятие исчезло, число не двинулось — краснеет так же", func(t *testing.T) {
		got := dropguard.AdjudicateDeclaredDropCount("demo", 0, 1, 20)
		if got == "" {
			t.Fatal("цепь потеряла все снятия при объявленных двадцати, и это не находка")
		}
		if !strings.Contains(got, "20") || !strings.Contains(got, "0") {
			t.Fatalf("находка не называет обе величины:\n%s", got)
		}
	})

	// ── ЗАКОННЫЕ БЛИЗНЕЦЫ. Без них отрицание зеленело бы на всём сломанном ──
	t.Run("объявленное совпало с найденным — молчит", func(t *testing.T) {
		if got := dropguard.AdjudicateDeclaredDropCount("demo", 11, 43, 11); got != "" {
			t.Fatalf("ложное срабатывание на согласии: %s", got)
		}
	})

	t.Run("ОБЪЯВЛЕННЫЙ ноль на цепи без снятий — молчит", func(t *testing.T) {
		// Сведённая цепь: одно состояние, а не история. Отказ здесь и был тем
		// дефектом, ради которого суждение вынесено сюда.
		if got := dropguard.AdjudicateDeclaredDropCount("iam", 0, 1, 0); got != "" {
			t.Fatalf("прочитанная цепь без снятий объявлена находкой — тревога на правильном ответе: %s", got)
		}
	})
}

func TestManifestAbsence_ProvenByInjection(t *testing.T) {
	notThere := fmt.Errorf("dropguard: read dropguard.json: %w", fs.ErrNotExist)
	malformed := errors.New("dropguard: decode dropguard.json: unknown field \"drpos\"")

	// ── ЗАКОННЫЙ СЛУЧАЙ: нечего объявлять, файла нет ───────────────────────
	if !dropguard.ManifestAbsenceIsLegitimate(0, notThere) {
		t.Error("цепь без снятий обязана обходиться без ведомости: объявлять нечего, " +
			"и это то же правило, по которому репо-широкий гейт пропускает сервис, ни разу не дропавший таблицу")
	}

	// ── ИНЪЕКЦИИ: каждая снимает РОВНО ОДИН факт против законного случая ───
	if dropguard.ManifestAbsenceIsLegitimate(3, notThere) {
		t.Error("ведомость отсутствует при трёх снятиях в цепи, и это принято за законное: " +
			"три снятия остались бы без объявленного числа строк")
	}
	if dropguard.ManifestAbsenceIsLegitimate(0, malformed) {
		t.Error("НЕЧИТАЕМАЯ ведомость принята за отсутствующую: «файл испорчен» разрешилось " +
			"в «ничего и не было должно», то есть страж не прочитал того, с чем сверяется")
	}
	if dropguard.ManifestAbsenceIsLegitimate(0, nil) {
		t.Error("отсутствие ошибки объявлено отсутствием файла: вызывающий подставил бы " +
			"пустую ведомость поверх прочитанной")
	}
}
