// NTF1-D01: make notifications порождает SendInvite и эталон структуры;
// поля структуры — атрибуты с типами из notification.yaml.
func TestNTF1D01_GeneratesTypedSendFunction(t *testing.T) {
	tr := newTree(t)
	tr.generate()
	src := tr.read("svc/notifications_invite.gen.go")
	require.True(t, strings.HasPrefix(src, "// Code generated by notifygen. DO NOT EDIT."))

	f, err := parser.ParseFile(token.NewFileSet(), "gen.go", src, 0)
	require.NoError(t, err)
	require.Equal(t, "svc", f.Name.Name)
	fields := map[string]string{}
	var send *ast.FuncDecl
	ast.Inspect(f, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.TypeSpec:
			if x.Name.Name == "InviteAttrs" {
				for _, fl := range x.Type.(*ast.StructType).Fields.List {
					for _, nm := range fl.Names {
						fields[nm.Name] = types(fl.Type)
					}
				}
			}
		case *ast.FuncDecl:
			if x.Name.Name == "SendInvite" {
				send = x
			}
		}
		return true
	})
	require.Equal(t, map[string]string{"To": "string", "Initiator": "string", "InviterName": "string", "Token": "string"}, fields)
	require.NotNil(t, send)
	require.Len(t, send.Type.Params.List, 3)
	require.Equal(t, "context.Context", types(send.Type.Params.List[0].Type))
	require.Equal(t, "pgx.Tx", types(send.Type.Params.List[1].Type))
	require.Equal(t, "InviteAttrs", types(send.Type.Params.List[2].Type))

	require.Contains(t, tr.read("svc/notifications/invite/revision.yaml"), "revision: 1\n")
}

func types(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return types(x.X) + "." + x.Sel.Name
	}
	return "?"
}

// NTF1-D01: порождённый файл собирается против corelib этого дерева —
// SendX действительно зовёт feed.Put с описанием feed.TemplateDesc.
func TestNTF1D01_GeneratedFileCompilesAgainstFeed(t *testing.T) {
	corelib, err := filepath.Abs("../..")
	require.NoError(t, err)
	tr := newTree(t)
	tr.write("svc/notifications/all/notification.yaml", allNotification)
	tr.write("svc/notifications/all/body.ru.yaml", allBody)
	tr.generate()
	tr.write("go.mod", "module example.invalid/src\n\ngo 1.26.0\n\nrequire github.com/PRO-Robotech/corelib v0.0.0\n\n"+
		"replace github.com/PRO-Robotech/corelib => "+corelib+"\n")
	sum, err := os.ReadFile(filepath.Join(corelib, "go.sum"))
	require.NoError(t, err)
	tr.write("go.sum", string(sum))
	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = tr.root
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GOPROXY=off", "GOWORK=off")
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "сборка порождённого: %s", out)
}

