// УК86 (а), УК77, УК83: лимиты описания упорядочены feed.LimitLess — по
// числу секунд (600 < 1800 < 3600 < 86400), повтор пары сведён к меньшему max;
// УК70: экспорт X<Scope>Per<Window>.
func TestUK86_LimitsAreOrderedBySecondsAndPairsReduced(t *testing.T) {
	tr := newTree(t)
	tr.write("svc/notifications/all/notification.yaml", allNotification)
	tr.write("svc/notifications/all/body.ru.yaml", allBody)
	tr.generate()
	src := tr.read("svc/notifications_all.gen.go")
	i600 := strings.Index(src, "WindowSeconds: 600,")
	i1800 := strings.Index(src, "WindowSeconds: 1800,")
	i3600 := strings.Index(src, "WindowSeconds: 3600,")
	i86400 := strings.Index(src, "WindowSeconds: 86400,")
	require.True(t, i600 >= 0 && i600 < i1800 && i1800 < i3600 && i3600 < i86400, "порядок по числу секунд")
	require.Equal(t, 1, strings.Count(src, "WindowSeconds: 3600,"), "повтор пары сведён в один")
	require.Contains(t, src, "WindowSeconds: 3600, Max: 3}", "сведён к меньшему max")
	for _, c := range []string{`AllRecipientPer10Minutes\s+= 2\n`, `AllRecipientPer30Minutes\s+= 4\n`, `AllRecipientPerHour\s+= 3\n`, `AllRecipientPerDay\s+= 9\n`} {
		require.Regexp(t, c, src)
	}
	inv := tr.read("svc/notifications_invite.gen.go")
	require.Regexp(t, `InviteRecipientPerDay\s+= 3\n`, inv)
	require.Regexp(t, `InviteInitiatorPerHour\s+= 20\n`, inv)
	// timestamp — time.Time; optional — через form.Presence
	require.Regexp(t, `IssuedAt\s+time.Time\n`, src)
}

// УК58: тело SendX не несёт литерала сравнения по виду и сравнения поля с
// нулём — решение «задано ли» принимает form.Presence (проба разбора).
func TestUK58_SendXCarriesNoKindComparison(t *testing.T) {
	tr := newTree(t)
	tr.write("svc/notifications/all/notification.yaml", allNotification)
	tr.write("svc/notifications/all/body.ru.yaml", allBody)
	tr.generate()
	for _, file := range []string{"svc/notifications_all.gen.go", "svc/notifications_invite.gen.go"} {
		findings, cmps := kindComparisons(t, tr.read(file))
		t.Logf("%s: сравнений осмотрено %d", file, cmps)
		require.Empty(t, findings, file)
	}
	// инъекция: сравнение поля с пустой строкой — находка
	findings, _ := kindComparisons(t, "package p\nfunc f(a struct{ Note string }) bool { return a.Note == \"\" }\n")
	require.Len(t, findings, 1)
	findings, _ = kindComparisons(t, "package p\nimport \"x/form\"\nfunc f(k form.Kind) bool { return k == form.KindText }\n")
	require.Len(t, findings, 1)
}

func kindComparisons(t *testing.T, src string) (findings []string, cmps int) {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "gen.go", src, 0)
	require.NoError(t, err)
	ast.Inspect(f, func(n ast.Node) bool {
		b, ok := n.(*ast.BinaryExpr)
		if !ok || (b.Op != token.EQL && b.Op != token.NEQ) {
			return true
		}
		cmps++
		for _, side := range []ast.Expr{b.X, b.Y} {
			switch x := side.(type) {
			case *ast.BasicLit:
				findings = append(findings, fset.Position(b.Pos()).String()+": сравнение с литералом")
			case *ast.SelectorExpr:
				if strings.HasPrefix(x.Sel.Name, "Kind") {
					findings = append(findings, fset.Position(b.Pos()).String()+": сравнение по виду")
				}
			case *ast.CompositeLit:
				findings = append(findings, fset.Position(b.Pos()).String()+": сравнение с составным литералом")
			}
		}
		return true
	})
	return findings, cmps
}

// NTF1-D01: -check -list печатает множество порождаемых файлов, равное
// множеству записанных генерацией в копию дерева без порождённых файлов, — в
// обе стороны.
func TestNTF1D01_ListEqualsWrittenSetBothWays(t *testing.T) {
	tr := newTree(t)
	tr.write("svc/notifications/all/notification.yaml", allNotification)
	tr.write("svc/notifications/all/body.ru.yaml", allBody)
	// рукописный файл с заголовком notifygen, которого генератор не порождает
	tr.write("svc/notifications_handmade.gen.go", "// Code generated by notifygen. DO NOT EDIT.\n\npackage svc\n")
	before := tr.files()
	tr.generate()
	after := tr.files()
	var written []string
	for p, c := range after {
		if b, ok := before[p]; !ok || b != c {
			written = append(written, p)
		}
	}
	sort.Strings(written)
	r := tr.run("-check", "-list")
	require.Equal(t, 0, r.code, r.stdout+r.stderr)
	got := listed(r.stdout)
	require.Empty(t, listDiff(written, got))
	require.Len(t, got, 4)
	require.NotContains(t, got, "svc/notifications_handmade.gen.go")
	require.Contains(t, got, "svc/notifications_invite.gen.go")
	require.True(t, slices.IsSorted(got))

	// инъекция: путь, которого генератор не пишет, — проба называет его
	injected := append(slices.Clone(got), "svc/notifications_ghost.gen.go")
	sort.Strings(injected)
	diff := listDiff(written, injected)
	require.Equal(t, []string{"лишний в -list: svc/notifications_ghost.gen.go"}, diff)
	diff = listDiff(written, got[1:])
	require.Equal(t, []string{"недостающий в -list: " + got[0]}, diff)
}

