// NTF1-D07: ревизию ведёт генератор — растёт ровно со сменой набора.
func TestNTF1D07_RevisionGrowsExactlyWithTheSet(t *testing.T) {
	tr := newTree(t)
	rev := func() string { return tr.read("svc/notifications/invite/revision.yaml") }
	num := func() string {
		for _, l := range strings.Split(rev(), "\n") {
			if strings.HasPrefix(l, "revision: ") {
				return strings.TrimPrefix(l, "revision: ")
			}
		}
		return ""
	}
	notif := "svc/notifications/invite/notification.yaml"
	steps := []struct {
		name string
		do   func()
		want string
		same bool
	}{
		{"(1) исходный каталог", func() {}, "1", false},
		{"(2) текст блока и ttl", func() {
			tr.edit("svc/notifications/invite/body.ru.yaml", "приглашает вас в облако.", "зовёт вас.")
			tr.edit(notif, "ttl: 168h", "ttl: 72h")
		}, "1", true},
		{"(3) атрибут inviter_email", func() {
			tr.edit(notif, "  token: {type: token, presence: required}\n",
				"  token: {type: token, presence: required}\n  inviter_email: {type: text, presence: required}\n")
			tr.edit("svc/notifications/invite/body.ru.yaml", "  - heading: \"Вас пригласили\"\n",
				"  - heading: \"Вас пригласили\"\n  - p: \"{{ inviter_email }}\"\n")
		}, "2", false},
		{"(4) тип inviter_email — secret", func() {
			tr.edit(notif, "inviter_email: {type: text,", "inviter_email: {type: secret,")
			tr.edit("svc/notifications/invite/body.ru.yaml", "  - p: \"{{ inviter_email }}\"\n", "  - code: \"{{ inviter_email }}\"\n")
		}, "3", false},
		{"(5) inviter_name в теме", func() {
			tr.edit(notif, `ru: "Приглашение в облако"`, `ru: "Приглашение от {{ inviter_name }}"`)
		}, "4", false},
		{"(6) класс notice", func() { tr.edit(notif, "class: security", "class: notice") }, "5", false},
		{"(7) inviter_email optional", func() {
			tr.edit(notif, "inviter_email: {type: secret, presence: required}", "inviter_email: {type: secret, presence: optional}")
			tr.edit("svc/notifications/invite/body.ru.yaml", "  - code: \"{{ inviter_email }}\"\n",
				"  - code: \"{{ inviter_email }}\"\n    when: inviter_email\n")
		}, "6", false},
		{"(8) limits и текст heading", func() {
			tr.edit(notif, "max: 3}", "max: 5}")
			tr.edit("svc/notifications/invite/body.ru.yaml", "Вас пригласили", "Приглашение")
		}, "6", true},
	}
	prev := ""
	for _, s := range steps {
		s.do()
		tr.generate()
		require.Equal(t, s.want, num(), s.name)
		if s.same {
			require.Equal(t, prev, rev(), "%s: файл побайтово прежний", s.name)
		}
		prev = rev()
		require.Equal(t, 0, tr.run("-check").code, s.name)
	}
	require.Contains(t, tr.read("svc/notifications_invite.gen.go"), "SchemaRev: 6,", "эталон пишет ревизию из файла")
}

