package observability

import "strings"

// BuildStampUnstamped — то, что метка витрины говорит, когда сборка величину НЕ
// ПРОСТАВИЛА.
//
// Пустая метка читается как «версии нет», правдоподобное `dev` — как имя ветки;
// оба неотличимы от «величину не измеряли». Отдельное слово делает это состояние
// НАБЛЮДАЕМЫМ: по нему пишется тревога, и оно не притворяется ответом.
//
// Слово обязано совпадать с тем, которым отвечает служба доступа: дежурный
// сверяет витрины разных процессов не пересчитывая, а два написания одного
// состояния дали бы две тревоги об одном предмете.
//
// ЧЕМ ЭТО ДЕРЖИТСЯ — ИЗМЕНИЛОСЬ, И ЭТО СКАЗАНО ВСЛУХ. Прежде совпадение
// держала проба этого дерева; служба вынесена отдельным репозиторием, её
// объявление уехало вместе с ней, и проба снята вместе со своим предметом.
// Общего объявления у двух продуктов быть не может — они разные модули, — а
// значит согласие двух написаний стало МЕЖРЕПОЗИТОРНЫМ обязательством, и в
// этом дереве его не проверяет никто. Координата уехавшей стороны здесь не
// приводится: путь, резолвящийся в другом дереве, читается как резолвящийся
// в этом.
const BuildStampUnstamped = "unstamped"

// NormalizeBuildStamp приводит штамп сборки к тому, что витрина вправе
// утверждать.
//
// # Зачем это отдельная функция, а не строка в каждом адаптере
//
// Ряд `*_build_info` держат ПЯТЬ процессов платформы, и предикат «величина не
// проставлена» у всех один. Выписанный пятью копиями, он разъехался бы молча —
// как разъехались бы любые пять копий одного предиката, — и разъехался бы именно
// там, где расхождение не видно: на витрине, которую читают в три часа ночи.
//
// # Что считается НЕ-величиной, и почему трёх форм мало не бывает
//
//   - пустая строка — аргумент сборки не передан вовсе;
//   - `dev`/`unknown` — умолчания ОБЪЯВЛЕНИЯ в композиционном корне: их видит
//     всякая сборка без `-ldflags` (`go run`, `go test`, сборка руками);
//   - пробельная строка — аргумент передан пустым через оболочку.
//
// Все три означают ОДНО, и потому обязаны читаться одинаково: у одного состояния
// не бывает трёх написаний, иначе тревога по нему тоже пишется трижды и две из
// трёх однажды забудут.
//
// # Чего она НЕ делает
//
// Не судит, ПРАВДУ ли говорит проставленная величина: `-X` с литералом доедет до
// двоичного файла и покажет не про это дерево. Что значение взято из аргумента,
// которым клеймится образ, держат гейты сборки — `internal/repohygiene`
// `TestBuildStampReachesEveryBinaryThatDeclaresIt` и его собрат у службы доступа.
func NormalizeBuildStamp(version, commit string) (string, string) {
	return normalizeBuildStampValue(version), normalizeBuildStampValue(commit)
}

// normalizeBuildStampValue — одна величина. Сравнение с умолчаниями идёт ПОСЛЕ
// обрезки: `" dev "` — то же самое умолчание, и пропустив его, витрина показала
// бы ряд, формально непустой и потому не попавший ни под одну тревогу.
func normalizeBuildStampValue(v string) string {
	switch strings.TrimSpace(v) {
	case "", "dev", "unknown":
		return BuildStampUnstamped
	default:
		return strings.TrimSpace(v)
	}
}
