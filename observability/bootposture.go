// BootPostureMsg — сообщение единственной boot-строки, в которой процесс
// САМ отчитывается о posture, с которой он реально стартовал.
//
// Зачем это существует: production-posture гейт раньше читал ХРАНИМЫЙ конфиг
// (values/ConfigMap) и потому рапортовал успех, пока сервис фактически работал в
// dev-режиме с незашифрованным DB-соединением. Гейт обязан утверждать на
// НАБЛЮДАЕМОМ факте — на самоотчёте живого процесса, а не на намерении.
//
// Сообщение и имена полей парсятся гейтом (jq) → это ХАРД-КОНТРАКТ: переименование
// ключа или msg молча ослепляет гейт. Менять только вместе с гейтом.
const BootPostureMsg = "boot security posture"

// DBSSLModeNotApplicable — значение поля db_sslmode для сервиса БЕЗ базы
// (api-gateway). Литерал, а не пустая строка: гейт отличает «БД нет» от
// «поле не заполнено».
const DBSSLModeNotApplicable = "n/a"

// Величины поля internal_mtls — ТРИ объявленных состояния внутреннего
// gRPC-листенера, и все три именованы.
//
// ПОЧЕМУ СТРОКА, А НЕ bool (решение задачи #1024). У края внутреннего листенера
// больше нет вовсе, и «слушателя нет» обязано быть отличимо от «слушатель есть и
// НЕ защищён»: схлопнуть их значило бы разрешить незащищённый листенер
// молчанием. Булево поле такого не выражает — состояний у него два, и нулевое
// НЕМО: процесс, забывший заполнить структуру, печатает ровно то же, что процесс,
// честно доложивший «выключено».
//
// Указатель (*bool) три состояния выражает, но кладёт послабление в НУЛЕВОЕ
// значение: забывший заполнить получал бы «слушателя нет», то есть забывчивость
// расслабляла бы гейт. У строки нулевое значение — пустая — не совпадает ни с
// одной из трёх объявленных, поэтому гейт посадки судит её ОТКАЗОМ наравне с
// отсутствием ключа. Забыть здесь можно только в строгую сторону.
//
// Форма выбрана зеркальной уже существующим в этом же самоотчёте DBSSLMode и
// IdentityProvider: третьего идиома «измерение неприменимо» в одной строке не
// заводится.
//
// Литералы парсит гейт (deploy/scripts/assert-production-posture.sh) → это
// ХАРД-КОНТРАКТ, менять только вместе с ним.
const (
	// InternalMTLSEnabled — листенер есть и проверяет клиентские сертификаты.
	InternalMTLSEnabled = "true"
	// InternalMTLSDisabled — листенер есть и работает БЕЗ mTLS.
	InternalMTLSDisabled = "false"
	// InternalMTLSNotApplicable — внутреннего листенера у процесса НЕТ ни одного:
	// защищать нечего, потому что входной поверхности нет. Не путать с Disabled.
	InternalMTLSNotApplicable = "n/a"
)

// InternalMTLSFrom — величина измерения для процесса, у которого внутренний
// листенер ЕСТЬ: остаётся сказать, проверяет ли он клиентские сертификаты.
//
// Функция, а не тернарник на месте: вызывающих семь, и семь раз написанное
// «если включено — одна строка, иначе другая» есть семь мест об одном предикате.
// Разойдутся они молча — обе ветки вернут непустую строку, и гейт увидит
// законное значение, сказанное о неверном состоянии.
//
// Случая «листенера нет» здесь НЕТ намеренно: он не выводится из ручки, потому
// что ручки у такого процесса не существует вовсе. Он называется константой
// InternalMTLSNotApplicable прямо в композиционном корне — там, где видно, что
// поверхность не поднимается.
func InternalMTLSFrom(mtlsEnabled bool) string {
	if mtlsEnabled {
		return InternalMTLSEnabled
	}
	return InternalMTLSDisabled
}

// Величины полей own_rest_public_tls / own_rest_internal_tls — ТРИ объявленных
// состояния СОБСТВЕННОГО REST-фронта процесса, и все три именованы.
//
// ЧТО ТАКОЕ «СОБСТВЕННЫЙ REST-ФРОНТ». HTTP-поверхность, которую процесс
// поднимает НАД СВОИМИ ЖЕ gRPC-слушателями: запрос по HTTP проходит ровно ту
// цепочку звеньев, что и тот же запрос по gRPC. Край платформы под это
// определение не подпадает by construction — он проксирует ЧУЖИЕ слушатели, а
// своего gRPC-API не имеет; его величина — OwnRESTFrontNotRaised.
//
// ПОЧЕМУ СТРОКА, А НЕ bool. Состояний три, а не два: «фронта нет вовсе» обязано
// быть отличимо от «фронт поднят и работает открытым текстом». Схлопнуть их
// значило бы разрешить открытый текст молчанием. У булева поля состояний два, и
// нулевое НЕМО: процесс, забывший заполнить структуру, печатает ровно то же, что
// процесс, честно доложивший «фронта нет». У строки нулевое значение — пустая —
// не совпадает ни с одной из трёх объявленных, поэтому гейт посадки судит её
// ОТКАЗОМ наравне с отсутствием ключа. Забыть здесь можно только в строгую
// сторону. Форма зеркальна уже существующим в этом же самоотчёте DBSSLMode,
// InternalMTLS и IdentityProvider: третьего идиома «измерение неприменимо» в
// одной строке не заводится.
//
// ПОЧЕМУ ОСЬ ПРО ТРАНСПОРТ, А НЕ ПРО «ПОДНЯТ ЛИ». Посадка прочих поверхностей
// читается в этой строке именно транспортом (public_mtls, internal_mtls), и
// «поднят ли» из величины восстанавливается: всё, что не n/a, — поднятый фронт.
// Ось, отвечающая только «поднят ли», не имела бы НЕВЕРНОГО значения, то есть
// гейту нечего было бы оценивать, и она осталась бы напечатанной, но не
// судимой.
//
// Литералы парсит гейт (deploy/scripts/assert-production-posture.sh) → это
// ХАРД-КОНТРАКТ, менять только вместе с ним.
const (
	// OwnRESTFrontTLS — фронт поднят, и его провод под транспортом.
	OwnRESTFrontTLS = "true"
	// OwnRESTFrontPlaintext — фронт поднят и работает ОТКРЫТЫМ ТЕКСТОМ.
	OwnRESTFrontPlaintext = "false"
	// OwnRESTFrontNotRaised — фронта НЕТ: адрес не объявлен профилем развёртывания
	// либо собственной HTTP-поверхности у этого процесса не бывает вовсе.
	// Не путать с Plaintext: защищать нечего, потому что поверхности нет.
	OwnRESTFrontNotRaised = "n/a"
)

// OwnRESTFront — ровно то, что самоотчёту нужно от ОБЪЯВЛЕНИЯ поверхности:
// поднимается ли она и под транспортом ли её провод.
//
// Узкий интерфейс здесь не украшение. Он (а) оставляет пакет самоотчёта листом
// графа импортов — иначе он потянул бы за собой весь пакет объявления
// поверхностей; (б) делает непредставимой перестановку доводов: два bool одного
// типа менялись бы местами молча, и в счастливом случае оба истинны, поэтому
// перестановка не показала бы себя ничем.
type OwnRESTFront interface {
	// Enabled — поднимается ли поверхность (адрес объявлен значением).
	Enabled() bool
	// UnderTLS — идёт ли её провод под транспортом.
	UnderTLS() bool
}

// OwnRESTFrontFrom — величина оси, ВЫВЕДЕННАЯ из того же объявления
// поверхности, по которому она поднимается.
//
// Почему выводится, а не вписывается: самоотчёт о посадке и доклад поверхности
// при подъёме — два утверждения об одном предмете. Выведенные из ОДНОГО
// объявления, разойтись они не могут by construction; вписанные порознь —
// разойдутся молча, и верным окажется одно.
//
// Случая «фронта нет вовсе» здесь НЕТ намеренно, ровно как у InternalMTLSFrom:
// он не выводится из объявления, потому что объявления у такого процесса не
// существует. Он называется константой OwnRESTFrontNotRaised прямо в
// композиционном корне — там, где видно, что поверхность не поднимается.
func OwnRESTFrontFrom(front OwnRESTFront) string {
	if !front.Enabled() {
		return OwnRESTFrontNotRaised
	}
	if front.UnderTLS() {
		return OwnRESTFrontTLS
	}
	return OwnRESTFrontPlaintext
}

// IdentityProviderNotApplicable — значение поля identity_provider для сервиса,
// который личность человека не проверяет вовсе (vpc, compute, storage, nlb,
// geo, registry: они принимают уже проверенного вызывающего).
//
// Литерал, а не пустая строка, по той же причине, что и у базы: «измерения нет»
// обязано быть отличимо от «поле не заполнено». Гейт посадки, увидевший пустую
// строку, не смог бы сказать, работает ли перед ним сервис без этого измерения
// или сервис, забывший его заполнить.
const IdentityProviderNotApplicable = "n/a"

// BootPosture — самоотчёт процесса о принятой security-posture.
//
// ВСЕ поля обязаны отражать то, что процесс РЕАЛЬНО собирается использовать
// (провалидированный config-struct / уже собранная проводка), а не сырое env и
// не константу. Заполняется в composition root каждого сервиса ПОСЛЕ
// secure-by-default boot-guard'ов и ДО старта листенеров.
type BootPosture struct {
	// Service — каноническое короткое имя сервиса: vpc | compute | nlb | iam |
	// geo | registry | storage | api-gateway.
	Service string
	// AuthMode — режим, который процесс реально принял (production |
	// production-strict | dev).
	AuthMode string
	// DBSSLMode — sslmode, который реально уходит в DSN/пул (у сервиса без БД —
	// DBSSLModeNotApplicable).
	DBSSLMode string
	// PublicMTLS — фактическое состояние mTLS на ПУБЛИЧНОМ gRPC-листенере (:9090).
	PublicMTLS bool
	// InternalMTLS — состояние cluster-internal листенера (:9091): одна из трёх
	// объявленных величин InternalMTLS* выше. Строка, а не bool, потому что
	// состояний три, а не два — разбор при константах.
	//
	// Заполняется тем, что процесс РЕАЛЬНО поднял, а не тем, что объявлено в
	// настройках: у процесса без внутреннего листенера это
	// InternalMTLSNotApplicable, и ручки, которую можно было бы прочитать, у
	// него нет вовсе.
	InternalMTLS string
	// AuthZCheck — проведён ли per-RPC authz-Check (непустой адрес / не-nil клиент).
	AuthZCheck bool
	// TrustedForwarders — сужен ли круг отправителей, которым процесс разрешает
	// ПЕРЕДАВАТЬ личность конечного пользователя (x-kacho-principal-*), то есть
	// непуст ли список, реально уехавший в grpcsrv.WithTrustedForwarders.
	//
	// Почему это отдельное измерение, а не следствие mTLS: contract corelib
	// (principalIsTrusted) сужает круг ТОЛЬКО на непустом списке — на пустом любой
	// пир, прошедший проверку сертификата, может представиться кем угодно, и решение
	// о правах будет принято от имени названного им пользователя. Значит «mTLS есть»
	// НЕ влечёт «личность нельзя подменить»: false здесь при public_mtls=true — это
	// осмысленное, а не противоречивое сочетание.
	//
	// Заполняется тем же значением, что уходит в проводку (не сырым полем конфига),
	// иначе отчёт снова описывал бы намерение вместо исхода.
	//
	// Как читать false (важно для гейта): поле отвечает на УЗКИЙ вопрос — «непуст ли
	// список WithTrustedForwarders», а не «безопасен ли сервис» и не «пинит ли сервис
	// хоть какие-нибудь личности сертификатов». false означает «ЭТОТ круг не сужен» и
	// покрывает ДВА разных случая:
	//   (а) сервис принимает переданную личность и никого не пинит — это дефект;
	//   (б) сервис переданную личность не принимает вовсе — сужать нечего. Так у
	//       api-gateway: он личность НЕ форвардит, а чеканит из проверенного токена и
	//       вырезает весь клиентский x-kacho-*. При этом свой SPIFFE-список у него
	//       ЕСТЬ (кого пускать на внутренний листенер) — просто это другое измерение,
	//       и данное поле про него ничего не говорит.
	// Гейт, который валит сборку по этому полю, обязан различать эти два случая —
	// иначе он покрасит сервис, у которого измерения нет. Список участвующих сервисов
	// ведётся в deploy/scripts/assert-production-posture.sh.
	TrustedForwarders bool
	// IdentityProvider — ПОСАДКА ЛИЧНОСТИ, которую процесс реально принял:
	// проверяет ли человека внешний поставщик удостоверений или наша
	// собственная чеканка (задача #1125).
	//
	// Зачем это в самоотчёте, а не в карте настроек: посадка разводит
	// ТРЕБОВАНИЯ СТАРТА, поэтому «какую посадку выбрал стенд» — вопрос, на
	// который обязан отвечать ЖИВОЙ процесс. Карта настроек отвечает на него
	// намерением: ручки приезжают через envFrom и читаются один раз при старте,
	// так что правка карты меняет её, а не процесс.
	//
	// Заполняется значением, ПРИНЯТЫМ проверкой настройки, а не сырым полем:
	// незаданное и негодное значения до этой строки не доживают — процесс на
	// них не стартует.
	//
	// У сервиса, который личность человека не проверяет,
	// IdentityProviderNotApplicable.
	IdentityProvider string
	// OwnRESTPublicTLS — состояние СОБСТВЕННОГО ПУБЛИЧНОГО REST-фронта: одна из
	// трёх объявленных величин OwnRESTFront* выше.
	//
	// Заполняется тем, что процесс РЕАЛЬНО объявил поверхностью, а не сырой
	// ручкой: у процесса без собственного фронта это OwnRESTFrontNotRaised, и
	// ручки транспорта, которую можно было бы прочитать, у него нет вовсе.
	OwnRESTPublicTLS string
	// OwnRESTInternalTLS — то же для СОБСТВЕННОГО ВНУТРЕННЕГО REST-фронта.
	//
	// Ось отдельная, а не общая с публичной: фронты поднимаются разными ручками,
	// досягаемы из разных мест и несут разный материал, поэтому одно значение на
	// двоих скрывало бы ровно тот случай, ради которого ось заведена, — один
	// фронт под транспортом, другой открытым текстом.
	OwnRESTInternalTLS string
	// ListenerForm — ФОРМА СЛУШАТЕЛЯ, которую процесс поднимает: пара (нулевое
	// значение) либо только внутренний слушатель. Печатается ключом
	// `listener_form`.
	//
	// Корень формы литералом не присваивает: обе величины — эту и
	// [BootPosture.NoServedServices] — он берёт ОДНОЙ функцией corelib
	// `servicehost.PostureOf` из того же значения дескриптора, которое передаёт
	// носителю. Тип свой, а не тип оси дескриптора, чтобы пакет самоотчёта
	// остался листом графа импортов.
	ListenerForm ListenerForm
	// NoServedServices — процесс не служит ни одного gRPC-сервиса: слушателей
	// нет вовсе. Ключа своего не имеет — при истине `listener_form` печатает
	// `none`, а сочетание с ненулевой [BootPosture.ListenerForm] отвергает
	// [NewBootPosture]: строка несла бы два утверждения о форме, из которых
	// верно одно.
	NoServedServices bool
	// ServiceIdentity — звено идентичности служб, которое процесс РЕАЛЬНО
	// поднял: перечень методов и строки таблицы `{SAN → имя службы}` одной
	// строкой. Заполняется `grpcsrv.ServiceIdentity.Report()` того звена, что
	// уехало в дескриптор; у процесса без звена — `grpcsrv.ServiceIdentityNotApplicable`.
	// Строка, а не тип звена, чтобы пакет самоотчёта остался листом графа
	// импортов; своего словаря написаний у самоотчёта нет. Гейт посадки
	// оценивает перечень и таблицу по этой строке (NTF1-M09).
	ServiceIdentity string
	// Notifications — флаг ленты извещений, который процесс РЕАЛЬНО принял
	// (kacho#2918): значение, разобранное корнем источника, а не сырое
	// окружение. Печатается ключом `notifications_enabled`.
	//
	// Нулевое значение — [NotificationsNotApplicable]: у служб без ленты
	// источника (geo, notify) это их настоящая посадка, а не «не объявлено».
	// Включённость и выключенность выражаются только [NotificationsFlagOf] —
	// тип закрыт, третьего способа сказать «выключено» нет.
	Notifications NotificationsFlag
}

// LogBootPosture пишет BootPosture единственной структурированной строкой.
// Единственное место, где живут msg и имена полей контракта — поэтому восемь
// сервисов не могут разъехаться по форме.
func LogBootPosture(logger *slog.Logger, p BootPosture) {
	logger.Info(BootPostureMsg,
		"service", p.Service,
		"auth_mode", p.AuthMode,
		"db_sslmode", p.DBSSLMode,
		"public_mtls", p.PublicMTLS,
		"internal_mtls", p.InternalMTLS,
		"authz_check", p.AuthZCheck,
		"trusted_forwarders", p.TrustedForwarders,
		"identity_provider", p.IdentityProvider,
		"own_rest_public_tls", p.OwnRESTPublicTLS,
		"own_rest_internal_tls", p.OwnRESTInternalTLS,
		"listener_form", p.listenerFormWire(),
		"service_identity", p.ServiceIdentity,
		"notifications_enabled", p.Notifications.String(),
	)
}

// ListenerForm — форма слушателя в самоотчёте посадки. Нулевое значение —
// пара: у каждой службы, не знающей о поле, это её настоящая форма, а не «не
// объявлено».
type ListenerForm uint8

const (
	// ListenerFormPair — пара gRPC-слушателей (публичный и внутренний).
	ListenerFormPair ListenerForm = iota
	// ListenerFormInternalOnly — только внутренний gRPC-слушатель.
	ListenerFormInternalOnly
)

// Написания ключа `listener_form`. Закрытый набор: гейт посадки читает его
// разбором строки самоотчёта, поэтому это — хард-контракт.
const (
	listenerFormPairWire         = "pair"
	listenerFormInternalOnlyWire = "internal_only"
	listenerFormNoneWire         = "none"
	// listenerFormInvalidWire — запись, которую конструктор не принял бы:
	// значение вне перечня либо «слушателей нет» вместе с формой. Не совпадает ни
	// с одним написанием набора, поэтому гейт посадки судит её отказом наравне с
	// отсутствием ключа, а не читает как одну из форм.
	listenerFormInvalidWire = "<invalid>"
)

// String — написание формы. Значение вне перечня печатается
// [listenerFormInvalidWire]: разбор — исчерпывающий switch без default.
func (f ListenerForm) String() string {
	switch f {
	case ListenerFormPair:
		return listenerFormPairWire
	case ListenerFormInternalOnly:
		return listenerFormInternalOnlyWire
	}
	return listenerFormInvalidWire
}

// listenerFormWire — значение ключа `listener_form` записи: `none` тогда и
// только тогда, когда запись несёт [BootPosture.NoServedServices].
func (p BootPosture) listenerFormWire() string {
	if p.NoServedServices {
		if p.ListenerForm != ListenerFormPair {
			return listenerFormInvalidWire
		}
		return listenerFormNoneWire
	}
	return p.ListenerForm.String()
}

// NewBootPosture — конструктор записи: отвергает запись, строка которой несла
// бы противоречие о форме слушателя.
//
// Из дескриптора такая запись не выражается (`servicehost.PostureOf` её не
// производит); конструктор — второй рубеж для корня, собирающего запись
// напрямую. Печать ([LogBootPosture]) запись не отвергает, а пишет
// противоречие написанием вне набора — гейт посадки судит его отказом.
func NewBootPosture(p BootPosture) (BootPosture, error) {
	if p.ListenerForm.String() == listenerFormInvalidWire {
		return BootPosture{}, errors.New("observability: форма слушателя вне перечня (ListenerFormPair | " +
			"ListenerFormInternalOnly): строка самоотчёта несла бы написание, которого гейт посадки не знает")
	}
	if p.NoServedServices && p.ListenerForm != ListenerFormPair {
		return BootPosture{}, errors.New("observability: запись несёт NoServedServices и форму слушателя " +
			p.ListenerForm.String() + " — строка утверждала бы и «слушателей нет», и «слушатель есть»; " +
			"берите обе величины из servicehost.PostureOf")
	}
	return p, nil
}

// Написания ключа `notifications_enabled`. Закрытый набор, строкой, а не bool:
// состояний три — «ленты нет» отличимо от «лента есть и выключена». Литералы
// читает гейт посадки разбором строки самоотчёта → ХАРД-КОНТРАКТ. Форма
// зеркальна InternalMTLS*: третьего идиома «измерение неприменимо» в одной
// строке не заводится.
const (
	// NotificationsOn — лента источника есть, флаг включён.
	NotificationsOn = "true"
	// NotificationsOff — лента источника есть, флаг выключен.
	NotificationsOff = "false"
	// NotificationsNotApplicable — ленты источника у процесса нет (geo,
	// notify). Не путать с NotificationsOff.
	NotificationsNotApplicable = "n/a"
)

// NotificationsFlag — флаг ленты извещений в самоотчёте посадки. Закрытый
// тип: включённость строит только [NotificationsFlagOf], нулевое значение —
// [NotificationsNotApplicable]. Тип свой, а не feed.Enabled, чтобы пакет
// самоотчёта остался листом графа импортов.
type NotificationsFlag struct {
	state notificationsState
}

type notificationsState uint8

const (
	notificationsNotApplicable notificationsState = iota
	notificationsOn
	notificationsOff
)

// NotificationsFlagOf — величина для процесса, у которого лента источника
// ЕСТЬ: остаётся сказать, включён ли флаг. Аргумент — значение, принятое
// разбором флага (feed.Enabled.On), а не сырое окружение.
func NotificationsFlagOf(on bool) NotificationsFlag {
	if on {
		return NotificationsFlag{state: notificationsOn}
	}
	return NotificationsFlag{state: notificationsOff}
}

// String — написание ключа `notifications_enabled`. Значений вне трёх тип не
// представляет: поле закрыто, строит его только [NotificationsFlagOf].
func (f NotificationsFlag) String() string {
	switch f.state {
	case notificationsOn:
		return NotificationsOn
	case notificationsOff:
		return NotificationsOff
	case notificationsNotApplicable:
	}
	return NotificationsNotApplicable
}
