// Package singlepass разводит фоновый проход между репликами: из всех процессов,
// подошедших к проходу одновременно, его исполняет ровно один.
//
// # Предмет
//
// Фоновая работа поднимается в КАЖДОЙ реплике: у процесса нет способа узнать,
// что он не один. Пока реплика одна, разницы не видно; вторую поднимает
// автомасштабирование по загрузке — то есть под нагрузкой, когда дублирование
// дороже всего, и между «работает» и «начало дублировать» нет ни решения
// человека, ни записи в журнале.
//
// # Когда брать замок прохода, а когда клеймить строки
//
// Замок прохода годится там, где проход — БЭКСТОП: он редок, ограничен своим
// пределом на партию и не обязан ускоряться от числа реплик. Тогда «исполняет
// один» есть ровно то, что уже написано в комментарии у предела партии, и код с
// развёртыванием перестают противоречить друг другу.
//
// Он НЕ годится там, где проход — несущий путь материализации: сериализовав его
// на весь кластер, мы лишили бы работу возможности идти в несколько реплик.
// Такому проходу нужен КЛЕЙМ СТРОКИ (`FOR UPDATE SKIP LOCKED` либо условная
// правка-CAS): реплики берут непересекающиеся партии и работают одновременно.
//
// # Почему сессионный замок, а не транзакционный
//
// Транзакционный (`pg_advisory_xact_lock`) живёт до конца транзакции, а проход
// транзакцией не является: он ходит к соседям и в плоскость данных, и держать
// транзакцию открытой всё это время значило бы занимать соединение и удерживать
// снимок ради взаимного исключения. Сессионный замок занимает ОДНО соединение
// пула и снимается закрытием, которое возвращает функция.
//
// # Что делает проигравший
//
// НИЧЕГО — и это штатный исход, а не отказ. Проигравший пропускает свой тик и
// приходит на следующем. Считать это ошибкой значило бы, что N−1 реплик пишут
// отказ на каждом успешном проходе: наблюдаемость деградирует ровно там, где
// она нужна.
package singlepass

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"
)

// ErrNoPool — проход просят развести, а базы не подали. Отдельная ошибка, а не
// «взяли и пошли»: молчаливый пропуск замка вернул бы ровно тот дубль, ради
// которого пакет заведён, и выглядел бы при этом исправной работой.
var ErrNoPool = errors.New("singlepass: pool is required")

// Release снимает замок прохода. Принимает контекст ЯВНО, потому что зовётся из
// defer, когда контекст прохода уже мог быть отменён.
type Release func(context.Context)

// TryAcquire пытается взять именованный замок прохода.
//
// Возвращает (release, true, nil), если проход достался нам; (nil, false, nil),
// если его уже исполняет другая реплика; ошибку — только на отказе базы.
//
// name — устойчивое имя прохода, а не идентификатор реплики: замок берётся по
// его хэшу, поэтому два процесса с одним именем встречаются на одном ключе.
// Пространство ключей — общее для всей базы, поэтому имя обязано нести домен
// («kacho.compute.stuck-delete-finisher»), а не глагол («sweep»).
func TryAcquire(ctx context.Context, pool *pgxpool.Pool, name string) (Release, bool, error) {
	if pool == nil {
		return nil, false, ErrNoPool
	}
	if name == "" {
		return nil, false, errors.New("singlepass: name is required")
	}

	// Соединение выделяется на весь проход: сессионный замок живёт в соединении,
	// и снятие, ушедшее в ДРУГОЕ соединение пула, не сняло бы ничего — замок
	// протёк бы до утилизации первого.
	conn, err := pool.Acquire(ctx)
	if err != nil {
		return nil, false, fmt.Errorf("singlepass %q: acquire conn: %w", name, err)
	}

	var got bool
	if err := conn.QueryRow(ctx,
		`SELECT pg_try_advisory_lock(hashtext($1)::bigint)`, name).Scan(&got); err != nil {
		conn.Release()
		return nil, false, fmt.Errorf("singlepass %q: pg_try_advisory_lock: %w", name, err)
	}
	if !got {
		conn.Release()
		return nil, false, nil
	}

	released := false
	release := func(rctx context.Context) {
		if released {
			return
		}
		released = true
		// Отвязываемся от контекста прохода: на отменённом контексте Exec стал бы
		// no-op, и замок дожил бы до утилизации соединения — то есть проход
		// остался бы «занятым» после своего конца.
		uctx := context.WithoutCancel(rctx)
		_, _ = conn.Exec(uctx, `SELECT pg_advisory_unlock(hashtext($1)::bigint)`, name)
		conn.Release()
	}
	return release, true, nil
}
