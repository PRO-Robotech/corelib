// Package identityposture — ПОСАДКА ЛИЧНОСТИ: кто проверяет, что перед
// платформой именно этот человек (задача #1125, подфаза Ф4д эпика #896).
//
// ─────────────────────────────────────────────────────────────────────────────
// ЗАЧЕМ ПОЛЕ ЕСТЬ, КОГДА ЗАКОННОЕ ЗНАЧЕНИЕ ОДНО
//
// Поле завели на время переезда со внешнего поставщика удостоверений на свою
// чеканку. Пока переезд шёл, в дереве жили ОБА тракта с противоположными
// требованиями: одному нужны три адреса поставщика, второму — ни одного. Поле
// разводило эти требования явно.
//
// Посадка `external` из словаря снята (corelib#30): законное значение одно —
// `own`. Поле при этом остаётся обязательным. Профиль, объявивший снятую
// посадку строкой, получает отказ с именем настройки от Parse — тем же текстом,
// что любое незнакомое имя. Число мимо Parse отвергает Validate — тем же
// текстом, что любое число вне словаря, — но только в процессе, чья проверка
// старта этот метод зовёт. Перевод проверок старта обоих потребителей — службы
// прав и края — на Validate ведут задачи PRO-Robotech/kaname#424 и
// PRO-Robotech/kacho#2862; пока они открыты, потребители Validate при старте не
// зовут и судят только IsSet.
//
// ─────────────────────────────────────────────────────────────────────────────
// ИМЯ `External` ОСТАЛОСЬ, ЗНАЧЕНИЕ — ВНЕ СЛОВАРЯ
//
// Путь модуля — без суффикса мажорной версии, и снятое экспортированное имя в
// минорном выпуске v1 ломало бы сборку потребителя, поднявшего пин. Поэтому
// `External` — устаревшая константа прежнего типа и прежнего числа с абзацем
// `Deprecated:`. Разбор её не производит, перечни её не называют, печатается
// она как величина вне словаря. Имя снимается только мажорным выпуском модуля.
//
// «Вне словаря» не значит «недостижимо». Тип — целое, и число снятой посадки
// записывает в поле всякий, кто идёт мимо Parse: преобразование типа, декодер
// настройки, кладущий число прямо в целое поле. Такое значение IsSet называет
// объявленным — и это правда: профиль поле объявил. Законным его называет
// только словарь — IsLegal, а проверке старта служит Validate: он различает три
// исхода (не объявлено · объявлено вне словаря · законно) и отвергает снятую
// посадку наравне с любым другим числом вне словаря. Поэтому ветку потребителя,
// читающую External, снимают не раньше, чем перед ней встанет Validate: до
// того она может оказаться единственным, что за этим значением стоит.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ УМОЛЧАНИЯ В КОДЕ НЕТ
//
// Умолчание `own` МОЛЧА подняло бы профиль, поля не объявивший, — в том числе
// написанный под снятую посадку и не обновлённый: адреса поставщика в нём
// остались бы без читателя, а стенд поднялся бы в посадке, которую никто не
// выбирал. Отказ старта заставляет выбрать явно. Второй довод прежней редакции
// — умолчание `external` требовало бы адресов у профиля, у которого их нет, —
// ушёл вместе со значением.
//
// Умолчание живёт В ПРОФИЛЕ: профиль объявляет значение явно, а отдельный клон
// обязан выбрать сам.
//
// ─────────────────────────────────────────────────────────────────────────────
// «НЕ ЗАДАНО» НЕ ПЕРЕСЕКАЕТСЯ С ОБЛАСТЬЮ ЗНАЧЕНИЙ
//
// Нулевое значение типа — Unset — означает РОВНО «профиль поля
// не объявил» и законным значением поля не является. Пустая строка значением
// тоже не является: она не «безопасное умолчание», а отсутствие ответа.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ В ОБЩЕМ ФУНДАМЕНТЕ, А НЕ В НАСТРОЙКЕ СЛУЖБЫ ПРАВ
//
// Посадку читают ДВА процесса: служба прав и край. Ни один из них не вправе
// импортировать внутренности другого, поэтому словарь, оставленный в настройке
// одного, был бы переписан во втором — и разошёлся бы с первым молча, на первом
// же новом значении. Горизонтальное живёт в общем фундаменте.
//
// ─────────────────────────────────────────────────────────────────────────────
// СЛОВАРЬ ТОЧНЫЙ, БЕЗ ПРИВЕДЕНИЯ РЕГИСТРА И БЕЗ ОБРЕЗКИ
//
// Разбор сверяет значение ДОСЛОВНО. Причина не в педантизме: соседняя раскладка
// (`Own`), лишний символ (`own `) и омоглиф кириллицы (`оwn` — буква `о` из
// другого алфавита) на глаз неотличимы от законного значения, а приведение
// регистра и обрезка сделали бы часть из них законными молча. Величина, от
// которой зависит, поднимется ли стенд, читается точным совпадением либо
// отвергается с именем поля.
package identityposture

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Provider — посадка личности: чем стенд проверяет человека.
type Provider int

// Значения. Нулевое — «не задано», и оно НЕ входит в словарь законных.
const (
	// Unset — профиль поля не объявил. Отказ старта.
	Unset Provider = iota
	// External — прежняя посадка «личность проверяет внешний поставщик». Из
	// словаря снята (corelib#30): разбор её не производит, перечни её не
	// называют, проверка старта Validate её отвергает. Число прежнее — значение
	// константы в v1 не меняется.
	//
	// Deprecated: the external identity posture is withdrawn. Parse refuses it
	// and Values and Names do not list it, but the type is an integer, so a
	// conversion or a decoder that writes a number into the field still yields
	// it past Parse. Refuse it at the start check with Validate, which rejects it
	// together with every other value outside the dictionary, and remove a
	// branch that reads External only once Validate stands in front of it. The
	// name is kept for consumers that raise their pin within v1 and is removed
	// only with a major release of the module.
	External
	// Own — личность проверяем мы сами; адреса поставщика не
	// требуются, вместо них обязательна своя чеканка и свой вход человека.
	//
	// Переходным была объявлена посадка `external` (решение оркестратора по
	// §15 приёмки Ф4д) — она снята; `own` — то, к чему платформа пришла.
	Own
)

// providerNames — ЕДИНСТВЕННОЕ объявление словаря: значение и его
// каноническое имя.
//
// Печать, разбор, перечень значений и перечень имён производятся ОТСЮДА. Второе
// перечисление этих же имён в файле этого модуля, знающем о посадке, — находка
// гейта provider_gate_test.go. Выписанный рядом перечень разошёлся бы с типом
// на первом же новом значении, и разошёлся бы молча. Чего гейт не видит —
// потребителей словаря, живущих в других репозиториях, — и что их сторона
// держится обзором, а не механизмом, названо в его шапке вместе с условием,
// при котором это решение пересматривается.
//
// Строки для External здесь нет: посадка снята со словаря (corelib#30), а имя
// осталось устаревшей константой — значение не разбирается и не печатается
// своим прежним именем. Литерал снятого имени — точный, в другом регистре либо
// собранный сложением литералов — в файле, знающем о посадке, находка того же
// гейта, и здесь тоже: вернувшаяся строка краснеет.
var providerNames = []struct {
	value Provider
	name  string
}{
	{Own, "own"},
}

// FieldName — КАНОНИЧЕСКОЕ имя поля, одинаковое у обоих процессов. Имя РУЧКИ
// у каждого своё (путь в настройке службы прав, переменная окружения на крае),
// и называет его вызывающий: отказ, назвавший чужую ручку, посылает оператора
// править не тот профиль.
const FieldName = "identity-provider"

// Values возвращает законные значения поля — ВЫВЕДЕННЫЕ из
// словаря, а не выписанные вызывающим.
func Values() []Provider {
	out := make([]Provider, 0, len(providerNames))
	for _, e := range providerNames {
		out = append(out, e.value)
	}
	return out
}

// Names возвращает канонические имена законных значений в
// порядке словаря — для текстов отказа и для табличных проб.
func Names() []string {
	out := make([]string, 0, len(providerNames))
	for _, e := range providerNames {
		out = append(out, e.name)
	}
	return out
}

// lookup — поиск значения в словаре: каноническое имя и признак, что значение
// в словаре стоит. Печать и суждение о законности читают словарь этим одним
// поиском, чтобы разойтись им было негде.
func lookup(p Provider) (name string, ok bool) {
	for _, e := range providerNames {
		if e.value == p {
			return e.name, true
		}
	}
	return "", false
}

// String — каноническое имя. У «не задано» имени в словаре нет, и печатается
// оно так, чтобы в тексте отказа не выглядеть значением.
func (p Provider) String() string {
	if name, ok := lookup(p); ok {
		return name
	}
	if p == Unset {
		return "<не задано>"
	}
	return fmt.Sprintf("identity-provider(%d)", int(p))
}

// IsSet сообщает, объявил ли профиль поле — каким угодно значением, в том
// числе вне словаря. Объявлено не значит законно: число, записанное в поле мимо
// Parse, IsSet считает объявленным, поэтому проверке старта его мало: число вне
// словаря отвергает только Validate. Потребители, судящие на старте IsSet, и
// задачи их перевода названы в шапке пакета.
func (p Provider) IsSet() bool { return p != Unset }

// IsLegal сообщает, стоит ли значение в словаре. Unset и любое число вне
// словаря, в том числе снятое External, законными не являются.
func (p Provider) IsLegal() bool {
	_, ok := lookup(p)
	return ok
}

// Validate — проверка старта. Исходов три, и у каждого свой ответ: законное
// значение — nil; поле не объявлено — NotDeclared(setting); объявлено числом
// вне словаря — отказ, называющий ручку вызывающего, это число и законный
// перечень. Последний исход отдельный намеренно: «не объявлено» послало бы
// оператора дописывать поле, которое он уже написал.
func (p Provider) Validate(setting string) error {
	if !p.IsSet() {
		return NotDeclared(setting)
	}
	if p.IsLegal() {
		return nil
	}
	return fmt.Errorf(
		"%s=%d is outside the dictionary (allowed, verbatim: %s) — no allowed name parses to this "+
			"number, so it did not come through Parse: a type conversion or a decoder that writes the "+
			"number itself put it into the field. A withdrawn posture is refused here like any other "+
			"value outside the dictionary; declare one of the allowed names",
		setting, int(p), strings.Join(Names(), ", "))
}

// Parse — поточечно обратная String() для законных значений.
//
// Отказ называет поле и перечень законных значений; отката к «безопасному»
// значению не происходит — возвращается Unset, то есть «ответа нет».
// Вызывающий, проглотивший ошибку, получит незаданную посадку и упрётся в тот
// же отказ старта, а не в молча выбранную полосу.
func Parse(setting, s string) (Provider, error) {
	for _, e := range providerNames {
		if e.name == s {
			return e.value, nil
		}
	}
	return Unset, fmt.Errorf(
		"%s=%q is not a legal value (allowed, verbatim: %s) — the value is matched exactly: "+
			"case is not folded, whitespace is not trimmed, and a look-alike letter from another "+
			"alphabet is not the same letter. This field names who verifies a person's identity, "+
			"so a value outside the dictionary is refused rather than read as a safe default",
		setting, s, strings.Join(Names(), ", "))
}

// NotDeclared — отказ старта на профиле, поля не объявившем. Текст один на оба
// процесса: расхождение диагностики по процессам заставило бы оператора учить
// два объяснения одного предмета.
func NotDeclared(setting string) error {
	return fmt.Errorf(
		"%s is not declared (allowed, verbatim: %s) — this field names who verifies a "+
			"person's identity, and there is no default in code on purpose: a default would bring "+
			"up a profile nobody chose a posture for, including one written for the withdrawn "+
			"posture and never updated. Declare it in the values profile",
		setting, strings.Join(Names(), ", "))
}

// MarshalJSON / UnmarshalJSON — сериализация под ту же дисциплину, что разбор.
func (p Provider) MarshalJSON() ([]byte, error) { return json.Marshal(p.String()) }

// UnmarshalJSON разбирает значение тем же Parse — второго
// разборщика не заводится.
func (p *Provider) UnmarshalJSON(b []byte) error {
	var s string
	if err := json.Unmarshal(b, &s); err != nil {
		return err
	}
	parsed, err := Parse(FieldName, s)
	if err != nil {
		return err
	}
	*p = parsed
	return nil
}
