// Решение о владении операцией по УЖЕ ПРОЧИТАННОЙ строке: единственное в дереве
// место, где выражена эта полоса.
//
// # Полос владения ДВЕ, и они решают один вопрос по-разному
//
// Первая — у ВЛАДЕЛЬЦА строки: ключ выводится из ctx (`OwnerFromContext`) и
// уходит в SQL `WHERE` (`GetOwned`/`CancelOwned`), поэтому «есть, но не твоя» и
// «нет такой» неразличимы by construction, а решение и мутация — один оператор.
//
// Вторая — у того, кто строку УЖЕ ПОЛУЧИЛ от владельца и не имеет ни таблицы,
// ни оператора: край (`gateway/internal/opsproxy`) отвечает на едином адресе
// `/operations/{id}` за все домены, поэтому обязан переспросить у владельца, а
// проверить — по полям ответа. Предикат в `WHERE` ему недоступен: сети не
// бывает атомарного сравнения-и-изменения.
//
// Пока эта полоса была выражена У КРАЯ, она была ВТОРЫМ ИСТОЧНИКОМ одного
// решения: край перечислял правила сам, включая имя внутренней личности
// (`{system, bootstrap}`) голыми строками — дважды. Сойтись двум перечислениям
// нечем, они не собираются вместе и друг друга не читают. Здесь они выражены
// один раз, а `internal/repohygiene` `TestOperationHandlerHasASingleSource`
// требует, чтобы полоса прочитанного владельца отдавала решение сюда, а не
// решала у себя (задача продукта #1399).
//
// # Чем эта полоса ОТЛИЧАЕТСЯ от полосы владельца — намеренно
//
// Отличий два, оба сохранены дословно и оба названы, чтобы следующий читатель
// не принял их за недосмотр:
//
//  1. ВНУТРЕННИЙ ВЫЗЫВАЮЩИЙ ПРОХОДИТ. Явная bootstrap-личность читает любую
//     операцию: фоновые пути и межсервисный реконсайл опрашивают чужие операции
//     по построению. У владельца такого обхода НЕТ и быть не должно — там
//     предикат в `WHERE`, и обход означал бы ветку «снять сужение», то есть
//     живой обход владения. Здесь это не обход, а ВТОРОЙ СЛОЙ: строка уже
//     получена от владельца, который своё сужение применил, поэтому пропуск
//     здесь ничего не расширяет — он лишь не сужает вторично.
//  2. ОТКАЗ — `PermissionDenied`, а не `NotFound` владельца. Второй слой
//     отвечает после того, как владелец УЖЕ решил: до этого отказа доходит
//     только тот, кому владелец строку отдал. Значит различить по нему «нет
//     доступа» и «не существует» нельзя — оракула существования тут не заводится.
//     Форма записана здесь и производится одним местом, чтобы она не разошлась
//     так, как разошёлся текст «нет такой операции» (#1370).
//
// # Порядок условий НЕСУЩИЙ
//
// Личность вызывающего судится ПЕРВОЙ, до полей строки. Иначе операция без
// именуемого владельца стала бы читаемой всем, минуя гейт анонимности.

// CheckRecordedOwnership — вправе ли `caller` читать и отменять операцию,
// владелец которой прочитан из самой строки (`recorded`).
//
// Возвращает nil, если вправе, и отказ полосы — если нет. Отказ ОДИН на все
// причины намеренно: он адресован арендатору, и различать в нём «твоя личность
// не извлеклась», «у строки нет владельца» и «владелец другой» значило бы
// рассказывать о чужой строке.
//
// `recorded` с пустой парой — законный вход, а не ошибка вызывающего: строка
// может быть записана до появления учёта владельцев либо безымянным запросом.
// Такая строка НЕ читается арендатором (владелец неизвестен), и это решается
// здесь, а не у каждого вызывающего своим `if`.
func CheckRecordedOwnership(caller, recorded Principal) error {
	// 1. Безымянный вызывающий не владеет ничем. Пустая пара и именованная
	//    анонимность здесь одно и то же — см. Principal.IsAnonymous: как только у
	//    «неизвестно кто» появляется имя, оно совпадает само с собой, и любые два
	//    безымянных запроса становятся друг для друга своими.
	if caller.IsAnonymous() {
		return foreignOperationStatus()
	}
	// 2. Явная внутренняя личность — второй слой её не сужает (см. отличие 1).
	if caller.IsSystem() {
		return nil
	}
	// 3. Дальше вызывающий — арендатор. Строка без ИМЕНУЕМОГО владельца ему не
	//    читается: настоящий владелец неизвестен, а «неизвестен» не значит «ничей».
	if recorded.IsAnonymous() {
		return foreignOperationStatus()
	}
	// 4. Строка, записанная внутренней личностью, арендатору тоже не читается:
	//    её настоящий владелец не установлен, и она строго менее атрибутируема,
	//    чем чужая арендаторская.
	if recorded.IsSystem() {
		return foreignOperationStatus()
	}
	// 5. Совпасть обязаны ОБА поля. Тип защищает от совпадения id между разными
	//    видами принципала (пользователь против служебной учётки).
	if caller.Type != recorded.Type || caller.ID != recorded.ID {
		return foreignOperationStatus()
	}
	return nil
}

// foreignOperationStatus — ЕДИНСТВЕННЫЙ производитель отказа этой полосы.
//
// Не экспортируется намеренно: производить отказ полосы вправе только сама
// полоса. Экспортированный производитель означал бы, что решение можно принять
// снаружи и лишь текст взять отсюда, — а расходятся полосы именно решениями.
func foreignOperationStatus() error {
	return status.Error(codes.PermissionDenied, "permission denied")
}
