package operations

import (
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// NotFoundStatus — ЕДИНСТВЕННЫЙ в дереве производитель отказа «нет такой
// операции».
//
// # Почему один, а не «два согласованных»
//
// Текст — часть контракта (`api-conventions.md`), и он же несёт СОКРЫТИЕ: на
// адресе `/operations/{id}` этот 404 приходит из двух мест — от владельца, у
// которого строки нет или она не принадлежит вызывающему («есть, но не твоя» и
// «нет такой» намеренно неразличимы), и от края, которому известен префикс id,
// но не подключён его backend. Различие хоть в один байт отличает «нет доступа»
// от «не существует» и заодно называет, какие backend'ы край держит
// подключёнными (`security.md` §Hardening-инварианты, п. 6).
//
// Две записи одного текста, сверяемые гейтом, — не то же самое, что одна.
// Сверка доказывает согласие в момент прогона; общий источник делает
// расхождение невыразимым. Здесь это не теория: производителей было два, и
// разошлись они регистром одной буквы — различие, которого не видно ни в
// обзоре изменения, ни в проверке, утверждающей код ответа (задача продукта
// #1370).
//
// Вызывающие — обработчик владельца (`pkg/operations/operationspb`) и край
// (`gateway/internal/opsproxy`). Третьего быть не должно; держит это гейт
// `internal/repohygiene` `TestOperationNotFoundHasOneProducer`. Гейт судит
// ФОРМУ строкового выражения, а не его исходный текст, поэтому собрать тот же
// текст склейкой — не обход: перечень известных ему форм и границы этого
// перечня названы в шапке гейта.
//
// От `ErrNotFound` отличается предметом: тот — внутреннее значение ошибки, по
// которому слой хранения узнают вызывающие внутри процесса, и id он не несёт
// by construction. Наружу уезжает только этот текст.
func NotFoundStatus(id string) error {
	return status.Errorf(codes.NotFound, "operation %s not found", id)
}
