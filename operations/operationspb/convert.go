// Package operationspb — арендаторская поверхность `OperationService`: перевод
// строки операции в контракт и обработчик, реализующий оба глагола.
//
// # Почему отдельный пакет, а не функции в pkg/operations
//
// `pkg/operations` не импортирует proto-стабы и не должен: он владеет строкой
// операции и её хранением, а не тем, как она выглядит на проводе. Тот же шов
// проведён у величин пределов (`pkg/quota/quotapb`), и он здесь повторён, а не
// изобретён.
//
// # Почему один пакет, а не семь копий
//
// `OperationService` — единственный сервис контракта, который несёт КАЖДЫЙ
// домен: любая мутация возвращает `Operation` (ban #9), и клиент поллит её у
// того же сервиса, который мутацию принял. До сведения реализация была
// объявлена семь раз, и семь копий давали семь поведений.
//
// Расхождения были не косметические, и увидеть их можно было только сравнив
// копии: одна из них отменяла операцию НЕАТОМАРНО — проверяла владение
// отдельным чтением, а мутацию звала несуженную, то есть предикат владения
// уходил из мутации совсем (ban #10, software check-then-act). По диффу обе
// половины выглядят добросовестной работой.
package operationspb

import (
	"time"

	"google.golang.org/protobuf/types/known/timestamppb"

	operationpb "github.com/PRO-Robotech/corelib/api/kacho/cloud/operation"
	"github.com/PRO-Robotech/corelib/operations"
)

// ToProto переводит строку операции в контракт.
//
// Здесь два РЕШЕНИЯ, а не механика, и у каждого одно место:
//
//   - усечение отметок времени до секунды — конвенция продукта для КАЖДОГО
//     proto-ответа (`api-conventions.md`): БД хранит микросекунды, клиент их не
//     видит. `Operation` — ответ каждой мутации, то есть самая частая
//     поверхность утечки долей секунды;
//   - охрана пустого значения: `nil` на входе даёт `nil` на выходе, а не панику.
//     До сведения одна из копий этой охраны НЕ несла — расхождение, невидимое до
//     первого пустого значения.
//
// Тело сведено к версии БОЛЬШИНСТВА, а не написано заново. Числа ниже сняты на
// предшествующей ревизии, и единица счёта названа явно: прежние редакции этого
// абзаца смешивали «объявление» с «именем помощника» и потому не сходились ни с
// одним предикатом.
//
// ОБЪЯВЛЕНИЙ было ДВЕНАДЦАТЬ. Четыре из них — обёртки nlb, делегировавшие в свой
// же общий помощник и собственного тела не имевшие; РЕАЛИЗАЦИЙ, стало быть,
// восемь. Все двенадцать несли все три поля принципала.
//
// Расходились они тремя способами, и ни один не косметический:
//
//   - УСЕЧЕНИЕ: четыре реализации звали именованный помощник (три РАЗНЫХ имени —
//     `ts`, `TimestampProto`, `prototime.Truncate`), четыре усекали инлайн;
//   - ОХРАНА ПУСТОГО ВХОДА (`op == nil`): её не несли ДВЕ реализации из восьми;
//   - ОХРАНА ПУСТОГО МОМЕНТА ВРЕМЕНИ: её несли ТРИ объявления из двенадцати —
//     те, что звали `TimestampProto` (iam, два места) и `prototime.Truncate`
//     (registry). То есть два именованных помощника из трёх:
//     if t.IsZero() { return nil }
//
// Здесь принята версия МЕНЬШИНСТВА, и это решение, а не перенос. Довод: пустой
// момент означает «не задано», и отдавать вместо него `0001-01-01T00:00:00Z`
// значит выдавать умолчание за факт.
//
// РЕГРЕССА БЫТЬ НЕ МОЖЕТ, НО ОСНОВАНИЕ НЕ ТО, КОТОРОЕ НАПРАШИВАЕТСЯ. Здесь
// стояло «обе колонки `NOT NULL DEFAULT now()`», и это неверно дважды:
// `DEFAULT` не срабатывает никогда, потому что вставка перечисляет `created_at`
// и `modified_at` ЯВНО (`pkg/operations/repo.go`, параметры `$3` и `$5`), а
// `NOT NULL` пустого времени не отсекает — `time.Time{}` пишется законным
// `0001-01-01T00:00:00Z`, на котором `IsZero()` истинно.
//
// Непустоту гарантирует единственный чеканящий конструктор: `operations.New`
// ставит обе метки до вставки, и другого в дереве нет. Значит охрана в проде
// НЕДОСТИЖИМА — она страхует не сегодняшний путь, а завтрашний второй
// конструктор, и сказать это надо прямо: следующий, кто такой конструктор
// заведёт, прочитал бы гарантию, которой нет.
func ToProto(op *operations.Operation) *operationpb.Operation {
	if op == nil {
		return nil
	}
	out := &operationpb.Operation{
		Id:                   op.ID,
		Description:          op.Description,
		CreatedAt:            truncateOrNil(op.CreatedAt),
		CreatedBy:            op.CreatedBy,
		ModifiedAt:           truncateOrNil(op.ModifiedAt),
		Done:                 op.Done,
		Metadata:             op.Metadata,
		PrincipalType:        op.Principal.Type,
		PrincipalId:          op.Principal.ID,
		PrincipalDisplayName: op.Principal.DisplayName,
	}
	if op.Error != nil {
		out.Result = &operationpb.Operation_Error{Error: op.Error}
	} else if op.Response != nil {
		out.Result = &operationpb.Operation_Response{Response: op.Response}
	}
	return out
}

// truncateOrNil — момент времени на проводе: усечён до секунды, а пустой не
// отдаётся вовсе.
//
// Две ответственности здесь намеренно вместе: усечение — конвенция контракта,
// охрана пустого — различение «не задано» и «начало эпохи». Разведи их по двум
// вызовам, и следующий вызывающий позовёт одну без другой.
func truncateOrNil(t time.Time) *timestamppb.Timestamp {
	if t.IsZero() {
		return nil
	}
	return timestamppb.New(t.Truncate(time.Second))
}
