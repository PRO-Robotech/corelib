// retention.go — уборка терминальных строк таблицы операций.
//
// Предмет — задача продукта #1360 и приёмка
// `docs/specs/sub-phase-RET-PLAT-1-platform-table-retention-acceptance.md`
// (APPROVED, круг 3). Строка таблицы операций заводится КАЖДОЙ мутацией
// платформы: контракт объявляет мутации асинхронными, и `Operation`
// возвращается вместо ресурса. Снятия строк не было ни у одного из восьми
// владельцев — рост монотонный и вечный, а темп задаёт внешний.
//
// Петля, партии и наблюдаемость живут в `pkg/retention` и здесь не
// повторяются; здесь — только ПРЕДИКАТ и его пороги, потому что предикат есть
// свойство схемы ЭТОЙ таблицы.
package operations

import (
	"context"
	"fmt"
	"log/slog"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/PRO-Robotech/corelib/retention"
)

// SubjectOperations — имя предмета уборки. Совпадает с именем таблицы: имя
// попадает в отчёт прохода и в метку метрики, и оператор обязан узнавать в нём
// таблицу.
const SubjectOperations = "operations"

// OperationRetention — сколько терминальная операция остаётся доступной.
//
// ВЕЛИЧИНА ВЫВЕДЕНА ИЗ ЧИТАТЕЛЯ, а не назначена числом. Читатель — оператор,
// разбирающий отказавшую мутацию: колонки `error_code`, `error_message`,
// `error_details` живут ТОЛЬКО здесь. Журнал аудита несёт актора и глагол
// мутации, но не текст отказа платформы, поэтому после снятия строки причина
// отказа не восстановима нигде. Предикат читателя — «строка ещё на месте, когда
// до неё дошли руки».
//
// Интервал между отказавшей мутацией и разбором ограничен снизу нерабочими
// днями: отказ вечером пятницы разбирают утром понедельника. Порог короче двух
// суток делает такой разбор невозможным by construction; недельный запас
// покрывает его вместе с отпускной подменой и остаётся величиной, которую видно
// оператору, а не запасом, покрывающим произвольную ошибку в слагаемых.
//
// ЧЕГО ВЕЛИЧИНА НЕ ОБЕЩАЕТ. Таблица операций не становится историей ресурса:
// история — предмет журнала аудита, чьё удержание объявлено намеренно. Списочное
// чтение после уборки отвечает «операции за последние OperationRetention», а не
// «все операции ресурса». Это смена наблюдаемого исхода, и она названа здесь, а
// не обнаруживается.
const OperationRetention = 7 * 24 * time.Hour

// ClockDrift — слагаемое запаса на РАЗНИЦУ ИСТОЧНИКОВ ЧАСОВ.
//
// `modified_at` пишется часами ПРОЦЕССА (`time.Now().UTC()` аргументом), а
// уборка судит часами БАЗЫ (`now()`) — чтобы источник был один на сервис, а не
// «столько источников, сколько реплик». Источники разные ⇒ разница входит в
// порог отдельным слагаемым, а не подразумевается нулём.
//
// `pkg/tokenpolicy.RemovalSlack` здесь НЕ переиспользуется, и причина не в
// удобстве: та величина объявлена как запас на отставание ВНЕШНИХ читателей и
// связана размером с временем жизни токена через своего названного потребителя.
// Здесь закрывается пара «НАШ процесс против НАШЕЙ базы». Переиспользование
// сделало бы так, что сдвиг одной величины двигает и отсрочку снятия ключа
// подписи, и порог уборки в другом домене.
//
// ВЕЛИЧИНА СЕГОДНЯ НЕ НЕСУЩАЯ, и это сказано числом, а не умолчано: порог
// удержания (7 суток) превосходит её на три порядка, поэтому сдвиг часов внутри
// кластера на минуты не меняет ни одного исхода. Несущей она станет, если
// `OperationRetention` когда-нибудь опустят к бюджету полла клиента
// (5 минут) — тогда сумма и станет тем, что сравнивают. Держит это
// TestOperationRetentionCoversTheDeclaredPollBudget: он утверждает ПРАВИЛО, а не
// сегодняшний запас.
const ClockDrift = 5 * time.Minute

// sweepTerminalSQL — предикат уборки.
//
// ЧЕТЫРЕ РЕШЕНИЯ, каждое со своим доводом:
//
//  1. `done = true` — уборка трогает ТОЛЬКО терминальные строки. Читатели
//     нетерминальных (воркер, реконсайлер) становятся непересекающимися с
//     убираемым множеством BY CONSTRUCTION, а не согласованными по величине:
//     уборка нетерминальной строки отняла бы работу у реконсайлера, а
//     работавший воркер получил бы «не найдено» вместо коммита.
//
//  2. Возраст от `modified_at`, а не от `created_at`: `created_at` говорит,
//     когда мутацию ПРИНЯЛИ, и нетерминальную фазу не ограничивает вовсе.
//
//  3. Сравнение СТРОГОЕ (`<`). На равенстве последний миг объявленного бюджета
//     полла застаёт строку уже снятой. Связано с нестрогим `>=` в границе
//     порога: поменять одно, не тронув другое, значит потерять этот миг молча.
//
//  4. Имя таблицы стоит ЛИТЕРАЛОМ, подставляется только схема. Гейт роста
//     (`internal/repohygiene` TestLiveTablesNameTheirGrowthLimit) разрешает имя
//     таблицы разбором исходника; имя, приехавшее подстановкой, уходит в
//     «слепую зону, названную числом» — механизм есть, гейт его не видит, а
//     запись реестра остаётся. Схема у каждого из восьми владельцев своя, имя
//     таблицы — одно на всех, поэтому ОДИН литерал покрывает все восемь.
//
// Партия и клеймо: `LIMIT` ограничивает длину оператора (уборка не вправе быть
// причиной отказа на пути запроса), `FOR UPDATE SKIP LOCKED` запирает строки,
// поэтому вторая реплика уносит только остаток и на пустой выборке не делает
// ничего.
const sweepTerminalSQL = `
DELETE FROM %s.operations
 WHERE id IN (
       SELECT id
         FROM %s.operations
        WHERE done = true
          AND modified_at < now() - make_interval(secs => $1)
        ORDER BY modified_at
        LIMIT $2
        FOR UPDATE SKIP LOCKED)`

// SweepTerminal снимает терминальные операции, чей возраст превысил порог.
//
// Момент времени входом НЕ приходит: часы уборки — базы (см. ClockDrift).
// Проверяемость от этого не теряется — проход зовётся методом
// (`retention.Sweeper.Pass`), поэтому пробе не приходится ни спать, ни подменять
// часы.
//
// Возвращает число снятых строк и признак «партия ушла полной»; признак
// отличает «убрал всё, что было» от «упёрся в партию».
func (r *pgRepo) SweepTerminal(ctx context.Context, grace time.Duration, batch int) (int64, bool, error) {
	// Схема — идентификатор, а не значение: подстановка параметром здесь
	// невозможна, поэтому она санитизируется тем же способом, что и в остальном
	// репо.
	schema := pgx.Identifier{r.schema}.Sanitize()
	tag, err := r.pool.Exec(ctx, fmt.Sprintf(sweepTerminalSQL, schema, schema),
		grace.Seconds(), batch)
	if err != nil {
		return 0, false, fmt.Errorf("operations: уборка терминальных строк: %w", err)
	}
	n := tag.RowsAffected()
	return n, n >= int64(batch), nil
}

// TerminalSweeper — порт уборщика таблицы операций.
//
// Объявлен здесь, а не у вызывающего: реестр уборки собирается этим же пакетом
// (RetentionSubject), и порт нужен ему, а не владельцу композиционного корня.
type TerminalSweeper interface {
	SweepTerminal(ctx context.Context, grace time.Duration, batch int) (int64, bool, error)
}

// RetentionSubject — запись реестра уборки для таблицы операций.
//
// Порог собирается ЗДЕСЬ, а не у каждого из восьми владельцев: восемь копий
// одного порога разошлись бы молча, и разойдясь — дали бы разный срок жизни
// операции у разных доменов при одном контракте.
func RetentionSubject(s TerminalSweeper) retention.Subject {
	return retention.Subject{
		Name:  SubjectOperations,
		Grace: OperationRetention + ClockDrift,
		Sweep: s.SweepTerminal,
	}
}

// DefaultRetentionConfig — величины ПЕТЛИ уборки таблицы операций.
//
// Расписание общее для всех предметов платформы и объявлено один раз в
// `pkg/retention`; здесь оно только называется, а не переписывается числами.
func DefaultRetentionConfig() retention.Config { return retention.DefaultConfig() }

// NewRetentionSweeper собирает уборщика таблицы операций, НЕ поднимая петлю.
//
// Отдельно от запуска, потому что «сборщик работает» обязано быть проверяемо без
// ожидания тикера: проба зовёт `Pass` методом и не спит.
func NewRetentionSweeper(s TerminalSweeper, cfg retention.Config, log *slog.Logger) (*retention.Sweeper, error) {
	sweeper, err := retention.New(cfg, []retention.Subject{RetentionSubject(s)}, log)
	if err != nil {
		return nil, fmt.Errorf("уборка таблицы операций: %w", err)
	}
	return sweeper, nil
}

// StartRetentionSweep поднимает фоновую уборку таблицы операций.
//
// ОДНА строка в композиционном корне каждого владельца — намеренно: восемь
// владельцев несут одну и ту же таблицу с одним и тем же контрактом, и всё, что
// у них могло бы разойтись, собрано здесь.
//
// Отказывает, а не предупреждает: отказ означает негодные величины расписания,
// то есть уборку, которая исполняется и не убирает ничего.
func StartRetentionSweep(ctx context.Context, s TerminalSweeper, cfg retention.Config, log *slog.Logger) (*retention.Sweeper, error) {
	sweeper, err := NewRetentionSweeper(s, cfg, log)
	if err != nil {
		return nil, err
	}
	sweeper.Start(ctx)
	return sweeper, nil
}
