// poolclose.go — почему интеграционная проба закрывает пул ЧЕРЕЗ этот пакет, а не
// через `defer pool.Close()`.
//
// # Предмет
//
// `pgxpool.Pool.Close` ждёт возврата ВСЕХ выданных соединений. Проба, упавшая
// внутри открытой транзакции, соединение не вернёт никогда: `require.NoError` →
// `t.FailNow` → `runtime.Goexit` завершает горутину пробы, отложенные функции
// исполняются, и `pool.Close()` встаёт ждать писателя, которого уже нет.
//
// Дальше происходит подмена вердикта. Пакет упирается в `-timeout` (по умолчанию
// `go test` даёт 600 с) и печатает `FAIL` — то есть «не выполнилось» приходит к
// читателю ПОД ВИДОМ красного вердикта. Читатель ищет расхождение поведения, а
// прогон не состоялся вовсе; вердикта нет ни у одной пробы пакета, включая те,
// что успели пройти. Наблюдалось: однострочная опечатка в фикстуре стоила десяти
// минут прогона вместо доли секунды, и умножалась на число прогонов.
//
// # Что делает этот файл
//
// Ровно одно: превращает зависание в ОТКАЗ С ИМЕНЕМ. Закрытие получает предел;
// не уложилось — проба падает, называя пробу, показания пула и снятие. Десять
// минут молчания меняются на несколько десятков секунд с причиной.
//
// Это НЕ замена дисциплине `defer w.Abort()` сразу после `Writer(ctx)` — та
// убирает утечку вовсе. Это то, что ловит её отсутствие: у следующей фикстуры,
// написанной до ужесточения инварианта миграцией, шанса промолчать больше нет.
package pgtest

import (
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// DefaultPoolCloseBound — сколько закрытие пула ждёт, прежде чем сдаться.
//
// Величина ВЫВЕДЕНА, а не выбрана на глаз. `pkg/db.NewPool` задаёт соединениям
// `statement_timeout = 30000` (30 с), поэтому законное закрытие вправе ждать
// столько же: соединение может быть занято запросом, который сервер снимет сам.
// Предел ниже тридцати секунд отвергал бы исправный случай — ровно та проверка,
// которую первый же ложный срабат отключит. Пятнадцать секунд сверху — запас на
// загруженную машину.
//
// Верхняя граница тоже названа: 45 с против 600 с умолчания `go test` — это
// тринадцатикратная разница, и при ней причина доезжает до читателя.
const DefaultPoolCloseBound = 45 * time.Second

// PoolCloseBoundEnv — ручка на случай, когда конвейеру нужен другой предел.
// Значение читается как `time.ParseDuration`; негодное игнорируется молча по
// умолчанию было бы неверно, поэтому оно печатается и предел остаётся штатным.
const PoolCloseBoundEnv = "KACHO_PGTEST_POOL_CLOSE_BOUND"

func poolCloseBound() time.Duration {
	raw := os.Getenv(PoolCloseBoundEnv)
	if raw == "" {
		return DefaultPoolCloseBound
	}
	d, err := time.ParseDuration(raw)
	if err != nil || d <= 0 {
		fmt.Fprintf(os.Stderr, "pgtest: %s=%q не разобрано как длительность — предел остаётся %s\n",
			PoolCloseBoundEnv, raw, DefaultPoolCloseBound)
		return DefaultPoolCloseBound
	}
	return d
}

// ClosePoolAtEnd регистрирует закрытие пула на конец пробы — С ПРЕДЕЛОМ.
//
// Ставится ВМЕСТО `defer pool.Close()`:
//
//	pool, err := coredb.NewPool(ctx, dsn)
//	require.NoError(t, err)
//	pgtest.ClosePoolAtEnd(t, pool)
//
// Почему `t.Cleanup`, а не `defer`: очистки исполняются ПОСЛЕ всех отложенных
// функций тела пробы, поэтому `defer w.Abort()` успевает вернуть соединение, и на
// исправной пробе не меняется ничего. А на неисправной — предел срабатывает и
// пакет живёт дальше, вместо того чтобы умереть целиком.
func ClosePoolAtEnd(t testing.TB, pool *pgxpool.Pool) {
	t.Helper()
	if pool == nil {
		return
	}
	t.Cleanup(func() {
		if msg := closePoolWithin(pool, poolCloseBound()); msg != "" {
			t.Errorf("%s", msg)
		}
	})
}

// closePoolWithin закрывает пул и возвращает "" , если тот закрылся в пределах
// bound. Иначе — текст отказа, по которому пробу можно починить, не читая этот
// файл.
//
// Брошенная горутина закрытия — осознанная цена: остановить `pgxpool.Close`
// нечем, а держать за неё весь пакет и есть предмет. Она разблокируется сама,
// когда `pgtest` дропнет базу пробы (`DROP DATABASE … WITH (FORCE)` снимает
// backend'ы), и в любом случае не мешает процессу завершиться.
func closePoolWithin(pool *pgxpool.Pool, bound time.Duration) string {
	done := make(chan struct{})
	go func() {
		defer close(done)
		pool.Close()
	}()

	select {
	case <-done:
		return ""
	case <-time.After(bound):
	}

	// Показания пула — доказательство, а не догадка: они говорят, сколько
	// соединений выдано и не возвращено на момент отказа.
	st := pool.Stat()
	return fmt.Sprintf(
		"закрытие пула не уложилось в %s — соединение выдано и не возвращено "+
			"(acquired=%d idle=%d total=%d).\n"+
			"Это НЕ расхождение поведения: проба завершилась (require/FailNow) при ОТКРЫТОЙ "+
			"транзакции, и её соединение не вернётся в пул уже никогда.\n"+
			"Снятие: сразу после `w, err := r.Writer(ctx)` поставить `defer w.Abort()` — "+
			"Abort идемпотентен, после Commit он no-op.\n"+
			"Настоящая причина отказа — в утверждении, которое упало ВЫШЕ этого сообщения.",
		bound, st.AcquiredConns(), st.IdleConns(), st.TotalConns())
}
