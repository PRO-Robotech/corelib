package quota

// startsync.go — единственный вход в подъём фоновой полосы ребра величин.
//
// # Почему вход один
//
// Решение «заводить ли тянущего» принимается здесь, а не у потребителя. Пока
// оно принималось у него, признаком служило НАЛИЧИЕ СОЕДИНЕНИЯ соседа по
// авторизации — и пять потребителей приняли его пятью копиями одной ветки.
// Копии разошлись бы на первом же владельце, у которого соседа два; хуже того,
// после снятия авторитета величин каждая из них подняла бы тянущего к
// слушателю, где службы величин нет, и отказала бы ПРИ СБОРКЕ — а отказ сборки
// у всех пяти фатален.
//
// Второй экспортируемой сборки тянущего у пакета НЕТ — прежняя снята вместе с
// переносом решения сюда, — поэтому обойти этот вход нельзя вовсе: свойство
// держит компилятор. Гейт дерева
// (`internal/repohygiene/quotaauthoritydeclared.go`) держит вторую половину —
// что вызов стоит БЕЗУСЛОВНО, то есть потребитель не решил ещё раз своим
// признаком.

import (
	"context"
	"fmt"
	"log/slog"
)

// StartLimitSync заводит фонового тянущего величины СТРОГО по объявлению
// домена величин и возвращает его останов.
//
// Объявление доезжает до строки курсора ВСЕГДА — и когда домен развёрнут, и
// когда нет. Это и есть то, чем «домен снят решением оператора» отличается от
// «тянущий умер»: после снятия авторитета «ни одна строка не синхронизирована
// за всё время» становится штатным и вечным, поэтому нулевые накопительные
// счётчики перестают что-либо означать, а сигнал застоя, оставленный как есть,
// срабатывал бы всегда. Проверку, кричащую на нормальной работе, перестают
// читать вместе с настоящими находками.
//
// src обязан быть согласован с объявлением, и рассогласование — отказ при
// сборке, а не предпочтение одной из сторон:
//
//   - домен объявлен адресом, источника нет ⇒ подъём исполнялся бы по
//     расписанию и не делал ничего, оставаясь на вид работающим;
//   - домен объявлен отсутствующим, а источник есть ⇒ потребитель дозвонился
//     туда, куда по объявлению обращаться не должен. Решение принято дважды, и
//     второе место невидимо оператору.
//
// Останов возвращается всегда — в том числе на неразвёрнутом домене: у
// вызывающего не должно быть ветки «а здесь останавливать нечего», иначе
// пятеро напишут её пятью способами.
func StartLimitSync(
	ctx context.Context,
	db Execer,
	authority Authority,
	src Source,
	schema string,
	cfg Config,
	logger *slog.Logger,
) (func(), error) {
	if logger == nil {
		logger = slog.Default()
	}

	proj, err := NewPgProjection(db, schema)
	if err != nil {
		return nil, fmt.Errorf("quota limit projection: %w", err)
	}

	// Состояние записывается ДО разбора согласованности: даже отвергнутая
	// посадка обязана оставить в курсоре то, что о ней объявил оператор.
	// Иначе разбор отказа начинается с состояния, которого никто не называл.
	if rerr := proj.RecordAuthority(ctx, authority.State()); rerr != nil {
		// Отказ здесь фатален намеренно. Состояние курсора и есть то, чем
		// «домен снят» отличается от «тянущий умер»; подняться, не сумев его
		// назвать, значит завести ровно ту неразличимость, ради устранения
		// которой оно существует.
		return nil, fmt.Errorf("объявление домена величин не доехало до курсора: %w", rerr)
	}

	if !authority.Deployed() {
		if src != nil {
			return nil, fmt.Errorf(
				"домен величин объявлен как %q, но источник дельты собран: потребитель "+
					"дозвонился туда, куда по объявлению обращаться не должен", NotDeployed)
		}
		// Строка говорит о ДВУХ следствиях, а не об одном. Прежняя редакция
		// называла только тянущего — а оператор, прочитавший «тянущий не нужен»,
		// получал ещё и путь запроса, ведущий себя иначе, чем он ожидал. Следствие
		// для пути запроса ему приходилось узнавать из отказов арендатора
		// (`PRO-Robotech/kacho#2216`; `security.md` §Hardening п. 8 — сообщать о
		// следствии для фонового механизма, умалчивая о следствии для пути
		// запроса, значит не отличать настройку от сбоя).
		logger.Info("resource-count quota: limit authority declared absent — "+
			"on the REQUEST PATH no ceiling applies at all (mutations of counted "+
			"kinds are charged but never refused: no ceiling is stateable in this "+
			"installation), and the delta puller is not started",
			slog.String("schema", schema),
			slog.String("authority_state", string(AuthorityAbsent)),
			slog.Bool("ceilings_enforced", false))
		return func() {}, nil
	}

	if src == nil {
		return nil, fmt.Errorf(
			"quota.authority объявляет адрес %q, но источник дельты не собран: "+
				"тянущий исполнялся бы по расписанию и не делал ничего, оставаясь "+
				"на вид работающим", authority.Endpoint())
	}

	syncer, err := NewSyncer(src, proj, cfg,
		logger.With(slog.String("component", "quota-limit-syncer")))
	if err != nil {
		return nil, fmt.Errorf("quota limit syncer: %w", err)
	}
	return startSyncer(ctx, syncer, schema, logger), nil
}
