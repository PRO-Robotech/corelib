package quota

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Тело функции отказа — РЕФЕРЕНТ, переживающий свод цепи.
//
// # Зачем понадобился второй референт
//
// Сверка «файл миграции владельца побайтово равен рендеру шаблона» держала единый
// источник, пока у каждого владельца цепь была историей файлов. Свод цепи одного
// владельца в одну первичную миграцию отнял у этой сверки предмет: файла нет и
// быть не может — рендерить его значило бы завести версию ниже уже применённой.
//
// Отказаться от проверки у сведённого владельца было бы послаблением без срока, а
// перенести её на имя файла — тем же промахом ещё раз, только позже. Поэтому
// референтом стало то, что цепь ПРОИЗВОДИТ независимо от своей формы: тело функции
// в схеме. Оно годится и там, и там — `pg_dump` печатает тело дословно, каким его
// создала миграция, потому что каталог хранит его текстом.
//
// # Почему это СИЛЬНЕЕ прежней сверки, а не слабее
//
// Сверка файла судит ОДИН файл. Тело же берётся ПОСЛЕДНИМ по цепи — то есть тем,
// которое в базе и окажется. Поздняя миграция с `CREATE OR REPLACE`, переписавшая
// отказ своими словами, прежней сверке невидима by construction: отрендеренный файл
// она не трогает. Обе сверки поэтому остаются: одна на файл там, где файл есть,
// другая на тело — у всех.
//
// # Что сюда НЕ входит и почему
//
// Комментарии `COMMENT ON FUNCTION` сверять нечем: шаблон складывает их из
// нескольких литералов подряд, `pg_dump` печатает одной строкой, и побайтовое
// равенство недостижимо. Контракт при этом несёт тело — текст исключения, ERRCODE
// и подробности стоят в нём.

// refusalFunctions — имена, чьи тела обязаны совпадать. Перечень закрытый: он же
// служит проверкой того, что извлечение вообще состоялось.
var refusalFunctions = []string{"kacho_quota_refuse", "kacho_quota_admit"}

// reRefusalFuncHead — заголовок ОБЪЯВЛЕНИЯ функции отказа.
//
// Именно объявления, а не упоминания: `PERFORM …kacho_quota_refuse(…)` внутри
// триггерной функции — вызов, и предикат по одному имени принял бы его за
// определение. Квалификатор схемы необязателен и не читается — он у каждого
// владельца свой, а сверяется здесь то, что у всех обязано быть одинаковым.
var reRefusalFuncHead = regexp.MustCompile(`CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+[\w.]*?\b(kacho_quota_(?:refuse|admit))\s*\(`)

// RefusalFunctionBodies извлекает тела функций отказа из текста SQL.
//
// Один извлекатель на обе стороны сравнения — и на рендер шаблона, и на дерево, —
// чтобы разбор не мог разойтись сам с собой. Отсюда же требование к вызывающему:
// сторона-эталон обязана дать ПОЛНЫЙ набор непустых тел, иначе «совпало» означало
// бы, что извлечение не состоялось у обеих сторон сразу.
//
// Возвращает последнее определение каждой функции в переданном тексте: в файле их
// не бывает двух, а по цепи побеждает позднейшее, и склейка текстов в порядке
// версий даёт ровно это.
func RefusalFunctionBodies(sqlText string) map[string]string {
	out := map[string]string{}
	for _, m := range reRefusalFuncHead.FindAllStringSubmatchIndex(sqlText, -1) {
		name := sqlText[m[2]:m[3]]
		open := strings.Index(sqlText[m[1]:], "AS $$")
		if open < 0 {
			continue
		}
		start := m[1] + open + len("AS $$")
		end := strings.Index(sqlText[start:], "$$;")
		if end < 0 {
			continue
		}
		out[name] = sqlText[start : start+end]
	}
	return out
}

// ExpectedRefusalBodies — тела, какими их рендерит шаблон для этого владельца.
//
// Отказывает, когда извлекла не то, что должна: пустое либо неполное множество
// означает, что разбор перестал понимать шаблон, а сравнение с пустым множеством
// сходится с чем угодно. Проверка собственной предпосылки, а не украшение.
func ExpectedRefusalBodies(o RefusalOwner) (map[string]string, error) {
	rendered, err := RenderRefusalMigration(o)
	if err != nil {
		return nil, err
	}
	bodies := RefusalFunctionBodies(rendered)

	var missing []string
	for _, fn := range refusalFunctions {
		if strings.TrimSpace(bodies[fn]) == "" {
			missing = append(missing, fn)
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return nil, fmt.Errorf("quota refusal: из рендера шаблона для %s не извлечены тела %s: "+
			"разбор перестал понимать шаблон, и сравнение с пустым множеством сошлось бы с любым деревом",
			o.Service, strings.Join(missing, ", "))
	}

	// Тела обязаны нести оба кода отказа. Без этого «тела совпали» осталось бы
	// верным на шаблоне, из которого контракт вынули: совпадение двух одинаково
	// выхолощенных сторон — не проверка.
	for _, code := range []string{"KQ001", "KQ002"} {
		if !strings.Contains(bodies[refusalFunctions[0]], code) {
			return nil, fmt.Errorf("quota refusal: в теле %s нет %s — контракт отказа вынут из шаблона, "+
				"а сравнение тел этого не заметило бы", refusalFunctions[0], code)
		}
	}
	return bodies, nil
}

// RefusalFunctionNames — имена, чьи тела сверяются. Копия, а не сам срез.
func RefusalFunctionNames() []string {
	out := make([]string, len(refusalFunctions))
	copy(out, refusalFunctions)
	return out
}
