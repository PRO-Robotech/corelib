package quota

// authority.go — объявление домена величин у потребителя.
//
// # Предмет: источник величин становится ОБЪЯВЛЕННЫМ, а не выведенным
//
// Прежде потребитель брал величины по соединению, объявленному для
// АВТОРИЗАЦИИ: своей ручки у резолва не было намеренно — второй адрес того же
// слушателя разошёлся бы с первым молча. Довод верен ровно до тех пор, пока
// авторитет величин и авторитет авторизации — одна служба. Уход модуля
// квотирования это условие снимает: после него выведенный адрес указывал бы на
// слушатель, где службы величин нет вовсе.
//
// # Одно объявление на ОБЕ полосы ребра
//
// Ребро потребитель → домен величин одно, а полос у него две: разрешение
// величины на пути запроса (fail-closed) и фоновая дельта, которой снимок
// догоняет авторитет (ограниченное отставание вне пути запроса). Недоступность
// соседа означает на них разное — но включаются они ОДНИМ объявлением. Два
// объявления об одном ребре разошлись бы молча, и разошлись бы именно там, где
// расхождение значит «спрашиваем у одного, догоняем у другого».
//
// # Незаданное значение — отказ старта, а не умолчание
//
// Умолчание здесь означает выбор за оператора между «потолки действуют» и
// «потолков нет», и выбор этот невидим. Оба возможных умолчания отвергнуты
// каждое своим доводом:
//
//   - умолчание «взять адрес авторизации» вернуло бы ВЫВЕДЕННЫЙ адрес, который
//     `security.md` §Hardening п.9 запрещает для решения, влияющего на доступ к
//     ресурсу: он всегда непуст, поэтому контроль выглядит настроенным и ведёт
//     в никуда;
//   - умолчание «не развёрнут» сняло бы потолки МОЛЧА — расширение поверхности,
//     которого никто не называл.
//
// # Отсутствие представимо ОТДЕЛЬНО от значения
//
// «Домен не развёрнут» — не пустая строка и не нулевой адрес, а СВОЁ значение
// с собственным написанием. Пустая строка означает «оператор ничего не сказал»,
// и это третье состояние, отличимое от обоих законных: иначе «не настроили» и
// «настроили на отсутствие» имели бы одно представление, и ни одна проверка
// ниже по потоку не различала бы их.

import (
	"fmt"
	"strings"

	"github.com/PRO-Robotech/corelib/quota/quotaread"
)

// NotDeployed — значение ручки, объявляющее, что домена величин в этой
// установке нет.
//
// То же написание служит и состоянием курсора синхронизации (AuthorityAbsent):
// одно написание в двух ролях, а не два написания одного смысла. Разойтись они
// не могут by construction — второе выведено из первого.
const NotDeployed = "not-deployed"

// AuthorityState — наблюдаемое состояние домена величин, каким его объявил
// оператор этому потребителю.
//
// Живёт в строке курсора синхронизации и существует ради РАЗЛИЧИМОСТИ: после
// снятия авторитета «ни одна строка не синхронизирована за всё время»
// становится штатным и вечным, поэтому нулевые накопительные счётчики
// перестают что-либо означать. Причина обязана НАЗЫВАТЬСЯ, а не выводиться из
// нуля.
type AuthorityState string

const (
	// AuthorityUnknown — объявления ещё не было ни от одного подъёма. Умолчание
	// столбца: между применением миграции и первым стартом процесса не сказано
	// ничего, и это третье состояние, а не одно из двух законных.
	AuthorityUnknown AuthorityState = "unknown"
	// AuthorityPresent — домен величин объявлен адресом.
	AuthorityPresent AuthorityState = "deployed"
	// AuthorityAbsent — домен величин объявлен отсутствующим.
	AuthorityAbsent AuthorityState = AuthorityState(NotDeployed)
)

// AuthorityStates — закрытый словарь состояний, признаваемых столбцом курсора.
//
// Объявлен здесь, у типа, а не выписан у каждого читателя: перечень, живущий в
// нескольких местах, расходится молча. Ограничение таблицы повторяет ровно этот
// перечень, и совпадение держится интеграционной пробой, а не совпадением
// написания.
func AuthorityStates() []AuthorityState {
	return []AuthorityState{AuthorityUnknown, AuthorityPresent, AuthorityAbsent}
}

// Declaration — сырое объявление домена величин, как его прочитал потребитель
// из своей посадки.
//
// Имена ручек здесь не для красоты: они попадают в текст отказа старта, а он
// обязан восстанавливать следующий шаг оператора. Без имени ручки стенд не
// поднять — это одно из трёх мест, прямо выведенных из-под запрета
// `security.md` §«Публичные артефакты».
type Declaration struct {
	// Knob — имя ручки, объявляющей домен величин.
	Knob string
	// Value — её сырое значение, как оно пришло из посадки.
	Value string
	// TransportKnob — имя ручки удостоверения, которым потребитель
	// представляется домену величин.
	TransportKnob string
	// TransportRequired — обязано ли удостоверение быть объявлено на ЭТОЙ
	// посадке.
	//
	// Посадочное правило у ребра величин ТО ЖЕ, что у остальных рёбер службы:
	// проверяемый транспорт требуется в боевом режиме. Заводить ребру величин
	// собственную строгость значило бы завести различие, которое пришлось бы
	// помнить, — и первым же следствием стал бы неподнимаемый локальный стенд
	// там, где все прочие рёбра ходят открытым текстом законно.
	//
	// Незаданное ОБЪЯВЛЕНИЕ (поле Value) режимом не смягчается никогда: оно
	// означает не «транспорт попроще», а «оператор не выбрал между „потолки
	// действуют" и „потолков нет"», и подставить за него разумное умолчание
	// нельзя ни в каком режиме.
	TransportRequired bool
	// TransportDeclared — объявлено ли это удостоверение.
	//
	// Половина пары хуже отсутствия обеих, потому что ВЫГЛЯДИТ настроенной:
	// адрес есть, обращение уходит, сосед отвечает «требуется сертификат
	// клиента», а наш потребитель классифицирует это как недоступность соседа.
	// Со стороны — «сосед недоступен», хотя сосед исправен и говорит ровно то,
	// что должен (`security.md` §«Контроль, у которого нет МЕХАНИЗМА
	// исполниться»).
	TransportDeclared bool
}

// Authority — разрешённое объявление домена величин.
//
// Тип суммы, а не строка: значение «не развёрнут» не может быть случайно
// использовано как адрес, потому что адреса у него нет вовсе.
type Authority struct {
	endpoint string
	deployed bool
}

// Deployed — развёрнут ли домен величин в этой установке.
func (a Authority) Deployed() bool { return a.deployed }

// Endpoint — адрес домена величин. Пуст, когда домен объявлен отсутствующим.
func (a Authority) Endpoint() string { return a.endpoint }

// State — наблюдаемое состояние, которое доедет до строки курсора.
func (a Authority) State() AuthorityState {
	if a.deployed {
		return AuthorityPresent
	}
	return AuthorityAbsent
}

// ResolveAuthority разбирает объявление и проверяет ОБЕ его половины разом.
//
// Одним вызовом намеренно: две отдельные проверки — форма объявления и наличие
// удостоверения — дают потребителю возможность позвать первую и забыть вторую,
// а забытая половина и есть предмет KAN-Q1-05. Забыть здесь нечего: проверка
// одна.
func ResolveAuthority(d Declaration) (Authority, error) {
	knob := d.Knob
	if knob == "" {
		knob = "<ручка домена величин>"
	}
	raw := strings.TrimSpace(d.Value)

	switch {
	case raw == "":
		return Authority{}, fmt.Errorf(
			"%s не задана: у неё ровно два законных значения — адрес домена величин "+
				"в форме host:port либо %q, если домена величин в этой установке нет. "+
				"Умолчания здесь не существует: оно означало бы выбор за оператора между "+
				"«потолки действуют» и «потолков нет», и выбор этот был бы невидим",
			knob, NotDeployed)

	case raw == NotDeployed:
		// Удостоверения не требуется: обращаться не к кому. Требовать его здесь
		// значило бы сделать законную посадку неподнимаемой.
		return Authority{}, nil

	case !strings.Contains(raw, ":"):
		// Не адрес и не слово. Отвергается СТАРТОМ, а не дозвоном: иначе
		// опечатка уезжает в сеть и приезжает арендатору отказом,
		// обещающим временность, — «повтори позже» на посадку, которая не
		// станет рабочей никогда.
		return Authority{}, fmt.Errorf(
			"%s = %q не является ни адресом, ни объявлением отсутствия: адрес пишется "+
				"в форме host:port, отсутствие — словом %q",
			knob, raw, NotDeployed)
	}

	if d.TransportRequired && !d.TransportDeclared {
		transportKnob := d.TransportKnob
		if transportKnob == "" {
			transportKnob = "<ручка удостоверения к домену величин>"
		}
		return Authority{}, fmt.Errorf(
			"%s = %q объявляет адрес домена величин, а %s не объявляет удостоверения, "+
				"которым потребитель ему представится. Половина пары хуже отсутствия обеих: "+
				"обращение уходит, сосед отвечает «требуется сертификат клиента», и отказ "+
				"читается как недоступность соседа при исправном соседе",
			knob, raw, transportKnob)
	}

	return Authority{endpoint: raw, deployed: true}, nil
}

// ReadPosture — объявление домена величин, каким его обязана назвать ВИТРИНА.
//
// ЕДИНСТВЕННЫЙ перевод объявления в посадку витрины, и он здесь намеренно.
// Владельцев пятеро; написанный у каждого, этот `if` был бы пятью копиями
// одного решения — и разошёлся бы там, где расхождение не видит ни один из
// пяти: у арендатора ОДНОГО домена витрина говорила бы про установку, у
// соседнего — про поломку, при одной и той же посадке.
//
// Перевод стоит у объявления, а не у витрины, потому что предмет здесь —
// объявление: витрина о ручке не знает и знать не должна.
// serviceDomain — имя сервиса, называющее источник ответа в машинном признаке.
// Приходит параметром, а не полем объявления: у балансировщика каталог величин
// знает виды как `loadbalancer`, а ответ на проводе обязан называть источником
// `nlb`, — вывести одно из другого нельзя, и объявление домена величин об этом
// различии не знает.
func ReadPosture(a Authority, serviceDomain string) quotaread.Posture {
	if a.Deployed() {
		return quotaread.AuthorityDeclared()
	}
	return quotaread.AbsentAuthority(serviceDomain)
}
