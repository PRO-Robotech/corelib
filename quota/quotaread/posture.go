package quotaread

// posture.go — РАЗВЁРНУТ ЛИ ДОМЕН ВЕЛИЧИН В ЭТОЙ УСТАНОВКЕ (#2515).
//
// # Предмет
//
// Ручка домена величин принимает два законных значения — адрес соседа либо слово
// «домена величин в этой установке нет» (`quota.NotDeployed`). Второе объявляет
// ВЫБОР ОПЕРАТОРА, а не поломку, и путь запроса ему уже подчиняется: считаемые
// виды списываются, но не отвергаются никогда.
//
// Витрина об этом выборе не знала, и «не знала» означало вот что. Полоса чтения
// собирается только под развёрнутый домен — спрашивать величины иначе не у кого.
// Поэтому на объявленном отсутствии владелец полосы не собирал, обработчика
// витрины не строил и метод НЕ РЕГИСТРИРОВАЛ вовсе, а незарегистрированный метод
// отвечает `UNIMPLEMENTED` — «такой возможности в этой сборке нет». Неправда
// дважды: метод существует, а отсутствует не он, а потолок.
//
// Отсутствие полосы означало РАЗОМ два состояния — «провязать забыли» (дефект
// сборки) и «оператор объявил, что домена величин нет» (законная посадка), — и
// ответ у обоих был один. Это ровно «недоступен ≠ не развёрнут» (`polyrepo.md`) и
// «пустое значение обязано означать пусто» (`api-conventions.md`): отсутствие
// обязано быть представимо ОТДЕЛЬНО от значения — тем же доводом, каким оно уже
// представимо отдельно у самой ручки (`pkg/quota/authority.go`).
//
// # Почему это живёт в полосе ЧТЕНИЯ, а не в переводе в контракт
//
// Две причины, и вторая решающая:
//
//  1. предмет здесь читательский — «назначаются ли потолки вообще», а не «как
//     уложить строку в сообщение»;
//  2. перевод объявления в посадку принадлежит объявлению (`pkg/quota`), а оно
//     лежит в ФУНДАМЕНТЕ. Импорт фундаментом пакета перевода — ребро
//     запрещённого целевой раскладкой направления (`corelib <- kaname <- kacho`),
//     и собиралось бы оно чисто сегодня, отказав только в день раскола модулей.
//     Полоса чтения — фундамент, поэтому её импортируют обе стороны законно.

import (
	"google.golang.org/genproto/googleapis/rpc/errdetails"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// Posture — как ЭТА установка объявила домен величин, доехавшее до витрины.
//
// Тип, а не булев параметр у вызывающего: на месте вызова `false` не читается
// никак, а пять владельцев написали бы пять разных его прочтений. Поля
// неэкспортируемые — собрать посадку, которой не бывает, за пределами пакета
// нельзя.
//
// НУЛЕВОЕ ЗНАЧЕНИЕ — «домен объявлен адресом», то есть прежнее поведение.
// Выбрано намеренно: владелец, ещё не научившийся называть посадку, остаётся при
// верном ответе для СВОЕГО случая — непровязанная полоса при объявленном адресе
// и есть дефект сборки. Обратное умолчание объявляло бы отсутствие потолков за
// оператора, причём молча.
type Posture struct {
	authorityAbsent bool
	// serviceDomain — имя сервиса, называющее ИСТОЧНИК ответа в машинном
	// признаке (`ErrorInfo.domain`). Нужно только полосе отсутствия: у неё нет
	// полосы чтения, у которой это имя можно было бы спросить.
	serviceDomain string
}

// AuthorityDeclared — домен величин объявлен адресом.
func AuthorityDeclared() Posture { return Posture{} }

// AbsentAuthority — домен величин объявлен отсутствующим этой установкой.
//
// Имя сервиса берётся параметром, а не выводится: у балансировщика каталог
// величин знает виды как `loadbalancer`, а ответ на проводе обязан называть
// источником `nlb`, — вывести одно из другого нельзя.
func AbsentAuthority(serviceDomain string) Posture {
	return Posture{authorityAbsent: true, serviceDomain: serviceDomain}
}

// AuthorityIsAbsent — объявлен ли домен величин отсутствующим.
func (p Posture) AuthorityIsAbsent() bool { return p.authorityAbsent }

// reasonQuotaAuthorityAbsent — машинный признак полосы «домен величин объявлен
// отсутствующим».
//
// СВОЙ признак, а не `QUOTA_NOT_PROVISIONED`, и различие несущее: у той полосы
// есть следующий шаг («администратор заведёт величину»), а у этой его НЕТ —
// величину в такой установке завести негде, потому что заводить её некому.
// Свести их в один признак значило бы отправить арендатора просить о действии,
// которое в этой установке не выполнимо ни при каком входе.
//
// Директивы подавления анализатора здесь НЕТ намеренно: по этой координате
// правило про учётные данные не срабатывает, и подавление читалось бы как
// принятое решение, не подавляя ничего. Соседние токены полос у пяти владельцев
// её тоже не несут.
const reasonQuotaAuthorityAbsent = "QUOTA_AUTHORITY_ABSENT"

// Refusal — отказ витрины на объявленном отсутствии домена величин; `nil`, когда
// домен объявлен адресом.
//
// # Почему ОТКАЗ, а не пустой ответ и не строки с нулями
//
// Пустой набор контракт делать запрещает: он читается как «ограничений нет»
// (`Band.States`), а полный перечень видов приходит даже проекту, в
// котором ещё ничего не создано. Строки же показать нечем: поле предела —
// `int64`, у него нет представления «величины не существует», а ноль есть
// ЗАКОННОЕ и осмысленное значение («этого вида создавать нельзя»), прямо
// оговорённое контрактом. Нарисовать ноль значило бы сказать арендатору
// обратное действительности: в этой установке не запрещено НИЧЕГО.
//
// Отсюда следует и то, чего здесь сделать НЕЛЬЗЯ без правки контракта: показать
// одно лишь занятое. «Занятое» живёт у владельца ресурса и остаётся, но выдать
// его без предела нечем — предел не пропустишь. Это отдельный предмет и
// отдельное решение о контракте, а не умолчание этой функции.
//
// # Код
//
// `FAILED_PRECONDITION` — тот же, что у соседней полосы «величины не назначены»
// (`notStated`): вопрос арендатора корректен, а состояние установки не
// позволяет на него ответить. Полосы различаются машинным признаком, а не кодом:
// клиент ключуется на признак, потому что тон сообщений — часть контракта и
// меняется осознанно.
//
// # Что говорит проза
//
// Она обязана восстанавливать следующий шаг, а следующий шаг здесь —
// БЕЗДЕЙСТВИЕ: потолков нет, и ни одна мутация по количеству отвергнута не
// будет. Отказ, сказавший только «не могу ответить», отправил бы арендатора в
// поддержку за пределом, которого в этой установке не бывает.
func (p Posture) Refusal() error {
	if !p.authorityAbsent {
		return nil
	}
	st := status.New(codes.FailedPrecondition,
		"resource count limits are not stated in this installation: no limit authority "+
			"is deployed, so no ceiling applies to any kind and no mutation is refused "+
			"for exceeding one")

	withDetails, derr := st.WithDetails(&errdetails.ErrorInfo{
		Reason: reasonQuotaAuthorityAbsent,
		Domain: p.serviceDomain + ".kacho.cloud",
	})
	if derr != nil {
		// Деталь не прикрепилась — код полосы важнее детали, отдаём его как есть.
		return st.Err()
	}
	return withDetails.Err()
}
