// dialect.go — шаг «открыть базу, дождаться её готовности и настроить goose под
// диалект», объявленный ОДИН раз на дерево.
//
// # Предмет: седьмое объявление одного шага, а не две формы
//
// Соседний preconditions.go свёл ту половину тракта, что базы не касается.
// Этот шаг базы касается — и потому ждал «проб на живой базе», названных
// предусловием в docs/architecture/migrator-form.md. Ждал он их семь объявлений
// подряд: три в обёртках `services/{vpc,iam,nlb}/internal/apps/migrator/
// postgres.go` (`openPgxDB`/`setupGoose`) и четыре встроенно в
// `services/{compute,geo,registry,storage}/cmd/migrator/main.go` (#1383).
//
// # Почему предусловие его НЕ покрывало
//
// Предусловие писалось про накат — про `goose.Up*`, отказ которого означает
// «сервис не разворачивается». Этот шаг цепочки НЕ применяет: он открывает
// соединение и ждёт готовности. Проверяется он одиночным контейнером
// (`opendb_integration_test.go`), а не поднятым стендом, — и мерка самого
// решения («часть тракта, проверяемая без стенда, выносится сразу») этим
// исполнена, а не обойдена.
//
// # Что расходилось, и в какую сторону
//
// Из трёх текстов отказа два были у двух форм разными, причём у прямой формы —
// беднее: `"open db: %w"` против `"open db (driver=%s): %w"` и
// `"goose dialect: %w"` против `"goose set dialect %q: %w"`. Оператор, читающий
// лог init-контейнера, узнавал имя драйвера и имя диалекта или не узнавал — в
// зависимости от того, какой сервис накатывает.
//
// Сведено к той редакции, что НАЗЫВАЕТ ЗНАЧЕНИЕ. Довод не в возрасте строки:
// `"goose dialect: %w"` не говорит даже, чтение это было или установка, а
// `"open db:"` не отличает опечатку в имени драйвера от опечатки в DSN. Более
// длинная строка здесь несёт больше, и стоит это ноль.
package migratorcli

import (
	"context"
	"database/sql"
	"fmt"
	"io/fs"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/stdlib"
	"github.com/pressly/goose/v3"

	"github.com/PRO-Robotech/corelib/dbready"
)

// DialectSpec — описательная метадата диалекта: имя для CLI, имя для goose и
// имя драйвера для sql.Open.
//
// Это НЕ runtime-поведение: применение цепочки живёт у вызывающего. Тип нужен,
// чтобы [OpenDB] и [SetupGoose] принимали три имени одним значением, а не
// тремя строками, которые легко переставить местами.
type DialectSpec struct {
	// Name — имя диалекта для CLI (`--dialect`).
	Name string
	// GooseDialect — строка, ожидаемая goose.SetDialect.
	GooseDialect string
	// SQLDriver — имя драйвера, которым открывается соединение.
	//
	// # Здесь стояло «общий пакет драйвер не тянет» — с #2544 это неверно
	//
	// Прежняя редакция объявляла выбор драйвера свойством бинаря: точка наката
	// регистрировала его blank-импортом, а общий шаг лишь называл имя. Держать
	// это дальше нельзя, и причина не в удобстве: доставка уведомлений сервера
	// живёт НА УРОВНЕ ДРАЙВЕРА (обработчик задаётся в конфигурации соединения
	// pgx, слой совместимости с `database/sql` его не выставляет вовсе). Шаг,
	// который драйвера не знает, доставить их не может — и не доставлял ни разу.
	//
	// Поэтому поле сменило роль: оно больше не выбирает драйвер, а ОБЪЯВЛЯЕТ
	// ожидаемый, и [OpenDB] на любом другом имени ОТКАЗЫВАЕТ. Это fail-closed, а
	// не педантизм: второй диалект, заведённый молча, применил бы цепочку и
	// выбросил каждое сказанное сервером слово — тот же дефект, только уже
	// объяснённый в коде.
	//
	// Blank-импорты `_ "github.com/jackc/pgx/v5/stdlib"` в семи точках наката
	// после этого несущими быть перестали (драйвер тянет сам общий пакет), но
	// сняты НЕ БУДУТ: `services/iam` — отдельный Go-модуль, пиненный на прежнюю
	// ревизию платформы, и снятие импорта там сломало бы сборку до бампа пина.
	// Шесть из семи без седьмого — расхождение, а не уборка.
	SQLDriver string
}

// driverPgx — единственный драйвер, через который эта платформа говорит с
// Postgres. Объявлен один раз: [SpecPostgres] берёт имя отсюда, [OpenDB] сверяет
// с ним же, и две редакции одного имени завестись негде.
const driverPgx = "pgx"

// SpecPostgres — метадата единственного поддерживаемого диалекта. Продукт
// Postgres-only, поэтому второй диалект заводится прямой веткой, когда станет
// реальным требованием, — без registry-таблицы под единственный элемент
// (non-negotiable #11).
//
// Name берётся из [DialectPostgres], а не пишется литералом: имя диалекта уже
// объявлено там и печатается в помощи и в отказе разбора. Две редакции одного
// имени разошлись бы молча.
var SpecPostgres = DialectSpec{
	Name:         DialectPostgres,
	GooseDialect: DialectPostgres,
	SQLDriver:    driverPgx,
}

// ResolveDialectSpec возвращает метадату диалекта по имени, названному
// оператором. Поддерживается один — [DialectPostgres]; любое другое имя даёт
// отказ, называющий поддерживаемое.
//
// # Пустое имя ОТВЕРГАЕТСЯ, и это решение
//
// Фабрик диалекта было три, и они разошлись: две отвергали пустое имя, третья
// принимала его как умолчание (`case "", …`) — живая строка ведомости различий
// `dialect-empty-accepted` (#1383). Различие снято в пользу отказа, потому что
// умолчание подставляет РАЗБОР аргументов ([Parse] и флаг cobra), и до сюда
// пустая строка доезжает только как явное `--dialect ""` — то есть как
// названный и неподдерживаемый диалект, а не как несказанный.
//
// Текст отказа тот же, каким его печатает [Parse]: две редакции одной строки
// разошлись бы молча, и один и тот же вход отвечал бы оператору по-разному в
// зависимости от того, где его перехватили.
func ResolveDialectSpec(name string) (DialectSpec, error) {
	if name != DialectPostgres {
		return DialectSpec{}, fmt.Errorf("unknown dialect %q (supported: %s)", name, DialectPostgres)
	}
	return SpecPostgres, nil
}

// OpenDB открывает соединение, ПРОВЯЗЫВАЕТ доставку уведомлений сервера и
// ДОЖИДАЕТСЯ готовности сервера.
//
// Барьер готовности — не украшение и не повтор того, что делает открытие:
// открытие ЛЕНИВО и до сервера не дозванивается, поэтому гонка init-контейнера с
// подом Postgres проявлялась не здесь, а на первой операции goose — мигратор
// падал отказом и уходил в CrashLoopBackOff до подъёма PG.
//
// Ждём ТОЛЬКО «база не принимает соединения» и ТОЛЬКО в пределах бюджета;
// неверный пароль, несуществующая база и негодный DSN падают сразу, а не
// проедают бюджет ожидания.
//
// На отказе соединение закрывается здесь: вызывающий получает ошибку и nil, и
// закрывать ему нечего.
//
// # notices — ОБЯЗАТЕЛЬНЫЙ параметр, и это построение, а не строгость
//
// Уведомления сервера (`RAISE NOTICE` / `RAISE WARNING` внутри миграции)
// доставляются только при заданном обработчике; незаданный роняет их молча и
// полностью. Приёмник поэтому не умолчание и не ручка, а параметр: забыть его
// нельзя — компилятор не даст, — а `nil` отвергается, потому что «доставка в
// никуда» и есть тот дефект, ради которого параметр заведён (#2544).
//
// # Почему [stdlib.OpenDB], а не регистрация имени соединения
//
// Обработчик живёт в конфигурации соединения pgx, поэтому открывать надо ЧЕРЕЗ
// неё. Форм две, и вторая отвергнута замером её цены, а не вкусом:
// `stdlib.RegisterConnConfig` кладёт конфигурацию в ПАКЕТНУЮ карту и возвращает
// имя для `sql.Open`, а снять запись нельзя, пока жив `*sql.DB` (пул резолвит имя
// на каждом новом соединении). У экспортируемой функции общего пакета это
// означало бы глобальное состояние, растущее с каждым вызовом, и договор об
// уборке, который вызывающий выполнить не может. `stdlib.OpenDB` собирает
// коннектор напрямую: ни карты, ни имени, ни уборки.
func OpenDB(ctx context.Context, dsn string, spec DialectSpec, notices *NoticeRelay) (*sql.DB, error) {
	if notices == nil {
		return nil, fmt.Errorf("open db (driver=%s): no notice relay given — a connection "+
			"without one drops every NOTICE and WARNING the migrations raise", spec.SQLDriver)
	}
	// Драйвер сверяется ДО разбора DSN: разбор — pgx-специфичный, и гнать через
	// него строку, предназначенную другому драйверу, значило бы отвечать про
	// синтаксис там, где неверен выбор.
	if spec.SQLDriver != driverPgx {
		return nil, fmt.Errorf("open db (driver=%s): notices are delivered through %q only; "+
			"another driver would apply the chain and drop everything the server says",
			spec.SQLDriver, driverPgx)
	}

	cfg, err := pgx.ParseConfig(dsn)
	if err != nil {
		// Тот же текст, что у прочих отказов открытия: для оператора это одна и
		// та же беда — соединение не открылось, — и две редакции одного отказа
		// были бы двумя разными строками для того, кто их разбирает.
		return nil, fmt.Errorf("open db (driver=%s): %w", spec.SQLDriver, err)
	}
	cfg.OnNotice = notices.Handler()

	// Порог, которым СЕРВЕР решает, отдавать ли уведомление, возвращается перед
	// каждой миграцией: обработчик выше бесполезен на сообщении, которого сервер
	// не отправил вовсе. Почему возврат стоит именно здесь, почему `RESET`, а не
	// подстановка величины, и почему параметр один — noticethreshold.go (#2560).
	db := stdlib.OpenDB(*cfg, stdlib.OptionResetSession(resetNoticeThreshold))
	if err := dbready.Wait(ctx, db, dbready.Options{}); err != nil {
		_ = db.Close()
		// Текст нейтральный: сюда приходит И «не дождались» (ошибка уже несёт
		// бюджет), И настоящая ошибка (пароль/DSN/база) — второй случай называть
		// «not ready» было бы враньём в логе.
		return nil, fmt.Errorf("database connection check failed: %w", err)
	}
	return db, nil
}

// SetupGoose наводит goose на набор миграций и на диалект.
//
// Обе операции пакетно-глобальны у самого goose, поэтому параллельный накат
// разными диалектами из одного процесса не поддерживается. CLI гоняет одну
// команду за раз — это и есть та посадка, под которую шаг написан.
func SetupGoose(fsys fs.FS, spec DialectSpec) error {
	goose.SetBaseFS(fsys)
	if err := goose.SetDialect(spec.GooseDialect); err != nil {
		return fmt.Errorf("goose set dialect %q: %w", spec.GooseDialect, err)
	}
	return nil
}
