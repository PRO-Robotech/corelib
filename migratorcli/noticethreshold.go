// noticethreshold.go — порог, которым СЕРВЕР решает, отдавать ли уведомление,
// возвращается перед каждой миграцией.
//
// # Предмет: второй слой той же потери, и обработчик его НЕ закрывает
//
// Соседний notice.go закрыл клиентскую половину: без заданного обработчика
// библиотека роняет каждое уведомление молча (#2544). Половина серверная
// осталась открытой, и она сильнее: сообщение, не прошедшее порог
// `client_min_messages`, сервер НЕ ОТПРАВЛЯЕТ вовсе — обработчику нечего
// доставлять, сколь бы верно он ни стоял.
//
// Производитель в дереве есть, назван координатой и один:
// `services/iam/internal/migrations/0001_initial.sql` объявляет
// `SET client_min_messages = warning`. `SET` без `LOCAL` переживает фиксацию
// своей транзакции и держится ДО КОНЦА СЕССИИ, а цепочку применяет одна
// сессия — значит всякое `RAISE NOTICE` каждой ПОСЛЕДУЮЩЕЙ миграции гаснет на
// сервере (#2560).
//
// # Почему это чинится в тракте, а не в миграции
//
// Свод применён, а применённую миграцию править запрещено (ban #5). Остаётся
// соединение: оно обязано вернуть себе порог, допускающий уведомление.
//
// # Точка возврата выбрана ЗАМЕРОМ устройства goose, а не наугад
//
// Легаси-путь goose применяет КАЖДУЮ миграцию отдельным `m.UpContext(ctx, db)`,
// то есть отдельным `db.BeginTx` (`up.go`, цикл `migrationsToApply`). Между
// миграциями соединение возвращается в пул, а `database/sql` зовёт
// `ResetSession` при следующей выдаче — там и стоит возврат. Провайдерный путь
// goose держит ОДНО соединение на весь прогон (`provider_run.go`, `initialize`
// → `db.Conn`), и на нём этот возврат не сработал бы: место возврата есть
// свойство того, как цепочку применяют, а не общая истина.
//
// # `RESET`, а не `SET … = notice`
//
// `RESET` возвращает величину, с которой соединение НАЧАЛОСЬ, — то есть выбор
// оператора (параметры DSN, настройка сервера, роль, база). Подстановка
// `notice` перебила бы оператора, который порог поднял НАМЕРЕННО, и накат стал
// бы решать за него.
//
// # Возвращается ОДИН параметр, а не `RESET ALL`
//
// Тот же свод объявляет `SET search_path TO kaname, public`, и последующие
// миграции на него опираются. `RESET ALL` снял бы и его — то есть починка
// диагностики сломала бы сам накат.
//
// # Отказ возврата — НЕ «продолжим молча»
//
// `database/sql` выбрасывает всякую ошибку `ResetSession`, кроме
// [driver.ErrBadConn], и продолжает на том же соединении: вернуть ошибку как
// есть значило бы продолжить с заглушённой сессией и не сказать об этом. Ответ
// [driver.ErrBadConn] заставляет пул выбросить соединение и открыть новое, а
// новое начинается с порога оператора BY CONSTRUCTION — то есть отказ возврата
// чинит сам себя, а не проглатывается.
package migratorcli

import (
	"context"
	"database/sql/driver"
	"fmt"

	"github.com/jackc/pgx/v5"
)

// noticeThresholdParam — единственный параметр сессии, который накат возвращает
// себе. Объявлен один раз: возврат и его проба сверяются с ним же, и две
// редакции одного имени завестись негде.
const noticeThresholdParam = "client_min_messages"

// resetNoticeThreshold возвращает соединению порог уведомлений перед тем, как
// пул отдаст его следующей миграции.
//
// Подпись задана [github.com/jackc/pgx/v5/stdlib.OptionResetSession]; отсюда
// параметры, а не выбор автора.
func resetNoticeThreshold(ctx context.Context, conn *pgx.Conn) error {
	if _, err := conn.Exec(ctx, "RESET "+noticeThresholdParam); err != nil {
		// Причина названа в тексте, а класс — обёрткой: `errors.Is` ищет
		// именно [driver.ErrBadConn], и без обёртки пул оставил бы себе
		// соединение с заглушённой сессией.
		return fmt.Errorf("reset %s (%v): %w", noticeThresholdParam, err, driver.ErrBadConn)
	}
	return nil
}
