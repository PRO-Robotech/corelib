// notice.go — то, что сервер СКАЗАЛ во время наката, доезжает до оператора.
//
// # Предмет: возможность объявлена и неисполнима
//
// Миграция вправе объявить наблюдаемым то, чего оператор не увидит ни при каком
// вводе. Уведомление сервера библиотека отдаёт клиенту ТОЛЬКО при заданном
// обработчике: ветка выдачи в pgx читает непустой `OnNotice`, а слой
// совместимости с `database/sql` его не задаёт вовсе. Значит накат, открывающий
// соединение простым `sql.Open`, терял КАЖДОЕ уведомление — молча, полностью и
// всегда.
//
// # Производитель НЕ ТОЛЬКО `RAISE`, и это выяснилось замером
//
// Первая редакция этого файла считала производителями операторы `RAISE NOTICE` /
// `RAISE WARNING` в миграциях — их в дереве 18 файлов, самый разговорчивый несёт
// пять. Предикат был слеп к самой многочисленной форме: уведомление поднимает и
// САМ Postgres — на `DROP … IF EXISTS`, `CREATE … IF NOT EXISTS` и подобных
// («constraint … does not exist, skipping»). Опровергла посылку не проверка
// текста, а прогон: цепочка, выбранная как заведомо молчаливая, доставила два.
//
// Цена не в потерянной строке, а в том, что «сказали оператору» становится
// неотличимо от «промолчали». Ближайший пример в дереве поимённо называет
// величины, перестающие действовать, и печатает перепись — чтобы «ноль
// перенесённого» было отличимо от «ничего не осмотрено». На штатном накате
// оператор не получал ни одного из этих сообщений (#2544).
//
// # Перепись печатается ВСЕГДА, и это несущее свойство
//
// Клиент не знает, сколько уведомлений сервер ПОДНЯЛ, — он знает лишь, сколько
// ему ДОСТАВИЛИ. Поэтому «ноль доставленных» само по себе не различает две вещи:
// цепочка ничего не сказала или её никто не слушал. Различает их сама перепись:
// строка в выводе доказывает, что обработчик стоял и был позван. Без неё правка
// выглядела бы исполненной ровно так же, как её отсутствие.
//
// # Предел объявлен и назван числом
//
// Один `RAISE` внутри цикла даёт столько сообщений, сколько строк в выборке, и
// вывод init-контейнера перестаёт читаться. Поэтому доставка ограничена сверху, а
// отброшенное СЧИТАЕТСЯ и попадает в перепись: подавление, о котором сказано, —
// не то же, что подавление молчком.
package migratorcli

import (
	"fmt"
	"io"
	"strings"
	"sync"

	"github.com/jackc/pgx/v5/pgconn"
)

// NoticeLimit — сколько уведомлений доставляется дословно за один накат.
//
// Число выбрано замером, а не ощущением, и обе величины замера названы рядом.
//
// ВЕРХНЯЯ ГРАНИЦА ПО ДЕРЕВУ — сколько операторов цепочки ВООБЩЕ способны поднять
// уведомление (`RAISE NOTICE|WARNING|INFO|LOG` плюс `IF EXISTS` / `IF NOT
// EXISTS`, на которых говорит сам сервер). Предикат:
//
//	for d in services/*/internal/migrations; do
//	  git ls-files "$d/*.sql" | xargs grep -oiE 'RAISE (NOTICE|WARNING|INFO|LOG)|IF (NOT )?EXISTS' | wc -l
//	done
//
// Разброс — от 29 (iam) до 332 (vpc); это ПОТОЛОК, а не факт: оператор `IF
// EXISTS`, которому нечего пропускать, молчит.
//
// ФАКТ НА ПУСТОЙ БАЗЕ — сколько доставлено настоящим накатом настоящего бинаря:
// vpc 42 · nlb 9 · compute 8 · registry 8 · storage 6 · geo 2. Числа сняты
// пробами `internal/migratorapply/notice_integration_test.go`, и они печатают
// перепись на КАЖДОМ прогоне — помнить эти значения не надо, их видно. Седьмой
// точки (iam) здесь нет намеренно: её модуль тянет платформу пином, и до бампа
// доставки там не будет вовсе.
//
// 500 стоит ВЫШЕ потолка самой длинной цепочки, то есть ни одна цепочка
// сегодняшнего дерева его не тронет. Заведён он ради единственного случая,
// которого статический счёт не видит вовсе: `RAISE` внутри цикла даёт сообщение
// на строку выборки, и его число не ограничено ничем.
//
// Ручкой предел НЕ настраивается намеренно: ручка без умолчания завела бы вопрос
// «сколько», на который у оператора нет данных, а ручка с умолчанием — второе
// место, где это число живёт.
const NoticeLimit = 500

// NoticeRelay доставляет оператору то, что сервер сказал во время наката, и
// ведёт счёт доставленному и отброшенному.
//
// Один экземпляр на одно открытое соединение: обработчик зовётся из горутин
// пула, поэтому счёт и запись идут под замком.
type NoticeRelay struct {
	service string
	out     io.Writer

	mu         sync.Mutex
	delivered  int
	suppressed int
	saidLimit  bool
}

// NewNoticeRelay заводит доставку уведомлений службы service в out.
//
// service — чей накат: вывод init-контейнеров нескольких служб читается вместе,
// и строка, не называющая себя, адресована никому. out обязателен: доставка
// «в никуда» и есть то состояние, ради которого этот файл заведён.
func NewNoticeRelay(service string, out io.Writer) *NoticeRelay {
	return &NoticeRelay{service: service, out: out}
}

// Handler — обработчик для pgx. Отдаётся значением, потому что библиотека
// требует функцию, а не интерфейс.
func (r *NoticeRelay) Handler() func(*pgconn.PgConn, *pgconn.Notice) {
	return func(_ *pgconn.PgConn, n *pgconn.Notice) { r.deliver(n) }
}

// deliver печатает одно уведомление либо считает его отброшенным.
func (r *NoticeRelay) deliver(n *pgconn.Notice) {
	if n == nil {
		return
	}
	r.mu.Lock()
	defer r.mu.Unlock()

	if r.delivered >= NoticeLimit {
		r.suppressed++
		if !r.saidLimit {
			r.saidLimit = true
			_, _ = fmt.Fprintf(r.out,
				"%s %s: limit %d reached — further notices are counted, not printed\n",
				noticeCensusPrefix, r.service, NoticeLimit)
		}
		return
	}
	r.delivered++
	_, _ = io.WriteString(r.out, formatNotice(n))
}

// Delivered / Suppressed — обе половины счёта. Порознь ни одна ничего не значит:
// «доставлено 3» без второго числа не говорит, было ли отброшено что-нибудь.
func (r *NoticeRelay) Delivered() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.delivered
}

func (r *NoticeRelay) Suppressed() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.suppressed
}

// noticeCensusPrefix — начало всякой строки этого файла в выводе. Одна константа,
// потому что по ней читатель отделяет сказанное сервером от сказанного накатом.
const noticeCensusPrefix = "migration-notices"

// Summary — перепись одной строкой: сколько доставлено, сколько отброшено и каков
// предел.
//
// На нуле строка договаривает то, чего числа сказать не могут: обработчик стоял.
// Без этого хвоста «0 delivered» читалось бы как состояние ДО правки, когда
// обработчика не было вовсе, — то есть перепись подтверждала бы ровно тот дефект,
// который она заведена наблюдать.
//
// # Хвост НЕ утверждает, что цепочка молчала, — он этого не знает
//
// Прежняя редакция говорила «and the chain raised nothing». Клиент такого факта
// не имеет: сообщение, не прошедшее порог `client_min_messages`, сервер не
// отправляет вовсе, и приёмнику оно неотличимо от несказанного. Наблюдалось
// дословно: цепочка, поднявшая уведомление после `SET client_min_messages =
// warning`, дала перепись «0 delivered … the chain raised nothing» — то есть
// утверждение о цепочке, сделанное вместо утверждения о доставке (#2560).
//
// Поэтому хвост называет ОБА условия нуля: обработчик стоял, а порог сессии
// ничего выше себя не пропустил. Возврат порога живёт в noticethreshold.go и
// делает первый случай штатным, но не отменяет второго: порог вправе поднять сам
// оператор.
func (r *NoticeRelay) Summary() string {
	r.mu.Lock()
	defer r.mu.Unlock()

	line := fmt.Sprintf("%s %s: %d delivered, %d suppressed, limit %d",
		noticeCensusPrefix, r.service, r.delivered, r.suppressed, NoticeLimit)
	if r.delivered == 0 && r.suppressed == 0 {
		line += " — the handler was installed; nothing above the session notice threshold reached it"
	}
	return line
}

// WriteCensus печатает перепись туда же, куда шли сами уведомления.
//
// Назначение НЕ параметр: перепись и то, что она считает, — один отчёт, и
// разведённые по разным потокам половины читались бы как два разных.
func (r *NoticeRelay) WriteCensus() {
	_, _ = fmt.Fprintf(r.out, "%s\n", r.Summary())
}

// formatNotice — как уведомление выглядит для оператора.
//
// Форма взята у psql (`УРОВЕНЬ: текст`, подробности отдельными строками с
// отступом): её оператор узнаёт с первого взгляда, а собственная форма требовала
// бы объяснения там, где объяснять некому — в логе init-контейнера в три часа ночи.
//
// Уровень берётся НЕЛОКАЛИЗОВАННЫЙ, когда сервер его прислал: `Severity`
// переводится сервером по `lc_messages`, поэтому на локали, отличной от
// английской, отбор по слову `WARNING` перестал бы находить предупреждения молча.
func formatNotice(n *pgconn.Notice) string {
	severity := n.SeverityUnlocalized
	if severity == "" {
		severity = n.Severity
	}
	if severity == "" {
		severity = "NOTICE"
	}

	var b strings.Builder
	fmt.Fprintf(&b, "%s: %s\n", severity, n.Message)
	if n.Detail != "" {
		fmt.Fprintf(&b, "  DETAIL: %s\n", n.Detail)
	}
	if n.Hint != "" {
		fmt.Fprintf(&b, "  HINT: %s\n", n.Hint)
	}
	return b.String()
}
