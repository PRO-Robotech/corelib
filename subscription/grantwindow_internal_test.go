// Предмет файла — ПЕРЕХОДЫ окна материализации гранта (`grant.go`), взятые
// отдельно от базы и транспорта.
//
// Отдельно потому, что предмет здесь — таблица исходов, а не путь события:
// поднимать контейнер ради утверждения о трёх ветвях `if` значило бы платить
// минутой за то, что доказывается микросекундой, и заодно сделать невоспроизводимым
// главный подслучай — истечение окна, которое иначе пришлось бы ЖДАТЬ по часам.

// clockAt — управляемые часы: окно измеряется временем, и проба обязана двигать
// его сама.
type clockAt struct{ t time.Time }

func (c *clockAt) now() time.Time { return c.t }
func (c *clockAt) add(d time.Duration) time.Time {
	c.t = c.t.Add(d)
	return c.t
}

func newClock() *clockAt { return &clockAt{t: time.Unix(1_700_000_000, 0)} }

// TestLiveRowIsHeldUntilItsWindowIsSpent — несущий переход: живая строка
// удерживается, пока окно не истрачено, и снимается ровно по его истечении.
func TestLiveRowIsHeldUntilItsWindowIsSpent(t *testing.T) {
	c := newClock()
	d := &delivery{}

	if !d.holds(100, true, c.now()) {
		t.Fatal("живая строка не удержана: без удержания она уезжает под курсор навсегда")
	}
	if !d.holds(100, true, c.add(GrantSettlingWindow-time.Millisecond)) {
		t.Fatal("удержание снято ДО истечения окна: отсрочка короче того, чего ждёт")
	}
	if d.holds(100, true, c.add(2*time.Millisecond)) {
		t.Fatal("удержание пережило своё окно: строка, которую не разрешат никогда, " +
			"держала бы партию вечно")
	}
	// Снятое удержание не воскресает тем же проходом: иначе окно отсчитывалось бы
	// заново с каждой партией и не истекало бы никогда.
	if d.heldSince.IsZero() != true {
		t.Fatal("удержание не снято после истечения окна")
	}
}

// TestWindowIsSpentOncePerBatchNotPerRow — партия простаивает окно ОДИН раз.
//
// Каждый проход перечитывает ТО ЖЕ окно журнала и спрашивает модель о тех же
// строках, поэтому к моменту истечения окно простояли все невидимые строки
// партии, а не одна первая. Отсчитывай сервер окно на каждую строку — партия из
// ста невидимых стоила бы сто окон.
func TestWindowIsSpentOncePerBatchNotPerRow(t *testing.T) {
	c := newClock()
	d := &delivery{}

	d.holds(100, true, c.now())
	if d.holds(100, true, c.add(GrantSettlingWindow)) {
		t.Fatal("окно не истекло")
	}
	// Курсор ушёл за всю партию — следующая невидимая строка берёт СВОЁ окно, а
	// не доедает чужое.
	if !d.holds(200, true, c.now()) {
		t.Fatal("следующая партия не получила своего окна")
	}
}

// TestCatchUpBatchIsNotHeld — ДОГОНЯЮЩАЯ партия не удерживается.
//
// Её строки устоялись раньше, чем поток начал проход: грант по ним либо давно
// лежит, либо не ляжет вовсе. Удерживать их значило бы платить окном за каждую
// сотню строк истории — то есть наказывать подписчика за то, что он
// возобновился со старой позиции.
func TestCatchUpBatchIsNotHeld(t *testing.T) {
	c := newClock()
	d := &delivery{}

	if d.holds(100, false, c.now()) {
		t.Fatal("догоняющая партия удержана: подписчик со старой позицией платил бы " +
			"окном за каждую сотню строк")
	}
	// Тот же вход, изменён ОДИН факт — партия дошла до головы журнала.
	if !d.holds(100, true, c.now()) {
		t.Fatal("партия у головы журнала не удержана")
	}
}

// TestHeadReachedEarlierStillHolds — всплеск больше партии на голове журнала.
//
// Строки, пришедшие разом, дают ПОЛНУЮ партию, которая головы не достигает, — и
// по одному лишь признаку «дошла до головы» осталась бы без отсрочки, хотя все
// её строки живые. Признак [delivery.atHead] отвечает на «была ли эта строка
// живой», и без него всплеск возвращал бы ровно ту потерю, ради которой окно
// заведено.
func TestHeadReachedEarlierStillHolds(t *testing.T) {
	c := newClock()
	d := &delivery{atHead: true}

	if !d.holds(100, false, c.now()) {
		t.Fatal("всплеск на голове журнала остался без отсрочки")
	}
}

// TestHoldTakenOnAnotherCursorIsReleased — удержание принадлежит СВОЕМУ курсору.
//
// Курсор ушёл вперёд (строка стала видимой либо партия отдана), значит прежнее
// удержание больше ни к чему не относится. Оставь его — и окно следующей
// невидимой строки отсчитывалось бы от чужого мига, то есть иногда истекало бы
// в тот же проход, в котором взято.
func TestHoldTakenOnAnotherCursorIsReleased(t *testing.T) {
	c := newClock()
	d := &delivery{}

	d.holds(100, true, c.now())
	d.released(140)
	if !d.heldSince.IsZero() {
		t.Fatal("удержание пережило свой курсор")
	}
	// Контроль: удержание на СВОЁМ курсоре снятию не подлежит.
	d.holds(140, true, c.now())
	d.released(140)
	if d.heldSince.IsZero() {
		t.Fatal("снято удержание, стоящее на своём курсоре: окно не отсчиталось бы никогда")
	}
}
