// retention.go — УБОРКА ЖУРНАЛА ПОДПИСКИ: предикат и его пороги.
//
// Предмет — задача продукта #1666. Журнал подписки заведён у пяти владельцев
// (`polyrepo.md` §runtime-edges), строка в него пишется НА КАЖДОЙ мутации
// ресурса, а снятия строк не было ни на одном пути ни у одного из них: рост
// монотонный и вечный, темп задаёт арендатор.
//
// Петля, партии, потолок проходов и наблюдаемость живут в `pkg/retention` и
// здесь не повторяются. Здесь — только ПРЕДИКАТ и его пороги, потому что
// предикат есть свойство ЭТОЙ семьи таблиц: у журнала подписки нет признака
// доставки, его читают КУРСОРОМ ПО ПОЗИЦИИ, и порог выводится из того, что
// обещано подписчику, а не из того, что кем-то применено.
//
// # ПОЧЕМУ ПРЕДИКАТ ЗДЕСЬ, А НЕ У КАЖДОГО ВЛАДЕЛЬЦА
//
// `pkg/retention` разводит петлю и предикат ровно потому, что предикат — свойство
// СХЕМЫ: у операций признак `done`, у очереди дренажа `sent_at`. У пяти журналов
// подписки схема одна и та же по существу — возрастающая позиция плюс отметка
// времени, — и объявлена она уже: `Storage.PositionColumn` и `Storage.AgeColumn`.
// Пять копий одного оператора разошлись бы молча и дали бы РАЗНЫЙ срок жизни
// события у разных доменов при ОДНОМ контракте подписки.
//
// # ЦЕНА РЕШЕНИЯ, НАЗВАННАЯ ВСЛУХ
//
// Имя таблицы приезжает сюда значением (`Storage.Table`), поэтому текста имени в
// исходнике НЕТ, и гейт роста (`internal/repohygiene`
// TestLiveTablesNameTheirGrowthLimit) этот оператор снятия у себя не резолвит —
// он уходит в НАЗВАННУЮ САМИМ ГЕЙТОМ слепую зону `RemovalsUnresolved`. Следствие
// обязано быть записано, а не умолчано: у журнала подписки остаётся запись
// реестра роста, и её вердикт — «предел» с причиной, называющей этот уборщик.
//
// Обратный размен рассматривался и отвергнут: чтобы гейт видел имя, оператор
// пришлось бы написать ПЯТЬ раз, по разу у каждого владельца, различая их одним
// токеном — именем таблицы. Это тот самый разъезд, ради устранения которого
// заведён `pkg/retention`. Взамен машинную сторону закрывает ДРУГОЙ гейт —
// `TestSubscriptionJournalLanesAgreeOnRetention`: он сверяет полосы попарно и
// требует, чтобы объявленное удержание и провязанный уборщик были ОДНИМ решением.
package subscription

import (
	"context"
	"fmt"
	"log/slog"
	"strings"
	"time"

	"github.com/jackc/pgx/v5/pgconn"

	"github.com/PRO-Robotech/corelib/retention"
)

// JournalRetention — сколько событие остаётся возобновимым.
//
// # ВЕЛИЧИНА ВЫВЕДЕНА ИЗ ЧИТАТЕЛЯ, а не назначена числом
//
// Читатель журнала подписки — ПОДПИСЧИК, возобновляющийся с сохранённой позиции.
// Его предикат: «моя позиция ещё выше нижней возобновимой». Значит порог есть
// ответ на вопрос «сколько подписчику позволено отсутствовать, не перечитывая
// каталог целиком».
//
// Снизу его ограничивает не поток запросов, а НЕРАБОЧЕЕ ВРЕМЯ потребителя:
// потребитель, упавший вечером пятницы, поднимается утром понедельника, и порог
// короче двух суток делает возобновление невозможным by construction. Недельный
// запас покрывает это вместе с отпускной подменой у оператора потребителя.
//
// # ПОЧЕМУ ТА ЖЕ ВЕЛИЧИНА, ЧТО У ТАБЛИЦЫ ОПЕРАЦИЙ, И ПОЧЕМУ ОНА НЕ ПЕРЕИСПОЛЬЗУЕТСЯ
//
// `pkg/operations.OperationRetention` выведена из ДРУГОГО читателя (оператор,
// разбирающий отказавшую мутацию) и совпала числом. Совпадение чисел не есть
// один предмет: связать их константой значило бы, что сдвиг срока разбора
// отказов двигает срок возобновления подписки. Величины объявляются порознь, и
// каждая — рядом со своим читателем.
//
// # У ПОРОГА НЕТ СЛАГАЕМОГО НА РАЗНИЦУ ЧАСОВ, и это замер, а не упущение
//
// У таблицы операций такое слагаемое есть (`pkg/operations.ClockDrift`): её
// `modified_at` пишется часами ПРОЦЕССА, а уборка судит часами БАЗЫ, и разница
// источников входит в порог отдельно. Здесь источник ОДИН: отметка времени
// строки журнала ставится умолчанием колонки (`DEFAULT now()`), то есть теми же
// часами базы, которыми судит оператор ниже. Слагаемое, покрывающее разницу,
// которой нет, было бы запасом без предмета.
//
// Это утверждение о СХЕМЕ ВЛАДЕЛЬЦА, а не о коде здесь, поэтому его держит гейт
// `TestSubscriptionJournalLanesAgreeOnRetention`: у чистящей полосы колонка
// срока обязана быть объявлена с `DEFAULT now()` в миграции, заводящей таблицу.
//
// # ЧЕГО ВЕЛИЧИНА НЕ ОБЕЩАЕТ
//
// Журнал не становится историей ресурса. Подписчик, отсутствовавший дольше,
// получает ЯВНЫЙ отказ [codes.OutOfRange] с названной возобновимой позицией
// (см. `positionLost` в `server.go`) и перечитывает каталог — а не молча
// получает неполное. Молчаливое начало с ближайшего удержанного места клиент
// записал бы как «изменений не было».
const JournalRetention = 7 * 24 * time.Hour

// Execer — то, чем уборщик и спрашивает границу, и исполняет свой оператор.
//
// [Querier] ВЛОЖЕН, а не приставлен рядом вторым параметром: вызывающему нечего
// выбирать между двумя источниками, и провязать половину пары он не может.
//
// Одного снимка это НЕ даёт и не обязано: наблюдение и оператор идут разными
// запросами, а на пуле — вообще разными сессиями. Верхняя граница безопасна не
// снимком, а МОНОТОННОСТЬЮ: устоявшаяся позиция только растёт, поэтому величина,
// наблюдённая до оператора, к моменту его исполнения остаётся НИЖНЕЙ оценкой —
// снимется не больше, чем позволено, и в худшем случае меньше. Ошибка в эту
// сторону стоит одного лишнего прохода; в обратную — потерянного события.
type Execer interface {
	Querier
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
}

// journalSweepSQL — предикат уборки журнала подписки.
//
// ЧЕТЫРЕ РЕШЕНИЯ, каждое со своим доводом, и первое из них несущее.
//
//  1. СНИМАЕТСЯ ПРЕФИКС, а не «все старые строки». Нижняя возобновимая позиция
//     выводится подписчиком из САМОЙ РАННЕЙ удержанной строки
//     ([Watermark.floor]), и весь контракт возобновления держится инвариантом
//     «выше пола дыр нет». Уборка «по возрасту» этот инвариант ломает: отметка
//     времени ставится в НАЧАЛЕ транзакции, а номер выдаётся на ВСТАВКЕ,
//     поэтому строка с бо́льшим номером бывает старше строки с меньшим. Тогда
//     оператор снял бы верхнюю, оставив нижнюю, — пол не сдвинулся бы, а над ним
//     появилась дыра, и подписчик, законно допущенный по полу, потерял бы
//     событие МОЛЧА. Поэтому оператор находит ПЕРВУЮ строку, которую снимать
//     ещё нельзя, и снимает всё строго ниже неё.
//
//  2. ОКНО ГОЛОВЫ ограничено партией (`LIMIT $2`). Границу ищем не по всей
//     таблице, а по голове: у журнала голова и есть самое старое, поэтому один
//     проход индекса по первичному ключу длиной в партию отвечает на вопрос
//     целиком. Без окна `min`/`max` по условию возраста дали бы просмотр всех
//     подлежащих снятию строк на КАЖДУЮ партию, то есть квадрат от накопленного.
//
//  3. ВЕРХНЯЯ ГРАНИЦА — УСТОЯВШАЯСЯ ПОЗИЦИЯ (`$3`), а не край таблицы. Номер
//     выдаётся на вставке, видимость наступает на фиксации, и у этих пяти
//     журналов порядок номеров с порядком фиксаций НЕ связан ничем: консультативной
//     блокировки перед `nextval` в их триггерах нет (предикат:
//     `git grep -c pg_advisory_xact_lock` по их миграциям → 0). Значит строка с
//     меньшим номером вправе появиться ПОЗЖЕ уже снятой соседки — и появиться
//     НИЖЕ снятого участка, оставив дыру над полом. Ограничение устоявшейся
//     границей закрывает это by construction: ниже неё каждый номер либо уже
//     видим, либо не появится никогда.
//
//  4. КЛЕЙМА (`FOR UPDATE SKIP LOCKED`) здесь НЕТ, и это отличие от соседнего
//     уборщика (`pkg/operations`) намеренное, а не забытое. Пропуск запертой
//     строки ломает решение 1: вторая реплика сняла бы участок ВЫШЕ того, что
//     заперла первая, и откат первой оставил бы дыру. Реплики поэтому
//     сериализуются на замках строк обычным порядком; вторая ждёт конца партии
//     первой (один короткий оператор) и находит участок уже снятым — её `DELETE`
//     снимает ноль. Размен назван: «дыры не бывает» дороже, чем «не ждать».
const journalSweepSQL = `
WITH head AS (
    SELECT %[1]s AS pos, %[2]s AS aged
      FROM %[3]s
     WHERE %[1]s <= $3
     ORDER BY %[1]s
     LIMIT $2
), keep AS (
    SELECT min(pos) AS pos
      FROM head
     WHERE aged >= now() - make_interval(secs => $1)
), cut AS (
    SELECT CASE
             WHEN (SELECT pos FROM keep) IS NULL THEN (SELECT max(pos) FROM head)
             ELSE (SELECT max(pos) FROM head WHERE pos < (SELECT pos FROM keep))
           END AS pos
)
DELETE FROM %[3]s
 WHERE %[1]s <= (SELECT pos FROM cut)`

// JournalSweeper — уборщик журнала ОДНОГО владельца.
//
// Держит собственное наблюдение границы: уборка судит «что уже устоялось» ТЕМ ЖЕ
// механизмом, которым это судит читающий поток, а не своей копией правила.
type JournalSweeper struct {
	db   Execer
	wm   *Watermark
	stmt string
	name string
}

// NewJournalSweeper собирает уборщика по объявлению владельца.
//
// Отказывает на объявлении, при котором уборка невыразима: владелец, не
// назвавший чистку, уборщика не получает вовсе — иначе оператор снимал бы
// строки у журнала, чей контракт обещает подписчику, что отказ «позиция
// утрачена» не наступает никогда.
func NewJournalSweeper(db Execer, j Journal, log *slog.Logger) (*JournalSweeper, error) {
	if err := j.Validate(); err != nil {
		return nil, err
	}
	if j.Storage.Retention != RetainsFromEarliestRow {
		return nil, fmt.Errorf(
			"subscription: уборщик собран для журнала, объявившего RetainsEverything: "+
				"обещание «позиция не утрачивается никогда» и снятие строк — одно решение, "+
				"и половина его не выражается (%s)", j.Storage.Table)
	}
	return &JournalSweeper{
		db:   db,
		wm:   NewWatermark(j.Storage.Table, j.Storage.PositionColumn, log),
		stmt: fmt.Sprintf(journalSweepSQL, j.Storage.PositionColumn, j.Storage.AgeColumn, j.Storage.Table),
		name: subjectName(j.Storage.Table),
	}, nil
}

// Sweep — один проход партии.
//
// Момент времени входом НЕ приходит: часы уборки — базы, те же, что ставят отметку
// строки (см. [JournalRetention], §«У порога нет слагаемого на разницу часов»).
// Проверяемость от этого не теряется — проход зовётся методом
// (`retention.Sweeper.Pass`), поэтому пробе не приходится ни спать, ни подменять
// часы.
//
// Возвращает число снятых строк и признак «партия ушла полной»; признак отличает
// «убрал всё, что было» от «упёрся в партию».
func (s *JournalSweeper) Sweep(ctx context.Context, grace time.Duration, batch int) (int64, bool, error) {
	if err := s.wm.Advance(ctx, s.db); err != nil {
		return 0, false, fmt.Errorf("subscription: уборка журнала %s: граница устоявшегося не наблюдена: %w", s.name, err)
	}
	// ХОЛОДНЫЙ СТАРТ — не «убирать нечего»: граница ещё не подтверждена, и
	// верхнего предела у оператора нет. Снять что-либо в этом состоянии значило
	// бы снять по номеру, о видимости которого мы ничего не знаем. Fail-closed:
	// удержать лишнее дешевле, чем потерять непрочитанное.
	if !s.wm.Established() {
		return 0, false, nil
	}
	tag, err := s.db.Exec(ctx, s.stmt, grace.Seconds(), batch, s.wm.Settled())
	if err != nil {
		return 0, false, fmt.Errorf("subscription: уборка журнала %s: %w", s.name, err)
	}
	n := tag.RowsAffected()
	return n, n >= int64(batch), nil
}

// RetentionSubject — запись реестра уборки для журнала этого владельца.
//
// Порог собирается ЗДЕСЬ, а не у каждого из пяти владельцев: пять копий одного
// порога разошлись бы молча и дали бы разный срок возобновления у разных доменов
// при ОДНОМ контракте подписки.
func (s *JournalSweeper) RetentionSubject() retention.Subject {
	return retention.Subject{
		Name:  s.name,
		Grace: JournalRetention,
		Sweep: s.Sweep,
	}
}

// StartJournalRetentionSweep поднимает фоновую уборку журнала подписки.
//
// ОДНА строка в композиционном корне каждого владельца — намеренно: пять
// владельцев несут журнал одной формы с одним и тем же контрактом, и всё, что у
// них могло бы разойтись, собрано здесь.
//
// Отказывает, а не предупреждает: отказ означает негодные величины расписания
// либо объявление, при котором уборка невыразима, — то есть уборку, которая
// исполняется и не убирает ничего.
func StartJournalRetentionSweep(
	ctx context.Context,
	db Execer,
	j Journal,
	cfg retention.Config,
	log *slog.Logger,
) (*retention.Sweeper, error) {
	sw, err := NewJournalSweeper(db, j, log)
	if err != nil {
		return nil, err
	}
	sweeper, err := retention.New(cfg, []retention.Subject{sw.RetentionSubject()}, log)
	if err != nil {
		return nil, fmt.Errorf("уборка журнала подписки: %w", err)
	}
	sweeper.Start(ctx)
	return sweeper, nil
}

// subjectName — имя предмета уборки: имя таблицы БЕЗ схемы.
//
// Имя попадает в отчёт прохода и в метку метрики, и оператор обязан узнавать в
// нём таблицу. Схема отбрасывается затем, чтобы у одного владельца имя предмета
// читалось так же, как у соседа, объявившего таблицу без схемы.
func subjectName(table string) string {
	if i := strings.LastIndex(table, "."); i >= 0 {
		return table[i+1:]
	}
	return table
}
