// Journal — ВСЁ, что владелец приносит, подключаясь к общему серверу потока:
// где журнал лежит, каким каналом он будит, и как его строка становится
// событием общей формы.
//
// Трёх объявлений достаточно, и это ПРЕДИКАТ КАЧЕСТВА ОБОБЩЕНИЯ, а не
// эстетика: всё, чего здесь нет — курсор, горизонт устоявшегося, пределы,
// сужение по правам, порядок отказов, — есть механизм СЕРВЕРА. Появись у
// владельца возможность принести своё вместо любого из них, механизм перестал
// бы быть общим, оставшись общим по имени.
//
// Владелец объявляет ЗНАЧЕНИЯ. Ни одного поля функционального типа, кроме
// отображения строки, здесь нет намеренно: восьмой владелец, желающий свой
// порядок отказов или свой курсор, не «нарушит правило» — ему не на чем его
// записать.
type Journal struct {
	// Storage — где журнал лежит и чем он удерживается.
	Storage Storage

	// Channel — имя канала `LISTEN`, на который пишет триггер журнала.
	//
	// Он назван ОТДЕЛЬНО от таблицы, а не выведен из её имени: у трёх владельцев
	// из четырёх они совпадают, у четвёртого таблица схемо-квалифицирована, а
	// канал — нет. Вывод одного из другого работал бы у большинства и молча
	// ошибался у меньшинства — то есть ровно там, где ошибку не ищут.
	Channel string

	// Mapping — отображение строки журнала в событие общей формы.
	Mapping Mapping
}

// Storage — координаты журнала и объявленные свойства его формы.
//
// Имена колонок стоят здесь, а не выводятся из «стандартной схемы», потому что
// стандартной схемы НЕТ: перепись четырёх ресурсных журналов дерева дала ТРИ
// разные формы — у одного вид предмета зовётся `resource_type`, а род изменения
// `action`; у остальных — `resource_kind` и `event_type`. Разнобой форм хранения
// дефектом не является: единой объявлена форма ПОДПИСКИ, а не форма журнала.
type Storage struct {
	// Table — таблица журнала, при необходимости со схемой (`kacho_vpc.vpc_outbox`).
	Table string

	// PositionColumn — колонка возрастающего номера (`bigint`), выдаваемого на
	// вставке. Номер НЕ есть позиция подписки: позицию производит сервер как
	// границу устоявшегося (см. `watermark.go`).
	PositionColumn string

	// KindColumn — колонка вида предмета.
	KindColumn string

	// IDColumn — колонка неизменяемого идентификатора предмета.
	IDColumn string

	// ChangeColumn — колонка рода изменения в словаре ВЛАДЕЛЬЦА.
	ChangeColumn string

	// PayloadColumn — колонка состояния предмета (`jsonb`), отдаваемая
	// отображению как есть.
	PayloadColumn string

	// ProjectColumn — колонка проектного якоря. Заполняется тогда и только
	// тогда, когда [Storage.Project] равен [ProjectInColumn].
	ProjectColumn string

	// Project — откуда берётся ПРОЕКТНЫЙ ЯКОРЬ. Ось якорная: по ней принимается
	// решение о показе, поэтому нулевое значение объявлением не является.
	Project ProjectDimension

	// Retention — что владелец обещает про удержание журнала.
	Retention Retention

	// AgeColumn — колонка отметки времени, по которой судится возраст строки.
	//
	// ПАРА к [Storage.Retention], а не независимое поле: заполняется тогда и
	// только тогда, когда объявлено [RetainsFromEarliestRow]. «Журнал чистится»
	// и «по чему судить возраст» — ОДНО решение, и половина его не выражается:
	// без колонки предикат уборки не построить вовсе, а колонка без чистки —
	// объявление, которого не читает никто (класс «принято-и-проигнорировано»,
	// `api-conventions.md`).
	//
	// Обе стороны отвергает [Journal.Validate]; уборщик, который эту колонку
	// читает, — `retention.go`.
	AgeColumn string
}

// ProjectDimension — откуда берётся проектный якорь события. Состояния ТРИ, и
// каждое названо: умолчания у якорной оси не бывает.
type ProjectDimension uint8

const (
	// ProjectDimensionUnset — владелец не сказал ничего. [Journal.Validate]
	// отвергает: «пусто» и «не применимо» здесь неразличимы, а решения по ним
	// противоположны.
	ProjectDimensionUnset ProjectDimension = iota

	// ProjectInColumn — якорь лежит колонкой, и ось отбирается запросом.
	ProjectInColumn

	// ProjectFromMapping — колонки нет, якорь даёт отображение. Ось отбирается
	// сервером ПОСЛЕ отображения строки — то есть по-прежнему СЕРВЕРОМ, а не
	// клиентом. Цена названа: прочитано будет больше, чем отдано.
	ProjectFromMapping

	// ProjectAbsent — у журнала проектного измерения НЕТ вовсе (предмет уровня
	// аккаунта или кластера). Подписка, назвавшая эту ось, ОТВЕРГАЕТСЯ: открыть
	// её значило бы отдать поток, который молчит навсегда.
	ProjectAbsent
)

// Retention — что владелец обещает про удержание журнала. Ноль объявлением не
// является: «удерживаю всё» — свойство владельца, а не умолчание формы.
type Retention uint8

const (
	// RetentionUnset — владелец не сказал ничего.
	RetentionUnset Retention = iota

	// RetainsEverything — журнал не чистится; отказ «позиция утрачена» не
	// наступает никогда, и служебное сообщение говорит это прямо.
	RetainsEverything

	// RetainsFromEarliestRow — журнал чистится; нижняя возобновимая позиция
	// выводится из самой ранней удержанной строки.
	RetainsFromEarliestRow
)

// Row — строка журнала, как её прочитал сервер.
type Row struct {
	// Position — номер строки в журнале владельца.
	Position int64
	// Kind — вид предмета в словаре владельца.
	Kind string
	// ID — идентификатор предмета.
	ID string
	// ProjectID — якорь из колонки; пуст, если якорь даёт отображение.
	ProjectID string
	// Change — род изменения словом владельца.
	Change string
	// Payload — состояние предмета, как оно лежит в журнале.
	Payload []byte
}

// Kind — как авторизовать событие этого вида: тип объекта модели прав и
// действие.
//
// Действие несётся В ТОЙ ЖЕ записи, а не берётся одно на всех: иначе
// добавленный позже вид унаследовал бы чужой глагол, и модель судила бы о нём
// по неверному действию, оставаясь при этом «зелёной».
type Kind struct {
	ObjectType string
	Action     string
}

// Mapping — отображение строки журнала в событие общей формы.
type Mapping struct {
	// Kinds — ЗАКРЫТЫЙ словарь видов владельца.
	//
	// Он закрыт в обе стороны. Наружу: вид вне словаря отвергается
	// `INVALID_ARGUMENT`, а не открывает поток, в который никогда ничего не
	// придёт. Внутрь: строка журнала с видом вне словаря не имеет типа объекта
	// модели прав, поэтому вопрос «вправе ли вызывающий её видеть» задать
	// НЕЛЬЗЯ — и строка не доставляется.
	Kinds map[string]Kind

	// Changes — словарь рода изменения: слово владельца → род платформы.
	//
	// Отдельный словарь, а не работа отображения, потому что род изменения
	// нужен серверу ДО того, как состояние собрано: событие, чьё состояние
	// собрать не удалось, всё равно обязано назвать род — подписчик по нему
	// ведёт своё состояние.
	Changes map[string]subscriptionv1.SubscriptionEvent_Change

	// Anchor — проектный якорь строки. Заполняется тогда и только тогда, когда
	// [Storage.Project] равен [ProjectFromMapping].
	//
	// Отказ здесь — НЕ «состояние недоступно», а невозможность авторизовать:
	// без якоря решение о показе принять не из чего. Такая строка не
	// доставляется, и это громко.
	Anchor func(Row) (string, error)

	// State — состояние предмета. Возвращает ТРИ вещи, и у каждой позиции ровно
	// одно значение: собранное состояние · НАЗВАННАЯ причина его отсутствия ·
	// отказ сборки.
	//
	// Отказ событие НЕ отменяет: оно доставляется с признаком «состояния не
	// будет». Пустая нагрузка вместо состояния запрещена формой by construction.
	//
	// # ПОЧЕМУ ПРИЧИНУ НАЗЫВАЕТ ВЛАДЕЛЕЦ, А НЕ ВЫВОДИТ СЕРВЕР
	//
	// Причин отсутствия по контракту четыре, и они означают РАЗНОЕ ДЕЙСТВИЕ
	// подписчика: на «не удалось собрать» разумно перечитать, на «владелец такого
	// не производит» — сразу идти за предметом, на «не удерживается» и «не
	// показывается» — не ходить вовсе. Знание, какая из них верна, есть у
	// ВЛАДЕЛЬЦА и больше ни у кого: сервер видит `nil` и о его происхождении
	// сказать не может.
	//
	// До этой пары возвращаемых значений владельцу было НЕЧЕМ назвать причину:
	// пара «состояние, отказ» имеет две ветви на четыре смысла, и сервер сводил
	// обе к «не удалось сериализовать». То есть у одного владельца КАЖДОЕ событие
	// объясняло отсутствие состояния неудавшейся попыткой, которой не было. Вывод
	// причины из бедности нагрузки был рассмотрен и отвергнут: он сработал бы и
	// на настоящем отказе сборки, и два противоположных исхода стали бы
	// неразличимы — ровно та потеря различения, ради недопущения которой словарь
	// причин и объявлен закрытым.
	//
	// Соблазн назвать причину СЕНТИНЕЛЬНОЙ ОШИБКОЙ отвергнут по существу:
	// отсутствие состояния — не сбой, и класть его в канал ошибок значит требовать
	// от каждого читателя помнить, что здесь `error` иногда означает «всё в
	// порядке».
	//
	// Владелец, вернувший `nil` без названной причины, получает
	// `REASON_UNSPECIFIED` — контракт держит это значение ровно для такого случая
	// («владелец обязан назвать причину») — и громкую строку в журнале процесса.
	// Корзины «прочее» здесь нет: неназванное названо неназванным, а не подшито к
	// соседней записи.
	State func(Row) (*anypb.Any, StateAbsence, error)
}

// StateAbsence — ПОЧЕМУ состояния нет. Словарь закрыт и отвечает словарю
// контракта один в один: заводя здесь значение, которого нет там, владелец
// получил бы причину, которую некуда положить.
//
// Тип отдельный, а не булев признак: «состояния нет» и «почему его нет» — разные
// вопросы, и подписчик действует по второму.
type StateAbsence uint8

const (
	// StateAbsenceUnnamed — владелец причину НЕ НАЗВАЛ.
	//
	// Законным исходом не является: значение нулевое ради того, чтобы забытая
	// причина была ВИДНА, а не подшита к соседней. Сервер отдаёт по нему
	// `REASON_UNSPECIFIED` и пишет громко.
	StateAbsenceUnnamed StateAbsence = iota

	// StateNotProduced — владелец состояния для этого предмета НЕ ПРОИЗВОДИТ.
	//
	// Свойство журнала, а не сбой: собирать было нечего, попытки не было, повтор
	// ничего не изменит. Два живых случая: журнал, не несущий состояния ни у
	// одного вида, и событие снятия — предмета больше нет by construction.
	StateNotProduced

	// StateNotRetained — состояние на эту позицию владельцем больше НЕ
	// УДЕРЖИВАЕТСЯ.
	//
	// Производителя в дереве сегодня НЕТ, и это утверждение о ВСЕХ владельцах, а не
	// о тех, что были видны заводившей полосе: удержание объявляют предикатом
	//
	//	git grep -c 'Retention: subscription\.' -- 'services/*/internal/subscriptionjournal/journal.go'
	//
	// и на сегодня каждая найденная строка называет [RetainsEverything]. Прежняя
	// редакция говорила «оба владельца» — верно для двух журналов, приведённых к
	// этой форме первыми, и неверно для остальных трёх, приехавших соседними
	// полосами: число мерилось на популяции полосы, а не дерева.
	//
	// Значение объявлено потому, что объявлено контрактом, и владельцу, заведшему
	// чистку журнала, будет чем назвать этот исход, — а не «на будущее»: без него
	// он назвал бы соседнее.
	StateNotRetained

	// StateWithheld — состояние ЕСТЬ, но вызывающему не показывается.
	StateWithheld
)

// reason переводит названную владельцем причину в слово контракта и говорит,
// НАЗВАЛ ли владелец причину вообще.
//
// Перевод ПОЛОН: у каждого объявленного значения есть своё слово, и ветви
// «прочее» здесь нет. Значение вне словаря (владелец собрал число сам) отвечает
// тем же, чем неназванное, — `REASON_UNSPECIFIED` и `named=false`: сервер не
// вправе выбирать за владельца, какую из трёх содержательных причин тот имел в
// виду.
//
// # ПОЧЕМУ ВТОРОЕ ЗНАЧЕНИЕ, А НЕ СРАВНЕНИЕ СЛОВА С НУЛЁМ У ВЫЗЫВАЮЩЕГО
//
// Потому что вызывающий этого не сделал, и проба это поймала. Ветвь «вне
// словаря» отдавала `REASON_UNSPECIFIED` МОЛЧА — то есть дефект объявления
// владельца был неотличим от законного исхода, и корзина «прочее» возвращалась
// под именем нулевого значения. Отличить «я перевёл» от «мне нечего было
// переводить» может только сам перевод; у вызывающего для этого нет входа.
func (a StateAbsence) reason() (word subscriptionv1.SubscriptionEvent_StateUnavailable_Reason, named bool) {
	switch a {
	case StateNotProduced:
		return subscriptionv1.SubscriptionEvent_StateUnavailable_NOT_PRODUCED, true
	case StateNotRetained:
		return subscriptionv1.SubscriptionEvent_StateUnavailable_NOT_RETAINED, true
	case StateWithheld:
		return subscriptionv1.SubscriptionEvent_StateUnavailable_WITHHELD, true
	default:
		return subscriptionv1.SubscriptionEvent_StateUnavailable_REASON_UNSPECIFIED, false
	}
}

// KindDictionary — ЗАКРЫТЫЙ СЛОВАРЬ ВИДОВ владельца в том написании, в котором
// его видит клиент: типы объекта модели прав, по одному разу, в возрастающем
// лексикографическом порядке.
//
// # ОДИН ВЫЗОВ — ТРИ ЧИТАТЕЛЯ, И ИМЕННО ПОЭТОМУ ОНИ НЕ РАЗОЙДУТСЯ
//
// Отсюда берут словарь все, кому он нужен: служебное сообщение открытия
// ([subscriptionv1.SubscriptionOpened.KnownKinds]), отказ на неизвестном виде
// ([Journal.Accept]) и пробы владельцев. Второго перечня не существует, поэтому
// «объявленное» и «то, чем сервер на самом деле судит» — один объект, а не два
// похожих.
//
// # ПОЧЕМУ СЛОВО ПРОВОДА — ТИП ОБЪЕКТА, А НЕ КЛЮЧ СЛОВАРЯ
//
// Ключ — слово ХРАНИЛИЩА: как владелец записал строку в своей таблице. Оно
// частное и разное у всех: перепись двух живых владельцев на день заведения
// этого метода дала `Instance` у одного и `nlb_load_balancer` у другого — два
// написания одного рода предмета, ни одного производителя. Тип объекта, наоборот,
// уже есть единственное платформенное имя предмета: им же сервер спрашивает
// модель прав о видимости строки, им же его знает каталог прав и аннотации
// контрактов домена.
//
// Следствие, ради которого выбрано именно оно: ВТОРОЕ НАПИСАНИЕ ЗАВЕСТИ НЕКУДА.
// У владельца нет поля, в которое он мог бы положить своё клиентское слово, —
// не «нельзя по правилу», а негде.
//
// # ПОРЯДОК — ЧАСТЬ КОНТРАКТА
//
// Словарь живёт отображением, обход отображения в Go случаен by construction.
// Неупорядоченный перечень клиент, ведущий состояние по индексу, читал бы как
// смену словаря на каждом открытии.
//
// # ПОВТОР СНИМАЕТСЯ
//
// Два слова хранилища об одном предмете (историческое и нынешнее) — законный
// случай, и клиенту он не виден: он спрашивает про предмет, а не про то, чем его
// записали.
func (j Journal) KindDictionary() []string {
	seen := make(map[string]struct{}, len(j.Mapping.Kinds))
	out := make([]string, 0, len(j.Mapping.Kinds))
	for _, binding := range j.Mapping.Kinds {
		if _, dup := seen[binding.ObjectType]; dup {
			continue
		}
		seen[binding.ObjectType] = struct{}{}
		out = append(out, binding.ObjectType)
	}
	sort.Strings(out)
	return out
}

// journalWords переводит виды провода в слова ХРАНИЛИЩА этого владельца.
//
// Перевод живёт здесь, а не у вызывающего: знание о том, чем владелец записал
// строку, принадлежит объявлению владельца и наружу не выходит. Один вид может
// дать НЕСКОЛЬКО слов — тогда отбор запросом перечислит их все, и историческая
// строка не потеряется.
//
// Виды на входе уже осуждены [Journal.Accept]; неизвестный сюда не доходит, и
// пустой результат означал бы отбор, которому не отвечает ни одна строка.
func (j Journal) journalWords(kinds []string) []string {
	if len(kinds) == 0 {
		return nil
	}
	want := make(map[string]struct{}, len(kinds))
	for _, k := range kinds {
		want[k] = struct{}{}
	}
	out := make([]string, 0, len(j.Mapping.Kinds))
	for word, binding := range j.Mapping.Kinds {
		if _, ok := want[binding.ObjectType]; ok {
			out = append(out, word)
		}
	}
	// Порядок здесь не контракт, а ВОСПРОИЗВОДИМОСТЬ запроса: несортированный
	// срез дал бы разный текст плана на одном и том же входе.
	sort.Strings(out)
	return out
}

// sqlIdent — законное имя таблицы (при желании со схемой) или колонки.
//
// Оно СУДИТСЯ У КОНСТРУКТОРА, а не экранируется на месте: экранирование
// оставляет негодное имя выразимым и переносит вопрос на того, кто следующим
// напишет запрос. Отвергнув здесь, мы получаем свойство построения — негодного
// имени не существует ни на одном пути.
var sqlIdent = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

// objectTypeForm — единственное законное написание вида на проводе.
//
// Это форма имени типа в модели прав (`compute_instance`,
// `nlb_network_load_balancer`), и она судится ЗДЕСЬ, при объявлении, а не
// прощается на месте. Разница существенная: прощение оставляет второе написание
// выразимым и переносит вопрос на клиента, который увидел бы `Instance` у одного
// владельца и `nlb_load_balancer` у другого и не смог бы знать, которое из них
// то. Отвергнув при объявлении, мы получаем свойство ПОСТРОЕНИЯ: владелец,
// объявивший вид иначе, не поднимается.
var objectTypeForm = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// Validate судит объявление владельца.
//
// Он судит ОБЪЯВЛЕНИЕ, а не дерево: существует ли таблица и та ли у неё форма —
// вопрос подъёма, и на него отвечает первый же запрос. Здесь закрывается то,
// что после подъёма закрыть уже нечем: незаявленная ось, разошедшиеся половины
// одного решения и имя, которое нельзя безопасно поставить в запрос.
func (j Journal) Validate() error {
	if err := j.Storage.validate(); err != nil {
		return err
	}
	if j.Channel == "" {
		return fmt.Errorf("subscription: Journal.Channel не назван — без канала поток живёт одним холостым перепросом и выглядит исправным")
	}
	if !sqlIdent.MatchString(j.Channel) {
		return fmt.Errorf("subscription: Journal.Channel %q негоден как идентификатор Postgres", j.Channel)
	}
	return j.Mapping.validate(j.Storage.Project)
}

func (s Storage) validate() error {
	if err := validTableName(s.Table); err != nil {
		return err
	}
	for name, col := range map[string]string{
		"Storage.PositionColumn": s.PositionColumn,
		"Storage.KindColumn":     s.KindColumn,
		"Storage.IDColumn":       s.IDColumn,
		"Storage.ChangeColumn":   s.ChangeColumn,
		"Storage.PayloadColumn":  s.PayloadColumn,
	} {
		if !sqlIdent.MatchString(col) {
			return fmt.Errorf("subscription: %s %q негодно как имя колонки Postgres", name, col)
		}
	}

	switch s.Project {
	case ProjectDimensionUnset:
		return fmt.Errorf("subscription: Storage.Project не объявлен — у якорной оси project_id умолчания не бывает: назовите ProjectInColumn, ProjectFromMapping либо ProjectAbsent")
	case ProjectInColumn:
		if !sqlIdent.MatchString(s.ProjectColumn) {
			return fmt.Errorf("subscription: Storage.Project = ProjectInColumn, но Storage.ProjectColumn %q негодно как имя колонки", s.ProjectColumn)
		}
	case ProjectFromMapping, ProjectAbsent:
		if s.ProjectColumn != "" {
			return fmt.Errorf("subscription: Storage.ProjectColumn назван (%q), хотя Storage.Project объявлен не колонкой — два источника одного якоря разойдутся молча", s.ProjectColumn)
		}
	default:
		return fmt.Errorf("subscription: Storage.Project = %d — такого состояния нет", s.Project)
	}

	switch s.Retention {
	case RetentionUnset:
		return fmt.Errorf("subscription: Storage.Retention не объявлен — «удерживаю всё» есть свойство владельца, а не умолчание формы: назовите RetainsEverything либо RetainsFromEarliestRow")
	case RetainsEverything:
		if s.AgeColumn != "" {
			return fmt.Errorf("subscription: Storage.AgeColumn назван (%q) при Retention = RetainsEverything — "+
				"уборки нет, значит колонку не читает никто, а следующий примет объявление за действующий механизм",
				s.AgeColumn)
		}
	case RetainsFromEarliestRow:
		if !sqlIdent.MatchString(s.AgeColumn) {
			return fmt.Errorf("subscription: Storage.Retention = RetainsFromEarliestRow, но Storage.AgeColumn %q "+
				"негодно как имя колонки — предикат уборки не из чего построить, "+
				"а подписчику уже обещана нижняя возобновимая позиция", s.AgeColumn)
		}
	default:
		return fmt.Errorf("subscription: Storage.Retention = %d — такого состояния нет", s.Retention)
	}
	return nil
}

func validTableName(table string) error {
	parts := strings.Split(table, ".")
	if len(parts) > 2 {
		return fmt.Errorf("subscription: Storage.Table %q — имя глубже пары «схема.таблица» не поддерживается", table)
	}
	for _, p := range parts {
		if !sqlIdent.MatchString(p) {
			return fmt.Errorf("subscription: Storage.Table %q негодно как имя таблицы Postgres", table)
		}
	}
	return nil
}

func (m Mapping) validate(project ProjectDimension) error {
	if len(m.Kinds) == 0 {
		return fmt.Errorf("subscription: Mapping.Kinds пуст — закрытый словарь видов есть то, чем поток авторизуется и чем отвергается неизвестный вид; пустой означал бы поток, из которого не доставляется ничего")
	}
	for kind, binding := range m.Kinds {
		if binding.ObjectType == "" {
			return fmt.Errorf("subscription: Mapping.Kinds[%q].ObjectType пуст — без типа объекта модели прав вопрос о видимости строки задать нельзя", kind)
		}
		if !objectTypeForm.MatchString(binding.ObjectType) {
			return fmt.Errorf("subscription: Mapping.Kinds[%q].ObjectType = %q — это НЕ имя типа модели прав (%s). "+
				"Тип объекта есть слово, которым вид едет клиенту, и написание у него одно на всё дерево; "+
				"слово, которым владелец записал строку в своём журнале, остаётся ключом и наружу не выходит",
				kind, binding.ObjectType, objectTypeForm)
		}
		if binding.Action == "" {
			return fmt.Errorf("subscription: Mapping.Kinds[%q].Action пуст — действие несётся в той же записи, чтобы вид не унаследовал чужой глагол", kind)
		}
	}

	if len(m.Changes) == 0 {
		return fmt.Errorf("subscription: Mapping.Changes пуст — род изменения обязан быть назван словарём, а не выведен из слова владельца")
	}
	for word, change := range m.Changes {
		if change == subscriptionv1.SubscriptionEvent_CHANGE_UNSPECIFIED {
			return fmt.Errorf("subscription: Mapping.Changes[%q] = CHANGE_UNSPECIFIED — подписчик, ведущий своё состояние, по неназванному роду не знает, добавить строку, обновить или снять", word)
		}
	}

	if m.State == nil {
		return fmt.Errorf("subscription: Mapping.State не назван — без него событие не несёт состояния предмета, ради которого подписка и заводится")
	}

	switch project {
	case ProjectFromMapping:
		if m.Anchor == nil {
			return fmt.Errorf("subscription: Storage.Project = ProjectFromMapping, но Mapping.Anchor не назван — якорь брать неоткуда")
		}
	default:
		if m.Anchor != nil {
			return fmt.Errorf("subscription: Mapping.Anchor назван, хотя Storage.Project объявлен не отображением — два источника одного якоря разойдутся молча")
		}
	}
	return nil
}
