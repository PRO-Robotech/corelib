// stallWarnAfter — с какого возраста удержанного горизонта поток жалуется в лог.
//
// Горизонт держит ЧУЖАЯ незавершённая транзакция; дольше одного холостого
// перепроса это означает зависшего писателя журнала, а не нормальную
// конкуренцию. Без жалобы «поток молчит, потому что кто-то не коммитится»
// неотличимо от «событий нет» — ровно тот немой отказ, который мы ловим в
// дренажах.
const stallWarnAfter = 30 * time.Second

// Querier — то, чем наблюдение задаёт свой единственный вопрос.
//
// Соединение и пул отвечают ему ОБА, и это не удобство, а условие
// переиспользуемости: у механизма подписки наблюдение живёт на выделенном
// соединении потока, а у возобновимого чтения, отвечающего на запрос
// (`InternalIAMService.PollSubjectChanges`), своего соединения нет вовсе — есть
// пул.
//
// Исключение СЕБЯ по идентификатору обслуживающего процесса остаётся верным и на
// пуле: наблюдатель в журнал не пишет, поэтому его собственная блокировка — не
// та, которую наблюдение ищет.
type Querier interface {
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// Watermark — ВОДЯНОЙ ЗНАК: граница устоявшегося в журнале одного потока.
//
// Имя взято у источника намеренно. Приёмка фазы Ф1 назначила предикатом переноса
// техники именно его: «`watermark` в дереве — не ноль ВНЕ `services/nlb`». Пока
// техника звалась здесь иначе, предикат отвечал «не перенесена» на перенесённой
// технике — и снятие мёртвого читателя nlb (kacho#1043) уничтожило бы
// единственный написанный ответ на этот класс, формально не нарушив ни одного
// условия.
//
// # Что здесь перенесено, а не изобретено
//
// Техника взята у `services/nlb/internal/repo/kacho/pg/lifecycle_feed.go`, где
// она написана, разобрана и покрыта пробой на трёх подслучаях. Перенос — а не
// повторное изобретение — был условием фазы: единственный написанный ответ на
// этот класс жил там, и снятие того файла до переноса уничтожило бы его.
//
// Обобщено ровно одно: имя таблицы и имя колонки номера пришли параметрами.
// Правило, разбор отката и размен остались дословно.
//
// # Правило
//
// Максимальный ВИДИМЫЙ номер M становится границей, когда ни одна транзакция,
// писавшая в журнал в момент наблюдения M, больше не пишет. Только такая
// транзакция может ещё выпустить номер ≤ M: писатель, взявший блокировку ПОСЛЕ
// наблюдения, вызовет счётчик позже и получит номер > M.
//
// # Почему блокировка таблицы, а не снимок транзакций
//
// Писатель держит `RowExclusiveLock` на журнале с момента ПЛАНИРОВАНИЯ своей
// вставки — то есть ещё до того, как счётчик выдал ему номер, — и до конца
// транзакции. Идентификатор транзакции назначается позже, на самой вставке:
// существует наблюдаемое состояние «номер уже выдан, идентификатора транзакции
// ещё нет», в котором горизонт по снимку транзакций СЛЕП. Дополнительно:
// верхняя граница снимка не является верхней границей работающих транзакций,
// поэтому «нижняя догнала прежнюю верхнюю» не доказывает ничего.
//
// `virtualtransaction` идентифицирует ТРАНЗАКЦИЮ, а не соединение: тот же
// процесс в следующей транзакции получит другой идентификатор. Поэтому
// непрерывно пишущие фоновые работники не могут удерживать горизонт вечно —
// зафиксированное множество всегда доистекает.
//
// # Осознанный размен
//
// Писатель, не завершающий транзакцию, задерживает поток целиком: у него может
// быть сколь угодно малый невыпущенный номер, и никакое наблюдение этого не
// опровергнет. Выбор в пользу «не потерять» против «доставить сейчас»;
// удержание дольше [stallWarnAfter] — в лог.
// # Наблюдатель ОДИН на дерево, и это держится гейтом
//
// Экземпляров у него столько, сколько журналов; РЕАЛИЗАЦИЯ одна, и второй такой
// файл — находка гейта `settledwatermarksingularity` ГДЕ БЫ ОН НИ ЛЕЖАЛ, включая
// сам `pkg/`. Поэтому потребитель вне механизма подписки берёт этот тип, а не
// пишет своё наблюдение: два наблюдения одного класса расходятся молча.
//
// # Тип ЗАЩИЩЁН ОТ СОВМЕСТНОГО ДОСТУПА
//
// У механизма подписки наблюдатель свой на каждый поток, и состязания нет. У
// чтения, отвечающего на запрос, экземпляр один на процесс, а проходов столько,
// сколько реплик потребителя поллит эту реплику владельца. Замок неоспариваемый
// в первом случае и несущий во втором.
type Watermark struct {
	mu sync.Mutex

	log   *slog.Logger
	query string
	// earliestQuery — вопрос ТОЛЬКО о самой ранней удержанной строке.
	earliestQuery string
	table         string

	// settled — граница устоявшегося: каждый номер ≤ settled либо уже видим,
	// либо не появится никогда (писатель откатился).
	settled int64

	// established — состоялось ли наблюдение хоть раз.
	//
	// Граница начинает жизнь нулём, и ноль этот означает «позиции ЕЩЁ НЕТ», а
	// не «позиция ноль»: подтверждать её нечем, пока держащий журнал писатель
	// не доистёк. Различать эти два значения обязан всякий, кто на границу
	// САДИТСЯ, — иначе подписчик, попросивший «с текущего места», садится в
	// НАЧАЛО журнала и вычитывает всю накопленную историю (kacho#1386).
	//
	// У пустого журнала ноль — настоящая позиция: пропускать в нём нечего, и
	// наблюдение состоялось сразу. Свести эти случаи в один значило бы либо
	// вернуть историю подписчику, либо не открыть ему поток никогда.
	//
	// Признак МОНОТОНЕН: граница только растёт, поэтому появление нового
	// писателя состоявшегося наблюдения не отзывает.
	established bool

	// earliest — самая ранняя удержанная строка журнала (0, если журнал пуст).
	earliest int64

	// pendingSeq / pendingWriters — наблюдение, ожидающее подтверждения.
	// Множество фиксируется ОДИН раз и не пополняется новыми писателями — иначе
	// под непрерывной записью оно никогда бы не опустело.
	pendingSeq     int64
	pendingWriters []string
	pendingSince   time.Time

	lastStallWarn time.Time
	now           func() time.Time
}

// NewWatermark собирает наблюдателя для одной таблицы.
//
// Имя таблицы и колонки попадают в текст запроса, поэтому вызывающий обязан
// подавать сюда СВОИ имена, а не пришедшие снаружи: наблюдение их не
// экранирует. У механизма подписки за это отвечает [Journal.Validate]; у
// прямого потребителя — то, что оба имени объявлены константами его же пакета.
func NewWatermark(table, positionColumn string, log *slog.Logger) *Watermark {
	if log == nil {
		log = slog.Default()
	}
	return newWatermark(table, positionColumn, log, time.Now)
}

// newWatermark — та же сборка с УПРАВЛЯЕМЫМИ часами: [stallWarnAfter]
// измеряется временем, и проба обязана двигать его сама, а не ждать.
func newWatermark(table, positionColumn string, log *slog.Logger, now func() time.Time) *Watermark {
	return &Watermark{
		log:   log,
		now:   now,
		table: table,
		// Вопрос ОДНОЙ величины, отдельно от полного наблюдения: чтение
		// спрашивает его перед КАЖДОЙ партией у владельца, который журнал чистит
		// (см. [Server.drain]), а полное наблюдение несёт ещё и просмотр
		// блокировок — платить за него на каждой партии незачем.
		earliestQuery: fmt.Sprintf(
			`SELECT COALESCE((SELECT min(%[1]s) FROM %[2]s), 0)`, positionColumn, table),
		query: fmt.Sprintf(`
			SELECT COALESCE((SELECT max(%[1]s) FROM %[2]s), 0),
			       COALESCE((SELECT min(%[1]s) FROM %[2]s), 0),
			       COALESCE((SELECT array_agg(DISTINCT l.virtualtransaction)
			                   FROM pg_locks l
			                  WHERE l.relation = $1::regclass
			                    AND l.mode = 'RowExclusiveLock'
			                    AND l.granted
			                    AND l.pid <> pg_backend_pid()
			                    AND l.database = (SELECT oid FROM pg_database
			                                       WHERE datname = current_database())),
			                '{}'::text[])`, positionColumn, table),
	}
}

// advance двигает границу устоявшегося по одному наблюдению.
//
// Два исхода:
//   - писателей нет — граница переносится сразу (обычный ненагруженный случай,
//     задержка доставки нулевая);
//   - писатели есть — наблюдение запоминается и подтверждается на следующем
//     проходе. Проход инициирует пробуждение того самого писателя (он держит
//     блокировку именно потому, что вставляет строку, а фиксация доставляет его
//     уведомление), поэтому нормальная задержка — время его транзакции.
//     Исключение — ОТКАТ писателя: уведомления не будет, и подтверждение
//     приедет на холостом перепросе.
//
// Дыра от отката закрывается тем же правилом: номер отменённой транзакции не
// появится никогда, а её блокировка снята — значит граница переносится ЗА дыру,
// и поток не залипает.
func (h *Watermark) Advance(ctx context.Context, q Querier) error {
	var (
		maxSeq  int64
		minSeq  int64
		writers []string
	)
	// Запрос идёт ВНЕ замка: держать замок на время обращения к базе значило бы
	// сериализовать параллельные проходы на времени сети, а не на состоянии.
	if err := q.QueryRow(ctx, h.query, h.table).Scan(&maxSeq, &minSeq, &writers); err != nil {
		return err
	}

	h.mu.Lock()
	defer h.mu.Unlock()
	h.observe(maxSeq, minSeq, writers)
	return nil
}

// observe — ЧИСТЫЙ переход состояния по одному наблюдению.
//
// Зовётся ПОД ЗАМКОМ ([Watermark.Advance]) либо из пробы, ведущей наблюдателя в
// одну горутину; сам замка не берёт, иначе [Watermark.Advance] взял бы его
// дважды.
//
// Отделён от запроса затем, чтобы холодное наблюдение можно было ПОДАТЬ:
// состояние «граница ещё не подтверждена» производится писателем, держащим
// журнал, и утверждение о нём иначе пришлось бы делать чтением кода.
func (h *Watermark) observe(maxSeq, minSeq int64, writers []string) {
	h.earliest = minSeq

	// 1. Подтвердить прошлое наблюдение: его писатели доистекли.
	confirmed := false
	if len(h.pendingWriters) > 0 && !anyStillWriting(h.pendingWriters, writers) {
		if h.pendingSeq > h.settled {
			h.settled = h.pendingSeq
		}
		h.pendingSeq, h.pendingWriters, h.pendingSince = 0, nil, time.Time{}
		confirmed = true
	}

	// 2. Новое наблюдение берём только когда прошлое снято — иначе под
	// непрерывной записью множество ожидания обновлялось бы вечно.
	if len(h.pendingWriters) == 0 && maxSeq > h.settled {
		if len(writers) == 0 {
			h.settled = maxSeq
		} else {
			h.pendingSeq, h.pendingWriters, h.pendingSince = maxSeq, writers, h.now()
		}
	}

	h.warnIfStalled()

	// Наблюдение состоялось, когда граница ПОДТВЕРЖДЕНА хотя бы однажды. Два
	// арма, и первый несущий:
	//
	//   - ожидание СНЯТО этим проходом (шаг 1). Писатели номера `pendingSeq`
	//     доистекли — значит он устоялся, и это верно независимо от того, взято
	//     ли следом ожидание для номера ВЫШЕ;
	//   - ожидания не осталось: писателей не было (шаг 2 перенёс границу
	//     сразу), либо максимум уже под границей, либо журнал пуст.
	//
	// Читать это как «ожидания не осталось» — и только — нельзя: под сплошной
	// записью шаг 2 берёт новое ожидание тем же проходом, каким шаг 1 снял
	// прошлое, поэтому пустого мига не бывает НИКОГДА. Тогда граница растёт, а
	// подписчика на неё не сажают: расход лечился бы отказом в обслуживании, и
	// притом немым (kacho#1386, возражение приёмки — 50 проходов дают
	// `settled=49` при `established=false`).
	if confirmed || len(h.pendingWriters) == 0 {
		h.established = true
	}
}

// Settled — граница устоявшегося на момент последнего наблюдения.
//
// Каждый номер ≤ этой границы либо уже видим, либо не появится НИКОГДА (писатель
// откатился). Окно возобновимого чтения — `(курсор, Settled]`, и никогда «всё,
// что больше курсора»: позиция, выданная за неустоявшийся номер, теряет его
// молча и навсегда.
//
// Ноль читать как «журнал пуст» НЕЛЬЗЯ — спрашивай [Watermark.Established]: у
// холодного наблюдателя первое наблюдение лишь ЗАПОМИНАЕТ писателей, и до
// подтверждения ноль означает «позиции ещё нет».
func (h *Watermark) Settled() int64 {
	h.mu.Lock()
	defer h.mu.Unlock()
	return h.settled
}

// Established — подтверждена ли граница хоть однажды.
//
// Признак МОНОТОНЕН: подтвердившись, он не отзывается появлением нового
// писателя. Поэтому отказ вызывающего, читающий его, есть состояние ХОЛОДНОГО
// СТАРТА, а не режим работы.
func (h *Watermark) Established() bool {
	h.mu.Lock()
	defer h.mu.Unlock()
	return h.established
}

// Floor — нижняя возобновимая позиция.
//
// У владельца, удерживающего журнал целиком, её не существует, и служебное
// сообщение говорит это отдельным признаком, а не нулём в поле позиции. У
// владельца, который журнал чистит, она выводится из самой ранней удержанной
// строки: с позиции `earliest-1` возобновление ещё не теряет ничего.
//
// Пустой журнал у чистящего владельца означает, что удержано ноль строк, и
// возобновиться можно только с текущей границы: всё, что было до неё, уже
// снято.
//
// # Почему ЭКСПОРТИРОВАН, хотя механизм подписки зовёт его изнутри
//
// Пол — половина ответа на «обнаружил ли читатель пропуск»; вторую половину
// (явный отказ) даёт тот, кто пол спросил. Пока имя было неэкспортировано,
// спросить его мог ТОЛЬКО механизм подписки, а тот же класс живёт у журнала,
// читаемого унарным глаголом (`kaname.subject_change_outbox`,
// `InternalIAMService.PollSubjectChanges`): окно `id > since AND id <= settled`
// снятой строки не показывает НИЧЕМ — курсор переезжает через неё, и «строк не
// было» становится неотличимо от «строки убрали».
//
// Экспорт — не послабление инкапсуляции, а исполнение уже объявленного правила:
// наблюдатель границы в дереве ОДИН и лежит здесь, поэтому потребитель вне
// механизма подписки берёт этот тип, а не пишет своё наблюдение. Второй расчёт
// пола разошёлся бы с этим молча.
//
// # Полосу удержания называет ВЫЗЫВАЮЩИЙ, и это его решение, а не свойство типа
//
// [RetainsEverything] означает «нижней границы не существует» и делает отказ
// «позиция утрачена» непроизводимым; [RetainsFromEarliestRow] — «журнал чистится,
// нижняя граница реальна». У механизма подписки значение приходит объявлением
// журнала и едет клиенту служебным сообщением; у прямого потребителя оно на
// провод не выходит вовсе и означает ровно то, что читатель обязан ВЫДЕРЖАТЬ.
func (h *Watermark) Floor(r Retention) int64 {
	h.mu.Lock()
	defer h.mu.Unlock()
	return floorOf(r, h.earliest, h.settled)
}

// ObserveFloor спрашивает нижнюю удержанную строку и отдаёт пол, выведенный ИЗ
// ЭТОГО ЖЕ наблюдения, а не из общего поля.
//
// # Зачем отдельный вопрос, если есть [Watermark.Floor]
//
// Наблюдатель бывает ОБЩИМ. У потока подписки он свой на каждый поток, и там
// разницы нет; у чтения, отвечающего на запрос, он ОДИН на процесс, а проходов
// столько, сколько реплик потребителя поллит эту реплику владельца. Тогда
// [Watermark.Floor] отдаёт значение, положенное туда ЧУЖИМ проходом, — и
// положенное им наблюдение может быть СТАРШЕ моего: `observe` пишет `earliest`
// безусловно, поэтому проход, чей запрос отработал раньше, а запись легла позже,
// возвращает поле НАЗАД.
//
// Направление вреда здесь несимметрично и потому несущее: пол, занизившийся
// чужим старым наблюдением, отказа НЕ производит — то есть страница со снятым
// префиксом уезжает вызывающему как полная. Это ровно тот молчаливый пропуск,
// ради обнаружения которого пол и заведён.
//
// # Общее поле двигается ТОЛЬКО ВПЕРЁД
//
// Нижняя строка непустого журнала монотонна: строки снимаются префиксом, номера
// растут. Поэтому наблюдение, оказавшееся ниже уже известного, — старое, и
// принимать его в общее поле нельзя. Свой ответ метод при этом отдаёт из своего
// наблюдения в любом случае: общее поле — удобство для соседей, а не источник
// этого ответа.
//
// Ноль означает ПУСТОЙ журнал, а не «раньше всех», и в монотонность не входит:
// пустота — состояние, а не позиция.
func (h *Watermark) ObserveFloor(ctx context.Context, q Querier, r Retention) (int64, error) {
	var minSeq int64
	if err := q.QueryRow(ctx, h.earliestQuery).Scan(&minSeq); err != nil {
		return 0, err
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	if minSeq > h.earliest {
		h.earliest = minSeq
	}
	return floorOf(r, minSeq, h.settled), nil
}

// floorOf — ФОРМУЛА пола, одна на оба вопроса.
//
// Вопроса два и они разные — «пол по последнему наблюдению» и «пол по
// собственному», — а формула обязана быть одна: две копии разошлись бы молча
// именно там, где расхождение не видно (обе непусты, обе выглядят полом).
func floorOf(r Retention, earliest, settled int64) int64 {
	if r == RetainsEverything {
		return 0
	}
	if earliest > 0 {
		return earliest - 1
	}
	return settled
}

// RefreshEarliest перечитывает ТОЛЬКО нижнюю удержанную строку.
//
// # Зачем отдельный вопрос, а не [Watermark.Advance]
//
// Владелец, который журнал ЧИСТИТ, двигает нижнюю границу под работающим
// потоком. Читающий поток обязан узнать об этом ДО того, как отдаст следующую
// партию: иначе снятые строки просто не придут в выборку, курсор переедет через
// них, и подписчик получит НЕПОЛНОЕ, ничем не отличимое от «изменений не было».
//
// Полное наблюдение отвечать на этот вопрос негодно по цене: оно несёт ещё и
// просмотр блокировок журнала, а спрашивать границу приходится перед КАЖДОЙ
// партией. Здесь — один просмотр индекса по первичному ключу.
//
// Верхнюю границу метод НЕ трогает: устоявшееся двигает только полное
// наблюдение, и подмешивать сюда его половину значило бы завести второй путь к
// одной величине.
//
// # МОМЕНТ вопроса — не раньше выборки
//
// «Узнать ДО выдачи партии» и «узнать до её ВЫБОРКИ» — разные моменты, и второй
// негоден: между двумя запросами уборка вправе зафиксироваться, и наблюдение,
// взятое раньше страницы, описывает журнал, которого к моменту выборки уже нет.
// Разбор — у вызывающего ([Server.drain]); здесь он не пересказывается, чтобы
// два места об одном предмете не разошлись.
func (h *Watermark) RefreshEarliest(ctx context.Context, q Querier) error {
	var minSeq int64
	if err := q.QueryRow(ctx, h.earliestQuery).Scan(&minSeq); err != nil {
		return err
	}
	h.mu.Lock()
	defer h.mu.Unlock()
	h.earliest = minSeq
	return nil
}

// anyStillWriting — пересекается ли зафиксированное множество писателей с
// текущим. Оба множества — единицы элементов, поэтому линейный проход дешевле
// любой индексации.
func anyStillWriting(pending, current []string) bool {
	for _, p := range pending {
		for _, cur := range current {
			if p == cur {
				return true
			}
		}
	}
	return false
}

// warnIfStalled жалуется, когда горизонт удерживается дольше [stallWarnAfter].
// Троттлинг — не чаще одной записи за тот же интервал: под потоком пробуждений
// проходов много, а событие ровно одно.
func (h *Watermark) warnIfStalled() {
	if len(h.pendingWriters) == 0 {
		h.lastStallWarn = time.Time{}
		return
	}
	held := h.now().Sub(h.pendingSince)
	if held < stallWarnAfter {
		return
	}
	if !h.lastStallWarn.IsZero() && h.now().Sub(h.lastStallWarn) < stallWarnAfter {
		return
	}
	h.lastStallWarn = h.now()
	h.log.Warn("subscription: settled watermark held by an unfinished journal writer",
		"held_for", held.Truncate(time.Second).String(),
		"withheld_up_to", h.pendingSeq,
		"writer_transactions", len(h.pendingWriters),
	)
}
