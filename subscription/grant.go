// grant.go — ОКНО МАТЕРИАЛИЗАЦИИ ГРАНТА: почему «нет» от модели прав не всегда
// окончательно, и чем ограничено ожидание.
//
// # ПРЕДМЕТ
//
// Строка журнала и строка ресурса коммитятся ОДНОЙ транзакцией — это несущее
// свойство формы подписки. Кортеж владения кладётся ПОСЛЕ фиксации: сначала
// синхронным докладом владельцу прав, а если тот не дошёл — дренажем намерения
// из той же writer-транзакции. Пробуждение потока приходит НА ФИКСАЦИИ, то есть
// в самый ранний возможный миг: строка уже видна, гранта ещё нет.
//
// Пообъектный вопрос в этот миг получает «нет» ЗАКОННО. До задачи #2264 такой
// ответ был ОКОНЧАТЕЛЬНЫМ: курсор идёт по ПРОЧИТАННОЙ строке (см. [Server.drain],
// и это верно — иначе невидимая партия перечитывалась бы вечно), поэтому строка
// уезжала под курсор, и открытый поток не отдавал её больше НИКОГДА.
//
// Наблюдаемое следствие — то, ради чего подписка заведена, и оно ТИХОЕ: у
// клиента нет ни пропуска в нумерации, ни отказа, поэтому «изменений не было» и
// «изменение было и не доехало» для него неразличимы. Возобновление с той же
// позиции предмет ПРИНОСИЛО (грант к тому времени уже лежал) — то есть строка
// была и в журнале, и видна вызывающему, а открытый поток её пропустил.
//
// # РЕШЕНИЕ: ОТСРОЧИТЬ СУЖДЕНИЕ, А НЕ РАСШИРИТЬ ЕГО
//
// Рассмотрен и отвергнут симметричный ход: судить создание ПО ЯКОРЮ, как уже
// судится снятие (см. `removalsAllowedByAnchor`). Довод там — «предмета уже нет
// в модели прав»; здесь он звучал бы «предмета ещё нет», и симметрия
// соблазнительна. Отвергнут по цене: у снятия расширение касается ОДНОГО рода
// изменения и предмета, которого больше нет, а у создания оно означало бы, что
// всякий, кому разрешён проект, видит КАЖДОЕ создание в нём — постоянно, а не в
// окне. Это расширение поверхности доступа, и принимать его молча нельзя.
//
// Отсрочка расширением не является BY CONSTRUCTION: наружу не уходит ни одна
// строка, которой модель не сказала «да». Платится ЛАТЕНТНОСТЬЮ, и она названа
// ниже числом.
//
// # ЧЕГО ОТСРОЧКА НЕ ОБЕЩАЕТ
//
// Она покрывает ДВУХ производителей гранта, разбуженных той же фиксацией:
// синхронный доклад и дренаж намерения. Реконсайлер — третий производитель, и
// его шаг измеряется десятками секунд; держать поток столько значило бы платить
// этой задержкой за КАЖДУЮ строку, которую вызывающему не разрешат никогда.
// Поэтому окно его не покрывает, а остаток называется ПЕРЕПИСЬЮ (см.
// [delivery.census]): строка, снятая по истечении окна, попадает в счётчик, и
// расхождение «прочитано против отдано» перестаёт быть немым.
package subscription

import (
	"log/slog"
	"time"
)

// GrantSettlingWindow — сколько поток ждёт кортеж владения, прежде чем счесть
// «нет» окончательным.
//
// # ВЕЛИЧИНА ВЫВЕДЕНА ИЗ ПРОИЗВОДИТЕЛЯ, а не назначена числом
//
// Ждут здесь ровно одного: чтобы владелец прав узнал о ресурсе, созданном мигом
// раньше. Производителей, разбуженных той же фиксацией, ДВА — синхронный доклад
// сразу после коммита и дренаж намерения, лежащего в той же writer-транзакции, —
// и каждый есть ОДИН вызов к соседу под сроком запроса. Срок такого вызова в
// этом дереве — секунды (пять у рёбер на пути запроса), поэтому окно взято как
// два таких срока: первая полоса плюс её замена, когда первая не дошла.
//
// # ПОЧЕМУ НЕ ДОЛЬШЕ
//
// Окно есть ПОТОЛОК ЗАДЕРЖКИ, которую платит вызывающий за строку, которую ему
// не разрешат никогда: такая строка удерживает партию ровно окно и лишь потом
// снимается. Растянуть его до шага реконсайлера значило бы обменять редкую
// потерю на постоянную задержку — размен в неверную сторону, потому что потеря
// теперь ВИДНА переписью, а задержка была бы не видна ничем.
//
// # ПОЧЕМУ НЕ КОРОЧЕ
//
// Окно короче срока ОДНОГО вызова к соседу не покрывает даже счастливый путь:
// синхронный доклад, начатый одновременно с пробуждением потока, не успел бы
// завершиться, и отсрочка истекала бы раньше того, чего ждёт.
//
// # ЭТО НЕ ВЕЛИЧИНА ПОСАДКИ
//
// Она не приезжает из объявления сервиса и не сужается оператором: у всех пяти
// владельцев журнала грант кладёт одна и та же пара производителей, а поведение
// подписки объявлено ОДНО на платформу. Ручка здесь означала бы, что два
// владельца вправе по-разному отвечать на один вопрос контракта.
const GrantSettlingWindow = 10 * time.Second

// delivery — состояние ОДНОГО потока: удержание и перепись доставки.
//
// Живёт у потока, а не у сервера: у каждого потока свой вызывающий, свой курсор
// и своё окно. Общий экземпляр смешал бы переписи и позволил бы одному потоку
// снять удержание другого.
type delivery struct {
	// heldAt — курсор, на котором стоит удержание; heldSince — когда оно начато.
	// Нулевой heldSince означает, что удержания нет.
	heldAt    int64
	heldSince time.Time

	// atHead — предыдущая партия дошла до границы устоявшегося.
	//
	// Признак несущий, а не оптимизация. Удерживать ДОГОНЯЮЩИЕ партии незачем:
	// их строки устоялись раньше, чем поток начал проход, и грант по ним либо
	// давно лежит, либо не ляжет вовсе, — а платил бы за это окном КАЖДЫЙ
	// подписчик, возобновившийся со старой позиции. Признак отвечает на «была ли
	// эта строка ЖИВОЙ», и без него всплеск больше партии на голове журнала
	// остался бы без отсрочки.
	atHead bool

	// Перепись доставки: ОБЕ величины, а не одна.
	//
	// «Прочитано» без «отдано» не показывает пропуска, «отдано» без
	// «прочитано» — не показывает его тоже. Расхождение между ними и есть
	// предмет наблюдения, поэтому счётчики печатаются вместе и всегда.
	rowsRead     int64
	eventsSent   int64
	rowsWithheld int64

	// readThrough — самая высокая ОСМОТРЕННАЯ позиция.
	//
	// Удержанная партия перечитывается каждым проходом — в том и смысл окна, —
	// поэтому счёт по числу прочитанных строк назвал бы одну строку столько раз,
	// сколько её спрашивали. Перепись тогда показывала бы расхождение, которого
	// нет, и тем громче, чем дольше держали: прибор, все находки которого ложные,
	// перестают читать.
	readThrough int64
}

// read вносит в перепись строки, которых она ещё не видела.
//
// Партия упорядочена по возрастанию позиции, поэтому «ещё не видела» — это
// строго выше [delivery.readThrough]; повторно прочитанные строки удержания
// в счёт не идут.
func (d *delivery) read(rows []Row) {
	for _, r := range rows {
		if r.Position > d.readThrough {
			d.rowsRead++
		}
	}
	if n := len(rows); n > 0 && rows[n-1].Position > d.readThrough {
		d.readThrough = rows[n-1].Position
	}
}

// holds — удерживается ли партия, чья первая невидимая строка стоит на позиции
// `at` при курсоре `cursor`.
//
// Три исхода, и порядок их проверки НЕСУЩИЙ:
//
//   - удержание уже стоит на этом курсоре и окно не истекло — держим дальше;
//   - окно истекло — снимаем удержание и отдаём партию, сняв невидимые строки;
//   - удержания не было — берём его, если строка ЖИВАЯ.
//
// «Живая» здесь значит «партия дошла до головы журнала либо предыдущая до неё
// доходила»: см. [delivery.atHead].
func (d *delivery) holds(cursor int64, reachesHead bool, now time.Time) bool {
	if !d.heldSince.IsZero() && d.heldAt == cursor {
		if now.Sub(d.heldSince) < GrantSettlingWindow {
			return true
		}
		// Окно истрачено: строка снимается, и это ЗАПИСЫВАЕТСЯ (см. census).
		d.heldAt, d.heldSince = 0, time.Time{}
		return false
	}
	if !reachesHead && !d.atHead {
		// Догоняющая партия: её строки старше окна by construction.
		return false
	}
	d.heldAt, d.heldSince = cursor, now
	return true
}

// released снимает удержание, взятое на ЧУЖОМ курсоре.
//
// Курсор ушёл вперёд (строка стала видимой либо партия отдана целиком), значит
// прежнее удержание больше ни к чему не относится. Не снять его здесь значило
// бы, что окно следующей невидимой строки отсчитывается от чужого мига, — то
// есть иногда не отсчитывается вовсе.
func (d *delivery) released(cursor int64) {
	if !d.heldSince.IsZero() && d.heldAt != cursor {
		d.heldAt, d.heldSince = 0, time.Time{}
	}
}

// census печатает ОБЕ величины доставки при закрытии потока.
//
// # Почему перепись, а не тревога
//
// Строка, снятая по истечении окна, бывает и законной: вызывающему её не
// разрешат никогда, и такое «нет» — штатное состояние, а не находка. Тревога на
// нём срабатывала бы постоянно и перестала бы читаться вместе с настоящей
// находкой. Перепись называет ЧИСЛО и оставляет суждение читателю: ноль снятых
// означает, что расхождения не было вовсе; ненулевое — что оно было, и его
// величина известна.
//
// # Почему при закрытии, а не по ходу
//
// Обе величины окончательны только тогда. Печатать их по ходу значило бы
// печатать их на каждой партии — то есть на каждом событии.
func (d *delivery) census(log *slog.Logger, table string) {
	log.Info("subscription: stream delivery census",
		"table", table,
		"rows_read", d.rowsRead,
		"events_sent", d.eventsSent,
		"rows_withheld", d.rowsWithheld,
	)
}
