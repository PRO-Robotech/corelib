// Package subscription — ГРАНИЦА УСТОЯВШЕГОСЯ у журнала, дописываемого в конец,
// и объявление того, что владелец обещает про его удержание.
//
// # Что здесь есть и почему именно это
//
// Журнал, в который пишут несколько транзакций сразу, нельзя читать по
// максимальному номеру строки: строка с меньшим номером может быть ещё не
// закоммичена, и читатель, ушедший вперёд, пропустит её НАВСЕГДА — курсор
// двигается только вперёд. [Watermark] отвечает на единственный вопрос «какая
// позиция уже не может измениться», наблюдая незавершённых писателей, а не
// строки.
//
// [Retention] — вторая половина того же предмета: нижняя возобновимая позиция
// выводится по-разному у владельца, который журнал чистит, и у того, который
// удерживает всё. Ноль объявлением не является, поэтому у перечисления есть
// [RetentionUnset], а не «умолчание».
//
// # Чего здесь НЕТ — и это решение, а не остаток работы
//
// Сервера потока изменений ресурсов здесь нет. Он объявляет форму подписки с
// ПЛАТФОРМЕННЫМ именем (`kacho.cloud.subscription`), служит её пяти владельцам
// платформы и ни одному потребителю за её пределами — значит его дом там же,
// где его контракт, а не в фундаменте, который линкуют оба продукта
// (решение владельца 2026-09-13, kacho#2601, kacho#2617).
//
// Здесь остаётся ровно то, у чего контракта нет вовсе: наблюдение позиции — про
// строки и транзакции, а не про вид ресурса, проект или право. Поэтому им
// пользуется и служба доступа — для своего журнала смены субъекта, который
// подпиской не служится и служиться не будет.
//
// # Кто это берёт
//
// Прямой потребитель собирает наблюдателя [NewWatermark] на СВОИ имена таблицы
// и колонки — они попадают в текст запроса и не экранируются, поэтому приходить
// снаружи не могут. Сервер потока, живущий в репозитории платформы, берёт
// [NewWatermarkWithClock]: предупреждение о застое измеряется временем, и проба
// обязана двигать часы сама, а не ждать их.
