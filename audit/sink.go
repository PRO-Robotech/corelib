// Package audit — ПРИЁМНИК журнала аудита control-plane и вывоз в него строк,
// накопленных мутациями.
//
// # Что здесь решено и почему именно так
//
// Журнал аудита отвечает на вопрос «кто, над чем и когда совершил значимое
// действие». Пишется он в ту же транзакцию, что и мутация (иначе врал бы в одну
// из двух сторон: запись без мутации либо мутация без записи), а доставляется —
// отсюда.
//
// Приёмником выбран ПОТОК СТРУКТУРНЫХ ЗАПИСЕЙ СЛУЖБЫ — тот же, куда служба уже
// пишет всё остальное, что о ней надо знать снаружи. Выбор объясняется тем, чем
// он НЕ является:
//
//   - брокера в продукте нет и он запрещён (non-negotiable #7), поэтому топик
//     приёмником быть не может;
//   - общих баз нет (non-negotiable #8), поэтому чужая таблица — тоже нет;
//   - внешний накопитель журналов пришлось бы объявлять в каждом профиле
//     развёртывания, а не объявленный он давал бы приёмник, отсутствующий ровно
//     на том стенде, где очередь и растёт. Адрес зависимости, которого никто не
//     задаёт, — это контроль, не отказавший ни разу за свою жизнь.
//
// Поток записей службы существует BY CONSTRUCTION везде, где служба поднята, и
// собирается тем же конвейером, что остальные её записи. Отсюда определение
// доставки: строка доставлена, когда запись журнала ПРИНЯТА обработчиком потока.
//
// # У этого приёмника ЕСТЬ ручка, и она умеет его заглушить
//
// Здесь стоял довод «приёмник, у которого нет собственной настройки, нельзя
// настроить неверно». Он ЛОЖЕН, и это измерено: уровень потока — первоклассная
// ручка развёртывания службы прав (`logger.level`, принимает WARN/ERROR/FATAL),
// и на WARN доставка равна нулю, а очередь растёт бессрочно — травления у
// журнала нет по замыслу. То есть ровно тот отказ, которым выше отвергается
// внешний накопитель.
//
// Верно же вот что, и разница существенная: у потока службы НЕТ адреса, поэтому
// «ведёт в никуда» с ним невозможно, а единственный его способ отказать —
// уровень — ЗНАЕМ ПРИ СТАРТЕ одним вызовом. Поэтому предпосылка проверяется
// fail-closed до подъёма ([LogSink.Preflight]), и служба, чей журнал не доедет,
// не поднимается вовсе. У внешнего накопителя решаемых при старте предпосылок
// нет: достижимость выясняется только обращением, а выведенный по умолчанию
// адрес всегда непуст и потому выглядит настроенным (`security.md` §Hardening 9).
//
// # Чего этот пакет НЕ решает
//
// Не решает срок хранения уже вывезенных строк и не заводит витрину чтения:
// это отдельные предметы. Здесь только доставка.
package audit

import (
	"context"
	"fmt"
	"log/slog"
	"sort"
	"time"
)

// Состояния доставки строки журнала. Их РОВНО ДВА, и это следствие контракта
// [Sink], а не экономия: у приёмника нет класса «отказ, который не пройдёт
// никогда», поэтому недоставленная строка всегда ждёт следующей попытки, а
// «доставлена» — терминально.
//
// Объявлены константами и здесь же подставляются в операторы: перечень
// состояний и то, что пишет вывоз, обязаны быть одним местом, иначе они
// разойдутся молча.
const (
	StatusPending = "pending"
	StatusSent    = "sent"
)

// Record — одна запись журнала, как она уезжает приёмнику.
//
// Fields несёт строку журнала ЦЕЛИКОМ за вычетом учётных колонок доставки. Так
// сделано намеренно: у разных служб журнал несёт разные колонки (актор, предмет,
// область, второе лицо, арендатор), и приёмник, знающий фиксированный список
// полей, доставлял бы запись без того, ради чего она заведена. Учётные колонки,
// наоборот, частью записи не являются — они про доставку, а не про действие.
type Record struct {
	// ID — идентификатор записи журнала (`aud…` / `evt_…`).
	ID string
	// EventType — глагол в форме «ресурс.действие».
	EventType string
	// CreatedAt — момент действия, а не момент доставки.
	CreatedAt time.Time
	// Fields — остальные колонки строки, как их отдала БД.
	Fields map[string]any
}

// Sink — приёмник журнала.
//
// # Исходов ДВА, и третьего нет by construction
//
// nil — запись принята. Любая ошибка — НЕ принята, и повтор осмыслен.
//
// Класса «принять невозможно никогда» у контракта нет, и это решение, а не
// упущение: единственная запись, которую нельзя принять, — структурно не запись
// журнала (нет идентификатора, нет глагола), а такой строки в журнале не
// существует — обе колонки объявлены NOT NULL и закрыты ограничениями формы.
// Ветка, которую нечему произвести, была бы мёртвой: её нельзя ни выполнить, ни
// проверить иначе как подставным приёмником.
//
// Отсюда и отсутствие травления у вывоза: постоянно отказывающий приёмник —
// это НАША неисправность (поток службы заглушён, устройство отказало), она
// чинится перекатом, а не выбрасыванием записи аудита. Цена решения названа:
// такая строка повторяется бессрочно с ограниченным сверху отступом, и это
// видно счётчиками — глубина очереди и возраст её головы растут.
type Sink interface {
	Ship(ctx context.Context, r Record) error
	// Name — имя приёмника, попадающее в диагностику вывоза.
	Name() string
}

// LogSink — приёмник, кладущий запись в поток структурных записей службы.
//
// # Почему обработчик, а не логгер
//
// `slog.Logger.Info` ошибку записи ГЛОТАЕТ. Приёмник, построенный на логгере,
// докладывал бы об успехе даже тогда, когда поток не принял ничего, — то есть
// строка помечалась бы доставленной ровно в том случае, ради которого повторы и
// заведены. Обработчик (`slog.Handler.Handle`) ошибку ВОЗВРАЩАЕТ; он же
// сериализует записи под собственным замком, поэтому строки не рвутся при
// параллельной записи.
type LogSink struct {
	handler slog.Handler
	level   slog.Level
}

// NewLogSink строит приёмник над логгером службы. Записи уезжают на уровне Info
// — том, на котором поток службы собирается всегда.
func NewLogSink(logger *slog.Logger) *LogSink {
	return &LogSink{handler: logger.Handler(), level: slog.LevelInfo}
}

// Name — имя приёмника для диагностики.
func (s *LogSink) Name() string { return "log-stream" }

// Preflight — единственная предпосылка этого приёмника, проверяемая ДО старта.
//
// # Зачем отдельный вызов, если Ship проверяет то же самое
//
// Потому что отказ на Ship наступает ПОЗЖЕ и тише: служба поднимается,
// принимает запросы, пишет журнал — и только очередь молча растёт. Уровень
// потока задаётся настройкой развёртывания (`logger.level` в профиле службы
// прав принимает WARN/ERROR/FATAL) и от неё не меняется в течение жизни
// процесса, поэтому вопрос «доедет ли журнал вообще» РЕШАЕТСЯ ОДНИМ ВЫЗОВОМ при
// старте. Служба, чей журнал аудита не доедет by construction, не имеет права
// подняться молча — это тот же fail-closed boot-guard, что и у прочих
// предпосылок безопасности (`security.md` §«Production boot-guard»,
// §Hardening 8: мягкий проход обязан отличать НАСТРОЙКУ от сбоя).
//
// Текст отказа общий с [LogSink.Ship] — намеренно: два текста об одном предмете
// разошлись бы, и оператор читал бы разное в зависимости от того, когда его
// поймали.
func (s *LogSink) Preflight(ctx context.Context) error {
	return s.refusalIfSilenced(ctx)
}

// refusalIfSilenced — отказ, если поток не принимает записи нашего уровня.
func (s *LogSink) refusalIfSilenced(ctx context.Context) error {
	if s.handler.Enabled(ctx, s.level) {
		return nil
	}
	return fmt.Errorf("audit: поток службы не принимает записи уровня %s — "+
		"журнал аудита не доедет, пока уровень потока не понижен", s.level)
}

// Ship кладёт одну запись в поток.
//
// Заглушённый уровень — это НАСТРОЙКА, а не сбой, и молчаливым успехом она быть
// не может: иначе журнал считался бы доставленным, не появившись в потоке ни
// разу. Отказ здесь такой же, как отказ устройства, — строка обязана дождаться
// починки настройки, а не быть потерянной из-за неё.
//
// Проверка ОСТАЁТСЯ и здесь, хотя [LogSink.Preflight] уже отказал бы в старте:
// приёмник — экспортированный тип, и поднять его может кто угодно, не спросив
// предпосылки. Проверка на пути доставки — не дубль стража, а его основание.
func (s *LogSink) Ship(ctx context.Context, r Record) error {
	if err := s.refusalIfSilenced(ctx); err != nil {
		return err
	}

	attrs := make([]any, 0, len(r.Fields)+3)
	attrs = append(attrs,
		slog.String("id", r.ID),
		slog.String("event_type", r.EventType),
		slog.Time("created_at", r.CreatedAt),
	)
	// Порядок полей детерминирован: запись журнала читают и глазами, и разбором,
	// а произвольный порядок делает две одинаковые записи различимыми на вид.
	keys := make([]string, 0, len(r.Fields))
	for k := range r.Fields {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		attrs = append(attrs, slog.Any(k, r.Fields[k]))
	}

	rec := slog.NewRecord(r.CreatedAt, s.level, "audit", 0)
	rec.AddAttrs(slog.Group("audit", attrs...))
	if err := s.handler.Handle(ctx, rec); err != nil {
		return fmt.Errorf("audit: поток службы не принял запись %s: %w", r.ID, err)
	}
	return nil
}

var _ Sink = (*LogSink)(nil)
