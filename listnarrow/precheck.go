package listnarrow

import "context"

// Precheck — предусловие списочного чтения: вызывающий НАЗВАН и посадка позволяет
// спросить модель. Возвращает ту же ошибку, что вернул бы IDs/Page, потому что
// исполняет ТУ ЖЕ функцию — второго кодека здесь не заводится, и разойтись им негде.
//
// Зачем отдельная дверь, если IDs проверяет то же самое. Затем, что между решением и
// сужением стоит ЧТЕНИЕ СТРАНИЦЫ ИЗ БД. Без предусловия безымянный запрос оплачивал
// бы курсорный запрос к своей базе, чтобы получить отказ на прочитанном, — работа,
// исход которой известен заранее. Порядок в вызывающем обязан быть:
//
//	формат пагинации → Precheck → чтение страницы → Page/IDs
//
// Формат ПЕРВЫМ и здесь не переставляется: ответ на некорректный ввод не должен
// зависеть от того, что вызывающему выдано, иначе один и тот же мусорный курсор
// получает разный ответ у разных субъектов.
//
// Аварийный режим Precheck НЕ считает: он ещё ничего не пропустил — страница не
// прочитана. Считает и называет тот проход, который действительно произошёл (IDs).
func Precheck(ctx context.Context, n *Narrower) error {
	_, err := gate(ctx, n)
	return err
}

// gate — общие первые две ветки обоих входов: ЛИЧНОСТЬ, затем ПОСАДКА.
//
// Порядок несущий и потому живёт в одном месте: пока отсечка безымянного стояла ЗА
// веткой посадки, посадка без модели отдавала всю страницу кому угодно, и держалось
// это лишь на загрузочном страже — то есть ровно до первой конфигурации, которая его
// не взвела.
//
// Аварийный режим здесь НЕ пропускает и не отказывает: он не относится ни к личности,
// ни к «спросить негде» — это отдельный, ПОСЧИТАННЫЙ исход, и принимается он там, где
// страница уже на руках.
func gate(ctx context.Context, n *Narrower) (string, error) {
	subject, err := SubjectFromContext(ctx)
	if err != nil {
		return "", err
	}
	if n == nil {
		return "", ErrModelNotWired()
	}
	if !n.cfg.Breakglass && n.cli == nil {
		return "", ErrModelNotWired()
	}
	return subject, nil
}
