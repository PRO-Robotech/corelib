// Package migratorrun — накат цепочки миграций, объявленный ОДИН раз на дерево.
//
// Все семь точек наката (`services/*/cmd/migrator`) применяют миграции через
// [Runner] и своей редакции этого шага не держат. Решение и его довод —
// docs/architecture/migrator-form.md; здесь они не пересказываются.
//
// # Что сюда переехало
//
// Один и тот же вопрос — «как этот сервис применяет миграции» — решался в дереве
// ДВУМЯ формами, и решения об этом не принимал никто: формы разошлись как
// побочный эффект того, что сервисы заводились в разное время (#1383). Три
// службы держали собственный пакет-обёртку `internal/apps/migrator`
// (`Dialect` + `Runner` + `Config.Validate`), четыре звали goose прямо из
// `main.go`. Три обёртки при этом копиями НЕ были: у двух `Dialect` был
// интерфейсом, у одной — структурой.
//
// # Почему дом здесь, а не в pkg/migratorcli
//
// Решение называет домом общего пакета `pkg/`, и `pkg/migratorcli` уже несёт всё,
// что базы не касается: разбор аргументов, приоритет источников DSN,
// предусловия, открытие базы с барьером готовности, настройку goose.
//
// Накат туда не переехал по ОДНОЙ измеренной причине: ему нужен живой счёт строк
// перед сносом (`pkg/dropguard`), а `pkg/` не имеет НИ ОДНОГО ребра в
// `internal/` (предикат: `git grep -l 'kacho/internal/' -- pkg ':!*_test.go'` →
// пусто). Завести первое такое ребро ради одного вызова значило бы принять
// решение о `pkg/` целиком, никем не принятое, и принять его молча.
//
// Довод содержательный, а не обходной: счёт перед сносом — политика об этом
// дереве и его цепочках, а не переиспользуемый фундамент. Пакет, которому он
// нужен, репозиторно-внутренний по природе. Довод самого решения при этом
// сохранён дословно — общий пакет не лежит внутри одной службы и потому не
// заводит ребра между службами (ban #8).
//
// # Счёт перед сносом стоит ПО ПОСТРОЕНИЮ
//
// Он живёт внутри [Runner.Up]: обойти его нельзя, не обойдя сам Up. В прямой
// форме это был отдельный оператор в `main.go`, и его наличие держал гейт —
// то есть шаг, который зовут отдельной строкой, однажды могли не позвать.
