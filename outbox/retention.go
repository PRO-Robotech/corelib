// retention.go — УБОРКА ДОСТАВЛЕННЫХ СТРОК очереди дренажа: предикат и порог.
//
// Предмет — задача продукта #1361. Дренаж помечает доставленную строку `sent_at`
// и НЕ УДАЛЯЕТ её никогда: и клейм, и применение, и повтор ключуются на
// `sent_at IS NULL`, а операторов снятия в этом пакете было ноль. Строка при
// этом заводится в writer-транзакции КАЖДОЙ мутации, то есть темп задаёт
// арендатор, и рост был монотонным и вечным у семи очередей шести владельцев.
//
// Петля, партии, потолок проходов и наблюдаемость живут в `pkg/retention` и
// здесь не повторяются. Здесь — только ПРЕДИКАТ и его порог, потому что предикат
// есть свойство ЭТОЙ семьи таблиц: у очереди дренажа признак доставки —
// `sent_at`, и он принадлежит дренажу, живущему рядом.
//
// # СЕМЬ ОЧЕРЕДЕЙ, ОДИН ПРЕДИКАТ — и почему не семь копий
//
// Семь расписаний об одном предмете разошлись бы молча и дали бы разный срок
// жизни доставленной строки у разных доменов при ОДНОМ контракте доставки. Имя
// таблицы и ключ партиции приезжают сюда ЗНАЧЕНИЯМИ, а оператор — один.
package outbox

import (
	"context"
	"fmt"
	"strings"
	"time"

	"log/slog"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"

	"github.com/PRO-Robotech/corelib/retention"
)

// DeliveredRetention — сколько доставленная строка остаётся в очереди.
//
// # ВЕЛИЧИНА ВЫВЕДЕНА ИЗ ЧИТАТЕЛЯ, а не назначена числом
//
// Читателей у доставленной строки ДВА, и они требуют разного.
//
//  1. `reconciler.RedrivePoisoned` — читает доставленных ПРЕЕМНИКОВ, решая, можно
//     ли оживить отравленную строку. Его требование СТРУКТУРНОЕ, а не временно́е,
//     и закрывается оно предикатом ниже, а не порогом: снять защищающую строку
//     нельзя НИКОГДА, сколько бы ей ни было лет.
//
//  2. ОПЕРАТОР, разбирающий «доехало ли снятие доступа». Вот его требование и
//     задаёт величину: столько, сколько разбирают инцидент. Та же неделя, что у
//     таблицы операций и у журнала подписки, и по той же причине — нерабочее
//     время: упавший в пятницу вечером разбирается в понедельник утром.
//
// # ПОЧЕМУ ТА ЖЕ ВЕЛИЧИНА, ЧТО У СОСЕДЕЙ, И ПОЧЕМУ ОНА НЕ ПЕРЕИСПОЛЬЗУЕТСЯ
//
// `pkg/operations.OperationRetention` и `pkg/subscription.JournalRetention`
// выведены из СВОИХ читателей и совпали числом. Совпадение чисел не есть один
// предмет: связать их константой значило бы, что сдвиг срока разбора отказов
// двигает срок жизни доставленной строки очереди. Величины объявляются порознь,
// и каждая — рядом со своим читателем.
//
// # У ПОРОГА НЕТ СЛАГАЕМОГО НА РАЗНИЦУ ЧАСОВ, и это замер, а не упущение
//
// Отметку `sent_at` ставит сам дренаж оператором `UPDATE … SET sent_at = now()`,
// то есть часами БАЗЫ — теми же, которыми судит оператор ниже. Слагаемое,
// покрывающее разницу, которой нет, было бы запасом без предмета. У таблицы
// операций такое слагаемое ЕСТЬ (`pkg/operations.ClockDrift`) именно потому, что
// её отметку пишет процесс.
const DeliveredRetention = 7 * 24 * time.Hour

// QueueExecer — то, чем уборщик исполняет свой оператор.
type QueueExecer interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
}

// QueueRetentionConfig — объявление владельца очереди.
type QueueRetentionConfig struct {
	// Table — полное имя таблицы очереди («<схема>.<таблица>» либо «<таблица>»).
	Table string
	// PartitionColumn — ключ партиции ПОРЯДКА: тот же, которым пользуются клейм
	// дренажа и анти-джойн реконсайлера. ОБЯЗАТЕЛЕН, см. NewQueueSweeper.
	PartitionColumn string
}

// queueSweepSQL — предикат уборки доставленных строк очереди дренажа.
//
// ТРИ РЕШЕНИЯ, и первое несущее.
//
//  1. ЩАДИТСЯ ДОСТАВЛЕННАЯ СТРОКА, У КОТОРОЙ В ПАРТИЦИИ ЕСТЬ НЕДОСТАВЛЕННЫЙ
//     ПРЕДШЕСТВЕННИК. Доставленную строку читает второй потребитель —
//     `reconciler.RedrivePoisoned`: отравленная строка НЕ оживляется, если в её
//     партиции уже доставлена БОЛЕЕ ПОЗДНЯЯ, иначе повтор устаревшего намерения
//     отменил бы уже применённое. На очереди регистрации это буквально
//     ВОСКРЕШАЕТ доступ, который был отозван. Уборка, снявшая защищающую строку,
//     снимает и защиту — молча, и обнаружилось бы это воскрешённым доступом.
//     Поэтому щадится любая доставленная строка, ниже которой в её партиции
//     лежит непременно недоставленная (`sent_at IS NULL` — и ожидающая, и
//     отравленная: ожидающая вправе стать отравленной завтра).
//
//     Ключ партиции — ТОТ ЖЕ, что у клейма и у анти-джойна, и приезжает
//     значением: второе написание того же ключа разошлось бы с ними молча.
//
//  2. НЕДОСТАВЛЕННОЕ НЕ СНИМАЕТСЯ НИ ПРИ КАКОМ ВОЗРАСТЕ. Условие `sent_at IS NOT
//     NULL` исключает отравленную строку BY CONSTRUCTION: у неё отметки доставки
//     нет. Это не побочный эффект, а требование — отравленная строка несёт
//     намерение, которое не доехало, и снять её значило бы потерять его молча.
//
//  3. ПАРТИЯ ОГРАНИЧЕНА (`LIMIT $2`), а отбор идёт по возрастанию id: уборка не
//     вправе быть причиной отказа на пути запроса. Клейма (`FOR UPDATE SKIP
//     LOCKED`) здесь НЕТ намеренно — в отличие от уборки таблицы операций:
//     пропуск запертой строки безопасен там, где строки независимы, но здесь
//     решение о строке зависит от СОСЕДЕЙ ПО ПАРТИЦИИ, и пропуск сделал бы
//     исход прохода зависящим от того, что заперто. Реплики сериализуются на
//     замках строк обычным порядком; вторая находит участок уже снятым.
const queueSweepSQL = `
DELETE FROM %[1]s
 WHERE id IN (
       SELECT s.id
         FROM %[1]s s
        WHERE s.sent_at IS NOT NULL
          AND s.sent_at < now() - make_interval(secs => $1)
          AND NOT EXISTS (
              SELECT 1
                FROM %[1]s p
               WHERE p.%[2]s = s.%[2]s
                 AND p.id < s.id
                 AND p.sent_at IS NULL)
        ORDER BY s.id
        LIMIT $2)`

// QueueSweeper — уборщик доставленных строк ОДНОЙ очереди.
type QueueSweeper struct {
	db   QueueExecer
	stmt string
	name string
}

// NewQueueSweeper собирает уборщика по объявлению владельца.
//
// ОТКАЗЫВАЕТ БЕЗ КЛЮЧА ПАРТИЦИИ, и это fail-closed, а не придирка к форме: без
// ключа предикат «пощадить защищающую строку» НЕВЫРАЗИМ, и собранный молча
// уборщик снимал бы защиту отзыва у каждой очереди. Отказ наступает на сборке,
// потому что тихо собранный уборщик обнаружился бы воскрешённым доступом.
func NewQueueSweeper(db QueueExecer, cfg QueueRetentionConfig) (*QueueSweeper, error) {
	if strings.TrimSpace(cfg.Table) == "" {
		return nil, fmt.Errorf("outbox: уборка очереди: имя таблицы не названо")
	}
	if !validQueueIdentifier(cfg.PartitionColumn) {
		return nil, fmt.Errorf(
			"outbox: уборка очереди %s: PartitionColumn не назван либо негоден (%q). "+
				"Без ключа партиции нельзя пощадить доставленную строку, которая не даёт "+
				"реконсайлеру оживить отравленного предшественника, — то есть уборка сняла "+
				"бы защиту отзыва доступа молча", cfg.Table, cfg.PartitionColumn)
	}
	return &QueueSweeper{
		db: db,
		stmt: fmt.Sprintf(queueSweepSQL,
			SanitizeTable(cfg.Table), pgx.Identifier{cfg.PartitionColumn}.Sanitize()),
		name: queueSubjectName(cfg.Table),
	}, nil
}

// Sweep — один проход партии.
//
// Момент времени входом НЕ приходит: часы уборки — базы, те же, что ставят
// отметку доставки (см. [DeliveredRetention]). Проверяемость от этого не
// теряется — проход зовётся методом, поэтому пробе не приходится ни спать, ни
// подменять часы.
//
// Возвращает число снятых строк и признак «партия ушла полной»; признак отличает
// «убрал всё, что было» от «упёрся в партию».
func (s *QueueSweeper) Sweep(ctx context.Context, grace time.Duration, batch int) (int64, bool, error) {
	tag, err := s.db.Exec(ctx, s.stmt, grace.Seconds(), batch)
	if err != nil {
		return 0, false, fmt.Errorf("outbox: уборка очереди %s: %w", s.name, err)
	}
	n := tag.RowsAffected()
	return n, n >= int64(batch), nil
}

// RetentionSubject — запись реестра уборки для этой очереди.
//
// Порог собирается ЗДЕСЬ, а не у каждого из шести владельцев: семь копий одного
// порога разошлись бы молча и дали бы разный срок жизни доставленной строки у
// разных доменов при ОДНОМ контракте доставки.
func (s *QueueSweeper) RetentionSubject() retention.Subject {
	return retention.Subject{
		Name:  s.name,
		Grace: DeliveredRetention,
		Sweep: s.Sweep,
	}
}

// StartQueueRetentionSweep поднимает фоновую уборку доставленных строк очереди.
//
// ОДНА строка в композиционном корне владельца — намеренно: шесть владельцев
// несут семь очередей одной формы с одним контрактом доставки, и всё, что у них
// могло бы разойтись, собрано здесь.
//
// Отказывает, а не предупреждает: отказ означает негодные величины расписания
// либо объявление, при котором уборка небезопасна.
func StartQueueRetentionSweep(
	ctx context.Context,
	db QueueExecer,
	cfg QueueRetentionConfig,
	rcfg retention.Config,
	log *slog.Logger,
) (*retention.Sweeper, error) {
	sw, err := NewQueueSweeper(db, cfg)
	if err != nil {
		return nil, err
	}
	sweeper, err := retention.New(rcfg, []retention.Subject{sw.RetentionSubject()}, log)
	if err != nil {
		return nil, fmt.Errorf("уборка доставленных строк очереди: %w", err)
	}
	sweeper.Start(ctx)
	return sweeper, nil
}

// queueSubjectName — имя предмета уборки: имя таблицы БЕЗ схемы.
//
// Имя попадает в отчёт прохода и в метку метрики, и оператор обязан узнавать в
// нём таблицу.
func queueSubjectName(table string) string {
	if i := strings.LastIndex(table, "."); i >= 0 {
		return table[i+1:]
	}
	return table
}

// validQueueIdentifier — имя колонки подставляется в оператор, поэтому
// проверяется на СБОРКЕ: негодное значение обязано отказать здесь, а не
// синтаксической ошибкой на первом проходе минутами позже. Пустая строка
// отвергается отдельно — именно она молча означала бы «партиции нет».
func validQueueIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c == '_':
		case i > 0 && c >= '0' && c <= '9':
		default:
			return false
		}
	}
	return true
}
