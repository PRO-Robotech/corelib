package grpcsrv

// admission_report.go — счёт допущенных и отвергнутых плюс уборка вёдер, ОДНИМ
// телом на все композиционные корни.
//
// # Почему здесь, а не у каждого корня
//
// Цикл отчёта был написан ДВАЖДЫ — у носителя контура (`pkg/servicehost`) и у
// iam, — слово в слово. Третья копия появилась бы вместе с краем: место,
// собирающее серверы само, обязано и считать само. Копии одного предмета
// расходятся молча, и разошлись бы они именно в том, ради чего заведены, — в
// ЧИСЛАХ, по которым отличают живой ограничитель от мёртвого.
//
// # Почему отчёт печатается ВСЕГДА, включая нули
//
// «Ноль отказов за всю жизнь контроля» обязано быть ЗАМЕТНО, иначе мёртвый
// ограничитель невидим: он навешен, исполняется на каждом запросе и не отверг ни
// разу — ровно как и тот, чей ключ всегда пуст. Отличает их ПАРА чисел: ноль
// отвергнутых при нуле допущенных означает «никто не звал», а при миллионе
// допущенных — «предел ни разу не достигнут». Это разные факты, и вывод, где
// печатаются только находки, их не различает.
//
// # Почему уборка вёдер живёт в отчёте, а не внутри ограничителя
//
// Пространство личностей задаёт ВЫЗЫВАЮЩИЙ, поэтому у роста числа вёдер обязан
// быть владелец в процессе, а не фоновая горутина, запущенная библиотекой за
// спиной у него. Собственный жёсткий потолок ограничителя при этом остаётся —
// уборка его дополняет, а не заменяет.

import (
	"context"
	"log/slog"
	"time"
)

const (
	// AdmissionReportInterval — как часто в журнал уходит счёт.
	AdmissionReportInterval = time.Minute
	// AdmissionIdleWindow — за сколько простоя ведро субъекта убирается.
	//
	// Величина щедрая намеренно: убрать ведро значит вернуть субъекту полный
	// всплеск, поэтому уборка обязана отставать от окна, в котором предел ещё
	// имеет смысл.
	AdmissionIdleWindow = 10 * time.Minute
)

// ReportAdmission — фоновая задача процесса: периодически печатает счётчики
// каждого ограничителя и убирает вёдра простаивающих субъектов. Возвращает
// управление по отмене контекста, напечатав итог.
//
// Ограничители подаются перечнем, а не парой: у края и у сервиса их по два, но
// перечень не заставляет вызывающего изобретать пустышку там, где слушатель
// один. `nil` в перечне пропускается — это объявленное изъятие, а не ошибка; а
// перечень БЕЗ единого живого ограничителя означает, что считать нечего, и
// задача завершается сразу, не занимая горутину до конца процесса.
//
// prefix — приставка сообщений. Параметр, а не константа, ровно по одной
// причине: строки журнала — то, по чему оператор ищет, и сведение трёх разных
// приставок к одной есть смена наблюдаемого поведения, которую принимают
// отдельно, а не заодно с переносом тела.
//
// РЕПЛИКИ: на-реплику — печатает счётчики СВОЕГО процесса и вычищает его же память. Общего
// состояния не трогает, к соседям не ходит; предел допуска здесь и
// публикуется полом — «не менее», что остаётся истинным при любом числе реплик.
func ReportAdmission(ctx context.Context, log *slog.Logger, prefix string, limiters ...*Admission) {
	live := make([]*Admission, 0, len(limiters))
	for _, l := range limiters {
		if l != nil {
			live = append(live, l)
		}
	}
	if len(live) == 0 {
		return
	}
	t := time.NewTicker(AdmissionReportInterval)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			LogAdmissionStats(log, prefix+"request admission final counters", live...)
			return
		case <-t.C:
			for _, l := range live {
				l.EvictIdle(AdmissionIdleWindow)
			}
			LogAdmissionStats(log, prefix+"request admission counters", live...)
		}
	}
}

// LogAdmissionStats печатает снимок счётчиков — по строке на листенер.
//
// Отдельная от [ReportAdmission] функция затем, чтобы «напечатать счёт» было
// доступно и вне цикла (итог при остановке, отладочный снимок), и чтобы форма
// строки была ОДНА: две формы одного факта читаются как два разных факта.
func LogAdmissionStats(log *slog.Logger, msg string, limiters ...*Admission) {
	if log == nil {
		return
	}
	for _, l := range limiters {
		if l == nil {
			continue
		}
		s := l.Stats()
		log.Info(msg,
			"listener", l.Listener(),
			"admitted", s.Admitted,
			"rejected_rate", s.RejectedRate,
			"rejected_in_flight", s.RejectedInFlight,
			"subjects", s.Subjects)
	}
}
