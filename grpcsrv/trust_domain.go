package grpcsrv

import (
	"fmt"
	"strings"
)

// TrustDomain — домен доверия установки: то, чьи сертификаты она признаёт
// своими.
//
// # Зачем это тип, а не строка
//
// Величину читают трое, и ровно так же, как круг отправителей
// ([TrustedForwarders]): транспорт (сверяет ей личность предъявленного
// сертификата), стража старта (решает, поднимать ли процесс) и самоотчёт о
// посадке (докладывает, под каким доменом процесс работает). Пока это была
// СКОМПИЛИРОВАННАЯ константа, каждый из троих отвечал на вопрос «наш ли это
// предъявитель» своим литералом, и литералов в дереве накопилось четыре штуки
// в четырёх файлах — в фундаменте, на крае и дважды в службе.
//
// Половина посадки при этом настраивалась честно: сертификаты выпускались под
// доменом из величины профиля. Значит правка величины давала сертификаты нового
// домена, а принимающая сторона оставалась прежней — и расходились они МОЛЧА:
// законный отправитель переставал опознаваться, а отказ выглядел как отсутствие
// личности, то есть как законный вызов без пользователя.
//
// # Нулевое значение — «домен НЕ объявлен», и это самое строгое прочтение
//
// `var d TrustDomain` соберётся всегда: запретить нулевое значение Go не даёт.
// Значит распорядиться можно только тем, ЧТО ОНО ЗНАЧИТ. Оно значит «установка
// домена не назвала», и личность по нему не опознаётся ни одна: [URIPrefix]
// пустого домена не собирается вовсе, а не вырождается в «принимаем любой».
// Пропущенная величина упирается в отказ старта ([Require]) — до транспорта она
// не доходит.
//
// # Почему умолчания нет
//
// Умолчание здесь всегда непусто, поэтому контроль выглядел бы включённым и вёл
// бы в чужой домен: установка, забывшая назвать свой, молча принимала бы
// сертификаты нашего. Это тот же класс, что адрес зависимости, выведенный из
// чужого адреса (`security.md` §«Адрес зависимости… НЕ выводится из чужого»).
//
// Значение неизменяемо после сборки: поле неэкспортируемое, а всё, что тип
// отдаёт, — производные строки.
type TrustDomain struct {
	// name — власть SPIFFE-идентификатора: то, что стоит между `spiffe://` и
	// первым `/`. Без схемы и без косых черт.
	name string
}

// NewTrustDomain собирает домен из того, что объявила установка.
//
// Пробелы по краям срезаются по той же причине, по какой их срезает круг
// отправителей: оператор, написавший величину с пробелом, получил бы не отказ
// старта, а молчаливый отказ в обслуживании законному отправителю — префикс
// " spiffe://…" не совпал бы ни с одним сертификатом.
//
// Схема, если оператор её написал, снимается: величина `spiffe://kaname.local`
// и величина `kaname.local` означают один и тот же домен, и различать их значило
// бы завести два написания одного предмета. Косые черты по краям снимаются по
// той же причине.
//
// Пустая строка даёт КАНОНИЧЕСКИЙ НОЛЬ — нулевое значение типа: у «не объявлен»
// обязано быть одно представление, иначе сравнение по одному из них однажды
// разойдётся с другим.
func NewTrustDomain(raw string) TrustDomain {
	name := strings.TrimSpace(raw)
	name = strings.TrimPrefix(name, spiffeScheme)
	name = strings.Trim(name, "/")
	if name == "" {
		return TrustDomain{}
	}
	return TrustDomain{name: name}
}

// spiffeScheme — схема идентификатора рабочей нагрузки. ЕДИНСТВЕННОЕ место
// дерева, где она объявлена значением: собранный где-то ещё префикс был бы
// вторым местом об одном предмете и разошёлся бы с этим молча.
const spiffeScheme = "spiffe://"

// TrustDomainPlaceholder — ЗАПОЛНИТЕЛЬ домена в образцах, справке и текстах
// отказа.
//
// Существует затем, чтобы образец не назывался конкретным доменом: домен
// выбирает установка, и написанный в справке он читался бы как выбор, сделанный
// за неё. Заполнитель на месте домена стоять не может, поэтому перепись
// объявлений домена его находкой не считает — и это её осознанное различие,
// а не слепая зона.
const TrustDomainPlaceholder = "<домен-доверия>"

// SANShape — ФОРМА личности сертификата: то, что оператор пишет в круге
// отправителей. Домена не несёт намеренно — его называет установка.
//
// Живёт у владельца разбора, потому что именно он решает, что считать
// личностью: образец, написанный рукой вызывающего, объявлял бы форму, которую
// разбор не обещал.
const SANShape = spiffeScheme + TrustDomainPlaceholder + "/ns/<пространство>/sa/<учётка>"

// IsDeclared — ЕДИНСТВЕННЫЙ предикат «назвала ли установка свой домен». Его
// спрашивают стража старта, самоотчёт о посадке и всякий, кому нужно решить,
// объявлена ли посадка. Транспорт принимает то же значение целиком, поэтому
// «стража пропустила» ⟺ «домен реально объявлен» — по построению.
func (d TrustDomain) IsDeclared() bool { return d.name != "" }

// Name — власть без схемы. Для диагностики и для тех, кто собирает адрес сам;
// решение принимается по [TrustDomain.IsDeclared], а не сравнением с пустой
// строкой.
func (d TrustDomain) Name() string { return d.name }

// URIPrefix — начало всякого идентификатора этого домена: `spiffe://<домен>/`.
// У необъявленного домена префикса НЕТ (пустая строка), и это не забывчивость:
// префикс `spiffe://` совпал бы с идентификатором ЛЮБОГО домена, то есть
// признал бы своим чужого предъявителя.
func (d TrustDomain) URIPrefix() string {
	if !d.IsDeclared() {
		return ""
	}
	return spiffeScheme + d.name + "/"
}

// NamespacePrefix — начало идентификатора рабочей нагрузки:
// `spiffe://<домен>/ns/`. Пусто у необъявленного домена по той же причине, что
// и [TrustDomain.URIPrefix].
func (d TrustDomain) NamespacePrefix() string {
	if !d.IsDeclared() {
		return ""
	}
	return d.URIPrefix() + "ns/"
}

// Matches — принадлежит ли предъявленный идентификатор этому домену.
//
// Единственный предикат сверки на всё дерево. Необъявленный домен не признаёт
// своим НИКОГО — включая пустой идентификатор: «домен не назвали» не означает
// «принимаем всех».
func (d TrustDomain) Matches(uri string) bool {
	p := d.URIPrefix()
	if p == "" {
		return false
	}
	return strings.HasPrefix(uri, p)
}

// String — читаемое представление для журнала. Домен не секрет (он написан в
// каждом выпущенном сертификате), поэтому печатается как есть: скрывать его
// значило бы делать неотлаживаемым отказ законному отправителю.
func (d TrustDomain) String() string {
	if !d.IsDeclared() {
		return "<not declared>"
	}
	return d.name
}

// TrustDomainGate — вход стражи домена: то, что стража обязана знать о посадке,
// чтобы решить, поднимать ли процесс.
//
// Ручка называется ЯВНО, потому что текст отказа читает оператор: сообщение, не
// называющее ручку, оставляет стенд неподнятым и непонятным. Это одно из трёх
// мест, выведенных из-под запрета на подробности в публичных артефактах, —
// рантайм-диагностика, а не рассказ о том, где было открыто.
type TrustDomainGate struct {
	// Knob — имя ручки, которой домен задаётся (для текста отказа).
	Knob string
}

// Require — стража домена доверия, ОДНА на все службы.
//
// # Почему она срабатывает на ЛЮБОМ старте, а не только в боевом режиме
//
// У необъявленного домена нет режима, в котором он работает: личность
// сертификата по нему не опознаётся ни одна, поэтому процесс, поднявшийся без
// него, отвергает КАЖДОГО отправителя — и отвергает молча, отказом, неотличимым
// от вызова без личности. Опт-ина «поднимусь без домена» нет и быть не может:
// он означал бы согласие не работать.
func (d TrustDomain) Require(g TrustDomainGate) error {
	if d.IsDeclared() {
		return nil
	}
	return fmt.Errorf("%s is empty: the installation has not named its trust domain, so no "+
		"client certificate is recognized as ours — every forwarded identity is dropped and "+
		"every module call is refused, indistinguishably from a call that carried no identity "+
		"at all; set it to the trust domain the installation issues certificates under "+
		"(the SAN shape is %s)", g.Knob, SANShape)
}
