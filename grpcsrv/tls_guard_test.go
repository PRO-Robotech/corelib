package grpcsrv_test

// tls_guard_test.go — страж: TLS-креды межсервисного gRPC собираются в
// фундаменте ТОЛЬКО помощниками `grpcsrv.TLSServerCreds` /
// `grpcclient.TLSClientCreds`. Прямой `credentials.NewTLS(…)` или собранный
// руками `tls.Config` в прод-коде фундамента роняет этот страж.
//
// # Область — ФУНДАМЕНТ, и выводится она из МЕСТА САМОГО СТРАЖА
//
// Осматривается каталог, СОДЕРЖАЩИЙ пакет этого стража. В монорепо это `pkg/`;
// в отдельном репозитории фундамента, где пакеты лежат в корне, это корень
// модуля. Набор пакетов в обеих раскладках получается один и тот же по
// ПОСТРОЕНИЮ, а не по совпадению двух литералов, которые правит разный человек.
//
// Прежде область была объявлена литералом пути дерева (`pkg`). Утверждение
// пережило свой предмет в тот день, когда фундамент впервые собрали отдельно:
// каталога `pkg` там нет, состав брать неоткуда, и страж падал не на находке, а
// на собственной области — с текстом «нет такого каталога». Свойство было
// выражено РАСКЛАДКОЙ, а предмет запрета от раскладки не зависит: это
// «фундамент, членом которого сам страж и является».
//
// Отсюда же форма ключа освобождения: путь от КОРНЯ ФУНДАМЕНТА
// (`grpcsrv/tls.go`), а не от корня репозитория. Только в ней ключ означает
// одно и то же в обеих раскладках.
//
// Предпосылка области проверяется, а не подразумевается: страж обязан найти в
// осмотренном составе СВОЙ СОБСТВЕННЫЙ помощник. Не нашёл — назван неверно
// корень, и говорит страж именно это, а не «снимите освобождение»: находка,
// называющая симптом, посылает читателя чинить перечень вместо области.
//
// # Что область НЕ обещает
//
// В монорепо `pkg/` несёт и каталоги, которые в фундамент не поедут (классы
// `kaname` и `kacho` карты границы — internal/repohygiene/foundationboundary.go).
// Значит здесь область — НАДМНОЖЕСТВО извлекаемого фундамента, и судится она
// строже требуемого. Разницы в находках это сегодня не даёт: запретную
// конструкцию под `pkg/` несут ровно два файла, и оба — объявленные помощники
// (предикат: `git grep -l -e 'credentials.NewTLS(' -e 'tls.Config{' -- 'pkg/*.go'`
// с отсевом `_test.go` → `pkg/grpcclient/tls.go` и `pkg/grpcsrv/tls.go`, замер
// на 7cd4cc8355). Сузить область до точного состава фундамента ОТСЮДА нельзя:
// карта классов живёт в internal/repohygiene, то есть в платформе, и фундаменту
// её импорт запрещён той самой границей, ради которой всё это делается.
//
// # За пределами фундамента запрет не действует, и цена названа числом
//
// Предикат:
//
//	git grep -l -e 'credentials.NewTLS(' -e 'tls.Config{' -- '*.go' \
//	  | grep -v '_test\.go$' | grep -vc '^pkg/'
//
// На 7cd4cc8355 он даёт 12 файлов. Два из них несут конструкцию ТОЛЬКО в
// комментарии (оба — примеры употребления в SDK домена vpc), то есть настоящих
// точек сборки ДЕСЯТЬ: край — 2 файла, его конфигурация — 1, служба доступа — 3,
// nlb, registry, vpc и провайдер инфраструктуры — по одному.
//
// Числа перемеряй предикатом, а не читай отсюда. Прежняя редакция называла 10 и
// 8 — обе величины устарели МОЛЧА, как устарела и перепись рядом (263 прод-файла
// под `pkg/` против сегодняшних 432). У выписанного числа нет владельца.
//
// Расхождение названо намеренно: признак этого стража ТЕКСТОВЫЙ (подстрока по
// содержимому файла), поэтому он не отличает код от комментария и строкового
// литерала, и число, полученное им, читать как «столько мест собирают креды»
// нельзя. Распространение запрета за пределы фундамента — отдельная работа со
// своим разбором; молча расширить область значило бы получить десять находок
// разом и отключить страж первым же прогоном. Числа названы, чтобы «страж
// зелёный» не читалось шире, чем есть: он утверждает свойство ФУНДАМЕНТА, а не
// всего дерева.
//
// # Освобождение ключуется ПУТЁМ, а не базовым именем файла
//
// Прежняя редакция держала перечень освобождений с ключом `filepath.Base(path)`,
// то есть выдавала освобождение по ИМЕНИ файла. Следствие: любой новый `tls.go`
// в любом каталоге фундамента наследовал освобождение МОЛЧА — освобождение
// раздавалось по имени, а не по предмету. Проверено внесением: файл `tls.go` в
// другом каталоге, собирающий креды напрямую, страж пропускал зелёным.
//
// # Освобождение обязано истекать само
//
// Запись перечня, у которой больше нет предмета, — находка, а не порядок: она
// переживает свой файл и достаётся по наследству следующему, кто назовёт файл так
// же. Поэтому у каждой записи проверяется предпосылка: файл обязан быть в
// осмотренном составе И обязан нести запретную конструкцию. Плюс причина: запись
// без обоснования неотличима от упущения.
//
// # Состав берётся у индекса, а не с диска
//
// `pkg/treecorpus` — то же множество файлов, что увидит свежий клон и CI.
// Обход диска читал бы и то, чего в репозитории нет: рабочие копии агентов под
// `.claude/worktrees/`, сборочные и сгенерированные каталоги, отчёты прогонов, —
// и вердикт стал бы свойством чужого рабочего каталога, а не коммита. Следствие
// ходит в обе стороны: красный на файле, которого в репозитории нет, и молчание
// в свежем checkout там, где страж обязан говорить.
//
// # Что вне запрета
//
// `_test.go` — генерация тестовых CA/сертификатов вправе обращаться к
// `crypto/tls` напрямую.

