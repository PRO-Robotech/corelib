package grpcsrv

import (
	"fmt"

	"google.golang.org/grpc"
)

// Пределы самого gRPC-сервера — платформенные константы, а не настройка стенда.
//
// # Почему константы, а не ручки
//
// Величина, которую объявляет ПОСАДКА, обязана быть настройкой: перечень
// служебных диапазонов или круг доверенных отправителей у каждого стенда свой, и
// литерал в коде описывал бы один стенд, оставаясь ложью про остальные. Здесь
// наоборот: это обещание ПРОДУКТА, одинаковое на любом стенде (документ решений,
// §8.6), и разные стенды с разными пределами означали бы, что клиентская
// библиотека не может исходить ни из чего. Поэтому величины живут здесь и
// правятся здесь.
//
// # Что было до них — измерено по исходнику собираемой версии
//
// Умолчания `google.golang.org/grpc v1.83.2` (прочитаны в исходнике, а не по
// памяти):
//
//   - `maxConcurrentStreams` = `math.MaxUint32` (server.go:189), и сервер при
//     этом ДАЖЕ НЕ ОБЪЯВЛЯЕТ предел клиенту: кадр настроек посылается только
//     когда значение НЕ равно `MaxUint32` (internal/transport/http2_server.go:186).
//     То есть «предела нет» и «предел бесконечен» на проводе неотличимы, и одно
//     соединение открывает столько одновременных вызовов, сколько захочет, —
//     каждый из них идёт в базу. Это не теоретический риск, а способ занять
//     процесс, обслуживающий всех арендаторов, одним соединением;
//   - `maxSendMessageSize` = `math.MaxInt32` (server.go:62) — не ограничен;
//   - `maxReceiveMessageSize` = 4 МиБ (server.go:61) — ограничен умолчанием.
//
// # Предел приёма ОСТАВЛЕН равным умолчанию, и это РЕШЕНИЕ, а не забывчивость
//
// Он объявляется здесь явно ровно затем, чтобы молчание о нём не читалось как
// пропуск: следующий читатель, не найдя третьей величины рядом с двумя, решит,
// что о ней забыли, — и либо заведёт вторую, расходящуюся с этой, либо снимет
// первые две как неполные. Явная константа плюс проба на проводе делают будущее
// ослабление видимым.
const (
	// DefaultConcurrentStreamsPerConnection — одновременных вызовов на ОДНО
	// соединение. Величина §8.6.
	DefaultConcurrentStreamsPerConnection uint32 = 250

	// DefaultSendMsgBytes — предельный размер ответа, 16 МиБ. Законная страница
	// из 1000 объектов (`page_size` до 1000 — часть контракта) — порядка 2 МиБ,
	// то есть запас восьмикратный, но величина КОНЕЧНА.
	DefaultSendMsgBytes int = 16 << 20

	// DefaultRecvMsgBytes — предельный размер запроса, 4 МиБ. Совпадает с
	// умолчанием библиотеки; см. §«Предел приёма ОСТАВЛЕН» выше.
	DefaultRecvMsgBytes int = 4 << 20
)

// ServerLimits — пределы одного gRPC-сервера, собранные в одно значение.
//
// Тип заведён, чтобы у величин был ОДИН источник на процесс: их читает и
// конструктор сервера, и проба, утверждающая наблюдаемое на проводе. Три
// разрозненных литерала разъехались бы молча — и разъехались бы именно там, где
// расхождение не видно, потому что предел, который никто не превысил, ведёт себя
// неотличимо от отсутствующего.
type ServerLimits struct {
	// ConcurrentStreamsPerConnection — одновременных вызовов на соединение.
	// Ноль библиотека молча трактует как «не ограничено», поэтому [Validate]
	// отвергает его: настройка, которую молча переворачивают в свою
	// противоположность, хуже отсутствующей.
	ConcurrentStreamsPerConnection uint32

	// SendMsgBytes — предельный размер одного ответа, байт.
	SendMsgBytes int

	// RecvMsgBytes — предельный размер одного запроса, байт.
	RecvMsgBytes int
}

// DefaultServerLimits — пределы, с которыми поднимается КАЖДЫЙ слушатель
// платформы (оба слушателя каждого сервиса — см. [NewServer]).
func DefaultServerLimits() ServerLimits {
	return ServerLimits{
		ConcurrentStreamsPerConnection: DefaultConcurrentStreamsPerConnection,
		SendMsgBytes:                   DefaultSendMsgBytes,
		RecvMsgBytes:                   DefaultRecvMsgBytes,
	}
}

// Validate отвергает набор, который библиотека исполнить не сможет.
//
// Отдельный метод, а не проверка внутри [ServerOptions], потому что у неё нет
// исхода: опции возвращаются вызывающему, и отказ пришлось бы либо проглотить,
// либо уронить процесс из библиотечной функции. Здесь исход есть, и его читает
// тот, кто собирает свой набор.
func (l ServerLimits) Validate() error {
	if l.ConcurrentStreamsPerConnection == 0 {
		return fmt.Errorf("grpcsrv: предел одновременных вызовов на соединение равен нулю; " +
			"библиотека молча трактует ноль как «не ограничено» И не объявляет предел клиенту вовсе, " +
			"поэтому такой набор выглядит настроенным и не ограничивает ничего")
	}
	if l.SendMsgBytes <= 0 {
		return fmt.Errorf("grpcsrv: предельный размер ответа должен быть положительным (получено %d)", l.SendMsgBytes)
	}
	if l.RecvMsgBytes <= 0 {
		return fmt.Errorf("grpcsrv: предельный размер запроса должен быть положительным (получено %d)", l.RecvMsgBytes)
	}
	return nil
}

// ServerOptions отдаёт набор опций, которыми пределы доезжают до сервера.
func (l ServerLimits) ServerOptions() []grpc.ServerOption {
	return []grpc.ServerOption{
		grpc.MaxConcurrentStreams(l.ConcurrentStreamsPerConnection),
		grpc.MaxSendMsgSize(l.SendMsgBytes),
		grpc.MaxRecvMsgSize(l.RecvMsgBytes),
	}
}
