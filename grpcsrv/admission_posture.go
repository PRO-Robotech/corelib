package grpcsrv

// admission_posture.go — ОПУБЛИКОВАННЫЙ ПОЛ допуска и ручки посадки.
//
// # Почему числа живут здесь, а не у каждого сервиса
//
// Величины допуска — свойство ПРОДУКТА, а не отдельного домена: арендатору
// обещан один пол на всю платформу, и «сколько мне можно» не должно зависеть от
// того, к какому сервису он обратился. Пока числа стояли в чарте единственного
// сервиса, провязавшего ограничитель, следующие шесть завели бы свои — шесть
// мест об одном предмете, расходящихся молча и без единого красного.
//
// # Почему это ПОЛ, а не потолок
//
// Вёдра живут В ПРОЦЕССЕ, без внешнего хранилища: при N репликах эффективный
// предел равен N × объявленного. Поэтому «не менее» остаётся правдой при любом
// N, а «не более» стало бы ложью при первой же второй реплике. Разбор — в шапке
// admission.go.
//
// # Три состояния ручек, а не два
//
// Посадка вправе молчать (берётся пол), вправе назвать ВЕСЬ набор (берётся он)
// и НЕ вправе назвать его часть. Последнее — самый опасный вход: он выглядит
// настройкой и не ограничивает по незаполненной оси, а оператор считает предел
// выставленным. Предикаты у всех трёх состояний ОДНИ И ТЕ ЖЕ, что у механизма
// ([AdmissionLimits.IsBlank], [AdmissionLimits.Unusable],
// [AdmissionLimits.IsDeclared]), — иначе «ручки приняли» и «ограничитель
// навесился» стали бы двумя условиями об одном предмете.

import "fmt"

// Пол публичного листенера — на ЛИЧНОСТЬ КОНЕЧНОГО ПОЛЬЗОВАТЕЛЯ.
//
// Числа не выведены из нагрузки железа, а назначены стоимостью запроса, и она
// названа в шапке admission.go: чтение стоит до 1000 объектов на страницу с
// проверкой прав партиями, мутация — три строки в базе (ресурс, очередь
// намерения, операция). Отсюда темп мутаций впятеро ниже темпа чтений.
//
// Одновременность — ОТДЕЛЬНАЯ ось, и сводить её с темпом нельзя: шестнадцать
// одновременных чтений по 1000 объектов укладываются в любой разумный темп и
// всё равно занимают базу целиком.
const (
	// FloorPublicReadPerSec — устойчивый темп чтений на арендатора.
	FloorPublicReadPerSec = 100
	// FloorPublicMutationPerSec — устойчивый темп мутаций на арендатора.
	FloorPublicMutationPerSec = 20
	// FloorBurstFactor — кратность всплеска, общая обоим листенерам: всплеск
	// покрывает нормальную пачку клиента, не давая ей занять секунду целиком.
	FloorBurstFactor = 5
	// FloorPublicInFlight — одновременных запросов на арендатора.
	FloorPublicInFlight = 16
)

// Пол внутреннего листенера — на ЛИЧНОСТЬ СЕРТИФИКАТА вызывающего модуля.
//
// Заведомо выше публичного, и это решение, а не щедрость: запрос модуля несёт
// личности РАЗНЫХ арендаторов, поэтому одно ведро модуля обслуживает поток
// многих. Ограничитель, задушивший наш собственный поток намерения,
// воспроизводит заклинивание головы очереди — класс, при котором работа
// перестаёт доезжать БЕЗ ЕДИНОГО ВИДИМОГО СИМПТОМА, потому что «работает» и «не
// доехало» выглядят одинаково.
const (
	// FloorInternalReadPerSec — устойчивый темп чтений на модуль.
	FloorInternalReadPerSec = 1000
	// FloorInternalMutationPerSec — устойчивый темп мутаций на модуль.
	FloorInternalMutationPerSec = 500
	// FloorInternalInFlight — одновременных запросов на модуль.
	FloorInternalInFlight = 256
)

// PlatformPublicAdmission — пол публичного листенера.
//
// Функция, а не переменная: значение обязано быть неизменяемым для вызывающего,
// а пакетная переменная позволила бы одному процессу подвинуть пол другому.
func PlatformPublicAdmission() AdmissionLimits {
	return AdmissionLimits{
		ReadPerSec:     FloorPublicReadPerSec,
		MutationPerSec: FloorPublicMutationPerSec,
		BurstFactor:    FloorBurstFactor,
		InFlight:       FloorPublicInFlight,
	}
}

// PlatformInternalAdmission — пол внутреннего листенера.
func PlatformInternalAdmission() AdmissionLimits {
	return AdmissionLimits{
		ReadPerSec:     FloorInternalReadPerSec,
		MutationPerSec: FloorInternalMutationPerSec,
		BurstFactor:    FloorBurstFactor,
		InFlight:       FloorInternalInFlight,
	}
}

// AdmissionKnobs — четыре оси допуска ОДНОГО листенера в том виде, в каком их
// объявляет посадка.
//
// Структура несёт ОБА набора тегов и НЕ несёт абсолютных имён — ровно как
// [TLSClient] рядом. Сервис на viper подставляет её под своим ключом
// (`api-server.rate-limit.public`), сервис на envconfig — под своей группой
// (`ADMISSION_PUBLIC` → `KACHO_<СЕРВИС>_ADMISSION_PUBLIC_READ_PER_SEC`). Одна
// структура на три семейства настроек: три копии тегов разъехались бы на первой
// же новой оси, и разъехались бы молча — незнакомый ключ viper игнорирует.
//
// Умолчаний в тегах НЕТ намеренно. Их пришлось бы написать дважды — для
// публичного и внутреннего листенера, у которых полы разные, — то есть завести
// вторую пропись чисел рядом с первой. Молчание посадки разрешается в
// [AdmissionKnobs.Resolve], где пол приходит ПАРАМЕТРОМ и остаётся в одном месте.
type AdmissionKnobs struct {
	// ReadPerSec — устойчивый темп ЧТЕНИЙ на вызывающего, запросов в секунду.
	ReadPerSec float64 `mapstructure:"read-per-sec" envconfig:"READ_PER_SEC"`
	// MutationPerSec — устойчивый темп МУТАЦИЙ на вызывающего.
	MutationPerSec float64 `mapstructure:"mutation-per-sec" envconfig:"MUTATION_PER_SEC"`
	// BurstFactor — во сколько раз всплеск превышает устойчивый темп.
	BurstFactor float64 `mapstructure:"burst-factor" envconfig:"BURST_FACTOR"`
	// InFlight — предел ОДНОВРЕМЕННЫХ запросов на вызывающего.
	InFlight int `mapstructure:"in-flight" envconfig:"IN_FLIGHT"`
}

// limits переводит объявление посадки в значение механизма БЕЗ суждения о нём.
//
// Приведение типа, а не перечисление полей: у структур один и тот же набор осей,
// и различаются они только тегами настроек. Цена выбора названа честно —
// приведение перестанет компилироваться, если наборы разойдутся. Это ЛУЧШЕ
// перечисления: то на разошедшихся наборах продолжает собираться и молча теряет
// новую ось, а потерянная ось не ограничивает ничего.
func (k AdmissionKnobs) limits() AdmissionLimits {
	return AdmissionLimits(k)
}

// IsSilent — посадка не сказала НИЧЕГО.
//
// Отличается от «сказала негодное»: у молчания есть законное прочтение («беру
// пол платформы»), у частичного набора — нет. Предикат тот же, которым механизм
// отличает канонический ноль ([AdmissionLimits.IsBlank]).
func (k AdmissionKnobs) IsSilent() bool { return k.limits().IsBlank() }

// Resolve — величины листенера: пол, если посадка молчит; её собственные, если
// она назвала ВЕСЬ набор; отказ, если назвала часть либо назвала негодное.
//
// Отказ, а не дополнение полом: оператор, задавший темп и забывший
// одновременность, получил бы наполовину свои, наполовину чужие величины и
// считал бы предел выставленным. Отказ называет ось, потому что искать её он
// пойдёт в файл, где, по его мнению, всё написано верно.
func (k AdmissionKnobs) Resolve(floor AdmissionLimits) (AdmissionLimits, error) {
	l := k.limits()
	if l.IsBlank() {
		return floor, nil
	}
	if reasons := l.Unusable(); len(reasons) > 0 {
		return AdmissionLimits{}, fmt.Errorf("величины допуска, объявленные посадкой, негодны: %s", joinReasons(reasons))
	}
	return l, nil
}

// joinReasons — причины одной строкой. Отдельная функция, чтобы форма отказа
// была одна и у конструктора ограничителя, и здесь.
func joinReasons(reasons []string) string {
	out := ""
	for i, r := range reasons {
		if i > 0 {
			out += "; "
		}
		out += r
	}
	return out
}
