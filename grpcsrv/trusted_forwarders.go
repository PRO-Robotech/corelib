// TrustedForwarders — круг личностей клиентского сертификата, которым разрешено
// ПЕРЕДАВАТЬ личность конечного пользователя (`x-kacho-principal-*`).
//
// # Зачем это тип, а не срез строк
//
// Величину читают трое: транспорт (собирает опцию извлечения), стража старта
// (решает, поднимать ли процесс) и самоотчёт о посадке (докладывает, сужен ли
// круг). Пока это был срез, каждый из троих отвечал на вопрос «сужено ли»
// СВОИМ предикатом, и предикатов в дереве накопилось четыре штуки в трёх
// сервисах — у одного из них стража и отчёт звали РАЗНЫЕ функции в РАЗНЫХ
// пакетах. Согласие держалось тем, что три автора написали одинаковое тело.
// Теперь предикат один — метод [TrustedForwarders.IsNarrowed], и разойтись
// нечему.
//
// # Нулевое значение — самое строгое прочтение, какое доступно предикату
//
// `var f TrustedForwarders` соберётся всегда: запретить нулевое значение Go не
// даёт. Значит распорядиться можно только тем, ЧТО ОНО ЗНАЧИТ, — и оно значит
// «круг НЕ сужен». Поэтому пропущенное поле упирается в отказ старта у каждого,
// кто сужает, а не в тихое «доверяем любому предъявившему сертификат».
//
// # Семантика транспорта этим типом НЕ меняется
//
// [WithTrustedForwarders] по-прежнему сужает круг ТОЛЬКО на непустом множестве;
// на пустом переданная личность принимается от любого пира, прошедшего проверку
// сертификата (см. principalIsTrusted). Это действующее, намеренное поведение
// общей библиотеки, и тип его не переопределяет. Защиту от «забыл заполнить»
// даёт отказ старта, а не смена значения пустого множества: сменить его значило
// бы поменять смысл величины у всех, кто её уже читает, включая тех, кто про
// этот тип ничего не знает.
//
// Значение неизменяемо после сборки: [TrustedForwarders.SANs] отдаёт копию,
// поэтому «один объект у троих» остаётся одним и тем же значением на всё время
// жизни процесса.
type TrustedForwarders struct {
	// sans — нормализованный круг: обрезанные по краям, непустые, без повторов,
	// в порядке, в котором их перечислил оператор. Неэкспортируемое поле — то,
	// что делает нулевое значение единственным способом получить «не сужено»
	// мимо конструктора.
	sans []string
}

// NewTrustedForwarders собирает круг из того, что написал оператор.
//
// Отбрасывает пустые записи, потому что их отбрасывает и транспорт
// ([WithTrustedForwarders] принимает только s != ""): список из одних пустых
// строк (`SANS=","`) вырождается там в пустое множество, то есть снова
// «доверяем любому». Считать такую строку заполненной значило бы пропустить
// дыру через стражу старта.
//
// Пробелы по краям срезаются — и это ОСОЗНАННОЕ расхождение с транспортом, а не
// его зеркало: транспорт сравнивает личность сертификата побайтово (CertIdentity
// отдаёт SAN как есть), поэтому запись " spiffe://…" не совпала бы там ни с
// одним сертификатом. Без среза оператор, написавший список через
// «запятая-пробел», получил бы не отказ старта, а молчаливый отказ в
// обслуживании законному отправителю. Круг от этого не расширяется: в него
// попадают ровно те строки, которые оператор перечислил.
//
// Повторы схлопываются: круг — множество, и «две записи» против «одной,
// написанной дважды» не различает ни одно решение, которое по нему принимается.
func NewTrustedForwarders(raw ...string) TrustedForwarders {
	out := make([]string, 0, len(raw))
	seen := make(map[string]struct{}, len(raw))
	for _, s := range raw {
		s = strings.TrimSpace(s)
		if s == "" {
			continue
		}
		if _, dup := seen[s]; dup {
			continue
		}
		seen[s] = struct{}{}
		out = append(out, s)
	}
	if len(out) == 0 {
		// Канонический ноль: пустой круг обязан быть неотличим от нулевого
		// значения, иначе у «не сужено» появилось бы два представления и
		// сравнение по одному из них однажды разошлось бы с другим.
		return TrustedForwarders{}
	}
	return TrustedForwarders{sans: out}
}

// IsNarrowed — ЕДИНСТВЕННЫЙ предикат «сужен ли круг». Его спрашивают стража
// старта, самоотчёт о посадке и всякий, кому нужно решить, объявлять ли посадку
// суженной. Транспорт принимает то же значение целиком, поэтому «стража
// пропустила» ⟺ «круг реально сужен» — по построению, а не по совпадению.
func (f TrustedForwarders) IsNarrowed() bool { return len(f.sans) > 0 }

// Len — размер круга. Для диагностики и отчётов; решение принимается по
// [TrustedForwarders.IsNarrowed], а не по сравнению этого числа с нулём.
func (f TrustedForwarders) Len() int { return len(f.sans) }

// SANs отдаёт КОПИЮ круга в виде среза — форма, которую принимает транспорт.
// Копия, а не внутренний срез: вызывающий не должен уметь изменить круг после
// того, как стража его одобрила.
func (f TrustedForwarders) SANs() []string {
	if len(f.sans) == 0 {
		return nil
	}
	out := make([]string, len(f.sans))
	copy(out, f.sans)
	return out
}

// String — читаемое представление для журнала. Личности сертификатов не
// секрет (они публикуются в самих сертификатах), поэтому круг печатается как
// есть: скрывать его значило бы делать неотлаживаемым отказ законному
// отправителю.
func (f TrustedForwarders) String() string {
	if len(f.sans) == 0 {
		return "<not narrowed>"
	}
	return strings.Join(f.sans, ",")
}

// ForwarderGate — вход стражи круга отправителей: то, что стража обязана знать
// о посадке, чтобы решить, поднимать ли процесс.
//
// Ручки называются ЯВНО, потому что текст отказа читает оператор: сообщение, не
// называющее ручку, оставляет стенд неподнятым и непонятным. Это одно из трёх
// мест, выведенных из-под запрета на подробности в публичных артефактах, —
// рантайм-диагностика, а не рассказ о том, где было открыто.
type ForwarderGate struct {
	// Production — боевой режим (production ИЛИ production-strict). В нём круг
	// обязан быть сужен, и опт-ин ниже НЕ действует.
	Production bool
	// DevTrustAny — явный dev-опт-ин «не сужаем». Действует только вне боевого
	// режима и только там, где посадка заведомо локальная (in-process фикстуры).
	DevTrustAny bool
	// SANsKnob — имя ручки, которой круг задаётся (для текста отказа).
	SANsKnob string
	// TrustAnyKnob — имя ручки опт-ина (для текста отказа).
	TrustAnyKnob string
}

// Require — стража круга отправителей, ОДНА на все семь сервисов.
//
// # Почему она срабатывает на ЛЮБОМ старте, а не только в боевом режиме
//
// Развёрнутый стенд обязан работать в боевой посадке независимо от того, dev он
// называется или нет. Стража, молчащая вне боевого режима, — контроль, чья ветка
// на локальном стенде не исполняется ни разу, поэтому «забыл выставить круг»
// обнаруживается только на боевом профиле, где цена ошибки максимальна. Вне
// боевого режима пустой круг остаётся возможным, но становится ЯВНЫМ опт-ином:
// его надо попросить, а не получить умолчанием.
//
// # Почему опт-ин не действует в боевом режиме
//
// Иначе он был бы ручкой, снимающей защиту на боевом стенде, — то есть ровно тем
// именованным обходом, которого у нас быть не должно.
func (f TrustedForwarders) Require(g ForwarderGate) error {
	if f.IsNarrowed() {
		return nil
	}
	if !g.Production && g.DevTrustAny {
		return nil
	}
	if g.Production {
		return fmt.Errorf("production mode: %s must pin at least one trusted-forwarder SAN "+
			"(an unnarrowed circle lets ANY certificate-verified peer forward an end-user identity, "+
			"so a neighbouring service acts as any tenant); the dev opt-in %s is not honoured in production",
			g.SANsKnob, g.TrustAnyKnob)
	}
	return fmt.Errorf("secure-by-default: %s is empty, which trusts ANY certificate-verified peer "+
		"to forward an end-user identity; pin the api-gateway SAN, or opt into trust-any for local "+
		"in-process fixtures by setting %s to true", g.SANsKnob, g.TrustAnyKnob)
}

// PrincipalExtractUnary — пара звеньев, отвечающая на вопрос «чью личность несёт
// этот запрос», для unary RPC. ОДИН И ТОТ ЖЕ набор на ОБОИХ листенерах:
// «internal = доверенный» — запрещённое допущение.
//
// Почему пара, а не одиночное звено: сертификат доказывает, ЧЕЙ это пир, и
// ничего не говорит о праве представляться другим. Первое звено достаёт личность
// сертификата, второе решает по ней, принимать ли переданные заголовки. Порядок
// обязателен — переставленные звенья означают решение о доверии по ещё не
// извлечённой личности.
//
// Конструктор существует затем, чтобы пару нельзя было ни разорвать, ни
// переставить в композиционном корне: до него семь сервисов собирали её вручную
// четырнадцатью литералами.
//
// Домен доверия стоит ПЕРВЫМ аргументом по той же причине, по какой первым
// стоит звено извлечения личности сертификата: сперва решается, чей это
// предъявитель, и только потом — вправе ли он представляться другим.
// Дополнительные опции ВАРИАДИЧНЫ намеренно: пара уже собирается семью
// композиционными корнями и двумя сборками, и расширение подписи развело бы их
// во времени — половина деревьев перестала бы собираться до сдвига пина.
// Сегодня отсюда приезжает счётчик исходов личности ([WithIdentityArrival]).
func PrincipalExtractUnary(d TrustDomain, f TrustedForwarders,
	opts ...TrustedPrincipalOption,
) []grpc.UnaryServerInterceptor {
	return []grpc.UnaryServerInterceptor{
		UnaryCertIdentityExtract(d),
		UnaryTrustedPrincipalExtract(append([]TrustedPrincipalOption{WithTrustedForwarders(f)}, opts...)...),
	}
}

// PrincipalExtractStream — то же для stream RPC (тот же инвариант порядка).
func PrincipalExtractStream(d TrustDomain, f TrustedForwarders,
	opts ...TrustedPrincipalOption,
) []grpc.StreamServerInterceptor {
	return []grpc.StreamServerInterceptor{
		StreamCertIdentityExtract(d),
		StreamTrustedPrincipalExtract(append([]TrustedPrincipalOption{WithTrustedForwarders(f)}, opts...)...),
	}
}
