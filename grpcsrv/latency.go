// Задержка обслуженного вызова наблюдается ЗДЕСЬ, а не у каждого сервиса.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ В ФУНДАМЕНТЕ
//
// Тот же довод, которым здесь стоят пределы слушателя (см. [NewServer]): пока
// гистограмму заводит каждый сервис у себя, «не завёл» НЕОТЛИЧИМО от «завёл
// такую же». Отсутствие серии ничего не печатает, слушатель поднимается молча,
// и узнают об этом ровно тогда, когда задержку понадобилось посмотреть, —
// то есть в разборе происшествия, когда данных уже не будет.
//
// Замер на дереве перед этой правкой: гистограмма длительности вызова была у
// ОДНОГО сервиса из семи; у остальных шести реестр метрик существовал, счётчики
// и измерители в нём были, а длительности не было. То есть наблюдаемость
// присутствовала, и именно поэтому её нехватка не бросалась в глаза.
//
// Здесь другого конструктора сервера в дереве нет, поэтому слушатель без
// измерителя задержки перестаёт существовать по построению, а не по правилу.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ОДНА СЕРИЯ С МЕТКОЙ СЕРВИСА, А НЕ СЕМЬ ИМЁН
//
// Имя серии — контракт с панелями и правилами тревог. Семь имён означают семь
// панелей, семь правил и невозможность спросить «где во всей платформе хвост
// вырос» одним запросом. Метка `grpc_service` уже несёт домен: полное имя
// метода начинается с пакета контракта (`kacho.cloud.vpc.v1.NetworkService`),
// поэтому различать сервисы отдельной меткой было бы удвоением.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ КОД ОТВЕТА — МЕТКА СЧЁТЧИКА, НО НЕ ГИСТОГРАММЫ
//
// Задержка отказа и задержка успеха — разные величины, и смешивать их нельзя:
// быстрый отказ занижает хвост, медленный — завышает. Но код в метке ГИСТОГРАММЫ
// умножает число рядов на число кодов, а их шестнадцать. Поэтому гистограмма
// несёт `outcome` из двух значений (`ok`/`error`), а полный код остаётся у
// счётчика, где ряд дёшев.
//
// Арифметика, чтобы выбор был измерен, а не объявлен. Гистограмма с этой сеткой
// даёт 19 рядов на сочетание меток (16 корзин плюс сумма, счёт и переполнение).
// Процесс на полсотни служимых методов, обе полосы, оба исхода — около 3800
// рядов; с полным кодом вместо исхода вышло бы примерно 30 тысяч, то есть в
// восемь раз больше ради различия, которое всё равно доступно у счётчика.
//
// Оценка ВЕРХНЯЯ: ряд заводится в момент первого наблюдения, поэтому метод, к
// которому не обращались, полосу, на которой его не служат, и исход, которого не
// было, не оплачивает никто.

// latencyBuckets — границы, выбранные под ЭТУ платформу, а не умолчание
// библиотеки.
//
// Умолчание (`prometheus.DefBuckets`) начинается с 5 мс и кончается 10 с. Обе
// границы здесь неверны: чтения из своей базы укладываются в единицы
// миллисекунд, и умолчание сваливает их все в первую корзину — то есть p50 и
// p90 становятся неразличимы ровно там, где живёт большинство запросов. С
// другой стороны, мутация с обращением к соседу и материализацией прав
// переваливает за секунду законно, и потолок в десять секунд лишает хвост
// разрешения.
//
// Сетка ниже покрывает четыре порядка — от четверти миллисекунды до тридцати
// секунд — и сгущается там, где принимаются решения: между миллисекундой и
// сотней миллисекунд.
// Listener — ПОЛОСА, на которой обслужен вызов.
//
// # Зачем метка, если метод уже назван
//
// Один и тот же метод служится ОБОИМИ слушателями: `OperationService` в этом
// дереве регистрируется и на публичном, и на внутреннем. Публичный вызов
// приходит от арендатора через край и тащит за собой выяснение личности и
// вопрос о правах; внутренний приходит от соседнего модуля по mTLS. Это разные
// величины, и слитый ряд — среднее двух разных, то есть число, неверное про обе
// полосы сразу и молча.
//
// # Почему тип, а не строка
//
// Метка обязана оставаться ОГРАНИЧЕННОЙ по числу значений: свободная строка —
// способ уронить хранилище рядами, которых никто не заказывал. Значение вне
// словаря схлопывается в `unknown` (см. [Listener.label]), а не заводит ряд.
type Listener string

const (
	// ListenerPublic — слушатель, досягаемый арендатором через край.
	ListenerPublic Listener = "public"
	// ListenerInternal — слушатель, досягаемый только внутри кластера.
	ListenerInternal Listener = "internal"
)

// label возвращает значение метки, схлопывая всё, чего нет в словаре.
//
// Пустая метка была бы хуже `unknown`: она читается как «полоса не указана», а
// на деле означает «полоса указана и не распознана», — и разница видна только
// тому, кто пойдёт читать этот код.
func (l Listener) label() string {
	switch l {
	case ListenerPublic, ListenerInternal:
		return string(l)
	default:
		return "unknown"
	}
}

var latencyBuckets = []float64{
	0.00025, 0.0005, 0.001, 0.0025, 0.005, 0.01, 0.025, 0.05, 0.1,
	0.25, 0.5, 1, 2.5, 5, 10, 30,
}

// streamBuckets — сетка СРОКА ЖИЗНИ ПОДПИСКИ, отдельная от сетки задержки
// вызова, потому что предмет другой.
//
// «Верхняя граница обработки» и «срок жизни подписки» — разные величины; это
// уже записано в дескрипторе двумя разными осями (`HandlingBudget` против
// `StreamBudget`). Сетка вызова кончается тридцатью секундами, а объявленный в
// дереве срок подписки — час: сложив их, мы получили бы все живые подписки в
// одном ряду переполнения, то есть величину без разрешения именно там, где она
// нужна.
//
// Потолок взят с запасом ВЫШЕ объявленного срока: подписка, живущая дольше
// собственного потолка, — это находка, и она обязана быть видна корзиной, а не
// растворяться в переполнении вместе со здоровыми.
var streamBuckets = []float64{
	1, 5, 15, 30, 60, 300, 900, 1800, 3600, 7200, 14400,
}

// ServerLatency — измеритель задержки обслуженных вызовов.
//
// Заводится один раз на процесс и регистрируется в реестре сервиса. Повторная
// регистрация того же реестра — ошибка вызывающего, а не причина ронять
// процесс: [NewServerLatency] возвращает ошибку, а не паникует.
type ServerLatency struct {
	duration *prometheus.HistogramVec
	stream   *prometheus.HistogramVec
	handled  *prometheus.CounterVec
}

// NewServerLatency заводит измеритель и регистрирует его в переданном реестре.
//
// Реестр передаётся, а не берётся глобальный: глобальный реестр делает две
// пробы одного пакета зависимыми друг от друга через состояние процесса, и
// вторая падает на «серия уже зарегистрирована» — отказ, не имеющий отношения
// к предмету пробы.
func NewServerLatency(reg prometheus.Registerer) (*ServerLatency, error) {
	l := &ServerLatency{
		duration: prometheus.NewHistogramVec(prometheus.HistogramOpts{
			Name: "kacho_grpc_server_handling_seconds",
			Help: "Длительность обслуженного gRPC-вызова, по контракту, методу и исходу. " +
				"Исход огрублён до ok/error намеренно: полный код живёт у счётчика, " +
				"где ряд дёшев, а в гистограмме он умножил бы число рядов на шестнадцать.",
			Buckets: latencyBuckets,
		}, []string{"grpc_service", "grpc_method", "listener", "outcome"}),
		stream: prometheus.NewHistogramVec(prometheus.HistogramOpts{
			Name: "kacho_grpc_server_stream_seconds",
			Help: "Срок жизни серверного стрима, по контракту, методу, полосе слушателя и исходу. " +
				"Отдельная серия от задержки вызова намеренно: это разные величины, и общая сетка " +
				"не разрешала бы ни ту, ни другую.",
			Buckets: streamBuckets,
		}, []string{"grpc_service", "grpc_method", "listener", "outcome"}),
		handled: prometheus.NewCounterVec(prometheus.CounterOpts{
			Name: "kacho_grpc_server_handled_total",
			Help: "Число обслуженных gRPC-вызовов, по контракту, методу и коду ответа.",
		}, []string{"grpc_service", "grpc_method", "listener", "grpc_code"}),
	}
	if err := reg.Register(l.duration); err != nil {
		return nil, err
	}
	if err := reg.Register(l.stream); err != nil {
		return nil, err
	}
	if err := reg.Register(l.handled); err != nil {
		return nil, err
	}
	return l, nil
}

// UnaryServerInterceptor возвращает интерсептор, наблюдающий длительность и
// исход каждого обслуженного вызова.
//
// Нулевой измеритель возвращает интерсептор, который ничего не наблюдает и
// ничего не стоит: это законное состояние для проб, которым метрики не нужны,
// — но НЕ для развёрнутого слушателя, где его отсутствие проверяется отдельно.
func (l *ServerLatency) UnaryServerInterceptor(on Listener) grpc.UnaryServerInterceptor {
	if l == nil {
		return func(ctx context.Context, req any, _ *grpc.UnaryServerInfo, h grpc.UnaryHandler) (any, error) {
			return h(ctx, req)
		}
	}
	return func(ctx context.Context, req any, info *grpc.UnaryServerInfo, handler grpc.UnaryHandler) (any, error) {
		start := time.Now()
		resp, err := handler(ctx, req)
		elapsed := time.Since(start).Seconds()

		svc, method := splitFullMethodName(info.FullMethod)
		lane := on.label()
		l.duration.WithLabelValues(svc, method, lane, outcomeOf(err)).Observe(elapsed)
		l.handled.WithLabelValues(svc, method, lane, status.Code(err).String()).Inc()
		return resp, err
	}
}

// StreamServerInterceptor наблюдает СРОК ЖИЗНИ серверного стрима и его исход.
//
// Длительность уходит в свою серию ([streamBuckets]), а счётчик обслуженных —
// общий с одиночными вызовами: подписка тоже обслуженный вызов, и её отсутствие
// в счётчике означало бы, что оборванные подписки не видны нигде.
//
// Нулевой измеритель прозрачен ровно на тех же условиях, что и у одиночного
// вызова.
func (l *ServerLatency) StreamServerInterceptor(on Listener) grpc.StreamServerInterceptor {
	if l == nil {
		return func(srv any, ss grpc.ServerStream, _ *grpc.StreamServerInfo, h grpc.StreamHandler) error {
			return h(srv, ss)
		}
	}
	return func(srv any, ss grpc.ServerStream, info *grpc.StreamServerInfo, handler grpc.StreamHandler) error {
		start := time.Now()
		err := handler(srv, ss)
		elapsed := time.Since(start).Seconds()

		svc, method := splitFullMethodName(info.FullMethod)
		lane := on.label()
		l.stream.WithLabelValues(svc, method, lane, outcomeOf(err)).Observe(elapsed)
		l.handled.WithLabelValues(svc, method, lane, status.Code(err).String()).Inc()
		return err
	}
}

// outcomeOf огрубляет исход до двух значений.
//
// Огрубление намеренное и объяснено в шапке пакета: полный код живёт у
// счётчика, где ряд дёшев, а в гистограмме он умножил бы число рядов на
// шестнадцать. Но СМЕШИВАТЬ отказ с успехом нельзя — быстрый отказ занижает
// хвост, медленный завышает, — поэтому двух значений и хватает, и нужно.
func outcomeOf(err error) string {
	if err != nil {
		return "error"
	}
	return "ok"
}

// splitFullMethodName разбирает "/пакет.Служба/Метод" на пару.
//
// Неразобранное значение даёт ("unknown", исходная строка): метка обязана
// оставаться ОГРАНИЧЕННОЙ по числу значений. Пустая метка на неразобранном
// входе была бы хуже — она сливает разные методы в один ряд и делает величину
// неверной молча.
func splitFullMethodName(fullMethod string) (service, method string) {
	trimmed := strings.TrimPrefix(fullMethod, "/")
	idx := strings.LastIndex(trimmed, "/")
	if idx < 0 {
		return "unknown", fullMethod
	}
	return trimmed[:idx], trimmed[idx+1:]
}
