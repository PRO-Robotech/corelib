// TestIndexIsReadOncePerRoot — состав индекса читается ОДИН раз на корень.
//
// # Почему свойство, а не время
//
// «Стало быстрее» на общей машине не измеряется: соседний прогон меняет ответ,
// и тот же кеш даёт то «в полтора раза лучше», то «в полтора хуже». Число
// поднятий процесса от нагрузки не зависит вовсе.
//
// # Цена, ради которой кеш заведён
//
// Проверки дерева спрашивают состав независимо друг от друга — в пакете гейтов
// 103 обращения на 823 пробы, и каждое поднимало отдельный процесс git. Прогон
// подошёл к пределу времени вплотную, и следующий заведённый гейт его ронял:
// цена была не «медленно», а «новую проверку больше не завести».
func TestIndexIsReadOncePerRoot(t *testing.T) {
	root := repoRootForCache(t)

	before := ListFilesProcesses()
	for i := 0; i < 5; i++ {
		if _, err := Under(root); err != nil {
			t.Fatalf("состав дерева не прочитан: %v", err)
		}
	}
	after := ListFilesProcesses()

	// Не больше одного поднятия: первое обращение могло случиться и в соседней
	// пробе — тогда прирост нулевой, и это тоже норма.
	if got := after - before; got > 1 {
		t.Fatalf("пять обращений к одному корню подняли процесс git %d раз — кеш не работает", got)
	}

	// Положительный контроль: кеш не подменяет ОТВЕТ. Проба на «процесс не
	// поднят» зеленела бы и на кеше, отдающем пустоту.
	files, err := Under(root)
	if err != nil {
		t.Fatalf("состав дерева не прочитан: %v", err)
	}
	if len(files) == 0 {
		t.Fatal("состав пуст: кеш отдал пустой корпус, и всякая проверка по нему отчиталась бы «ноль находок»")
	}
	t.Logf("перепись: файлов в корпусе %d; поднятий процесса git на этот корень %d", len(files), after-before)

	// Отказ тоже кешируется — и остаётся ОТКАЗОМ для каждого спрашивающего.
	// Иначе первый упал бы, а остальные увидели бы пустой корпус.
	outside := t.TempDir()
	if _, err := Under(outside); err == nil {
		t.Fatal("каталог вне репозитория принят: «git недоступен» обязано быть отказом, а не пустым составом")
	}
	if _, err := Under(outside); err == nil {
		t.Fatal("повторный вопрос о том же каталоге прошёл — кеш превратил отказ в тишину")
	}
}

func repoRootForCache(t *testing.T) string {
	t.Helper()

	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("рабочий каталог: %v", err)
	}
	for i := 0; i < 12; i++ {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	t.Fatal("корень дерева не найден")
	return ""
}
