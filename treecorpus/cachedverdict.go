// cachedverdict.go — почему проверка дерева ОТКАЗЫВАЕТСЯ отвечать на прогоне,
// результат которого `go test` положит в кеш.
//
// # Предмет
//
// `go test` кеширует успешный результат пакета по содержимому самого пакета, его
// импортов и тех файлов и переменных окружения, к которым проба обратилась САМА.
// Проверка дерева нарушает эту посылку by construction: состав она берёт из
// индекса git ПОДПРОЦЕССОМ, а подпроцесс инструменту невидим. Правка в чужом
// каталоге кеш не инвалидирует — и над деревом, где проверка красная, печатается
// `ok (cached)`, отличимое от настоящего прохода ровно одним словом.
//
// Следствие называется точно: вердикт становится функцией того, КОГДА его в
// последний раз считали.
//
// # Воспроизведение (2026-08-25, дерево вровень с origin/main)
//
// Прогрет гейт латинских имён; в каталог чужого сервиса добавлен отслеживаемый
// файл Go с кириллическим идентификатором. Обычный прогон — `ok (cached)`; тот
// же прогон с `-count=1` — находка с координатой. Правка чужого каталога до
// проверки не доехала.
//
// # Почему ОТКАЗ, а не «объявить пробу некэшируемой»
//
// Штатного способа объявить пробу некэшируемой в языке НЕТ. Это измерено, а не
// вычитано: изолированный модуль, шесть форм обращения к внешнему состоянию,
// каждая прогрета и затем проверена добавлением чужого файла.
//
//	чтение переменной окружения        кеш применён — не помогает
//	открытие файла ВНЕ корня модуля    кеш применён — не помогает
//	перечисление состава подпроцессом  кеш применён — ЭТО И ЕСТЬ ДЕФЕКТ
//	чтение уже прочитанного файла      кеш сброшен, но только на правку
//	                                   СОДЕРЖИМОГО, не на появление файла
//	обход каталогов (os.ReadDir)       кеш сброшен, но состав тогда берётся с
//	                                   ДИСКА, а не из индекса: `git add` уже
//	                                   лежащего файла листинга не меняет, и
//	                                   в отпечаток заезжают игнорируемые
//	                                   каталоги — ровно то, ради устранения
//	                                   чего написан этот пакет
//	файл с меткой времени в будущем    кеш не применяется НИКОГДА — но требует
//	                                   оставить такой файл ВНУТРИ корня модуля,
//	                                   то есть записи пробы в дерево, из
//	                                   которого она запущена (собственная
//	                                   находка гейта); убранный за собой файл
//	                                   снова кешируется, а меток времени git не
//	                                   хранит — в свежем клоне механизм умирает
//	                                   молча
//
// Остаётся отказ, и он безопасен: `go test` кеширует ТОЛЬКО успешные результаты,
// поэтому красный прогон кеша не отравляет (проверено тремя прогонами подряд —
// исполнились все три, зелёный сосед в том же пакете остался кешируемым).
//
// # Дискриминатор — заявление САМОГО инструмента, а не наша реконструкция правил
//
// `go test` передаёт пробе флаг журнала обращений РОВНО ТОГДА, когда собирается
// положить результат в кеш: журнал нужен ему, чтобы посчитать отпечаток входа.
// Нет флага — не будет и кеша. Реконструировать правила кеширования (перечень
// «кешируемых» флагов) не требуется, и это важно: перечень принадлежит
// инструменту и может измениться, а флаг журнала есть его собственный вывод.
//
// Проверено по семи осям на изолированном модуле — рядом с ожидаемым исходом
// стоит фактическое поведение кеша, то есть контроль в обе стороны:
//
//	go test ./пакет/                   флаг ЕСТЬ    и кеш применяется
//	go test ./пакет/ -count=1          флага НЕТ    и кеш не применяется
//	go test ./пакет/ -count=2          флага НЕТ    и кеш не применяется
//	go test ./пакет/ -race             флаг ЕСТЬ    и кеш применяется
//	go test ./пакет/ -timeout 5m       флаг ЕСТЬ    и кеш применяется
//	go test ./пакет/ -bench=.          флага НЕТ    и кеш не применяется
//	go test (режим текущего каталога)  флага НЕТ    и кеш не применяется
//
// Последняя строка — та, ради которой дискриминатор выбран именно такой:
// восстановление правил по перечню флагов дало бы здесь ЛОЖНУЮ находку (флагов
// не задано ни одного, а кеш инструмент всё равно не применяет).
package treecorpus

import (
	"os"
	"strings"
)

// testlogFlagName — имя флага журнала обращений. `go test` передаёт его пробе
// только тогда, когда намерен кешировать её результат.
const testlogFlagName = "-test.testlogfile"

// runArgs — командная строка ЭТОГО прогона.
//
// Переменная, а не прямой os.Args, ради ОДНОГО читателя: пробы, которая обязана
// позвать НАСТОЯЩИЕ Under и NewTree на обеих формах командной строки — и на той,
// где кеш применяется, и на той, где нет. Прод-кода у неё нет и быть не должно;
// подмена в пробе обязана возвращаться на место (t.Cleanup).
var runArgs = os.Args

// RunResultWillBeCached — положит ли `go test` результат этого прогона в кеш.
//
// В прод-бинаре всегда false: флаг журнала передаёт только `go test`, поэтому
// вопрос там беспредметен by construction.
func RunResultWillBeCached() bool { return resultWillBeCached(runArgs) }

// resultWillBeCached — тот же вопрос к ЗАДАННОЙ командной строке. Отдельно от
// экспортированной формы ради инъекции: подать сюда настоящую командную строку
// прогона можно, не запуская второй `go test`.
func resultWillBeCached(argv []string) bool {
	for i, arg := range argv {
		name, value, split := strings.Cut(arg, "=")
		if !isTestlogFlag(name) {
			continue
		}
		if split {
			// Слитная форма — её и передаёт инструмент.
			return value != ""
		}
		// Форма из двух слов принимается тоже: предикат не должен зависеть от
		// того, как именно инструмент решит написать флаг завтра.
		return i+1 < len(argv) && argv[i+1] != ""
	}
	return false
}

func isTestlogFlag(name string) bool {
	return name == testlogFlagName || name == "-"+testlogFlagName
}

// CachedVerdictRefusal — текст отказа, если вердикт этого прогона пойдёт в кеш,
// и ПУСТАЯ строка иначе.
//
// Отдаётся текстом, а не завершением процесса: место отказа выбирает вызывающий.
// Конструкторы этого пакета возвращают его ошибкой, пакет проверок — печатает из
// TestMain и выходит ненулём, потому что там ещё нет ни одной пробы, которой
// можно было бы сообщить.
func CachedVerdictRefusal() string {
	if !RunResultWillBeCached() {
		return ""
	}
	return cachedVerdictRefusalText
}

const cachedVerdictRefusalText = "" +
	"проверка ДЕРЕВА на кэшируемом прогоне — вердикт был бы недействителен.\n" +
	"\n" +
	"починить — прогонять с отключённым кешем:\n" +
	"    go test <пакеты> -count=1\n" +
	"    make test-unit            — цель уже несёт -count=1\n" +
	"\n" +
	"почему это ОТКАЗ, а не предупреждение: состав дерева проверка берёт из\n" +
	"индекса git подпроцессом, а `go test` о подпроцессе не знает и кеширует\n" +
	"результат по содержимому ПАКЕТА и его импортов. Правка в чужом каталоге\n" +
	"кеш не инвалидирует, и над красным деревом печатается `ok (cached)` —\n" +
	"строка, отличимая от настоящего прохода ровно одним словом. Предупреждение\n" +
	"здесь не работает by construction: на кешированном прогоне проба не\n" +
	"исполняется вовсе, а без -v её вывод и не печатается."
