// identifiers.go — разбор ИМЁН Go: имя в коде обязано быть латинским.
//
// # Зачем это разбор, а не вопрос вкуса
//
// Кириллица даёт ОМОГЛИФЫ — знаки, неотличимые от латинских на глаз: «В» и «B»,
// «С» и «C», «Р» и «P», «А» и «A», «о» и «o». Имя с таким знаком выглядит
// обычным и не находится ни поиском, ни отбором по имени.
//
// Цена измерена, а не предположена. Пять проб разбора доступа назывались с
// кириллической «В», и отбор по видимому имени отвечал «no tests to run»: пробы
// существовали, были зелёными и НЕ ЗАПУСКАЛИСЬ тем, кто их звал. «Прогнал»
// молча означало «не прогнал», и отличить это можно было только счётом.
//
// # Что именно запрещено — и что нет
//
// Запрещено не-ASCII в ИМЕНИ: функции, типа, поля, переменной, параметра,
// константы, параметра типа, псевдонима импорта. Разрешено — и не проверяется —
// всё остальное: комментарии, строковые литералы, имена файлов, содержимое
// данных. Правило владельца дословно: «никаких русскоязычных вставок в коде; на
// русском могут быть комментарии и документация, но не сам код».
//
// # Почему РАЗБОР, а не поиск по образцу
//
// Поиск по образцу этот класс не измеряет: он не отличает имя от строки и от
// комментария, а законной кириллицы в обоих деревьях десятки тысяч строк — ею
// написан весь разбор находок. Перепись, сделанная образцом при заведении гейта
// в платформе, занизила счёт на четверть: она не видела имён из
// деструктуризации. Разбор видит каждое объявленное имя by construction.

package treehygiene

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"unicode"
)

// NonASCIIIdent — одно нелатинское имя с координатой.
//
// Координата обязательна: находка без неё — не действие. Правится такое имя ПО
// ПОЗИЦИИ РАЗБОРА, а не текстовой заменой: замена попадает внутрь строковых
// литералов и комментариев, где кириллица законна, и видно это только в готовом
// тексте.
type NonASCIIIdent struct {
	// Position — файл:строка:колонка объявления либо употребления имени.
	Position string
	// Name — само имя, как оно записано.
	Name string
	// Rune — первый нелатинский знак имени. Печатается отдельно, потому что на
	// глаз он от латинского двойника неотличим — в этом и предмет разбора.
	Rune rune
}

func (f NonASCIIIdent) String() string {
	return fmt.Sprintf("%s: %s — знак %q (U+%04X) не латинский",
		f.Position, f.Name, f.Rune, f.Rune)
}

// ScanNonASCIIIdents разбирает ОДИН исходник и возвращает: сколько имён
// осмотрено и какие из них нелатинские.
//
// Отдельная функция, а не обход дерева, ради двух вещей сразу. Первая —
// доказательство: разбор обязан показать, что различает ИМЯ и текст, а показать
// это можно только позвав его синтетикой, где обе формы стоят рядом. Вторая —
// перепись: «имён осмотрено N» делает «ноль находок» отличимым от «разбор ничего
// не увидел».
//
// Обход дерева остаётся у вызывающего вместе с корнем: судить чужое дерево
// значило бы краснеть на чужом (см. шапку пакета).
//
// Неразбираемый файл возвращает признак, а не пустой успех: такой файл и
// собраться не может, об этом скажет сборка, — но молчать о нём нельзя, иначе
// перепись завысит объём осмотренного.
func ScanNonASCIIIdents(name string, src []byte) (seen int, findings []NonASCIIIdent, err error) {
	fset := token.NewFileSet()
	file, perr := parser.ParseFile(fset, name, src, parser.ParseComments)
	if perr != nil {
		return 0, nil, perr
	}
	ast.Inspect(file, func(n ast.Node) bool {
		id, ok := n.(*ast.Ident)
		if !ok {
			return true
		}
		seen++
		for _, r := range id.Name {
			if r > unicode.MaxASCII {
				findings = append(findings, NonASCIIIdent{
					Position: fset.Position(id.Pos()).String(),
					Name:     id.Name,
					Rune:     r,
				})
				return true
			}
		}
		return true
	})
	return seen, findings, nil
}
