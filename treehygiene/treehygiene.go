// Package treehygiene несёт ОБЩУЮ часть двух запретов корпуса, у которой до сих
// пор не было дома: словарь форм отложенной работы (ban #11) и разбор
// нелатинских узлов-идентификаторов Go (ban #17).
//
// # Предмет: у общей части не было владельца
//
// Держатели обоих запретов заведены дважды — в платформе
// (`PRO-Robotech/kacho:internal/repohygiene`) и в службе доступа
// (`PRO-Robotech/kaname:internal/check`). Предмет у каждого СВОЙ: каждый судит
// своё дерево, и снять ни один нельзя. Но РАЗБОР у них был общий, и держателя у
// его одинаковости не было ни одного.
//
// Цена названа числом, а не словом. Замер по стволам обоих репозиториев
// 2026-09-13 (норма: непустые строки кода без комментариев, `LC_ALL=C sort -u`,
// сверка `comm -12`): пара разборов отложенной работы совпала на 99 строках из
// 186, пара разборов имён — на 17 из 34, а словарь форм совпадал по составу
// ТОЧНО — двенадцать записей с обеих сторон.
//
// Совпадение содержимого нарушением не смягчается, а ДОКАЗЫВАЕТ его: одинаковы
// копии были сегодня, а держателя у одинаковости не было ни одного. Расхождение
// наступило бы молча — заведут в одном дереве тринадцатую форму, в другом её не
// будет, и написанное в ней окажется не находкой и не чистотой, а
// НЕВИДИМОСТЬЮ. Ни сборка, ни гейт, ни обзор диффа этого не видят: каждое
// дерево по отдельности исправно.
//
// Расхождение при этом уже НАЧАЛОСЬ, и это замер, а не опасение: на день
// заведения пакета двенадцать форм совпадали затравкой и образцом дословно, но
// пример двенадцатой формы разошёлся («на время релиза» против «на время
// выпуска»), а объяснение одного вида вычитания — на два слова. Решающая
// половина (что именно ловится) ещё сходилась; заметить это было нечем.
//
// # Что здесь, а что остаётся у ПОТРЕБИТЕЛЯ
//
// Здесь — всё, что об одном предмете говорит одинаково в любом дереве: словарь
// форм, образец, отсев по затравке, граница употребления и упоминания, вычет
// имени функции стандартной библиотеки, обход и перепись, разбор узлов-имён.
//
// У потребителя остаются ровно две вещи, и обе суть утверждения о ЕГО дереве:
//
//   - КОРЕНЬ ОБХОДА. Судить чужое дерево — краснеть на чужом, а в
//     самостоятельном клоне соседа нет вовсе;
//   - ВИДЫ ВЫЧИТАНИЯ ([DeferralSkip]). Перечень вычитаемого есть утверждение о
//     составе конкретного дерева, и проверяется он там же: вид, которому больше
//     нечего вычитать, — находка потребителя, а не этого пакета. Готовых видов
//     здесь нет НАМЕРЕННО: раздавая их, фундамент утверждал бы о чужом дереве
//     то, чего не измерял, и предикат «вид без предмета» обессмыслился бы —
//     под общим именем можно положить что угодно, и счёт не сдвинется.
//
// # Почему два предмета в одном пакете
//
// Их роднит не тема, а ЧИТАТЕЛЬ: оба разбора зовёт гейт гигиены дерева, оба
// берут состав у [github.com/PRO-Robotech/corelib/treecorpus], и оба обязаны
// печатать объём осмотренного, чтобы «ноль находок» было отличимо от «ноль
// прочитанного». Разнеся их по двум пакетам, мы получили бы два дома для одной
// провязки и два места, где следующий будет искать.
//
// # Чего этот пакет НЕ делает
//
// Он не гейт и вердикта не выносит. Он отдаёт находки и перепись; решение —
// падать ли, и с каким текстом — принимает проба потребителя, потому что текст
// отказа обязан называть исходы, принятые в ЕГО дереве.
//
// Он не судит ПРОЗУ: имя маркера внутри объяснения запрета — не отложенная
// работа, а её имя. Граница проходит между УПОТРЕБЛЕНИЕМ и УПОМИНАНИЕМ и
// описана у [DeferralForms].
//
// Он не держит ЭТО дерево. Фундамент своего гейта гигиены сегодня не несёт, и
// пакет его не заводит: гейт есть утверждение о дереве, и заводить его надо
// своим изменением, с инъекцией и переписью по этому дереву.
