// Package peer — носитель полосы ответа соседа: ОДНО место, где чужой отказ
// классифицируется, и ОДНО, где он превращается в наш ответ.
//
// # Зачем носитель
//
// Когда сервис зовёт соседа и тот отказывает, вызывающий обязан различить
// ПОЛОСЫ: чужого объекта нет у владельца · объект есть, но состояние не
// позволяет · владелец недоступен · нам отказано в правах · владелец счёл
// ссылку негодной. От полосы зависит код ответа, право на повтор и то, что
// увидит арендатор (api-conventions.md §By-lane code-split).
//
// До носителя это читалось руками: каждый клиент писал свой `switch
// status.Code(err)`, и наборы разошлись. Разошлись они молча — по таблице
// `api-conventions.md` §«gRPC-код → HTTP» и INVALID_ARGUMENT, и
// FAILED_PRECONDITION дают 400, поэтому ни REST-клиент, ни e2e-утверждение о
// статусе перехода не заметят разницы.
//
// # Что здесь запрещено по построению
//
//   - Корзины «прочее» нет. Код соседа, которому не назначена полоса, даёт
//     [OutcomeUnclassified] — это СОСТОЯНИЕ («не смог классифицировать»), а не
//     молчаливый выбор политики повтора. Оно терминально и выходит наружу
//     фиксированным INTERNAL.
//   - Отказ в правах ([OutcomeDenied]) НЕ временный. Повтор идентичного запроса
//     не пройдёт; трактовать его как временный значит вечно держать голову
//     очереди (data-integrity.md §«Межсервисное намерение»: очередь, у которой
//     за всю жизнь не доехало ни одной строки, выглядела исправной).
//   - Проза, утверждающая отсутствие НЕНАЗВАННОГО ресурса, невыразима:
//     идентификатор подставляет носитель, и на пустом идентификаторе он
//     подставляет не пустое место, а говорит, что ссылка пуста (реальный дефект
//     `resolveVipSources`: `"subnet  not found"` — утверждение об отсутствии
//     того, чего вызывающий не называл).
//   - Машинный признак едет вместе с кодом: и то и другое берётся у полосы
//     [github.com/PRO-Robotech/kacho/pkg/errors.Reason], собрать их порознь
//     нельзя. Клиент ключуется на токен; тон прозы остаётся контрактом и
//     принадлежит вызывающему.
//
// # Граница пакета
//
// Носитель судит ОТВЕТ соседа. Он не владеет соединением, сроком вызова и
// повтором — эта половина (`Conn`/`Open`/`Do` из §4.7 приёмки XC-7) в дереве
// пока отсутствует, и её отсутствие названо, а не замаскировано: сроки и
// повторы сегодня живут у каждого клиента.
//
// Внешние системы (хранилище прав, провайдер токенов, реестр образов) — ИНАЯ
// полоса: там нет ни нашего каталога, ни наших токенов, и носитель их не судит.
package peer
