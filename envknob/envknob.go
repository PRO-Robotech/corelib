// Package envknob — ИМЯ РУЧКИ ФУНДАМЕНТА НЕЙТРАЛЬНО, и переход к нему имеет окно.
//
// # Предмет
//
// Фундамент читал семь переменных окружения с приставкой ПЛАТФОРМЫ. Оператор,
// ставящий службу доступа БЕЗ платформы, настраивал её переменными с чужим
// брендом, а сменить их не мог: имя выбирает фундамент, и выбор уезжает пином к
// каждому потребителю разом. Норма «служба наследует от платформы код, но не
// имя» на них не выполнялась (`PRO-Robotech/corelib#11`).
//
// # Решение: нейтральное имя, приставку выбирает НЕ фундамент
//
// Имя ручки называет её ПРЕДМЕТ (`MIGRATOR_DSN`), а не того, кто её читает.
// Прецедент в продукте есть: доводы образа переведены на `OCI_IMAGE_*`.
//
// Альтернатива «пусть потребитель объявит свою приставку» рассмотрена и
// отвергнута: она требует изменяемого состояния уровня пакета, устанавливаемого
// из композиционного корня, — то есть глобального синглтона, который архитектура
// запрещает, — и не даёт ничего сверх нейтрального имени, потому что приставка у
// каждого потребителя всё равно одна на установку.
//
// Стандартное имя не переприсваивается: у телеметрии ручка называется так, как
// её называет сама спецификация, а не нашей копией её имени с приставкой.
//
// # Окно, а не слом
//
// Переход объявлен окном: читаются ОБА написания, нейтральное СИЛЬНЕЕ. Слом был
// бы отказом у каждого потребителя в день подъёма пина, причём отказом
// молчаливым — незаданная ручка обычно означает «умолчание», а не ошибку.
//
// Окно ЗАКРЫВАЕТСЯ, и предикат его закрытия внешний: ни один профиль
// развёртывания и ни одна страница установки в деревьях-потребителях не называет
// прежнего написания. До тех пор прежнее имя остаётся в прод-коде фундамента
// НАЗВАННЫМ решением, а не остатком.
//
// # Что возвращается вызывающему — И ПОЧЕМУ ИМЯ, А НЕ ТОЛЬКО ЗНАЧЕНИЕ
//
// [Lookup] возвращает ИМЯ, которым значение получено. Без него оператор,
// задавший прежнее написание, неотличим от задавшего новое, — и окно не
// закроется никогда: закрывать его будет нечем, кроме памяти.
package envknob

import "os"

// Lookup — значение ручки по НЕЙТРАЛЬНОМУ имени, с окном на прежнее.
//
// Возвращает значение, ИМЯ, которым оно получено, и найдено ли оно. Пустое
// значение заданной переменной значением НЕ считается: у всех семи ручек
// фундамента пустое означает «не задано», и трактовать его иначе значило бы
// завести восьмое поведение, о котором никто не решал.
//
// legacy пустое — окна нет, читается только нейтральное имя.
func Lookup(neutral, legacy string) (value, name string, ok bool) {
	if v, found := os.LookupEnv(neutral); found && v != "" {
		return v, neutral, true
	}
	if legacy != "" {
		if v, found := os.LookupEnv(legacy); found && v != "" {
			return v, legacy, true
		}
	}
	return "", "", false
}

// Get — значение либо пустая строка. Для вызывающих, которым имя не нужно.
func Get(neutral, legacy string) string {
	v, _, _ := Lookup(neutral, legacy)
	return v
}

// UsesLegacyName сообщает, что значение пришло ПРЕЖНИМ написанием. Вызывающий, у
// которого есть журнал, обязан сказать это оператору: иначе окно не закроется.
func UsesLegacyName(neutral, legacy string) bool {
	_, name, ok := Lookup(neutral, legacy)
	return ok && name == legacy
}
