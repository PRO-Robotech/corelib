package servicehost

// graceful_stop_test.go — остановка ПО НАШЕЙ ЖЕ просьбе не является отказом, и
// это верно для ОБОИХ слушателей.
//
// # Предмет
//
// Носитель гасит слушателей по отмене контекста. gRPC отвечает на это своим
// сентинелом, и вернуть его вызывающему значит сказать «сервис не поднялся» про
// сервис, который поднялся и штатно остановился.
//
// Внутренний слушатель сентинел фильтровал, публичный — нет. Асимметрия
// проявлялась флейком: исход зависел от того, успела ли отмена опередить начало
// обслуживания. Флейк был симптомом; неверным поведение было всегда.
//
// # Почему проба на сведении исхода, а не на подъёме
//
// Свойство принадлежит функции сведения: она решает, что считать отказом. Проба
// через подъём проверяла бы то же самое через гонку — то есть подтверждала бы
// свойство недетерминированно, а это ровно то, что здесь и чинится.

import (
	"errors"
	"testing"

	"google.golang.org/grpc"
)

func TestServeResult_GracefulStopIsNotAFailure(t *testing.T) {
	boom := errors.New("порт занят")

	cases := []struct {
		what             string
		public, internal error
		wantErr          bool
	}{
		{"оба погашены штатно", grpc.ErrServerStopped, grpc.ErrServerStopped, false},
		{"публичный погашен, внутренний тих", grpc.ErrServerStopped, nil, false},
		{"внутренний погашен, публичный тих", nil, grpc.ErrServerStopped, false},
		{"настоящий отказ публичного", boom, nil, true},
		{"настоящий отказ внутреннего", nil, boom, true},
		// Отказ обязан пережить соседнее штатное гашение: иначе падение одного
		// слушателя пряталось бы за остановкой другого.
		{"отказ публичного при погашенном внутреннем", boom, grpc.ErrServerStopped, true},
		{"отказ внутреннего при погашенном публичном", grpc.ErrServerStopped, boom, true},
	}

	for _, c := range cases {
		got := serveResult(c.public, c.internal)
		if (got != nil) != c.wantErr {
			t.Errorf("%s: исход = %v, ожидалась ошибка = %v — «нас попросили остановиться» и "+
				"«мы упали» обязан различать носитель: у вызывающего для этого нет ничего, "+
				"кроме текста", c.what, got, c.wantErr)
		}
	}
	t.Logf("осмотрено сочетаний исхода: %d", len(cases))
}
