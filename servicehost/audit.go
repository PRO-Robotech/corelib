// servedSet — что процесс РЕАЛЬНО служит.
//
// Набор снимается У САМИХ СЕРВЕРОВ после регистрации (`grpc.Server.GetServiceInfo`),
// а не с того, что сервис о себе сказал. Разница несущая: сказанное можно
// забыть обновить, а служимое — нельзя, потому что служить RPC и не отдать его
// дескриптор невозможно, это одна операция. Поэтому набор не обходится и
// регистрацией мимо носителя: что бы ни зарегистрировали на сервере и как бы ни
// зарегистрировали, оно окажется здесь.
type servedSet struct {
	methods []servicecontract.MethodFQN
}

// catalogRow — одна строка каталога прав в том виде, в каком её производит
// вывод из АННОТАЦИЙ дескрипторов, слинкованных в бинарь.
//
// Источник один и тот же — опции методов proto, — поэтому «каталог, который
// читает оператор» и «правило, которое исполняет сервис» суть одно утверждение,
// и расходиться им нечему.
type catalogRow struct {
	// Method — полное имя метода в форме grpc-go.
	Method servicecontract.MethodFQN
	// Domain — proto-пакет, ВЫВЕДЕННЫЙ из имени службы, а не объявленный.
	Domain string
	// ScopeFiltered — владелец сужает выдачу на уровне данных, поэтому единичной
	// проверки на крае нет и второго рубежа за ней тоже.
	ScopeFiltered bool
	// HideExistence — отказ обязан прийти текстом промаха владельца.
	HideExistence bool
	// ObjectType — тип объекта модели прав, названный аннотацией.
	ObjectType servicecontract.ObjectType
	// ServerStreaming — метод отдаёт СТРИМ, а не единичный ответ. Признак снят
	// с дескриптора метода, а не выведен из имени: «Watch» и «Subscribe» —
	// сегодняшние имена подписок, а завтрашнее имя никто не обещал.
	ServerStreaming bool
}

// catalogView — строки каталога, доступные этому процессу.
type catalogView struct {
	rows map[servicecontract.MethodFQN]catalogRow
}

// platformService — регистрация, которая приезжает вместе с сервером, а не с
// доменом сервиса.
//
// # Зачем это ЗАКРЫТЫЙ ИМЕНОВАННЫЙ перечень, а не признак «не наш пакет»
//
// Конструктор сервера общего фундамента регистрирует здоровье и рефлексию сам.
// Строк каталога у них нет и быть не может — это не домены Kachō. Без изъятия
// НИ ОДИН процесс не поднялся бы: О2 и О9 находили бы их на каждом старте.
//
// Соблазн — написать «изымаем всё, что не `kacho.*`». Это была бы корзина
// «прочее»: в неё однажды попадёт доменный RPC, переименованный или заведённый
// в чужом пакете, и попадёт МОЛЧА. Поэтому изъятие идёт по ПОЛНОМУ ИМЕНИ
// службы, у каждой записи названа причина, и перечень истекает сам: запись,
// чью службу конструктор сервера больше не регистрирует, — находка
// (`TestPlatformExemptionsAllStillHaveASubject`).
type platformService struct {
	// why — почему у этой службы не может быть строки каталога.
	why string
}

// platformServices — те самые изъятия, поимённо.
var platformServices = map[string]platformService{
	"grpc.health.v1.Health": {
		why: "проба готовности пода; регистрируется конструктором сервера общего фундамента, " +
			"домена Kachō не имеет и в каталоге прав не представлена",
	},
	"grpc.reflection.v1.ServerReflection": {
		why: "рефлексия сервера для grpcurl и отладки; регистрируется конструктором сервера " +
			"общего фундамента, домена Kachō не имеет",
	},
	"grpc.reflection.v1alpha.ServerReflection": {
		why: "прежняя версия той же рефлексии; регистрируется тем же конструктором ради " +
			"клиентов, не умеющих v1",
	},
}

// census — объём осмотренного. Существует затем, чтобы «ноль находок» было
// отличимо от «ноль прочитанного»: отказ, который ничего не осмотрел, выглядит
// в точности как исправный процесс.
type census struct {
	methods   int
	domains   int
	rows      int
	exempted  int
	narrowers int
	hidden    int
	// probed — типы, о которых порт существования БУДЕТ спрошен. Считается
	// отдельно от `hidden`: множества разные, и именно их расхождение было
	// находкой — скрытие расширялось на типы шире осмотренного.
	probed int
	// covered — типы, которые проба ОБЪЯВИЛА своим охватом. Считается рядом с
	// `probed` и печатается рядом: расходятся именно эти два числа, и «охват
	// шире» с «охват уже» неразличимы, пока напечатано одно из них.
	covered int
	// streams — служимые методы, отдающие стрим. Ноль здесь обязан быть
	// напечатанным, а не подразумеваемым: «стримов нет» и «стримы не считали»
	// иначе неразличимы.
	streams int
}

func (c census) String() string {
	return fmt.Sprintf("осмотрено: методов %d (изъято платформенных %d, стримов %d), доменов %d, "+
		"строк каталога %d, сужаемых методов %d, скрывающих типов %d, спрашиваемых портом типов %d, "+
		"объявленных охватом пробы типов %d",
		c.methods, c.exempted, c.streams, c.domains, c.rows, c.narrowers, c.hidden, c.probed, c.covered)
}

// domainOf выводит proto-пакет из полного имени метода (К-2: домен ВЫВОДИТСЯ, а
// не объявляется).
//
// Разбор НЕ ВПРАВЕ вернуть пустую строку молча. Если бы он это делал, «имя не
// разобралось» и «у домена ноль строк каталога» стали бы одним исходом, и О9
// докладывал бы о втором, когда случилось первое, — то есть посылал бы чинить
// не туда.
func domainOf(m servicecontract.MethodFQN) (string, error) {
	s := string(m)
	if !strings.HasPrefix(s, "/") {
		return "", fmt.Errorf("имя метода %q не начинается со слэша — это не та форма, "+
			"в которой grpc-go передаёт полное имя", s)
	}
	svc, _, ok := strings.Cut(strings.TrimPrefix(s, "/"), "/")
	if !ok || svc == "" {
		return "", fmt.Errorf("имя метода %q не содержит имени службы", s)
	}
	pkg := svc[:strings.LastIndex(svc, ".")+1]
	if pkg == "" {
		return "", fmt.Errorf("имя службы %q не содержит proto-пакета: домен вывести не из чего", svc)
	}
	pkg = strings.TrimSuffix(pkg, ".")
	if pkg == "" {
		return "", fmt.Errorf("имя службы %q даёт пустой proto-пакет", svc)
	}
	return pkg, nil
}

// serviceOf возвращает полное имя службы из полного имени метода.
func serviceOf(m servicecontract.MethodFQN) string {
	svc, _, _ := strings.Cut(strings.TrimPrefix(string(m), "/"), "/")
	return svc
}

// audit — отказы старта, которым нужен СЛУЖИМЫЙ НАБОР: О2, О3, О4, О5, О9.
//
// Возвращает перепись осмотренного даже при отказе — вызывающий обязан уметь
// сказать, сколько было прочитано, а не только сколько найдено.
//
// Все находки собираются РАЗОМ: отказ по первой заставил бы автора чинить по
// одной и узнавать о следующей на следующем старте.
func audit(spec servicecontract.Spec, served servedSet, cat catalogView, rpcMap authz.RPCMap) (census, error) {
	var c census
	var f findings

	if len(served.methods) == 0 {
		return c, fmt.Errorf("servicehost: %s не поднимается — служимый набор RPC пуст (ноль методов). "+
			"Ноль целей есть ОТКАЗ, а не успех: процесс, не служащий ничего, неотличим от исправного "+
			"по всякому признаку, кроме этого", nameOf(spec))
	}

	// ── О2 и О9: служимое против каталога и против карты ────────────────────
	domains := map[string]int{} // домен -> сколько записей он дал КАРТЕ
	seenDomain := map[string]bool{}
	for _, m := range served.methods {
		svc := serviceOf(m)
		if p, exempt := platformServices[svc]; exempt {
			c.exempted++
			_ = p
			continue
		}
		c.methods++

		dom, err := domainOf(m)
		if err != nil {
			f.add(string(m), "домен не выводится: "+err.Error())
			continue
		}
		seenDomain[dom] = true

		// О2: служится RPC, у которого нет строки каталога его домена.
		if _, ok := cat.rows[m]; !ok {
			f.add(string(m), "служится, но строки каталога у метода нет: звено решения о доступе "+
				"отвергнет его как незамапленный, и отказ этот не назовёт ни метода, ни упущения")
		}
		// Карта — то, что звено спрашивает НА САМОМ ДЕЛЕ. Считаем вклад домена
		// именно в неё: строка каталога, не доехавшая до карты, оставляет метод
		// без правила ровно так же, как её отсутствие.
		if _, ok := rpcMap[string(m)]; ok {
			domains[dom]++
		}
	}
	for dom := range seenDomain {
		if domains[dom] == 0 {
			f.add(dom, "выведенный домен не дал карте прав НИ ОДНОЙ записи. Ноль целей есть отказ, "+
				"а не успех: домен, о котором карта не знает ничего, неотличим от домена, у которого всё на месте")
		}
	}
	c.domains = len(seenDomain)
	c.rows = len(cat.rows)

	auditNarrowers(&c, &f, spec, served, cat)     // О3 + О4
	auditHideExistence(&c, &f, spec, cat, rpcMap) // О5
	auditStreamBudget(&c, &f, spec, served, cat)  // О11

	if err := f.err(nameOf(spec)); err != nil {
		return c, err
	}
	return c, nil
}

// auditNarrowers — О3 и О4, ОБЕ половины сразу.
//
// Без второй половины пропажа проводки невидима: сужатель, потерянный при
// переносе слоёв, не краснеет нигде, потому что каталог о нём не спрашивает —
// ровно тот случай, который уже был.
//
// Здесь же истекает заявление «не применимо»: пока у домена нет строк
// `scope_filtered`, оно законно; появилась первая — то же самое заявление стало
// находкой, и вспоминать о нём никому не нужно.
func auditNarrowers(c *census, f *findings, spec servicecontract.Spec, served servedSet, cat catalogView) {
	declared := map[servicecontract.MethodFQN]struct{}{}
	for _, m := range served.methods {
		if row, ok := cat.rows[m]; ok && row.ScopeFiltered {
			declared[m] = struct{}{}
		}
	}
	c.narrowers = len(declared)

	wired, hasValue := spec.Narrowers.Get()

	// О3: объявлено каталогом, не предъявлено дескриптором.
	for m := range declared {
		n, ok := wired[m]
		if !hasValue || !ok || n == nil {
			why := "каталог объявляет метод сужаемым (`scope_filtered`), а дескриптор проводки " +
				"сужателя на него не несёт: за таким методом пообъектной проверки на крае нет вовсе, " +
				"поэтому отсутствующий сужатель означает не «строже», а «без рубежа»"
			if !hasValue {
				if because, na := spec.Narrowers.NotApplicableBecause(); na {
					why += ". Ось объявлена неприменимой (" + because + ") — заявление истекло: " +
						"у домена появилась строка, которую оно исключало"
				}
			}
			f.add("Narrowers "+string(m), why)
		}
	}
	// О4: предъявлено дескриптором, каталогом не объявлено.
	for m, n := range wired {
		if _, ok := declared[m]; ok {
			continue
		}
		if n == nil {
			continue // уже названо выше либо не относится к сужаемым
		}
		f.add("Narrowers "+string(m), "дескриптор несёт проводку сужателя на метод, которого каталог "+
			"сужаемым не объявлял: либо метод перестал быть сужаемым и проводка пережила свой предмет, "+
			"либо строку каталога потеряли — и без этой половины пропажа была бы невидима")
	}
}

// auditHideExistence — О5, тоже в обе стороны.
//
// Скрытие существования работает ровно настолько, насколько текст отказа
// неотличим от настоящего промаха владельца. Поэтому проверяется не только
// НАЛИЧИЕ формы, но и её ФОРМА: ровно одна подстановка идентификатора.
func auditHideExistence(c *census, f *findings, spec servicecontract.Spec, cat catalogView, rpcMap authz.RPCMap) {
	auditProbedTypes(c, f, spec, rpcMap)
	// Скрывающее множество выводится ТЕМ ЖЕ предикатом, каким скрывает рантайм, —
	// `authz.HidesExistenceOnDeny`, а не по одной аннотации каталога.
	//
	// Прежняя редакция читала только аннотацию, и это расходилось с исполнением в
	// обе стороны сразу. Рантайм скрывает по аннотации ИЛИ по ФОРМЕ (`/Get` с
	// глаголом чтения у типа, за который есть чем говорить), поэтому сервис без
	// единой аннотации мог скрывать на десятке методов — и судья этого не видел.
	// Следствия были не косметические:
	//
	//   - сервис, который РЕАЛЬНО скрывает, не мог объявить формы отказа: каждая
	//     объявленная давала находку зеркальной половины («форма для типа, который
	//     каталог скрывающим не называет»), а не объявить с портом не давал
	//     конструктор. Два слоя блокировали то, что рантайм уже делает;
	//   - и обратное, дороже: изъятие «скрывать нечего» ПРОХОДИЛО у сервиса, чей
	//     рантайм скрывает. Заявление было ложным, а судья его не опровергал,
	//     потому что смотрел не на то. Ось, которая пропускает ложное изъятие,
	//     проверяет форму объявления, а не предмет.
	//
	// Аннотация при этом не отменена: она входит в предикат первым дизъюнктом.
	// Изменилось одно — судья перестал быть УЖЕ исполнения.
	hidden := map[servicecontract.ObjectType]struct{}{}
	for m, row := range cat.rows {
		entry, ok := rpcMap.Lookup(string(m))
		if !ok {
			// Метод без записи в карте прав ловится отдельным отказом (О2);
			// здесь он не наш предмет и молча пропускается, а не додумывается.
			continue
		}
		// Тип объекта резолвится ТЕМ ЖЕ способом, каким его получает рантайм, —
		// из записи карты прав, а не из строки каталога.
		//
		// Строка каталога несёт тип только когда он выписан аннотацией области;
		// у части методов она пуста, а рантайм всё равно знает тип — он берёт его
		// извлекателем. Читая строку, судья пропускал такие методы молча, и сервис
		// с пустой аннотацией области выглядел «ничего не скрывающим», хотя скрывал.
		// Замерено на storage: три `/Get` скрывают по форме, а аннотации области у
		// них нет — заявление «скрывать нечего» проходило именно поэтому.
		ots, ok := catalogderive.ScopeObjectType(string(m), entry)
		if !ok {
			if row.ObjectType == "" {
				continue
			}
			ots = string(row.ObjectType)
		}
		ot := servicecontract.ObjectType(ots)
		row.ObjectType = ot
		if authz.HidesExistenceOnDeny(string(m), entry, ots) {
			hidden[ot] = struct{}{}
			continue
		}
		// Аннотация ЕСТЬ, а рантайм по ней не скрывает — расхождение объявления с
		// исполнением, и его нельзя пропустить молча.
		//
		// Единственная причина такого исхода: у типа нет голоса владельца (первый
		// дизъюнкт предиката). Тогда аннотация обещает скрытие, которого не будет:
		// отказ придёт своей, отличимой формой — то есть ровно оракулом, ради
		// закрытия которого аннотацию и ставят. Прежний судья ловил это иначе (тип
		// попадал в скрывающие, а форма не находилась), и при сведении предиката
		// проверка исчезла бы вместе со своей ветвью.
		if row.HideExistence {
			f.add("HideExistence "+string(ot),
				"каталог объявляет тип скрывающим существование, но рантайм по нему НЕ скрывает: "+
					"у типа нет голоса владельца в таблице промахов владельцев (pkg/authz), и отказ придёт "+
					"своей, отличимой формой. Аннотация обещает то, чего не произойдёт — "+
					"либо заведите тип в таблицу, либо снимите аннотацию")
		}
	}
	c.hidden = len(hidden)

	forms, hasValue := spec.HideExistence.Get()

	for ot := range hidden {
		form, ok := forms[ot]
		if !hasValue || !ok {
			why := "каталог называет тип среди скрывающих существование, а форма отказа для него " +
				"не объявлена: ресурс ответил бы своей, отличимой формой — то есть оракулом существования"
			if !hasValue {
				if because, na := spec.HideExistence.NotApplicableBecause(); na {
					why += ". Ось объявлена неприменимой (" + because + ") — заявление истекло"
				}
			}
			f.add("HideExistence "+string(ot), why)
			continue
		}
		if n := strings.Count(string(form), "%s"); n != 1 || strings.Count(string(form), "%") != n {
			f.add("HideExistence "+string(ot), fmt.Sprintf(
				"форма отказа %q обязана нести РОВНО одну подстановку `%%s` под идентификатор, "+
					"который назвал вызывающий; любой другой текст отличим от настоящего промаха владельца",
				string(form)))
			continue
		}
		// Форма сверяется с ТЕМ, ЧТО РЕАЛЬНО ОТВЕТИТ звено решения о доступе.
		// Объявление и производитель текста — два места об одном предмете, и без
		// сверки расхождение между ними осталось бы невидимым: отвечает всегда
		// таблица владельцев, поэтому объявленная форма могла бы разойтись с
		// действительностью и не покраснеть нигде.
		owner, known := authz.OwnerNotFoundFormat(string(ot))
		switch {
		case !known:
			f.add("HideExistence "+string(ot), "форма отказа объявлена для типа, которого нет в таблице "+
				"промахов владельцев: звено ответит нейтральным «not found» — текстом, не похожим ни на "+
				"один ответ владельца, то есть той самой приметой, ради устранения которой скрытие и делается")
		case owner != string(form):
			f.add("HideExistence "+string(ot), fmt.Sprintf(
				"объявленная форма %q расходится с той, которой ответит звено решения о доступе (%q). "+
					"Отвечает вторая, поэтому объявление здесь описывает не действительность; сведите их "+
					"дословно — скрытие работает ровно настолько, насколько текст отказа неотличим от промаха владельца",
				string(form), owner))
		}
	}
	// Зеркально: форма, которой больше нечего скрывать, — находка.
	for ot := range forms {
		if _, ok := hidden[ot]; !ok {
			f.add("HideExistence "+string(ot), "объявлена форма отказа для типа, который каталог "+
				"скрывающим не называет: запись пережила свой предмет и утверждает, что платформа "+
				"отвечает голосом владельца там, где владельца уже нет")
		}
	}
}

// auditProbedTypes — О5б: каждый тип, о котором БУДЕТ спрошен порт существования,
// обязан иметь голос владельца.
//
// # Почему это отдельный отказ, а не часть О5
//
// О5 осматривает множество, которое НАЗВАЛ каталог: типы строк с
// `hide_existence`. Порт существования спрашивается о другом множестве — о
// пообъектных типах, ВЫВЕДЕННЫХ из карты прав ([withExistenceHiding]), и оно
// шире. Пока эти два множества не сведены, тип может попасть под скрытие, ни
// разу не будучи осмотренным: О5 про него не спрашивает, потому что каталог не
// называл его скрывающим.
//
// Чем это кончается на пути отказа: наш собственный решатель отвечает «объект
// есть, но не твой», звено идёт за текстом владельца, не находит его и отдаёт
// нейтральное «not found» — строку, не похожую ни на один ответ владельца. То
// есть скрытие включается и тут же выдаёт себя приметой. Производитель в дереве
// назван проверяющим: пообъектный тип на трёх RPC iam, у которого строки в
// таблице промахов владельцев нет.
//
// Отказ вместо выбора в рантайме — намеренно. У состояния «скрываем тип, за
// который нечем говорить» нет правильного исхода: нейтральный текст отличим от
// промаха владельца, а откат к отказу в доступе отличим по КОДУ. Поэтому
// состояние делается недостижимым, а не разрешается в пользу меньшего зла.
//
// Молчит по построению, пока сервис не принёс порт: спрашивать будет некому.
func auditProbedTypes(c *census, f *findings, spec servicecontract.Spec, rpcMap authz.RPCMap) {
	if spec.Existence == nil {
		return
	}
	probed := catalogderive.ObjectScopedTypes(rpcMap)
	c.probed = len(probed)
	if len(probed) == 0 {
		f.add("Existence", "порт проверки существования принесён, а спрашивать его не о чем: из карты "+
			"прав не вывелось НИ ОДНОГО пообъектного типа. Ноль целей есть отказ, а не успех — порт, "+
			"который никогда не спросят, неотличим от работающего")
		return
	}
	types := make([]string, 0, len(probed))
	for ot := range probed {
		types = append(types, ot)
	}
	sort.Strings(types)

	// О5в — ОХВАТ пробы против того, о чём её спросят.
	//
	// Обе стороны выведены: пообъектные типы — из карты прав (тем же
	// предикатом, каким рантайм решает, спрашивать ли пробу), охват — из самой
	// пробы. Выписанного перечня в месте сравнения нет ни одного, поэтому
	// расхождение не переживает правку одной стороны.
	//
	// Почему это отдельная ось, а не следствие ошибки пробы на запросе: проба
	// отвергает незнакомый тип ошибкой, а вызывающий отрабатывает fail-closed и
	// оставляет отказ отказом. На запросе это верно; как ЕДИНСТВЕННАЯ проверка
	// негодно — тип вне охвата ведёт себя не как дефект, а как «нет доступа»,
	// то есть неотличимо от исправной работы. Наблюдалось на compute: из трёх
	// пообъектных типов проба знала один, и два соседних типа того же сервиса
	// отвечали на одном входе разным кодом (задача продукта #1931).
	covered := map[string]struct{}{}
	for _, ot := range spec.Existence.ProbeableTypes() {
		covered[ot] = struct{}{}
	}
	c.covered = len(covered)
	if len(covered) == 0 {
		f.add("Existence", "порт существования принесён, а ОХВАТ не объявлен: перечень типов, о "+
			"которых проба умеет ответить, пуст. Пустой перечень здесь означает «ни о чём», а не «обо "+
			"всём» — каждый пообъектный тип получил бы ошибку пробы, то есть отказ в правах там, где "+
			"обязан быть промах владельца")
	}
	for _, ot := range types {
		if _, ok := covered[ot]; ok {
			continue
		}
		if len(covered) == 0 {
			// Отказ об охвате уже назван выше; поимённый перечень поверх него
			// был бы вторым обвинением об одном предмете.
			break
		}
		f.add("Existence "+ot, "тип пообъектен по карте прав — порт БУДЕТ о нём спрошен, — а в охват "+
			"пробы он не входит: сверка ответит ошибкой, вызывающий отработает fail-closed, и отказ "+
			"придёт кодом отказа в правах там, где соседний тип того же сервиса отвечает промахом "+
			"владельца. Либо заведите типу запись в таблице пробы, либо снимите с него пообъектную полосу")
	}
	// Зеркально: охват, которому больше нечего покрывать, — находка. Без этой
	// половины запись пережила бы снятие своего типа молча, и следующий читатель
	// принял бы её за действующее утверждение о продукте.
	for _, ot := range spec.Existence.ProbeableTypes() {
		if _, ok := probed[ot]; !ok {
			f.add("Existence "+ot, "проба объявляет охват на тип, который карта прав пообъектным не "+
				"называет: спросить её о нём некому, и запись утверждает про продукт то, чего в нём нет")
		}
	}

	for _, ot := range types {
		if _, known := authz.OwnerNotFoundFormat(ot); !known {
			f.add("Existence "+ot, "порт существования будет спрошен об этом типе (он пообъектный по карте "+
				"прав), а голоса владельца у типа нет: отказ на существующем чужом объекте пришёл бы "+
				"нейтральным «not found» — текстом, не похожим ни на один ответ владельца, то есть той самой "+
				"приметой, ради устранения которой скрытие и делается. Либо заведите типу строку в таблице "+
				"промахов владельцев (pkg/authz), либо снимите с него пообъектную полосу")
		}
	}
}

// auditStreamBudget — О11: СЛУЖИМЫЕ серверные стримы против оси срока их жизни,
// и обе стороны сразу.
//
// # Предмет
//
// Для запроса верхняя граница обработки — ровно её предмет; для серверного
// стрима та же величина означает другое: СРОК ЖИЗНИ ПОДПИСКИ. Обоснование
// границы обработки говорит про исчерпание пула соединений ЗАПРОСАМИ и про срок
// подписки не говорит ничего, поэтому распространять одно правило на два вида
// вызовов с принципиально разным сроком жизни молча нельзя. Решение принимается
// ЯВНО — осью [servicecontract.Spec.StreamBudget].
//
// # Обе стороны, и вторая несущая
//
//   - служится серверный стрим, а величины у оси нет (изъятие либо ось не
//     объявлена вовсе) → отказ старта, поимённо по каждому такому методу.
//     Молчаливой альтернативой была бы подписка, рвущаяся раз в границу, — то
//     есть отказ, который клиент читает как сетевой сбой;
//   - величина объявлена, а служимых серверных стримов НЕТ → тоже находка:
//     проводка без предмета. Без этой половины ось ловила бы форму («автор
//     что-то объявил»), а не существо («объявленное относится к тому, что
//     процесс служит»), и величина пережила бы снятие последней подписки молча.
//
// Первая половина ЕСТЬ самоистечение изъятия: заявление «серверных стримов не
// служу» законно ровно пока это верно, и проверяется оно служимым набором, а не
// памятью автора.
//
// Изъятия по методу здесь нет намеренно: перечень служимых стримов даёт сам
// процесс, а решение про их срок — одно на процесс.
func auditStreamBudget(c *census, f *findings, spec servicecontract.Spec, served servedSet, cat catalogView) {
	streaming := make([]servicecontract.MethodFQN, 0, len(served.methods))
	for _, m := range served.methods {
		if row, ok := cat.rows[m]; ok && row.ServerStreaming {
			streaming = append(streaming, m)
		}
	}
	sort.Slice(streaming, func(i, j int) bool { return streaming[i] < streaming[j] })
	c.streams = len(streaming)

	budget, hasValue := spec.StreamBudget.Get()
	because, notApplicable := spec.StreamBudget.NotApplicableBecause()

	switch {
	case len(streaming) > 0 && !hasValue:
		for _, m := range streaming {
			why := "метод отдаёт СЕРВЕРНЫЙ СТРИМ, а срок жизни подписки этим процессом не объявлен " +
				"величиной: носитель либо оборвал бы её потолком одиночного вызова, либо не накрыл " +
				"сроком вовсе — и оба исхода выбраны не автором, а умолчанием. Объявите " +
				"servicecontract.Value[time.Duration](<сколько живёт подписка>) в поле StreamBudget " +
				"дескриптора; величина обязана превосходить HandlingBudget"
			if notApplicable {
				why += ". Ось объявлена неприменимой (" + because + ") — заявление ИСТЕКЛО: " +
					"у процесса появился служимый серверный стрим, которого оно исключало"
			}
			f.add(string(m), why)
		}
	case len(streaming) == 0 && hasValue:
		f.add("StreamBudget", fmt.Sprintf("объявлен срок жизни подписки (%v), а служимых серверных "+
			"стримов у процесса НЕТ НИ ОДНОГО: величина пережила свой предмет и утверждает решение "+
			"про подписки там, где подписок нет. Либо снимите её изъятием "+
			"servicecontract.NotApplicable(\"серверных стримов не служу\"), либо верните стрим, "+
			"ради которого она объявлена", budget))
	}
}

func nameOf(s servicecontract.Spec) string {
	if strings.TrimSpace(string(s.Service)) == "" {
		return "<безымянный сервис>"
	}
	return string(s.Service)
}

// findings — накопитель отказов старта носителя. Отдельный от накопителя
// дескриптора намеренно: тексты разные, и смешивать «поле не заполнено» с
// «объявленное не сходится со служимым» значило бы терять, что именно чинить.
type findings struct{ items map[string][]string }

func (f *findings) add(subject, why string) {
	if f.items == nil {
		f.items = map[string][]string{}
	}
	f.items[subject] = append(f.items[subject], why)
}

func (f *findings) err(svc string) error {
	if len(f.items) == 0 {
		return nil
	}
	subjects := make([]string, 0, len(f.items))
	for k := range f.items {
		subjects = append(subjects, k)
	}
	sort.Strings(subjects)

	var b strings.Builder
	fmt.Fprintf(&b, "servicehost: %s не поднимается — объявленное не сходится со служимым (%d предмет(ов)):",
		svc, len(subjects))
	for _, k := range subjects {
		for _, why := range f.items[k] {
			fmt.Fprintf(&b, "\n  · %s: %s", k, why)
		}
	}
	return fmt.Errorf("%s", b.String())
}
