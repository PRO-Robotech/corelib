package filter

import "testing"

// TestParseEmitsOnlyKnownOperators — набор операторов, которые Parse способен
// выпустить, закрыт и известен: сегодня это `=` и `CONTAINS`.
//
// # Что здесь было раньше и почему изменилось
//
// Предыдущая редакция утверждала, что оператор РОВНО ОДИН, и была заведена
// самоистекающей: покраснеть в тот день, когда в грамматику добавят второй, и
// текстом падения назвать работу, которую тогда надо сделать. Она это и сделала
// — сработала на слиянии, принёсшем `CONTAINS`, и перечислила владельцев,
// строивших предикат с зашитым равенством (#460).
//
// Дальше её нельзя было оставить как есть: утверждение «оператор один» стало
// ложным, то есть проба падала бы вечно — не на дефекте, а на ДОСТИЖЕНИИ
// собственной цели. Проба, красная от того, что предмет запрета появился и
// обработан, толкает снять её как надоевшую, и вместе с ней исчезает механизм.
// Поэтому она не удалена и не заморожена, а перенацелена на состояние, которое
// существует сейчас.
//
// # Что она держит теперь
//
// Тот же механизм на новом рубеже: ТРЕТИЙ оператор обязан быть замечен. Появление
// нового отношения в грамматике — правка в одном файле, а неверными от неё
// становятся места, которых она не касается: каждый владелец, применяющий
// оператор, должен научиться его применять, а каждый, кто его отвергает, —
// назвать его в отказе. Диффом это не видно ни с одной стороны.
//
// # Чем это дополняется, а не подменяется
//
// Здесь проверяется ПОВЕРХНОСТЬ грамматики — что она выпускает. Что владельцы
// это применяют, держит `internal/repohygiene`
// `TestFilterOwnerHonoursTheParsedOperator`: он обходит дерево и требует от
// каждого читателя значения либо применить оператор, либо отвергнуть его явно.
// Два разных предмета, поэтому две проверки: грамматика может вырасти без
// владельцев, а владелец — потерять оператор без правки грамматики.
func TestParseEmitsOnlyKnownOperators(t *testing.T) {
	// known — операторы, которые дерево умеет применять. Расширять этот набор
	// значит принимать на себя обход владельцев: см. гейт, названный выше.
	known := map[string]bool{OpEquals: true, OpContains: true}

	// Корпус намеренно содержит формы ДРУГИХ отношений вперемешку с известными:
	// принятая форма вне `known` — сигнал, что грамматика выросла.
	corpus := []string{
		`name="v"`,
		`name = "v"`,
		`name CONTAINS "v"`,
		`name:"v"`,
		`name~"v"`,
		`name!="v"`,
		`name>"v"`,
		`name<"v"`,
		`name IN ("a","b")`,
		`name STARTS_WITH "v"`,
		`name LIKE "%v%"`,
		`name NOT_CONTAINS "v"`,
	}

	accepted := 0
	seen := map[string]bool{}
	for _, expr := range corpus {
		ast, err := Parse(expr, []string{"name"})
		if err != nil || ast == nil {
			continue
		}
		accepted++
		seen[ast.Op] = true
		if !known[ast.Op] {
			t.Fatalf(
				"Parse(%q) выпустил оператор %q — грамматика выросла.\n"+
					"Прежде чем это станет рабочим, обойди владельцев выражения и научи их "+
					"НОВОМУ отношению: тот, кто его применяет, обязан его применить, а тот, "+
					"кому оно не подходит, — отвергнуть его явно, назвав. Молча свести к "+
					"равенству нельзя: вызывающий получит уверенный и неверный ответ.\n"+
					"Перечень владельцев не держи здесь — его выводит по дереву "+
					"internal/repohygiene.TestFilterOwnerHonoursTheParsedOperator; "+
					"прогони его, он назовёт места сам.",
				expr, ast.Op)
		}
	}

	// Перепись: «все отвергнуты» и «ни одно не разобрано» — разные исходы. Без
	// этого проверка осталась бы зелёной, даже если бы Parse перестал принимать
	// вообще всё.
	t.Logf("осмотрено выражений: %d, принято грамматикой: %d, различных операторов: %d",
		len(corpus), accepted, len(seen))
	if accepted == 0 {
		t.Fatal("грамматика не приняла ни одного выражения корпуса — " +
			"проверка ничего не утверждает, вердикт недействителен")
	}

	// Обе известные формы обязаны быть ПРЕДСТАВЛЕНЫ в корпусе и приняты. Иначе
	// «оператор вне набора не встретился» могло бы означать, что корпус не
	// содержит ни одной живой формы, а не что грамматика на месте.
	for op := range known {
		if !seen[op] {
			t.Fatalf("корпус не содержит ни одного выражения с оператором %q — "+
				"проверка не покрывает объявленный набор", op)
		}
	}
}
