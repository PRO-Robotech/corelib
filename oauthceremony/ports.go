// SecretVerdict — исход сверки предъявленного секрета клиента.
//
// # Почему нулевое значение не объявлено
//
// По той же причине, что у StoreOutcome: реализация, забывшая назвать исход,
// вернула бы ноль, и ноль читался бы как тот из двух вердиктов, который
// назначили нулём. Нулевое значение и значение вне словаря церемония
// отвергает как нарушение контракта порта (ErrPortContract), а не толкует.
type SecretVerdict uint8

// Вердикты сверки. Перечень ЗАКРЫТ.
const (
	// SecretVerdictUnspecified — вердикт не назван. Не вердикт.
	SecretVerdictUnspecified SecretVerdict = iota
	// SecretMatched — предъявленный секрет совпал с проверочным значением
	// клиента: нынешним либо прежним на время оборота.
	SecretMatched
	// SecretMismatched — не совпал: секрет неверен, не предъявлен, либо
	// клиента, которого назвали, у службы нет.
	SecretMismatched
)

// Declared отвечает, входит ли вердикт в словарь. Нулевое значение НЕ входит.
func (v SecretVerdict) Declared() bool { return v == SecretMatched || v == SecretMismatched }

// PresentedSecret — секрет клиента В ЧИСТОМ ВИДЕ, как его предъявил клиент.
//
// # Почему отдельный тип, а не строка
//
// Значение уезжает службе — в порт сверки (ClientSecretVerifier), то есть в
// код, который пишет журнал. Строку, переданную в журнал аргументом или полем
// структуры, форматирование напечатало бы целиком. Этот тип значения не
// печатает: String отдаёт метку, а само значение лежит за указателем, и печать
// поля-указателя даёт адрес при ЛЮБОМ глаголе — в том числе там, где String не
// зовётся (глагол %d, поле, закрытое от отражения). Значение отдаёт только
// Reveal — и каждое его чтение видно в коде по имени.
//
// Нулевое значение законно: клиент секрета не предъявил.
type PresentedSecret struct {
	value *string
}

// redactedMark — то, что печать PresentedSecret отдаёт вместо значения.
const redactedMark = "oauthceremony.PresentedSecret(redacted)"

// NewPresentedSecret — предъявленный секрет из его значения. Церемония
// собирает его сама; конструктор нужен службе, которая проверяет свою
// реализацию порта.
func NewPresentedSecret(value string) PresentedSecret { return PresentedSecret{value: &value} }

// Reveal отдаёт значение — для сверки постоянного времени, и только для неё.
// У нулевого значения — пустая строка: секрета не предъявили.
func (s PresentedSecret) Reveal() string {
	if s.value == nil {
		return ""
	}
	return *s.value
}

// String отдаёт метку без значения.
func (PresentedSecret) String() string { return redactedMark }

// ClientSecretVerifier — сверка секрета клиента.
//
// Реализует СЛУЖБА: она владеет проверочным значением секрета — его функцией,
// солью, ценой и оборотом — и сравнением постоянного времени. У церемонии нет
// ни значения, ни хешера: хешер движка на её путях не участвует, и цену
// сверки назначает служба, а не настройки церемонии.
//
// # Когда церемония зовёт порт
//
// РОВНО ОДИН РАЗ на доказательство клиента — в обмене, интроспекции и
// отзыве, — и для клиента, которого справочник знает, и для клиента, которого
// он НЕ знает (ClientDirectory ответил ErrGrantNotFound). Отказ неизвестному
// клиенту обязан стоить столько же, сколько отказ неверному секрету, иначе
// время ответа — прибор для перебора зарегистрированных клиентов. Церемония
// держит свою половину — число вызовов и один и тот же отказ; служба свою:
// для клиента без проверочного значения она сверяет предъявленное с
// приманкой того же класса и отвечает SecretMismatched.
//
// Публичного клиента (ClientRegistration.Public) точки токена и отзыва не
// сверяют: он себя не доказывает. Интроспекция требует доказательства от
// всякого клиента и принимает его только заголовком (RFC 7662 §2.1): запрос
// без заголовка движок отвергает раньше, чем спросит справочник, и порт не
// зовётся ни для кого.
//
// # Исходы
//
//   - (SecretMatched, nil) — секрет совпал с нынешним проверочным значением
//     клиента либо с прежним на время оборота: оборот секретов — забота
//     службы, и вызов на оба один.
//   - (SecretMismatched, nil) — не совпал, не предъявлен (пустое значение)
//     либо клиента у службы нет.
//   - (_, ошибка) — сверка не состоялась: сбой, недоступность, срок или
//     отмена вызова. Это отказ ОПЕРАЦИИ, а не «клиент не доказан»:
//     несостоявшаяся сверка не вправе стать ни одним из вердиктов.
//
// Ошибка со случаем этого пакета — ErrPortContract: в контракте сверки нет ни
// одного такого отказа, и случай порта исходом протокола не становится.
//
// Нулевой вердикт и вердикт вне словаря — ErrPortContract. SecretMatched о
// клиенте, которого справочник не знает, — тоже ErrPortContract: доказать себя
// может только зарегистрированный клиент, и порт, сказавший иное,
// противоречит справочнику.
//
// # Секрет
//
// presented — предъявительский секрет. Порт НЕ пишет его в журнал и НЕ кладёт
// в текст своего отказа; печать типа его не выдаёт (PresentedSecret), значение
// отдаёт только Reveal.
//
// Срок вызова — Config.PortTimeout, тот же, что у прочих портов.
type ClientSecretVerifier interface {
	// VerifyClientSecret сверяет секрет, предъявленный от имени клиента
	// clientID. Идентификатор — такой, каким его назвал клиент: знает ли его
	// служба, порт выясняет сам.
	VerifyClientSecret(ctx context.Context, clientID string, presented PresentedSecret) (SecretVerdict, error)
}

// UnitOfWork — НЕОБЯЗАТЕЛЬНЫЙ порт единицы работы.
//
// Реализует СЛУЖБА, если её хранилище умеет транзакции.
//
// # Что он даёт и чего НЕ даёт
//
// Движок оборачивает транзакцией выдачу — «положить токен доступа +
// положить токен обновления» (на обороте токена обновления — вместе с его
// оборотом): либо уедет всё, либо ничего. Погашение кода в эту связку НЕ
// входит: церемония гасит код раньше, при предъявлении (см.
// AuthorizationCodeVault), и код, чья выдача откатилась, остаётся погашенным —
// предъявленный код второго предъявления не получает. Транзакция не защищает
// и от повторного использования кода — чтение кода стоит до её открытия. Один
// порт закрывает частичную запись, другой — гонку; подменять один другим
// нельзя.
//
// Если порт не назван, церемония собирает мост БЕЗ транзакционных методов, и
// движок, проверяющий их наличие утверждением типа, честно видит хранилище
// без транзакций. Мост с методами-пустышками солгал бы движку, и связка выше
// перестала бы быть неделимой молча.
type UnitOfWork interface {
	// Begin открывает единицу работы и возвращает контекст, несущий её.
	// Все последующие вызовы портов придут с этим контекстом.
	Begin(ctx context.Context) (context.Context, error)

	// Commit закрепляет единицу работы, найденную в контексте.
	Commit(ctx context.Context) error

	// Rollback отменяет единицу работы, найденную в контексте.
	Rollback(ctx context.Context) error
}

// Ports — полный набор портов церемонии.
//
// Все поля, кроме Transaction, ОБЯЗАТЕЛЬНЫ: New отвергает набор с пустым
// полем поимённо. Необязательное хранилище означало бы ветку «а если его
// нет», то есть второй, непроверяемый путь исполнения.
type Ports struct {
	Clients            ClientDirectory
	AuthorizationCodes AuthorizationCodeVault
	AccessTokens       AccessTokenVault
	RefreshTokens      RefreshTokenVault
	Grants             GrantRevoker
	AccessTokenIssuer  AccessTokenIssuer
	ClientSecrets      ClientSecretVerifier

	// Transaction — необязателен. Пусто означает «хранилище службы не
	// умеет транзакций», и церемония ведёт себя соответственно.
	Transaction UnitOfWork
}
