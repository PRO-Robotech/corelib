// ── Число затронутых строк как ТИП ──────────────────────────────────────────

// StoreOutcome — исход записи: сколько строк она затронула.
//
// # Зачем отдельный тип, а не int64
//
// Контракт всех пишущих портов здесь — ОДНОИНСТРУКЦИОННАЯ запись с условием
// в самой инструкции:
//
//	UPDATE authorization_codes
//	   SET consumed_at = now()
//	 WHERE signature = $1 AND consumed_at IS NULL
//
// и возврат `tag.RowsAffected()`. Противоположный способ — «прочитать,
// проверить в коде, потом записать» — между чтением и записью оставляет окно,
// в котором второй запрос успевает погасить тот же код. Никакая
// изолированность транзакции этого окна не закрывает, если чтение и запись
// разнесены по разным инструкциям без блокировки.
//
// Если бы метод возвращал `(int64, error)`, реализация, забывшая передать
// число, вернула бы ноль — и ноль неотличим от честного «строк не затронуто».
// Обе ветви выглядели бы одинаково, и ошибка реализации стала бы ошибкой
// протокола на проводе.
//
// StoreOutcome отличает «не названо» от «названо нулём». Нулевое значение
// типа НЕ ОБЪЯВЛЕНО, и церемония отвергает его как нарушение контракта порта
// (ErrPortContract), а не как «строк не затронуто». Собрать объявленный исход
// можно ТОЛЬКО через RowsTouched, то есть только назвав число.
//
// # Что это НЕ гарантирует
//
// Тип не может заставить реализацию исполнить одну инструкцию вместо двух. Он
// делает другое: делает невозможным ВЕРНУТЬ исход, не назвав число, и делает
// видимым число, отличное от единицы. Реализация «проверить-потом-записать»,
// честно вернувшая RowsTouched(1) после гонки, всё равно даст двойное
// погашение — и это ловится пробой службы на конкурентное погашение, не
// типом. Тип закрывает МОЛЧАЛИВЫЙ путь, а не все пути.
type StoreOutcome struct {
	// declared — исход собран конструктором, а не нулевым значением.
	declared bool
	// rows — сколько строк затронула инструкция.
	rows int64
}

// RowsTouched собирает исход записи из числа, которое вернул драйвер.
//
//	tag, err := tx.Exec(ctx, q, sig)
//	if err != nil { return oauthceremony.StoreOutcome{}, err }
//	return oauthceremony.RowsTouched(tag.RowsAffected()), nil
//
// Отрицательное число — тоже законный вход: драйвер, который не умеет считать
// строки, возвращает −1, и церемония обязана увидеть это как нарушение
// контракта, а не превратить в ноль по дороге.
func RowsTouched(n int64) StoreOutcome { return StoreOutcome{declared: true, rows: n} }

// Rows — число затронутых строк. Осмысленно только при Declared() == true.
func (o StoreOutcome) Rows() int64 { return o.rows }

// Declared — назван ли исход. Ложь означает нулевое значение типа, то есть
// реализацию, вернувшую исход в обход RowsTouched.
func (o StoreOutcome) Declared() bool { return o.declared }

// ── Порты ───────────────────────────────────────────────────────────────────
//
// # Кто это реализует
//
// НИКТО В ФУНДАМЕНТЕ. Все интерфейсы ниже реализует СЛУЖБА, владеющая базой:
// сегодня это служба доступа `kaname`, завтра — любая другая, решившая быть
// сервером авторизации. Фундамент объявляет форму и требования
// и не приносит ни одной реализации, даже «в памяти для проб»: реализация в
// памяти в фундаменте немедленно стала бы тем, на что сошлются в рабочем
// пути. Пробы этого пакета носят свои подставки в файлах `_test.go`, то есть
// в графе сборки потребителя их нет.
//
// # Что общего у всех портов
//
// Порт отвечает НАШИМИ ошибками (ErrGrantNotFound, ErrStorageConflict,
// ErrAuthorizationCodeConsumed, ErrRefreshTokenRotated, ErrPortContract) либо
// любой своей — тогда
// церемония переложит её в CodeServerError, сохранив текст в Debug. Порт НЕ
// обязан знать ни о движке, ни о его системе ошибок.
//
// Какие из наших ошибок порт вправе вернуть, говорит ЕГО контракт. У портов
// доказательства клиента — ClientDirectory и ClientSecretVerifier — наш
// случай вне контракта читается как ErrPortContract, а не как исход протокола.
//
// Срок каждого вызова назначает церемония: она передаёт порту контекст с
// дедлайном Config.PortTimeout. Порт обязан этот контекст уважать и обязан
// вернуть отказ, а не висеть.

// ClientDirectory — откуда берутся записи клиентов.
//
// Реализует СЛУЖБА. Ожидается чтение из таблицы клиентов с кэшем на стороне
// службы; церемония не кэширует ничего — отзыв клиента обязан действовать
// немедленно.
type ClientDirectory interface {
	// LookupClient отдаёт запись клиента по его публичному
	// идентификатору.
	//
	// Клиента нет → ErrGrantNotFound. Отдавать пустую запись без ошибки
	// запрещено: «клиента нет» и «клиент есть, но пуст» — разные события.
	//
	// ErrGrantNotFound — ЕДИНСТВЕННЫЙ случай пакета в контракте этого
	// вызова. Любой другой наш случай церемония читает как нарушение
	// контракта (ErrPortContract), а не как исход протокола; прочий отказ —
	// отказ операции (срок и отмена — своими случаями).
	//
	// В операции, где клиент доказывает себя (обмен, интроспекция, отзыв),
	// «клиента нет» доказательства не обрывает: церемония всё равно зовёт
	// порт сверки (ClientSecretVerifier) — ровно один раз, как для известного
	// клиента, — и отвечает тем же отказом, что неверному секрету.
	LookupClient(ctx context.Context, clientID string) (ClientRegistration, error)
}

// AuthorizationCodeVault — хранилище кодов авторизации.
//
// Реализует СЛУЖБА.
//
// # КОД И ЕГО ПРИВЯЗКА PKCE — ОДНА ЗАПИСЬ
//
// Запись кода (AuthorizationCodeRecord) несёт и грант, и привязку кода к
// доказательству владения ключом (RFC 7636): вызов и метод — её поля, у службы
// — столбцы той же строки. Отдельного хранилища привязки нет: код и привязка
// рождаются одной выдачей и умирают одним погашением.
//
// # ГДЕ ЗДЕСЬ АТОМАРНОСТЬ И ПОЧЕМУ ОНА ЦЕЛИКОМ НА НАШЕЙ СТОРОНЕ
//
// Измерено по внесённому движку (ветка волны 32 @84b9be8): обработчик кода
// читает код на строке 33 `internal/oauth2/handler/oauth2/
// flow_authorize_code_token.go`; обработчик PKCE затем снимает привязку на
// строке 150 `internal/oauth2/handler/pkce/handler.go` — ДО сверки
// доказательства; выдача читает код снова (строка 127), открывает транзакцию
// (156) и гасит код (168). Чтение стоит СНАРУЖИ транзакции, и между чтением и
// погашением нет ни блокировки, ни повторной проверки: два одновременных обмена
// одним кодом оба проходят чтение.
//
// Церемония гасит код РОВНО ОДИН РАЗ за обмен и в первом из этих мест — при
// снятии привязки, то есть при ПРЕДЪЯВЛЕНИИ кода, до сверки доказательства:
// предъявление и есть использование кода (RFC 6749 §4.1.2), и код, предъявленный
// с неверным доказательством, второго предъявления не получает. Погашение
// на выдаче ту же запись уже не трогает.
//
// Значит защита от повторного использования кода — РОВНО ОДНА инструкция
// ConsumeAuthorizationCode, и никакая часть её не лежит в движке.
type AuthorizationCodeVault interface {
	// StoreAuthorizationCode кладёт запись кода под его подписью — sha256
	// значения кода в hex, 64 знака. Само значение сюда не приходит: код
	// непрозрачен, и строка хранилища его не выдаёт.
	//
	// Подпись уникальна: ожидается INSERT, затронувший ровно одну строку.
	// Затронуто 0 → ErrPortContract (вставка, ничего не вставившая, —
	// дефект). Затронуто больше 1 → ErrPortContract (подпись не
	// уникальна). Столкновение подписей → ErrStorageConflict.
	//
	// Привязка в записи ВСЕГДА годна (метод S256, вызов — свёртка в
	// base64url): запрос без неё отвергается до выдачи, и служба вправе
	// держать оба столбца обязательными.
	StoreAuthorizationCode(ctx context.Context, signature string, code AuthorizationCodeRecord) (StoreOutcome, error)

	// FetchAuthorizationCode отдаёт запись кода по его подписи.
	//
	// Исходов ТРИ, и все три названы:
	//
	//  1. Код есть и не погашен → (запись, nil).
	//  2. Кода нет вовсе → (пустая запись, ErrGrantNotFound).
	//  3. Код есть и УЖЕ ПОГАШЕН → (ЗАПИСЬ, ErrAuthorizationCodeConsumed).
	//
	// Третий исход обязан отдавать запись ВМЕСТЕ с ошибкой. Это не
	// небрежность контракта: повторное предъявление кода отзывает ВСЕ
	// артефакты того гранта (RFC 6749 §4.1.2, замечание о безопасности) —
	// отзыв исполняет церемония по завершении операции, — а для отзыва
	// нужен идентификатор гранта. Грант без идентификатора при третьем
	// исходе — ErrPortContract: реализация превратила бы обнаруженную атаку
	// в тихий отказ, оставив выданные токены живыми.
	//
	// Привязка отдаётся ТАКОЙ, КАКОЙ ЛЕГЛА: живой код без годной привязки S256
	// — ErrPortContract (порча записи), а не «PKCE не было».
	FetchAuthorizationCode(ctx context.Context, signature string) (AuthorizationCodeRecord, error)

	// ConsumeAuthorizationCode гасит код.
	//
	// ОДНОЙ ИНСТРУКЦИЕЙ, с условием внутри неё:
	//
	//	UPDATE authorization_codes
	//	   SET consumed_at = now()
	//	 WHERE signature = $1 AND consumed_at IS NULL
	//
	// и возвратом RowsTouched(tag.RowsAffected()).
	//
	// Исходы по числу строк:
	//   1 → код погашен нами; обмен продолжается;
	//   0 → код уже был погашен — одновременный ПОВТОР: выборку кода прошли
	//       двое, и этот обмен опередили. Церемония отвечает
	//       ErrAuthorizationCodeConsumed и отзывает семейство гранта (через
	//       GrantRevoker, вне единицы работы движка) — вместе с парой,
	//       которую получил опередивший; обмен не состоится;
	//   иное → ErrPortContract: подпись не уникальна либо драйвер не
	//       умеет считать строки.
	//
	// ЗАПРЕЩЕНО: читать, сравнивать в коде и потом писать. Запрещено
	// возвращать StoreOutcome{} — незаполненный исход отвергается как
	// нарушение контракта, а не толкуется как ноль строк.
	ConsumeAuthorizationCode(ctx context.Context, signature string) (StoreOutcome, error)
}

// AccessTokenVault — хранилище токенов доступа.
//
// Реализует СЛУЖБА.
type AccessTokenVault interface {
	// StoreAccessToken кладёт грант под подписью токена доступа — его jti,
	// названным при выпуске (AccessTokenIssuer.IssueAccessToken). Ожидается
	// ровно одна затронутая строка.
	StoreAccessToken(ctx context.Context, signature string, grant GrantRecord) (StoreOutcome, error)

	// FetchAccessToken отдаёт грант по подписи. Нет → ErrGrantNotFound.
	// Токен отозванного семейства (см. GrantRevoker) — тоже ErrGrantNotFound,
	// когда бы он ни был положен.
	FetchAccessToken(ctx context.Context, signature string) (GrantRecord, error)

	// DropAccessToken снимает токен доступа по подписи.
	//
	// Затронуто 0 строк — ЗАКОННЫЙ исход, а не отказ: снятие
	// несуществующего артефакта идемпотентно по RFC 7009 §2.2, и служба
	// не обязана знать, кто снял его первым. Больше одной строки →
	// ErrPortContract.
	DropAccessToken(ctx context.Context, signature string) (StoreOutcome, error)
}

// RefreshTokenVault — хранилище токенов обновления.
//
// Реализует СЛУЖБА.
type RefreshTokenVault interface {
	// StoreRefreshToken кладёт грант под подписью токена обновления —
	// sha256 его значения в hex, — связывая его с подписью (jti)
	// выпущенного вместе с ним токена доступа. Связь нужна, чтобы отзыв
	// одного снимал второй.
	StoreRefreshToken(ctx context.Context, signature, accessSignature string, grant GrantRecord) (StoreOutcome, error)

	// FetchRefreshToken отдаёт грант по подписи.
	//
	// Исходов ТРИ, и все три названы:
	//
	//  1. Токен есть и не обёрнут → (грант, nil).
	//  2. Токена нет вовсе либо его семейство отозвано (см. GrantRevoker) →
	//     (пустой грант, ErrGrantNotFound).
	//  3. Токен есть и УЖЕ ОБЁРНУТ → (ГРАНТ, ErrRefreshTokenRotated).
	//
	// Третий исход — ПОВТОР (RFC 9700 §4.14.2): токеном владеют двое, и
	// сервер не знает, кто из них законный. Грант обязан ехать ВМЕСТЕ с
	// ошибкой по той же причине, что у погашенного кода: по нему отзывается
	// семейство. Обёрнутый токен, отданный как живой, превращает повтор в
	// обычный оборот, и пара, выданная первым оборотом, переживает его; грант
	// без идентификатора при третьем исходе — ErrPortContract (отзывать
	// нечего).
	FetchRefreshToken(ctx context.Context, signature string) (GrantRecord, error)

	// DropRefreshToken снимает токен обновления по подписи. Ноль строк —
	// законный исход, как и у DropAccessToken.
	DropRefreshToken(ctx context.Context, signature string) (StoreOutcome, error)

	// RotateRefreshToken помечает токен обновления использованным при
	// обороте.
	//
	// ОДНОЙ ИНСТРУКЦИЕЙ, по тем же основаниям, что и погашение кода:
	//
	//	UPDATE refresh_tokens
	//	   SET rotated_at = now()
	//	 WHERE grant_id = $1 AND signature = $2 AND rotated_at IS NULL
	//
	// Исходы: 1 → оборот наш; 0 → токен уже обернули — одновременный ПОВТОР:
	// выборку прошли двое, и этот оборот опередили. Церемония отвечает
	// ErrRefreshTokenRotated и отзывает семейство гранта; иное →
	// ErrPortContract.
	RotateRefreshToken(ctx context.Context, grantID, signature string) (StoreOutcome, error)
}

// RevocationReason — почему церемония отзывает семейство гранта.
//
// # Зачем причина в порте
//
// Все пути отзыва снимают одно и то же семейство одними и теми же методами
// GrantRevoker. По одному факту вызова служба не различила бы повтор кода
// авторизации, повтор токена обновления и отзыв клиентом, а различать их ей
// обязательно: причина ложится в её журнал и в её закрытый словарь, и разные
// причины означают разные события — атаку на код, атаку на токен и выход
// клиента из сеанса.
//
// # Почему у типа нет значения «причина не названа»
//
// Отзыв без причины до порта не доходит: мост, не знающий, почему отзывает,
// отказывает случаем CodeCeremonyMisuse, не позвав порта. Значение «не
// названа» служба была бы вынуждена либо записать — и её закрытый словарь
// перестал бы быть закрытым, — либо отвергнуть, то есть оставить семейство
// живым. Нулевое значение типа словарю не принадлежит (Declared отвечает
// «нет»), и церемония его порту не передаёт.
type RevocationReason string

// Причины отзыва. Перечень ЗАКРЫТ: значение вне его церемония порту не
// передаёт, и служба вправе отвергать его как нарушение контракта.
// Написание — контракт со службой: она сопрягает его со своим словарём по
// значению.
const (
	// RevocationCodeReplay — код авторизации предъявлен повторно (RFC 6749
	// §4.1.2): последовательно, после обмена, либо одновременно с другим
	// обменом того же кода.
	RevocationCodeReplay RevocationReason = "code-replay"

	// RevocationRefreshReplay — предъявлен уже обёрнутый токен обновления
	// (RFC 9700 §4.14.2): последовательно, после оборота, либо одновременно
	// с другим оборотом того же токена.
	RevocationRefreshReplay RevocationReason = "refresh-replay"

	// RevocationClientRevoke — клиент попросил отзыва через точку отзыва
	// (RFC 7009 §2.1), в том числе прежним, уже обёрнутым токеном
	// обновления: семейство снимается по просьбе клиента, а не потому, что
	// токеном владеют двое.
	RevocationClientRevoke RevocationReason = "client-revoke"
)

// RevocationReasons возвращает словарь целиком — службе, которая сопрягает его
// со своим и обязана убедиться, что сопряжение полное.
func RevocationReasons() []RevocationReason {
	return []RevocationReason{RevocationCodeReplay, RevocationRefreshReplay, RevocationClientRevoke}
}

// Declared отвечает, входит ли причина в словарь. Нулевое значение НЕ входит:
// «причина не названа» — не причина.
func (r RevocationReason) Declared() bool {
	return slices.Contains(RevocationReasons(), r)
}

// GrantRevoker — отзыв всех артефактов одного гранта.
//
// Реализует СЛУЖБА.
//
// # Отзыв — СЕМЕЙСТВА, и он НЕОБРАТИМ
//
// Отозванный грант не годен целиком: его токен доступа и токен обновления не
// годны, КОГДА БЫ ОНИ НИ БЫЛИ ПОЛОЖЕНЫ — до отзыва или после. Выборка такого
// токена отвечает ErrGrantNotFound.
//
// Почему «и после». На одновременном повторе (см. RotateRefreshToken и
// ConsumeAuthorizationCode) проигравший отзывает семейство, пока победитель
// ещё кладёт выданную ему пару. Порядок этих записей держит только единица работы, а она
// необязательна (UnitOfWork). Отзыв, снимающий лишь уже лежащие строки, при
// таком порядке оставил бы пару победителя живой — ровно ту, ради снятия
// которой отзыв и исполнялся. Ожидаемая форма — отметка отзыва у самого
// семейства (`token_families.revoked_at`), которую выборка сверяет, а не
// удаление строк.
//
// # Отзыв действует и там, где токен доступа ПРЕДЪЯВЛЯЮТ
//
// Токен доступа сверяют по ключам его издателя, без этого хранилища (см.
// AccessTokenIssuer): место, принимающее токен, выборки гранта не делает.
// Поэтому отзыв семейства ОБЯЗАН дойти и туда: токен доступа отозванного
// семейства получает отказ при предъявлении в любом месте, которое его
// принимает, — и раньше своего exp. Ключ семейства в токене — GrantID гранта,
// который порт выпуска кладёт в токен (IssueAccessToken), и отзыв записывает
// отсечку по этому ключу там, где её читает проверка предъявленного токена.
// Отзыв, снимающий только строки и отметку этого хранилища, оставил бы
// отозванный токен годным везде, где его сверяют по ключам, до конца срока.
//
// Отсечка действует на ВСЯКИЙ токен семейства, КОГДА БЫ ОН НИ БЫЛ ВЫПУЩЕН —
// до отметки отзыва или после, — а не на выпущенные до неё. Почему «и
// после»: на одновременном повторе кода опередивший гасит код при
// предъявлении, то есть раньше своего выпуска (см. AuthorizationCodeVault), и
// его выпуск может лечь ПОЗЖЕ отметки, которую ставит отзыв отставшего.
// Отсечка, судящая по моменту выпуска, пропустила бы ровно этот токен — токен
// пары, ради снятия которой отзыв исполнялся. Предпосылка — проба
// TestConcurrentCodeReplayWinnerMayIssueAfterTheRevocation.
//
// # Причина отзыва
//
// Каждый вызов несёт причину (RevocationReason) — всегда одну из словаря.
// Семейство отзывают оба метода одной операции, и причина у них одна и та же.
// Повторный отзыв уже отозванного семейства законен (ноль строк — не отказ);
// причину уже отозванного семейства служба вправе не переписывать: первая
// причина и есть та, по которой семейство умерло.
type GrantRevoker interface {
	// RevokeGrantRefreshTokens снимает ВСЕ токены обновления гранта по
	// причине reason. Ноль строк — законный исход (нечего снимать).
	RevokeGrantRefreshTokens(ctx context.Context, grantID string, reason RevocationReason) (StoreOutcome, error)

	// RevokeGrantAccessTokens снимает ВСЕ токены доступа гранта по причине
	// reason. Ноль строк — законный исход.
	RevokeGrantAccessTokens(ctx context.Context, grantID string, reason RevocationReason) (StoreOutcome, error)
}

// AccessTokenIssuer — выпуск и опознание токена доступа.
//
// Реализует СЛУЖБА — своим подписантом токенов. Подписного материала у
// церемонии нет: ни ключа, ни общего секрета, ни библиотеки подписи. Токен
// доступа подписывает тот, кто публикует ключи его проверки, и его
// предъявления сверяют по тем же ключам; второй подписант с отдельным
// секретом был бы вторым материалом, который служба обязана хранить, вращать
// и беречь.
//
// Код авторизации и токен обновления этот порт НЕ выпускает: они
// непрозрачны, их значение — случайные байты церемонии, а в хранилище лежит
// подпись значения (см. AuthorizationCodeVault, RefreshTokenVault).
//
// Срок каждого вызова — Config.PortTimeout, тот же, что у портов хранения.
type AccessTokenIssuer interface {
	// IssueAccessToken выпускает токен доступа по гранту.
	//
	// # Что порт получает
	//
	// Грант — тот же, что церемония положит под jti этого выпуска
	// (AccessTokenVault.StoreAccessToken), очищенный тем же перечнем полей.
	// Отличие одно: срок токена доступа в сеансе у порта — граница (см. ниже),
	// а у записи — exp этого выпуска. Предъявленных секретов — кода,
	// `code_verifier`, токена обновления, секрета клиента — в гранте нет.
	//
	// # Что идёт в токен
	//
	// Утверждения о доступе берутся ТОЛЬКО из того, что назначили согласие и
	// церемония: субъект — grant.Session.Subject, клиент — grant.ClientID,
	// области и получатели — grant.GrantedScopes и grant.GrantedAudiences.
	// grant.RequestedScopes и grant.RequestedAudiences — то, что клиент ПРОСИЛ
	// в запросе авторизации, а не то, что дало согласие; в токен они не идут.
	// grant.Form — протокольные поля запроса, а не утверждения; тоже не идут.
	//
	// Токен несёт КЛЮЧ СЕМЕЙСТВА — grant.GrantID. Проверка предъявленного
	// токена сверяет по нему отзыв семейства (см. GrantRevoker, «Отзыв
	// действует и там, где токен доступа ПРЕДЪЯВЛЯЮТ»): токен без ключа
	// семейства отзыв пережил бы до своего exp.
	//
	// # Срок и момент выпуска
	//
	// Срок назначает церемония: grant.Session.ExpiresAt[TokenKindAccess] —
	// граница, позже которой токен истечь НЕ ВПРАВЕ (срок из
	// Config.AccessTokenLifespan от мига обмена, сжатый границей семейства).
	// Выпуск раньше неё законен: подписант режет срок до своего потолка или
	// до целых секунд. Позже неё — ErrPortContract, и выпуск клиенту не
	// уезжает.
	//
	// Момент выпуска — не раньше начала секунды, в которой церемония позвала
	// порт: iat в целых секундах законен, iat раньше этой секунды —
	// ErrPortContract. Срок в ответе обмена — ExpiresAt − IssuedAt, и момент
	// выпуска раньше вызова удлинил бы его сверх того, что токену осталось
	// жить.
	//
	// Исход — IssuedAccessToken, у которого названо всё: значение, jti,
	// момент выпуска и exp, причём exp позже момента выпуска. Под jti
	// церемония кладёт грант (AccessTokenVault.StoreAccessToken), а срок в
	// ответе обмена считает как ExpiresAt − IssuedAt — те же exp и iat, что
	// лежат в самом токене; незаполненное поле — ErrPortContract.
	IssueAccessToken(ctx context.Context, grant GrantRecord) (IssuedAccessToken, error)

	// IdentifyAccessToken проверяет предъявленный токен и отдаёт его jti.
	//
	// Проверяет ТОЛЬКО ПОДЛИННОСТЬ: подпись ключом издателя и форму. Срок
	// порт НЕ судит: его судит церемония по записи гранта. Исходов три, и все
	// три названы:
	//
	//  1. Токен выпущен этим издателем → (jti, nil) — в том числе ИСТЁКШИЙ и
	//     в том числе токен отозванного семейства. Истёкший церемония называет
	//     негодным по записи гранта (`active: false`, RFC 7662 §2.2), а отзыв
	//     по нему снимает семейство (RFC 7009 §2.1) — так же, как по живому.
	//     Пустой jti при nil — ErrPortContract.
	//  2. Токен не его: чужая подпись, неизвестный ключ, не та форма →
	//     ("", ErrGrantNotFound). На интроспекции это `active: false`, на
	//     отзыве — успех без действия (RFC 7662 §2.2, RFC 7009 §2.2).
	//  3. Проверить не удалось: сбой, недоступность, срок или отмена вызова →
	//     отказ ОПЕРАЦИИ. Опознание, которое не состоялось, не вправе стать ни
	//     «негоден», ни «отозвано»: отзыв ответил бы успехом, не сняв живой
	//     токен.
	//
	// Всякий иной названный портом случай — вердикт о токене вместо jti:
	// ErrTokenExpired, ErrInactiveToken, ErrTokenSignatureMismatch и прочие.
	// Это ErrPortContract, и операция отказывает, а не отвечает: прочитанный
	// как «не наш», вердикт «истёк» сделал бы отзыв по истёкшему токену
	// доступа успехом, оставив живым токен обновления его семейства.
	//
	// Грант ищется ТОЛЬКО по опознанному jti. Поэтому значение, jti которого
	// взято из чужого токена, а подпись не сходится, гранта не находит.
	//
	// # Значение token — предъявительский секрет
	//
	// Порт получает предъявленное значение как есть: токен доступа, а на
	// интроспекции и отзыве без подсказки вида — и токен обновления. Порт НЕ
	// пишет его в журнал и НЕ кладёт в текст своего отказа — ни целиком, ни
	// частью. Церемония со своей стороны вырезает предъявленное значение из
	// каждого текста отказа опознания (описание, подсказка, подробности), но
	// отказ порта остаётся причиной отказа (Unwrap) таким, каким порт его
	// вернул.
	IdentifyAccessToken(ctx context.Context, token string) (string, error)
}

// IssuedAccessToken — выпущенный токен доступа.
type IssuedAccessToken struct {
	// Token — значение токена, которое уезжает клиенту как есть.
	Token string

	// ID — идентификатор токена (утверждение `jti`). Под ним церемония кладёт
	// грант и под ним же ищет его при предъявлении.
	ID string

	// IssuedAt, ExpiresAt — момент выпуска и срок годности, ровно те, что
	// лежат в токене (`iat`, `exp`).
	IssuedAt  time.Time
	ExpiresAt time.Time
}

