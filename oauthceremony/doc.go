// Package oauthceremony — церемония OAuth 2.0 платформы: ОДНА объявленная
// граница между службами и движком авторизации.
//
// # Главное правило пакета
//
// НИ ОДИН ЭКСПОРТИРОВАННЫЙ ЭЛЕМЕНТ ЭТОГО ПАКЕТА НЕ НАЗЫВАЕТ ЧУЖОГО ТИПА.
// Ни подпись функции, ни поле структуры, ни метод интерфейса, ни возвращаемая
// ошибка. Потребитель, читающий этот пакет, не обязан знать, какой движок
// внутри, и не может узнать это из его поверхности.
//
// Правило не уговор, а ПРЕДИКАТ: проба TestNoForeignTypeInExportedSurface
// разбирает исходники пакета деревом и отвергает всякое упоминание чужого
// пакета в типе экспортированного элемента. Словарь дозволенного — только
// стандартная библиотека, и он объявлен в самой пробе.
//
// # Зачем так
//
// Движок внесён в фундамент поддеревом (`internal/oauth2`, происхождение — в
// `internal/oauth2/PROVENANCE.md`). Правило языка запрещает потребителю
// импортировать `internal/`, и это первая половина защиты. Вторая половина —
// здесь: пакет, стоящий над движком, обязан не протаскивать его типы наружу
// своими руками. Иначе `internal/` защищал бы от прямого импорта, а этот
// пакет молча выдавал бы то же самое через свои подписи, и смена движка снова
// стала бы правкой каждой службы.
//
// # Из чего состоит граница
//
// Типы запроса и ответа: AuthorizationRequest, AuthorizationIntent,
// AuthorizationGrant, AuthorizationResult, TokenRequest, TokenResult,
// IntrospectionRequest, IntrospectionResult, RevocationRequest.
//
// Отказ: ProtocolError с полем Code типа FailureCode. Случаи различаются ПО
// ЗНАЧЕНИЮ (`errors.Is(err, oauthceremony.ErrInvalidGrant)`), а не по тексту.
//
// Порты хранения: ClientDirectory, AuthorizationCodeVault, AccessTokenVault,
// RefreshTokenVault, GrantRevoker и необязательный UnitOfWork. Порт выпуска
// токена доступа: AccessTokenIssuer. Все они объявлены здесь и реализуются
// СЛУЖБОЙ; фундамент не приносит ни одной реализации. Привязка кода к
// доказательству владения ключом (PKCE, RFC 7636) — поля записи кода
// (AuthorizationCodeRecord), а не отдельное хранилище: обязательна всякому
// клиенту, метод — только S256. Порт отзыва получает причину из закрытого
// словаря RevocationReason — повтор кода, повтор токена обновления, отзыв
// клиентом, — и служба сопрягает её со своим словарём.
//
// # Чего здесь НЕТ и почему
//
// Нет реализации хранилища: она принадлежит службе, владеющей базой. Нет
// сетевых обработчиков: церемония возвращает то, что следует написать, но
// ничего не пишет — поверхность может быть HTTP, может быть шлюзом, может
// быть пробой.
//
// Нет утверждений клиента (RFC 7523 §2.2) и объектов запроса OpenID Connect:
// им нужен набор ключей клиента типом библиотеки JOSE движка, а она заключена в
// поддерево (гейт `internal/engineconfinement`); клиент доказывает себя
// секретом либо, будучи публичным, не доказывает себя вовсе, и PKCE несёт
// всякий. Нет вида гранта
// `client_credentials`: у машинных клиентов службы доступа своя выдача.
//
// Нет неявного потока (`response_type=token`): OAuth 2.1 его исключает. Нет
// способа `urn:ietf:params:oauth:grant-type:jwt-bearer`: он требует своего
// порта ключей доверенного выпускающего, и слово без обработчика обещало бы
// несуществующее поведение. Нет выдачи токена личности (OpenID Connect): это
// отдельный состав портов и отдельные настройки ключей.
//
// # Артефакты и подписной материал
//
// Подписного материала у церемонии нет: ни ключа, ни общего секрета, ни
// библиотеки подписи. Код авторизации и токен обновления НЕПРОЗРАЧНЫ — 256
// случайных бит, а в хранилище лежит подпись значения, sha256 в hex; сверяются
// они только поиском по подписи. Токен доступа выпускает и опознаёт порт
// службы (AccessTokenIssuer) — тот, кто публикует ключи его проверки; грант
// лежит под его jti, а срок в ответе обмена — срок этого выпуска. Предикаты —
// пробы `opaque_artifact_test.go` и `access_issuer_test.go`.
//
// # Приставка выпускающего в артефактах
//
// Стратегия выпуска движка, назначенная у него по умолчанию, ШТАМПУЕТ В ТЕКСТ
// КАЖДОГО ТОКЕНА приставку с именем поставщика (`ory_at_`, `ory_rt_`,
// `ory_ac_`). Это привязка в самом видном месте из возможных: приставка
// уезжает клиенту, попадает в его журналы и в его код разбора, и снять её
// потом нельзя, не сломав всех, кто на неё смотрит.
//
// Церемония выпускает артефакты СВОЕЙ стратегией, без приставки, а значение
// токена доступа отдаёт таким, каким его выпустил порт. Предикат — проба
// TestIssuedArtifactsCarryNoVendorPrefix.
//
// Своей приставки пакет тоже не ставит: приставки платформы — предмет пакета
// `ids`, а не поставщика движка, и заводить их здесь значило бы завести
// второе место об одном предмете.
//
// # Атомарность
//
// Движок читает код авторизации СНАРУЖИ транзакции (замер — в доке
// AuthorizationCodeVault), а церемония гасит его РОВНО ОДИН РАЗ за обмен — при
// предъявлении, до сверки доказательства. Значит защита от повторного
// использования кода целиком на нашей стороне, и она вынесена в контракт
// порта: тип StoreOutcome не даёт вернуть исход записи, не назвав число
// затронутых строк.
//
// # Повтор кода и токена обновления
//
// Токен обновления, предъявленный после оборота, — повтор (RFC 9700 §4.14.2),
// и он отзывает СЕМЕЙСТВО гранта целиком: прежний токен доступа и пару,
// выданную оборотом. Повтор замечается двумя путями — выборкой, отдавшей токен
// обёрнутым (ErrRefreshTokenRotated из RefreshTokenVault.FetchRefreshToken), и
// нулём строк оборота, когда выборку прошли двое.
//
// Код авторизации, предъявленный второй раз, — тоже повтор (RFC 6749 §4.1.2),
// и полоса кода устроена так же: семейство отзывается вместе с парой, которую
// получил опередивший. Путей два — выборка погашенного кода
// (ErrAuthorizationCodeConsumed) и ноль строк погашения. Код гасит первое же
// предъявление, и предъявление с неверным доказательством — тоже: второе
// предъявление такого кода — повтор.
//
// На обеих полосах отзыв исполняет церемония по завершении операции, вне
// единицы работы движка, и отвечает отдельным случаем (на проводе —
// `invalid_grant`); отказ отзыва возвращается отказом операции, а не этим
// случаем. Предикат — пробы `refresh_replay_test.go` и
// `code_replay_test.go`, утверждающие СОСТОЯНИЕ гранта после отказа, в том
// числе при отказавшем порте отзыва.
