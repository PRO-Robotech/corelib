package servicecontract

// HostForm — ФОРМА ХОСТА: какие gRPC-слушатели поднимает процесс. Одна закрытая
// ось, а не набор логических полей.
//
// # Почему ось одна
//
// О том, какие слушатели у процесса, дескриптор уже говорил полем [Spec.OwnContour],
// и рядом просились ещё два элемента о том же предмете: «сервисов нет» у
// службы без gRPC-слушателей и «только внутренний слушатель». Будь каждый
// независимым полем, сочетания «сервисов нет + адрес слушателя задан» или
// «сервисов нет + собственный контур» стали бы выразимы, и каждый страж —
// конструктор, носитель, самоотчёт, гейт посадки — решал бы по своему полю.
// Здесь «сервисов нет» — значение оси ([HostNoGRPC]), а «сервисов нет» как
// утверждение — ПРОИЗВОДНОЕ ([Descriptor.NoServedServices]), вводом не
// являющееся. Следующая форма добавляется третьим значением этой же оси, второго
// поля не заводит.
//
// # Почему нуль — пара
//
// Нулевое значение — [HostPair], то есть пара слушателей, как у всех служб до
// заведения оси. Иначе каждый существующий дескриптор, не знающий об оси,
// перестал бы приниматься, а смысла «не объявлено» у пары нет: её ровно и
// поднимает носитель.
//
// # Разбор — исчерпывающий switch без default
//
// Каждое место, решающее по оси, перечисляет её значения явно и ветки default не
// несёт. Значение вне перечня не попадает в «прочее» молча: [New] отвергает его
// с именем поля ([HostForm.known]), поэтому форма, добавленная без разбора,
// становится отказом старта, а не тихим поведением пары.
type HostForm uint8

const (
	// HostPair — пара gRPC-слушателей (публичный и внутренний), которую поднимает
	// носитель, либо собственный контур процесса ([Spec.OwnContour]). Нулевое
	// значение.
	HostPair HostForm = iota
	// HostNoGRPC — gRPC-слушателей у процесса нет вовсе. Посадка судится как
	// обычно; адреса и транспорты слушателей, собственный контур и проводка
	// носителя — отказ старта с именем поля: объявлять их не о чем.
	HostNoGRPC
)

// hostFormUnknown — написание значения вне перечня оси. Само по себе в
// самоотчёт не попадает: такой дескриптор [New] не принимает.
const hostFormUnknown = "<unknown>"

// String — написание значения для самоотчёта о посадке. Самоотчёт заполняется
// `d.HostForm().String()` принятого дескриптора, своего словаря у него нет,
// поэтому это — ЕДИНСТВЕННОЕ место написаний оси. Гейт посадки
// (`assert-production-posture.sh`) их парсит: это хард-контракт.
func (h HostForm) String() string {
	switch h {
	case HostPair:
		return "pair"
	case HostNoGRPC:
		return "no-grpc"
	}
	return hostFormUnknown
}

// known — объявлено ли значение перечнем оси. Читает тот же разбор, что и
// [HostForm.String]: второго перечня нет.
func (h HostForm) known() bool { return h.String() != hostFormUnknown }

// HostForm — форма хоста ПРИНЯТОГО дескриптора. Дескриптор, собранный литералом,
// отвечает нулевым значением: решения по нему носитель не принимает вовсе.
func (d Descriptor) HostForm() HostForm {
	if !d.accepted {
		return HostPair
	}
	return d.spec.HostForm
}

// NoServedServices — ПРОИЗВОДНОЕ «процесс не служит ни одного gRPC-сервиса».
// Не поле ввода: выводится из оси формы хоста принятого дескриптора, поэтому
// разойтись с ней не может.
func (d Descriptor) NoServedServices() bool { return d.HostForm() == HostNoGRPC }

// checkNoGRPCCarriesNoListener — О15: при форме [HostNoGRPC] всё, что описывает
// gRPC-слушатель или его контур, — сочетание, которого не бывает.
//
// Отказ, а не молчание, по той же причине, что и О14: принесённое и никем не
// читаемое объявление — второе место об одном предмете. Процесс, объявивший «слушателей
// нет» и принёсший адрес слушателя, говорит о себе две вещи, и верна из них одна.
//
// Перечень полей проводки — тот же, что у О14 ([carriedWiring]): второго
// перечня нет. Сверх него — [Spec.OwnContour]: собственный контур есть контур
// gRPC-слушателей, а их нет.
func checkNoGRPCCarriesNoListener(f *findings, s Spec) {
	why := "форма хоста " + HostNoGRPC.String() + " (gRPC-слушателей нет), а поле описывает gRPC-слушатель " +
		"или его контур: объявлять его не о чем, и рядом с формой оно было бы вторым утверждением о том же " +
		"предмете, из которых верно одно. Либо снимите поле, либо объявите форму пары слушателей"
	if s.OwnContour != "" {
		f.add("OwnContour", why)
	}
	for _, c := range carriedWiring(s) {
		if c.set {
			f.add(c.field, why)
		}
	}
}
