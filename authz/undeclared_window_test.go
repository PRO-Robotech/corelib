// undeclared_window_test.go — окно отзыва не заводится само.
//
// Кешируется положительный вердикт, поэтому срок жизни записи И ЕСТЬ время,
// в течение которого субъект с уже отобранным правом продолжает проходить.
// Это параметр безопасности, и `pkg/authz.RevocationPolicy` объявляет, каким
// ему быть позволено.
//
// Объявление накрывает ровно те площадки, которые кеш НАЗЫВАЮТ. Пока
// конструктор интерсептора заводил кеш сам, когда его об этом не просили,
// существовал второй путь получить окно — молча и не попав ни в перепись, ни
// под потолок. Такое окно нельзя ни обсудить, ни заметить при смене: у него
// нет автора.
package authz_test

import (
	"strings"
	"testing"

	"github.com/PRO-Robotech/corelib/authz"
)

// TestInterceptorRefusesUndeclaredRevocationWindow — конструктор отказывает
// вызывающему, который кеш вердиктов не назвал.
//
// Отказ, а не умолчание: умолчание, меняющее посадку безопасности, невидимо по
// построению — вызывающий не писал строки, значит и в обзоре правки её нет, и
// в переписи её нет, и потолок к ней не приложен. Отказ же случается в
// композиционном корне, то есть при старте процесса, и называет ручку.
func TestInterceptorRefusesUndeclaredRevocationWindow(t *testing.T) {
	defer func() {
		r := recover()
		if r == nil {
			t.Fatalf("конструктор принял вызов БЕЗ поля Cache и завёл окно отзыва сам.\n" +
				"Тогда у окна нет автора: оно не попадает ни в перепись " +
				"pkg/authz.RevocationPolicy, ни под её потолок, и сменить его можно, " +
				"не тронув ни одной строки, которую кто-нибудь прочтёт.\n" +
				"Требуется отказ при старте с именем ручки.")
		}
		msg, ok := r.(string)
		if !ok {
			t.Fatalf("отказ есть, но он не строка: %#v", r)
		}
		// Текст отказа читает оператор, поднимающий стенд: он обязан назвать
		// ручку, иначе процесс не поднять.
		if !strings.Contains(msg, "Cache") {
			t.Errorf("текст отказа не называет ручку: %q", msg)
		}
	}()

	authz.NewInterceptor(authz.InterceptorOptions{
		Map:        authz.RPCMap{},
		Breakglass: true,
	})
}

// TestInterceptorAcceptsDeclaredRevocationWindow — законный близнец.
//
// Отрицание в одиночку зеленеет сильнее всего именно тогда, когда сломано всё:
// конструктор, отказывающий ВСЕМ, прошёл бы проверку выше. Поэтому рядом стоит
// положительный случай — та же форма вызова, но кеш назван.
func TestInterceptorAcceptsDeclaredRevocationWindow(t *testing.T) {
	defer func() {
		if r := recover(); r != nil {
			t.Fatalf("конструктор отверг вызов, который кеш НАЗВАЛ: %v.\n"+
				"Проверка обязана сужать неявный путь, а не запрещать явный.", r)
		}
	}()

	intr := authz.NewInterceptor(authz.InterceptorOptions{
		Map:        authz.RPCMap{},
		Breakglass: true,
		Cache:      authz.NewCache(0),
	})
	if intr == nil {
		t.Fatalf("конструктор вернул nil на корректных параметрах")
	}
}
