package catalogderive

import "sort"

// foundationlanes.go — ПОЛОСА ДОСТУПА методов фундамента, объявленная ПЕРЕЧНЕМ,
// а не разметкой контракта.
//
// # Зачем перечень появился
//
// Словарь разметки доступа принадлежит СЛУЖБЕ ДОСТУПА (решение владельца
// 2026-09-13: «authz — должна же жить в канаме»). Фундамент — ЛИСТ графа
// модулей: `kacho → corelib`, `kaname → corelib`, и обратного ребра нет ни
// одного. Импортируй фундамент словарь службы — ребро пошло бы от листа к
// потребителю, то есть завелось бы КОЛЬЦО.
//
// Поэтому два служебных контракта фундамента (длящаяся операция и подписка)
// разметки больше не несут. Полоса у их методов от этого не исчезает — она
// переезжает сюда.
//
// # Почему ЗАПИСЬ, а не изъятие
//
// Соблазн — изъять пакет из вывода карты по образцу `platformServices`
// (`servicehost/audit.go`). Это проверено и НЕ ГОДИТСЯ: изъятие убирает метод
// из карты прав целиком, и звено решения отвергает его как НЕОПИСАННЫЙ. Исход
// был бы хуже исходного — зелёный старт и мёртвый опрос исхода каждой
// асинхронной мутации платформы. Нужна ЗАПИСЬ, а не дыра.
//
// # Почему это не ослабляет защиту
//
// Две записи из трёх — не право, а ОБЪЯВЛЕНИЕ ЕГО ОТСУТСТВИЯ: `<exempt>` с
// причиной `HANDLER_DECIDES` значит «модель прав не спрашивают, решает
// обработчик». Настоящая проверка для них производится КОДОМ ФУНДАМЕНТА вне
// контракта — `operations.CheckRecordedOwnership` сверяет принципала
// вызывающего с принципалом, записанным в строке операции. Опция здесь была
// МАРКЕРОМ ПОЛОСЫ, а не правилом, поэтому перенос маркера переносит объявление,
// а не защиту.
//
// # Форма взята у прецедента, а не придумана
//
// `servicehost.platformServices` — закрытый ИМЕНОВАННЫЙ перечень с причиной у
// каждой записи и самоистечением. Здесь то же устройство и по той же причине:
// «изымаем всё, что не размечено» было бы корзиной «прочее», в которую однажды
// МОЛЧА попадёт доменный RPC, забывший разметку.
//
// # Читателей ДВА, объявление ОДНО
//
// Карта прав процесса берёт полосу через `AnnotationsOf` (ниже по файлу
// `derive.go`), генератор каталога края — через `FoundationLaneOf`. Второго
// объявления не заводится: пакет `catalogderive` создан своей же шапкой затем,
// чтобы УБРАТЬ второе объявление прав, а не добавить третьего проверяющего.
//
// # Чем держится
//
// `TestFoundationLanesAllStillHaveASubject` — самоистечение: запись, чей метод
// в двоичном не резолвится, и запись, чей метод ВЕРНУЛ СЕБЕ разметку в
// контракте, — обе находки. Второе важнее первого: два объявления об одном
// предмете расходятся молча, и расходится то, которое не читают.

// FoundationLane — полоса доступа одного метода фундамента.
//
// Поля — ровно те четыре величины, из которых состоит строка каталога прав у
// этих методов. Больше их быть не может: запись, которой понадобилось пятое
// поле, описывает уже не полосу фундамента, а разметку — и её место в
// контракте своего домена, а не здесь.
type FoundationLane struct {
	// Permission — право, которого метод требует, либо `<exempt>`.
	Permission string
	// ExemptReason — почему проверки нет. Обязателен ровно при `<exempt>`.
	ExemptReason string
	// RequiredACRMin — минимальная сила подтверждения личности.
	RequiredACRMin string
	// ScopeFiltered — владелец сужает выдачу пообъектно сам.
	ScopeFiltered bool

	// Why — почему полоса объявлена ЗДЕСЬ, а не разметкой контракта. Читается
	// человеком при снятии записи; без неё объявление нечем оспорить.
	Why string
	// Enforcement — где производится НАСТОЯЩЕЕ решение о доступе, если оно
	// производится не моделью прав. Пусто у записи, которая право называет.
	Enforcement string
}

// foundationLanes — те самые полосы, поимённо.
//
// Ключ — полное имя метода в той форме, в какой grpc-go передаёт его звену
// решения: с ведущей косой. Форм записи полного имени в дереве ДВЕ (с косой и
// без), и предикат, знающий одну, о второй молчит, — поэтому форма здесь
// названа, а не подразумевается.
var foundationLanes = map[string]FoundationLane{
	"/corelib.operation.OperationService/Get": {
		Permission:   ExemptPermission,
		ExemptReason: "HANDLER_DECIDES",
		Why: "опрос исхода длящейся операции; модель прав не спрашивается, потому что " +
			"единого объекта у вопроса нет — операция принадлежит тому, кто её начал, и " +
			"это записано в её собственной строке",
		Enforcement: "operations.CheckRecordedOwnership — сверка принципала вызывающего с " +
			"принципалом, записанным в строке операции",
	},
	"/corelib.operation.OperationService/Cancel": {
		Permission:   ExemptPermission,
		ExemptReason: "HANDLER_DECIDES",
		Why: "отмена длящейся операции; полоса та же, что у опроса, и по той же причине — " +
			"право отменить принадлежит начавшему",
		Enforcement: "operations.CheckRecordedOwnership — сверка принципала вызывающего с " +
			"принципалом, записанным в строке операции",
	},
	"/corelib.subscription.InternalSubscriptionService/Subscribe": {
		Permission:     "platform.subscription.subscribe",
		RequiredACRMin: "1",
		ScopeFiltered:  true,
		Why: "поток изменений журнала владельца; единого объекта для вопроса при открытии " +
			"не существует — поток несёт события разных предметов разных проектов, — поэтому " +
			"владелец сужает выдачу на КАЖДОЙ отдаваемой строке, а не отвечает одним " +
			"вопросом при открытии",
	},
}

// FoundationLaneOf — полоса метода, объявленная перечнем.
//
// `ok=false` означает «перечень об этом методе молчит», и это НЕ разрешение:
// вызывающий обязан читать разметку контракта, как читал всегда.
func FoundationLaneOf(fullMethod string) (FoundationLane, bool) {
	l, ok := foundationLanes[fullMethod]
	return l, ok
}

// FoundationLaneMethods — имена методов перечня, отсортированные.
//
// Существует для гейта самоистечения: он обязан пройти по ЗАПИСЯМ и спросить
// дерево о каждой, а не наоборот. Обход в обратную сторону («у каждого метода
// без разметки есть запись») отвечал бы на другой вопрос и молчал бы ровно на
// записи, потерявшей предмет.
func FoundationLaneMethods() []string {
	out := make([]string, 0, len(foundationLanes))
	for m := range foundationLanes {
		out = append(out, m)
	}
	sort.Strings(out)
	return out
}
