package authz

import "time"

// RevocationWindowPolicy — объявленная политика окна отзыва доступа.
//
// # Что такое это окно
//
// Срок жизни записи И ЕСТЬ окно отзыва — время, в течение которого субъект, у
// которого право уже отобрали, продолжает проходить. Иного пути снять запись у
// backend-сервиса нет.
//
// # Асимметрия есть НЕ ВЕЗДЕ, и это надо знать ДО того, как менять число
//
// Кешируются ТОЛЬКО положительные вердикты — на ВСЕХ площадках, включая край.
// Поэтому свежая ВЫДАЧА видна сразу (промах по кешу всегда идёт к авторитетному
// Check), а ждёт один лишь ОТЗЫВ. Асимметрия намеренная и правильная:
// администратор, выдавший доступ, не должен ждать; администратор, отобравший
// доступ, ждёт ограниченное и объявленное время.
//
// # Край отступал от этого правила, и цена отступления была измерена
//
// До 2026-08-05 край (api-gateway) складывал в тот же кеш и ОТКАЗ, из-за чего
// то же число работало второй, необъявленной стороной — как ЗАДЕРЖКА ВЫДАЧИ.
// Следствие наблюдалось не в теории: запрос, проигравший гонку материализации
// owner-tuple, сам записывал свой отказ и держал его весь срок жизни записи уже
// ПОСЛЕ появления права. В прогоне e2e это дало квантованное окно: из 75 шагов,
// восстановившихся ограниченным клиентским ретраем, 68 сошлись ровно на десятом
// повторе (10×500ms = 5.0s = ровно это число), ещё 3 — на двадцатом (второе
// такое же окно). Разброс, свойственный настоящей задержке материализации,
// отсутствовал: окно производил кеш, а не материализация.
//
// Отказ и так fail-closed, поэтому его кеширование не защищает НИЧЕГО — оно
// только откладывает выдачу. Край приведён к общему правилу, и нарушение
// сделано непредставимым по построению: у записи кеша края, как и у `Cache`
// ниже, нет поля «разрешено» (`gateway/internal/middleware.decisionCacheEntry`).
//
// # Почему это объявлено здесь, а не в комментарии каждого сервиса
//
// До этой записи окно было эмерджентным. Шесть сервисов несли положительный
// кеш вердиктов, каждый называл своё число в своём комментарии, и ни одно место
// не говорило, каким числу быть позволено. Параметр безопасности, которого
// никто не выбирал, нельзя ни обсудить, ни отозвать, ни заметить при смене.
// Гейт `internal/repohygiene.TestRevocationWindowIsDeclaredPolicy` связывает эту
// запись с деревом: смена умолчания без правки политики роняет проверку.
//
// # Второй путь получить окно, которого перепись не видела
//
// Перепись накрывает площадки, которые кеш НАЗЫВАЮТ. Пока `NewInterceptor`
// заводил кеш за вызывающего, оставившего поле пустым, существовал второй путь:
// сервис получал полноценное окно, ни разу его не назвав, и в исходнике не
// оставалось ни одной строки, по которой перепись могла бы его найти. Гейт при
// этом такой файл читал, засчитывал в «осмотрено» и объявлял чистым — то есть
// не просто не ловил, а отвечал «чисто» на вопрос, которого не задавал.
//
// Путь снят: неназванный кеш — отказ в старте (`NewInterceptor`), плюс
// `internal/repohygiene.TestNoServiceTakesTheWindowImplicitly` называет файл и
// строку до того, как процесс поднимут.
//
// # Ручка есть всегда; незаданной бывает только ВЕЛИЧИНА
//
// Состояний тут ДВА, и до 2026-09-08 они были склеены в одно — из-за чего
// платформа объявляла законным то, что сама же и запрещает:
//
//	ручка ЕСТЬ, величина не задана  → Resolve даёт Default. Законно: оператор
//	                                  видит ручку и вправе сузить окно на своей
//	                                  посадке. Так живёт край.
//	ручки НЕТ вовсе                 → окно принадлежит платформе, сузить его
//	                                  на посадке НЕЛЬЗЯ, и в конфигурации
//	                                  процесса о нём нет ни строки. ЗАПРЕЩЕНО.
//
// Второе запрещено не этой строкой, а решением, уже стоящим в дереве:
// `pkg/servicecontract` объявляет у окна «умолчания быть не может» и ОТКАЗЫВАЕТ
// В СТАРТЕ процессу, не назвавшему величину; а по дереву своей ручки требует от
// каждого держателя гейт TestEveryVerdictCacheProcessDeclaresItsOwnKnob
// (`internal/repohygiene`).
//
// Здесь стояла третья редакция того же предмета — карта `Inherited`,
// перечислявшая площадки «без своей ручки» как законные. Она пережила свой
// предмет: собственные фабрики звена сняты у всех, кеш каждому строит носитель
// по значению из ЕГО ручки, и карта стояла пустой. Пустой она была безвредна, а
// действующей стала бы неисполнимой: следующий, кто записал бы туда площадку,
// как велела эта строка, получил бы красное от гейта — состояние, объявленное
// законным и запрещённое by construction. Карта снята вместе с предметом;
// утверждение о площадке без своей ручки в дереве теперь ОДНО.
//
// # Что НЕ ездит по этому окну
//
// Окно относится к отзыву ГРАНТА (AccessBinding). Оно НЕ относится к отзыву
// УЧЁТНЫХ ДАННЫХ — скомпрометированный токен, уволенный сотрудник, утёкший ключ.
// Такой отзыв обязан быть немедленным, и он немедленный не потому, что окно
// мало, а потому, что идёт другим путём: сессия/токен снимается на краю
// (`session_revocations` плюс сброс кэша вердиктов на самом крае: немедленный на
// обслужившей реплике, окном чтения журнала `subject_change_outbox` — на
// соседних), и
// закешированный положительный вердикт backend-сервиса ему не помогает — до
// backend-сервиса запрос с отозванным токеном просто не доходит.
//
// Смешивать эти два отзыва — ошибка, которая толкает «сделать окно поменьше»
// вместо «снять учётные данные». Окно ниже размерено под отзыв гранта, и
// уменьшать его ради сценария, который им не решается, не нужно.
type RevocationWindowPolicy struct {
	// Default — величина, которой разрешается НЕЗАДАННАЯ ручка окна. Читается
	// конструктором кеша и функцией Resolve: это единственный источник значения,
	// а не литерал, повторённый по дереву.
	//
	// Это НЕ «окно процесса без ручки»: такого процесса быть не должно (см.
	// §«Ручка есть всегда» выше). Живой потребитель — край, у которого ручка
	// есть и величину которого оператор вправе не задавать.
	Default time.Duration

	// Ceiling — потолок ТРЕТЬЕЙ ступени (видимость на крае): ни одно окно кэша
	// вердиктов не вправе быть больше. Это обещание платформы про отзыв гранта.
	Ceiling time.Duration

	// DeliveryCeiling — потолок ПЕРВОЙ ступени: доставки намерения регистрации
	// из очереди владельца РЕСУРСА до владельца прав. Строка очереди пишется
	// той же транзакцией, что и смена носителя, дренаж будится уведомлением, а
	// откат — периодический перепрос; величина отката и есть эта ступень.
	DeliveryCeiling time.Duration

	// MaterializationCeiling — потолок ВТОРОЙ ступени: пересчёта производного
	// пообъектного доступа у владельца ПРАВ. Ускоритель после коммита в пределе
	// даёт ноль, очередь сверки будится уведомлением, а внешний backstop —
	// периодический обход; величина обхода и есть эта ступень.
	MaterializationCeiling time.Duration

	// Windows — перепись объявленных окон, ключ «<сервис> <ручка>».
	// Значение обязано совпадать с тем, что реально написано в исходнике
	// сервиса; расхождение — находка гейта.
	Windows map[string]time.Duration
}

// RevocationPolicy — действующая политика.
//
// # Обоснование числа
//
// Потолок 10s выбран как сумма трёх слагаемых, каждое из которых наблюдаемо:
// срок жизни записи (≤5s) + дренаж очереди отзыва до хранилища прав (≤2s) +
// запас на переспрос под нагрузкой. Меньше 5s означало бы ходить к iam почти на
// каждый RPC — та самая нагрузка, ради амортизации которой кеш и заведён;
// больше 10s означало бы, что снятие права заметно человеку, который его снял.
//
// Число НЕ выведено из механизма проактивной инвалидации: такого механизма у
// backend-сервисов нет (см. ниже). Прежняя запись в doc.go складывала окно с
// членом «NOTIFY≤1s» от пути, у которого в этом репозитории нет ни одного
// отправителя, и потому обещала распространение, которого не происходит.
var RevocationPolicy = RevocationWindowPolicy{
	Default: 5 * time.Second,
	Ceiling: 10 * time.Second,

	// Потолки первых двух ступеней РАВНЫ их сегодняшним умолчаниям, и это
	// решение, а не совпадение: ручку можно только СУЗИТЬ. Запас «на всякий
	// случай» здесь означал бы, что платформа обещает границу, которой сама
	// пользоваться не собирается, — а величина, которую никто не выбирал, тем и
	// плоха. Ни один профиль развёртывания этих ручек не задаёт (замер
	// 2026-08-31: `git grep -rn 'poll-fallback\|RECONCILE_SWEEP_INTERVAL_MS' --
	// deploy/ services/*/deploy/` → пусто), поэтому потолок не меняет ни одной
	// сегодняшней посадки — он делает границей то, что и так наблюдается.
	DeliveryCeiling:        30 * time.Second,
	MaterializationCeiling: 30 * time.Second,

	// Windows — перепись на 2026-08-04, снятая с дерева гейтом (8 площадок,
	// 7 процессов). Ключ — «<процесс> <ручка>».
	//
	// Три семьи кешей, все кешируют вердикт и все задерживают отзыв:
	//   - `authz.cache*` — пообъектная проверка на КАЖДОМ RPC (оба листенера);
	//   - `authz.list-filter.*` — пообъектная видимость строки страницы List;
	//   - край (`api-gateway`) — решение по запросу до того, как он вообще уйдёт
	//     в сервис.
	//
	// Значения намеренно ОДИНАКОВЫ (5s) везде, кроме registry: у registry на
	// той же поверхности сидит docker-клиент, тянущий образы по выданному
	// гранту, поэтому там окно сужено вдвое осознанно и это записано у ручки.
	//
	// # Почему края здесь не было до 2026-08-04
	//
	// Перепись искала кеши двумя предикатами, и оба были привязаны к тому, КАК
	// кеш сделан, а не к тому, ЧТО он хранит: обход начинался с каталога
	// `services/` (край лежит в `gateway/`), а конструктор искался по имени
	// `authz.NewCache` (край строит свой `newDecisionCache` над общим LRU).
	// Поэтому процесс, через который проходит КАЖДЫЙ внешний запрос, не был
	// прочитан ни одной из проверок — ни разу, ни одним файлом, — и его окно
	// не было записано нигде. Это не недосмотр обхода: край находился вне того,
	// что обход был способен выразить.
	//
	// Оба предиката расширены, и перепись теперь считает ПРОЦЕССЫ, а не каталоги
	// под `services/`. Прежняя редакция называла здесь имя набора конструкторов,
	// которого в дереве нет ни одного: перечень живёт в
	// `tools/revocationwindowgate`, и цитировать его отсюда значит завести второе
	// место об одном предмете — оно и разошлось.
	//
	// # Форм владения окном ДВЕ, и перепись обязана считать их порознь
	//
	// Процесс держит окно либо строя кеш вердиктов сам, либо НАЗЫВАЯ величину
	// дескриптору носителя, который строит один кеш на всех. Вторая форма — не
	// экзотика: сегодня ею и только ею держат окно пять площадок из восьми.
	// Перепись, задавшая один вопрос «строит ли процесс кеш», для них слепа by
	// construction — строить там нечего, — а её молчание читается как «чисто».
	// Поэтому распознаватель один на обе формы, а перепись печатает величину ПО
	// КАЖДОЙ: сумма не отличает «форма ослепла» от «площадок стало меньше».
	Windows: map[string]time.Duration{
		"vpc authz.cache-ttl":                            5 * time.Second,
		"vpc authz.list-filter.cache-ttl":                5 * time.Second,
		"nlb authz.cache.ttl":                            5 * time.Second,
		"nlb authz.list-filter.cache-ttl":                5 * time.Second,
		"registry KACHO_REGISTRY_AUTHZ_CACHE_TTL":        2 * time.Second,
		"compute KACHO_COMPUTE_LIST_FILTER_CACHE_TTL_MS": 5 * time.Second,
		"storage KACHO_STORAGE_LIST_FILTER_CACHE_TTL_MS": 5 * time.Second,

		// Три площадки, у которых своей ручки НЕ БЫЛО: они строили кеш как
		// NewCache(0) и потому держали умолчание политики. Значение не изменилось
		// — изменилось то, что число стало ВЫБРАННЫМ: до этого оператор не мог
		// сузить окно отзыва на конкретной посадке, а обсуждать было нечего, потому
		// что величина принадлежала платформе, а не сервису. Площадок этого вида в
		// дереве не осталось ни одной, и вернуться им некуда: держатель без своей
		// ручки не поднимается (`pkg/servicecontract`) и роняет гейт дерева.
		"compute KACHO_COMPUTE_AUTHZ_CACHE_TTL": 5 * time.Second,
		"storage KACHO_STORAGE_AUTHZ_CACHE_TTL": 5 * time.Second,
		"geo KACHO_GEO_AUTHZ_CACHE_TTL":         5 * time.Second,

		// Край — единственная площадка с ПРОАКТИВНЫМ снятием записи, и полос у
		// него две: реплика, обслужившая мутацию, гасит кэш НЕМЕДЛЕННО, а
		// соседние сходятся чтением журнала смены субъекта `subject_change_outbox`
		// — чтением, которое край открывает САМ (задача #1024 развернула
		// направление: прежде строку толкал дренаж владельца прав, и это было
		// ребро из листа обратно к потребителю). Строка пишется в той же
		// транзакции, что и снятие привязки.
		//
		// Поэтому обычный отзыв здесь укладывается в окно чтения, а это окно —
		// ЗАПАСНОЕ: столько действует отозванный грант, если чтение отстало или
		// лежит. Запасное окно — всё равно окно, и незаписанное запасное окно —
		// всё равно ничей параметр безопасности.
		//
		// Отличий от остальных строк по СЕМАНТИКЕ у этой величины больше нет:
		// край, как и все, кеширует только положительный вердикт, поэтому число
		// работает ровно одной стороной — как окно отзыва. Уменьшать его —
		// значит платить обращением к iam почти на каждый запрос именно там,
		// где запросов больше всего.
		"api-gateway KACHO_API_GATEWAY_AUTHZ_CACHE_TTL_SECONDS": 5 * time.Second,

		// Владелец модели — площадка, появившаяся последней, и появилась она не
		// от роста нагрузки, а от закрытия дыры: до собственной двери iam НЕ
		// задавал пообъектного вопроса на своих слушателях вовсе, полагаясь на
		// край. Вынесенный в чужое облако iam края не имеет, поэтому дверь у него
		// теперь своя — а вместе с дверью появилось и окно.
		//
		// ЗДЕСЬ СТОЯЛА ПЛОЩАДКА СЛУЖБЫ ДОСТУПА — владельца модели прав. Запись
		// снята вместе со своим предметом: служба вынесена отдельным продуктом,
		// её конфигурация и процесс живут в другом дереве, и площадки, которую
		// эта запись объявляла, перепись здесь не находит.
		//
		// Прежняя редакция сама это предсказала: «на вынесенной посадке сузить
		// это окно сможет только тот, кто её держит». Так и вышло — окно объявляет
		// теперь её собственное дерево, тем же фундаментом, который она берёт
		// опубликованным.
		//
		// ОСТАТОК: согласие окна отзыва службы с потолком политики в ЭТОМ дереве
		// не проверяется. Потолок при этом остаётся общим и приезжает к ней вместе
		// с фундаментом — снят только замер, не правило.
	},
}

// Resolve — окно, с которым процесс БУДЕТ работать, из величины, которую он
// объявил.
//
// Неположительное значение означает «ручка есть, величина не задана» — и только
// это. Оно НЕ означает «ручки нет»: держатель окна без собственной ручки не
// поднимается вовсе (`pkg/servicecontract`, отказ в старте) и роняет гейт дерева
// (`internal/repohygiene`.TestEveryVerdictCacheProcessDeclaresItsOwnKnob).
// Различать эти два состояния обязательно: первое оператор вправе оставить
// незаданным, второе отбирает у него ручку насовсем.
//
// Функция одна на всех: её зовёт и тот, кто строит кэш, и тот, кто судит
// величину при старте.
// Второй копии этого правила в дереве быть не должно — расходятся такие копии
// именно там, где расхождение не видно: обе отвечают одинаково на всяком
// положительном входе и по-разному на нуле, то есть ровно на той посадке, где
// ручку не трогали.
func (p RevocationWindowPolicy) Resolve(declared time.Duration) time.Duration {
	if declared <= 0 {
		return p.Default
	}
	return declared
}

// ChainCeiling — верхняя граница ВСЕЙ цепочки отзыва гранта: доставка намерения
// (первая ступень) + пересчёт производного доступа (вторая) + видимость на крае
// (третья).
//
// # Почему сумма, а не максимум
//
// Ступени идут ПОСЛЕДОВАТЕЛЬНО: пока намерение не доехало, пересчитывать нечего;
// пока пересчёт не прошёл, край спрашивает и получает прежний ответ. Худший
// случай — потеря сигнала на обеих первых ступенях, и тогда каждая ждёт свой
// откат целиком. Максимум описывал бы полосу, в которой ступени идут
// параллельно, а такой полосы нет.
//
// # Что эта величина НЕ покрывает
//
// Недоступность владельца прав переводит доставку в ОТДЕЛЬНЫЙ режим повтора со
// своими величинами: там намерение не опаздывает, а не доезжает вовсе, и ловится
// это глубиной и возрастом очереди, а не границей окна. Складывать те величины с
// этой суммой нельзя — у них другой предмет и другой исход.
//
// И она не относится к отзыву УЧЁТНЫХ ДАННЫХ: у него свой немедленный путь (см.
// §«Что НЕ ездит по этому окну» выше). Смешивать их — ошибка, толкающая сузить
// это окно вместо того, чтобы снять учётные данные.
func (p RevocationWindowPolicy) ChainCeiling() time.Duration {
	return p.DeliveryCeiling + p.MaterializationCeiling + p.Ceiling
}
