package db

// connbudget.go — сколько соединений посадка обещает базе и сколько база готова
// принять.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ПРОВЕРКА, А НЕ СЛЕДСТВИЕ НАСТРОЙКИ
//
// Две величины назначаются в РАЗНЫХ местах и ни одна не знает о другой: размер
// пула объявлен на ОДНУ реплику, а предел базы — общий на ВСЕ. Их произведение
// не записано нигде, поэтому расхождение между «обещано» и «принимается» не
// видно ни в одном файле по отдельности. Пока нагрузки нет, оно ничем себя не
// выдаёт: соединения открываются лениво, и пул, объявленный вдвое шире предела,
// выглядит точно так же, как посильный. Узнаётся оно отказом в подключении —
// ровно тогда, когда соединения действительно понадобились.
//
// ─────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ ПРЕДЕЛ СПРАШИВАЕТСЯ У БАЗЫ, А НЕ ОБЪЯВЛЯЕТСЯ НАСТРОЙКОЙ
//
// Объявленный предел — второе место об одном предмете, и оно разойдётся с базой
// молча. Хуже: он бывает НЕ ОБЪЯВЛЕН вовсе — тогда база работает на умолчании
// сборки, о котором посадка не знает ничего, и «настройка не задана» читалось бы
// как «ограничения нет». База отвечает на этот вопрос сама, авторитетно и
// одинаково на любой посадке.
//
// ─────────────────────────────────────────────────────────────────────────────
// ЧТО ЭТА ПРОВЕРКА НЕ ПОКРЫВАЕТ — НАЗВАНО, А НЕ УМОЛЧАНО
//
//  1. Она считает ТОЛЬКО пул. Служба держит соединения и помимо него — ожидание
//     оповещений, опросчики очередей, — и они тоже занимают слоты. Значит
//     пройденная проверка НЕОБХОДИМА, но не достаточна: это нижняя граница
//     обещанного, а не полная. Число фоновых соединений здесь не выдумывается:
//     невыдуманного значения у него нет, а вписанное «на глаз» превратило бы
//     проверку в источник ложной точности.
//  2. Бюджет реплик посадка СООБЩАЕТ, а не измеряет: под сколько реплик она
//     рассчитана, знает тот, кто её раскладывает. Реплика, поднятая помимо
//     объявленного бюджета, этой проверке не видна by construction — она видна
//     только тому, кто менял раскладку.

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5"
)

// ConnBudget — сколько соединений посадка ОБЕЩАЕТ базе.
type ConnBudget struct {
	// PoolMaxConns — потолок пула ОДНОЙ реплики.
	//
	// Берётся у самого пула (`pool.Config().MaxConns`), а НЕ из настройки:
	// настройка бывает не задана, и тогда действует умолчание драйвера, которое
	// зависит от числа ядер узла. Посадка о нём не знает, а база его получит.
	PoolMaxConns int32

	// Replicas — сколько реплик посадка может поднять ОДНОВРЕМЕННО.
	//
	// Это ПОТОЛОК раскладки, а не текущее число живых подов: проверка отвечает на
	// вопрос «поместится ли посадка целиком», и брать текущее число значило бы
	// признавать годной посадку, которая перестаёт быть годной от собственного
	// штатного роста.
	Replicas int
}

// ConnCeiling — что база готова принять.
type ConnCeiling struct {
	MaxConnections    int
	SuperuserReserved int
}

// Available — слоты, которые база отдаёт обычным клиентам.
//
// Запас суперпользователя вычтен: он существует затем, чтобы к исчерпавшей себя
// базе можно было подключиться и разобраться. Раздав его службе, мы отнимаем
// ровно тот доступ, которым чинят последствия.
func (c ConnCeiling) Available() int { return c.MaxConnections - c.SuperuserReserved }

// Validate отвечает, помещается ли обещанное в принимаемое.
//
// Имя — по здешнему обычаю (`Config.Validate`), и оно НЕ `Check`: так зовётся
// вопрос к хранилищу отношений, и гейт, стерегущий полосы этого вопроса, честно
// поймал бы одноимённый метод про пул как неучтённое место. Предикат по имени
// мерит соглашение об именовании — значит соглашение и надо соблюсти.
//
// Незаявленная величина — ОТКАЗ, а не пропуск. Ноль в любом сомножителе обращает
// произведение в ноль, и проверка проходила бы всегда, ничего не проверив: «не
// объявлено» стало бы означать «не ограничиваем» — тот же класс, что пустой круг
// доверенных отправителей, который пропускает всех.
func (b ConnBudget) Validate(c ConnCeiling) error {
	if b.PoolMaxConns <= 0 {
		return fmt.Errorf("предел пула не объявлен (%d): без него произведение «пул × реплики» "+
			"обращается в ноль и проходит любую проверку", b.PoolMaxConns)
	}
	if b.Replicas <= 0 {
		return fmt.Errorf("бюджет реплик не объявлен (%d): под сколько реплик рассчитана посадка, "+
			"знает тот, кто её раскладывает, — служба этого о себе не знает и обязана быть "+
			"уведомлена явно", b.Replicas)
	}
	if c.MaxConnections <= 0 {
		return fmt.Errorf("предел соединений базы не прочитан (%d): «не прочитан» не может "+
			"означать «не ограничен»", c.MaxConnections)
	}
	promised := int(b.PoolMaxConns) * b.Replicas
	available := c.Available()
	if promised > available {
		return fmt.Errorf("посадка обещает базе больше соединений, чем та принимает: "+
			"пул %d на реплику × %d реплик = %d, база принимает %d "+
			"(max_connections %d − запас суперпользователя %d). "+
			"Обещанное сверх принимаемого не «иногда медленнее» — это отказ в подключении "+
			"ровно тогда, когда соединения понадобились. Приведите предел пула к "+
			"(принимается ÷ реплик) = %d либо поставьте пулер между службой и базой. "+
			"Учтён ТОЛЬКО пул: ожидание оповещений и опросчики очередей занимают слоты "+
			"сверх него, поэтому это нижняя граница обещанного",
			b.PoolMaxConns, b.Replicas, promised, available,
			c.MaxConnections, c.SuperuserReserved, available/b.Replicas)
	}
	return nil
}

// CeilingReader — узкий порт: ровно один вопрос, который здесь задаётся.
type CeilingReader interface {
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// ReadConnCeiling спрашивает у базы её собственные пределы.
//
// `current_setting` вместо `SHOW` — чтобы обе величины приехали одним запросом и
// относились к одному мгновению; читаются они как текст и приводятся здесь,
// потому что тип настройки в каталоге — строка.
func ReadConnCeiling(ctx context.Context, q CeilingReader) (ConnCeiling, error) {
	var c ConnCeiling
	err := q.QueryRow(ctx, `
		SELECT current_setting('max_connections')::int,
		       current_setting('superuser_reserved_connections')::int`).
		Scan(&c.MaxConnections, &c.SuperuserReserved)
	if err != nil {
		return ConnCeiling{}, fmt.Errorf("db: чтение пределов соединений: %w", err)
	}
	return c, nil
}
